//! SACRED (architect-only) — M-49 rev5 / **блокер `research/reviews/R-002-M-49-rev4.md`**:
//! операторская декларация на ПРОД-МАСШТАБНОМ СЫРОМ сегменте.
//!
//! ## Дефект (описан reviewer'ом, воспроизведён запуском, не рассуждением)
//!
//! Путь декларации входит ТОЛЬКО когда хвостовой скан вернул `Err`. После задачи 4a
//! появился новый повод для `Err`: **сырой сегмент больше `TAIL_SCAN_CHUNK` (4 MiB), в
//! хвостовом окне которого нет валидных фреймов, но заголовок цел и префикс файла полон
//! читаемых событий.** Валидация декларации спрашивает пол у той же функции, получает тот
//! же `Err` и **выбрасывает сегмент целиком вместе с читаемым префиксом**. Пол падает до
//! максимума ПРЕДЫДУЩЕГО сегмента, а если повреждённый сегмент один — до `None` ⇒
//! `unwrap_or(0)` ⇒ проходит ЛЮБОЙ `next_seq >= 1` ⇒ защиты нет вообще.
//!
//! Замер reviewer'а на `276083d`: сегмент 9 981 549 B, читаемый максимум `seq = 95141`,
//! декларация `next_seq = 1` **ПРИНЯТА** — запись пошла в уже занятый диапазон.
//!
//! ## Почему это прод, а не экзотика
//!
//! Прод-каталог (ssh, 2026-07-31): `segment-00000139.jrnl` = 1 073 709 677 B (закрытый),
//! `segment-00000140.jrnl` = 868 073 435 B и растёт. Активный сегмент **СЫРОЙ**, на три
//! порядка больше окна скана 4 MiB. Триггер milestone'а — restore-drill R1 (~2026-08-10),
//! где `journal.meta` отсутствует по определению.
//!
//! ## Форма фикстуры (совпадает с прод-формой)
//!
//! ДВА сырых сегмента: закрытый + активный больше окна скана — чтобы оракул различал
//! «реализация прочитала префикс повреждённого сегмента» и «реализация откатилась на
//! ПРЕДЫДУЩИЙ сегмент» (второе тоже даёт какой-то пол, но НЕ тот, и защита рушится ровно
//! на тех `seq`, которые лежат в повреждённом сегменте).
//!
//! ## Почему файл отдельный
//!
//! Фикстура пишет >8 MiB; в основном наборе это замедляло бы каждый прогон.
//! В `verify_M-49.sh` вынесен отдельной строкой и гоняется `--release`.

mod common;

use common::{
    cfg_with, corrupt_tail, is_segment_name, ls, max_seq_in, tolerant_bytes, tolerant_readable_max,
    trade, write_decl, DECL, DECL_APPLIED, TAIL_SCAN_CHUNK,
};
use journal::{Journal, WriterConfig};

/// Порог ротации. ОБЯЗАН быть строго больше `ACTIVE_TARGET`, иначе активный сегмент
/// закроется раньше, чем дорастёт до цели, и фикстура зациклится (поймано прогоном).
const MAX_SEGMENT_BYTES: u64 = 8 * 1024 * 1024;

/// Закрытый сегмент №0 (~8 MiB) + активный №1, который мы доращиваем заведомо больше
/// окна хвостового скана.
fn cfg() -> WriterConfig {
    cfg_with(MAX_SEGMENT_BYTES, "prodscale operator fixture")
}

/// Порча хвоста: строго БОЛЬШЕ окна скана — окно обязано содержать ТОЛЬКО мусор.
const CORRUPT_BYTES: usize = 4 * 1024 * 1024 + 512 * 1024;
/// Активный сегмент доращиваем настолько, чтобы после порчи остался существенный
/// ЧИТАЕМЫЙ ПРЕФИКС (~1.5 MiB) — именно он и есть предмет спора.
const ACTIVE_TARGET: u64 = TAIL_SCAN_CHUNK + 2 * 1024 * 1024;

// Компайл-тайм setup-guard'ы фикстуры (падают ДО прогона, а не зацикливают его).
const _: () = assert!(
    ACTIVE_TARGET < MAX_SEGMENT_BYTES,
    "фикстура невыполнима: активный сегмент не может превысить порог ротации — он \
     закроется раньше цели, и цикл набора объёма не завершится (поймано прогоном)"
);
const _: () = assert!(
    CORRUPT_BYTES as u64 > TAIL_SCAN_CHUNK,
    "фикстура: порча обязана перекрывать окно хвостового скана целиком — иначе в окне \
     найдётся валидный фрейм и путь декларации не входится"
);

fn seg_size(dir: &std::path::Path, name: &str) -> u64 {
    std::fs::metadata(dir.join(name))
        .map(|m| m.len())
        .unwrap_or(0)
}

/// Каталог прод-формы: два сырых сегмента, у активного испорчен ХВОСТ, `journal.meta`
/// удалена (холодный restore). Возвращает `(каталог, читаемый максимум, имя активного)`.
fn prodscale_raw_with_corrupt_tail() -> (tempfile::TempDir, u64, String) {
    let dir = tempfile::tempdir().expect("dir");
    let active = "segment-00000001.jrnl".to_string();
    {
        let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
        let mut n: u64 = 0;
        loop {
            j.append(trade(n)).expect("append");
            n += 1;
            if n.is_multiple_of(20_000) {
                j.flush().expect("flush");
                if seg_size(dir.path(), &active) > ACTIVE_TARGET {
                    break;
                }
            }
            assert!(
                n < 20_000_000,
                "фикстура не набрала объём — проверь размер события"
            );
        }
        j.flush().expect("flush");
    }

    // Максимум ПРЕДЫДУЩЕГО (закрытого) сегмента — то, чем ошибочно ограничивается пол,
    // если реализация выбрасывает повреждённый сегмент целиком.
    let prev_max = max_seq_in(&tolerant_bytes(&dir.path().join("segment-00000000.jrnl")))
        .expect("фикстура: закрытый сегмент обязан читаться");

    // Прод-режим restore: меты нет (ретеншен выгружает сегменты, не мету — замерено в M-40).
    let _ = std::fs::remove_file(dir.path().join("journal.meta"));

    let active_size = seg_size(dir.path(), &active);
    corrupt_tail(&dir.path().join(&active), CORRUPT_BYTES);

    let readable_max =
        tolerant_readable_max(dir.path()).expect("фикстура: префикс обязан читаться");

    // ── Setup-guard'ы: без них оракул молча проверяет НЕ ТУ ветку ────────────────────
    let segs: Vec<String> = ls(dir.path())
        .into_iter()
        .filter(|n| is_segment_name(n))
        .collect();
    assert_eq!(
        segs.len(),
        2,
        "фикстура: нужно РОВНО два сырых сегмента (прод-форма: закрытый + активный): {segs:?}"
    );
    assert!(
        active_size > TAIL_SCAN_CHUNK,
        "фикстура не состоялась: активный сегмент {active_size} B ≤ окна скана \
         {TAIL_SCAN_CHUNK} B. Оракул обязан проверять случай «файл БОЛЬШЕ окна», где буфер \
         хвостового скана не достаёт до начала файла."
    );
    assert!(
        readable_max > prev_max,
        "ФИКСТУРА НЕ ДАВИТ НА ИНВАРИАНТ: читаемый максимум каталога {readable_max} не \
         превышает максимум ПРЕДЫДУЩЕГО сегмента {prev_max}. Значит у повреждённого \
         активного сегмента не осталось читаемого префикса, и оракул не отличит «прочитали \
         префикс» от «откатились на предыдущий сегмент» — ровно та слепота, из-за которой \
         регресс 4b прошёл все зелёные гейты (R-002)."
    );

    (dir, readable_max, active)
}

// ═════════════════════════════════════════════════════════════════════════════════════
// OP-5 — декларация НЕ становится каналом seq-reuse на ПРОД-МАСШТАБНОМ СЫРОМ сегменте
// ═════════════════════════════════════════════════════════════════════════════════════

#[test]
fn op_5_declaration_guard_holds_on_prodscale_raw_segment() {
    let (dir, readable_max, active) = prodscale_raw_with_corrupt_tail();
    let size = seg_size(dir.path(), &active);

    // ── (1) Грубое нарушение: позиция в самом начале занятого диапазона ──────────────
    for (declared, what) in [
        (1u64, "начало занятого диапазона"),
        (
            readable_max,
            "РОВНО максимальный читаемый seq (правило «строго больше»)",
        ),
    ] {
        write_decl(
            dir.path(),
            declared,
            "ошибка оператора под давлением инцидента",
        );
        let err = Journal::open_with(dir.path(), cfg())
            .err()
            .unwrap_or_else(|| {
                panic!(
                    "op_2/JR-I-8 НАРУШЕН НА ПРОД-МАСШТАБЕ ({what}).\n\
                 Сегмент {active} = {size} B (> окна скана {TAIL_SCAN_CHUNK} B), ЧИТАЕМЫЙ \
                 максимум seq = {readable_max}, декларация next_seq={declared} ПРИНЯТА → \
                 запись пошла в уже занятый диапазон seq.\n\
                 ДОЛЖНО БЫТЬ: Err — пол защиты обязан учитывать ЧИТАЕМЫЙ ПРЕФИКС \
                 повреждённого сегмента, а не выбрасывать сегмент целиком из-за того, что \
                 хвостовой скан вернул Err.\n\
                 Прод-форма совпадает с фикстурой: активный сегмент сырой, 868 MB → 1 GiB, \
                 окно скана 4 MiB (R-002, Находка 1)."
                )
            });
        let msg = err.to_string();
        assert!(
            msg.to_lowercase().contains("seq"),
            "отказ обязан объяснить, что именно неверно в декларации: «{msg}»"
        );
        assert!(
            !ls(dir.path()).iter().any(|n| n == DECL_APPLIED),
            "отвергнутая декларация не должна помечаться применённой"
        );
        assert!(
            ls(dir.path()).iter().any(|n| n == DECL),
            "отвергнутая декларация обязана остаться на месте — оператор её правит"
        );
    }

    // ── (2) ПАРНЫЙ vantage: честная декларация обязана РАБОТАТЬ ─────────────────────
    // Иначе fail-closed убивает escape-hatch, ради которого он существует: оператору
    // останется только удалить каталог, то есть потерять историю.
    let declared = readable_max + 1;
    write_decl(
        dir.path(),
        declared,
        "хвост невосстановим: холодной копии нет",
    );
    let mut j = Journal::open_with(dir.path(), cfg()).unwrap_or_else(|e| {
        panic!(
            "честная декларация next_seq={declared} (СТРОГО больше читаемого максимума \
             {readable_max}) обязана РАЗБЛОКИРОВАТЬ старт.\nПОЛУЧЕНО: Err: {e}\n\
             Если пол вычислен ВЫШЕ реально читаемого (например по заголовку сегмента, а не \
             по фактически прочитанным фреймам), escape-hatch перестаёт работать и сбор \
             данных стоит навсегда."
        )
    });
    assert_eq!(
        j.next_seq(),
        declared,
        "запись обязана идти РОВНО с объявленной позиции (иначе SegmentHeader.first_seq и \
         Journal.next_seq разойдутся — дефект, закрытый в rev3)"
    );
    j.append(trade(7_777_777)).expect("append");
    j.flush().expect("flush");
    drop(j);

    let files = ls(dir.path());
    assert!(
        !files.iter().any(|n| n == DECL) && files.iter().any(|n| n == DECL_APPLIED),
        "применённая декларация обязана быть помечена (одноразовость + аудит): {files:?}"
    );
}
