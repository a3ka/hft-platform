//! SACRED (architect-only) — M-52 / **TD-052 + TD-054: пол защиты ограничен по ПАМЯТИ,
//! но не по ВРЕМЕНИ**.
//!
//! ## Дефект
//!
//! `readable_floor` (`segments.rs`) в состоянии `Unknown` прочитывает и декодирует **весь
//! каталог**: для каждого непустого сегмента с конца — `tolerant_max_seq_from_start`, то
//! есть скан С НАЧАЛА ФАЙЛА до EOF. Память ограничена и запиннена (`op_8`, rev5 M-49),
//! **работа — нет**. Прод-замер (ssh, read-only, 2026-08-02):
//!
//! ```text
//! $ ls -la /var/lib/docker/volumes/hft-platform_journal-data/_data | tail -3
//!   segment-00000156.jrnl   1 073 713 123
//!   segment-00000157.jrnl   1 073 739 468
//!   segment-00000158.jrnl      66 764 331   <- активный
//! $ ls $D | wc -l                    -> 161  (158 сегментов + meta + heartbeat + legacy)
//! $ ls $D | grep -c '\.zst$'         -> 152 сжатых
//! $ ls $D | grep -c '\.jrnl$'        ->   6 сырых
//! $ du -sh $D                        -> 26G  (сжатых; сырой объём ≈ 140 GiB)
//! ```
//!
//! Худший случай пути декларации — прочитать и раздекодировать ВСЁ это, прежде чем ответить
//! `Unknown`. Происходит ровно тогда, когда оператор поднимает recorder ПОД ИНЦИДЕНТОМ.
//!
//! И это не линейно. TD-054: side-верификация крупного кандидата (M-50, JR-I-9) на
//! равномерном мусоре запускается примерно на каждой 64-й позиции байт-ресинка
//! (доля значений `u32` в окне `(READABLE_SCAN_MAX_CARRY, FRAME_LEN_SANITY_CAP]` ≈ 1.56 %)
//! и КАЖДЫЙ раз перечитывает до `len` байт вторым источником. Замер reviewer'а:
//!
//! | хвост мусора | до M-50 | после M-50 |
//! |---|---|---|
//! | 4 MiB | — | 18.07 s |
//! | 8 MiB | — | 92.00 s |
//! | 16 MiB | **0.182 s** | **384.94 s** (×2114) |
//!
//! ## Контракт JR-I-10 (см. `milestones/M-52-journal-hardening.md`)
//!
//! **Скан пола не имеет права выполнить неограниченный объём работы.** Суммарная работа
//! (прочитанные/раздекодированные байты по ВСЕМУ каталогу, ВКЛЮЧАЯ байты side-верификации
//! крупных кандидатов) ограничена ЕДИНОЙ именованной константой-бюджетом, не зависящей ни
//! от числа сегментов, ни от их размера. При исчерпании бюджета единственный допустимый
//! исход — `Unknown` с диагностикой, называющей файл, на котором скан остановился, и
//! операторское действие. **`Known`, посчитанный по частично просмотренному каталогу,
//! запрещён**: заниженный пол — это принятая декларация внутри занятого диапазона, то есть
//! seq-reuse, необратимая порча append-only журнала. Деградация только в сторону отказа.
//!
//! ## Почему фикстуры здесь — ПСЕВДОСЛУЧАЙНЫЕ, а не `0x5A`
//!
//! Вся серия M-49/M-50 портит хвост заливкой `0x5A`. Для скана это САМАЯ ДЕШЁВАЯ форма
//! мусора: `0x5A5A5A5A` ≈ 1.4 GiB > санити-капа ⇒ мгновенный ресинк на 1 байт, ноль
//! side-верификаций. Именно поэтому «на реальных формах порчи кандидаты единичны»
//! продержалось до PR-гейта M-50 и было опровергнуто замером (TD-054). Оракул ресурсной
//! границы обязан брать равномерный мусор (`common::lcg_garbage`) — иначе он зелёный
//! поверх открытой дыры («фикстура счастливого пути», `.claude/rules/testing.md`).

mod common;

use common::{
    append_bytes, cfg_with, event_of_frame_size, frame_of, lcg_garbage, ls, max_seq_in,
    open_with_deadline, write_decl, DECL_APPLIED, TAIL_SCAN_CHUNK,
};
use journal::{Journal, WriterConfig};

const SEG0: &str = "segment-00000000.jrnl";

/// Ровно тот размер, на котором цена ЗАМЕРЕНА (384.94 s). Меньше брать нельзя: на 8 MiB
/// замер даёт 92 s — это уже в полутора потолках, и оракул начал бы мерить машину.
const LCG_TAIL: usize = 16 * 1024 * 1024;

/// Мусор `0x5A` в хвосте — дешёвая часть фикстуры, нужна лишь чтобы окно хвостового скана
/// (4 MiB) целиком не содержало валидных фреймов и путь декларации ВООБЩЕ входился.
const CHEAP_TAIL: usize = 4 * 1024 * 1024 + 512 * 1024;

const _: () = assert!(
    CHEAP_TAIL as u64 > TAIL_SCAN_CHUNK,
    "фикстура: дешёвый хвост обязан перекрывать окно хвостового скана — иначе в окне \
     найдётся валидный фрейм, `open_with` не отдаст tail-unreadable и путь декларации \
     (единственный вызов readable_floor) не входится"
);

/// Потолок операторского пути. 6.4× запаса к замеренным 384.94 s: ресурсный оракул не
/// должен превращаться в измеритель CI-машины, но и потолок в «несколько минут» не
/// отличал бы «ограничено» от «неограниченно» (прод — 158 сегментов, не один).
const CEILING_SECS: u64 = 60;

fn cfg() -> WriterConfig {
    cfg_with(256 * 1024 * 1024, "floor work-budget fixture")
}

// ═════════════════════════════════════════════════════════════════════════════════════
// WB-0 — SETUP-GUARD фикстуры: в псевдослучайном мусоре нет валидных фреймов
// ═════════════════════════════════════════════════════════════════════════════════════

/// Эталон читаемого максимума в оракулах ниже собирается из БАЙТ, которые фикстура
/// записала САМА (валидные фреймы), а не полным терпимым проходом по файлу с мусором:
/// эталонный проход `common::max_seq_in` на 16 MiB равномерного мусора стоит ~2 минуты по
/// той же причине, что и сам дефект (кандидаты + crc32 по мегабайтам).
///
/// Допущение «мусор не содержит CRC-валидного postcard-фрейма» стоит ≈2⁻³² на кандидата.
/// Здесь оно ПРОВЕРЯЕТСЯ на выборке 4 MiB того же детерминированного потока (тот же seed,
/// та же конструкция) — дёшево (кандидатов ~n²/2³², то есть на 4 MiB их единицы).
#[test]
fn wb_0_pseudorandom_garbage_carries_no_valid_frame() {
    let sample = lcg_garbage(4 * 1024 * 1024, 0xC0FFEE);
    assert_eq!(
        max_seq_in(&sample),
        None,
        "setup-guard: в псевдослучайном мусоре обнаружен CRC-валидный фрейм — эталоны \
         оракулов WB-* перестают быть верными; смени seed и перепроверь"
    );
}

// ═════════════════════════════════════════════════════════════════════════════════════
// WB-1 — ЯДРО TD-052/TD-054: работа скана пола ограничена
// ═════════════════════════════════════════════════════════════════════════════════════

/// Каталог формы «restore под инцидентом»: читаемый префикс, затем РАВНОМЕРНЫЙ мусор,
/// затем дешёвый `0x5A`-хвост (чтобы окно хвостового скана было нечитаемым).
/// Возвращает (каталог, читаемый максимум seq).
fn dir_with_pseudorandom_garbage(prefix: u64) -> (tempfile::TempDir, u64) {
    let dir = tempfile::tempdir().expect("dir");
    {
        let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
        for i in 0..prefix {
            j.append(common::trade(i)).expect("append");
        }
        j.flush().expect("flush");
    }
    let seg = dir.path().join(SEG0);
    // Эталон ИЗМЕРЯЕТСЯ на файле ДО добавления мусора (мусор валидных фреймов не несёт —
    // wb_0), а не выводится арифметически из prefix: урок дефекта фикстуры R-002.
    let measured = max_seq_in(&std::fs::read(&seg).expect("read"))
        .expect("setup-guard: у каталога обязан быть читаемый префикс");
    assert_eq!(
        measured,
        prefix - 1,
        "setup-guard: измеренный префикс разошёлся с записанным — фикстура не та, что \
         описана"
    );
    append_bytes(&seg, &lcg_garbage(LCG_TAIL, 0xC0FFEE));
    append_bytes(&seg, &vec![0x5A_u8; CHEAP_TAIL]);
    let _ = std::fs::remove_file(dir.path().join("journal.meta"));
    (dir, measured)
}

/// **Ядро.** Операторский путь обязан ЗАВЕРШИТЬСЯ за ограниченное время на форме порчи,
/// которая сегодня стоит 385 s на 16 MiB (и линейно-квадратично хуже на прод-каталоге в
/// 158 сегментов ≈ 140 GiB сырого объёма).
///
/// Что именно ассертится:
///  1. **завершение в потолке** — сегодня FAIL (замер 384.94 s против потолка 60 s);
///  2. **если старт РАЗРЕШЁН — только с честной позиции**: `Ok(next_seq)` обязан быть
///     строго больше реального читаемого максимума. Бюджет не имеет права купить скорость
///     ценой заниженного пола (это и есть fail-open ⇒ seq-reuse).
#[test]
fn wb_1_floor_scan_work_is_bounded_on_uniform_garbage() {
    let (dir, max) = dir_with_pseudorandom_garbage(60);
    // Честная декларация: строго больше читаемого максимума.
    write_decl(
        dir.path(),
        max + 1,
        "хвост невосстановим: холодной копии нет",
    );

    let t0 = std::time::Instant::now();
    let outcome = open_with_deadline(dir.path(), cfg(), CEILING_SECS);
    let elapsed = t0.elapsed();

    let outcome = outcome.unwrap_or_else(|| {
        panic!(
            "JR-I-10 НАРУШЕН: скан пола не уложился в {CEILING_SECS} s на хвосте {} MiB \
             равномерного мусора. Работа скана НИЧЕМ не ограничена: замер reviewer'а на \
             этой же форме — 384.94 s (×2114 к 0.182 s до M-50, TD-054), а прод — 158 \
             сегментов ≈ 140 GiB сырого объёма, и путь входится ровно под инцидентом. \
             Нужен именованный бюджет РАБОТЫ (байты чтения/декодирования, включая байты \
             side-верификации) с деградацией в `Unknown`, а не «медленно, но верно».",
            LCG_TAIL / (1024 * 1024)
        )
    });

    if let Ok(next) = outcome {
        assert!(
            next > max,
            "JR-I-10 НАРУШЕН (fail-open): старт разрешён с next_seq={next} при реальном \
             читаемом максимуме {max} — бюджет купил скорость ценой ЗАНИЖЕННОГО пола. \
             Частичный ответ = принятая декларация внутри занятого диапазона = seq-reuse, \
             необратимая порча append-only журнала. Исчерпан бюджет ⇒ `Unknown` ⇒ отказ."
        );
    }
    // Информационно (не ассерт): фактическое время попадает в вывод при падении соседей.
    eprintln!("wb_1: путь декларации отработал за {elapsed:?}");
}

// ═════════════════════════════════════════════════════════════════════════════════════
// WB-2 — ЗАПРЕТ ЧАСТИЧНОГО ОТВЕТА: высокие seq ЗА мусором (множественность + асимметрия)
// ═════════════════════════════════════════════════════════════════════════════════════

/// Форма, на которой «остановились по бюджету и ответили тем, что успели» — это ровно
/// seq-reuse: валидные фреймы с ВЫСОКИМИ `seq` лежат ЗА дорогим мусорным регионом.
///
/// Раскладка сегмента (одна сторона от мусора читается дёшево, другая — нет: **асимметрия**):
/// `[header][seq 0..P-1 дёшево][16 MiB равномерного мусора][seq H..H+9 — множественность]
///  [4.5 MiB 0x5A — окно хвостового скана нечитаемо]`
///
/// - сегодня: скан доходит до конца (385 s) ⇒ `Known(H+9)` ⇒ декларация внутри диапазона
///   отвергнута — но ПОТОЛОК ВРЕМЕНИ провален;
/// - наивный бюджет («ответить тем, что успели»): `Known(P-1)` ⇒ декларация `next_seq`
///   между `P` и `H+9` ПРИНЯТА ⇒ запись пойдёт поверх существующих seq;
/// - контракт: бюджет исчерпан ⇒ `Unknown` ⇒ отказ. Оба провала ловятся одним оракулом.
#[test]
fn wb_2_budget_exhaustion_never_yields_a_lowered_floor() {
    const PREFIX: u64 = 60;
    const HIDDEN_FIRST: u64 = 5_000;
    const HIDDEN_N: u64 = 10;

    let dir = tempfile::tempdir().expect("dir");
    {
        let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
        for i in 0..PREFIX {
            j.append(common::trade(i)).expect("append");
        }
        j.flush().expect("flush");
    }
    let seg = dir.path().join(SEG0);
    append_bytes(&seg, &lcg_garbage(LCG_TAIL, 0xBADF00D));

    // Валидные фреймы с ВЫСОКИМИ seq — ЗА мусором. Эталон измеряется по этим же байтам.
    let mut hidden_bytes: Vec<u8> = Vec::new();
    for k in 0..HIDDEN_N {
        hidden_bytes.extend_from_slice(&frame_of(&event_of_frame_size(HIDDEN_FIRST + k, 1_024)));
    }
    let hidden_max = max_seq_in(&hidden_bytes).expect("setup-guard: скрытые фреймы валидны");
    assert_eq!(
        hidden_max,
        HIDDEN_FIRST + HIDDEN_N - 1,
        "setup-guard: скрытые фреймы собраны не с теми seq"
    );
    append_bytes(&seg, &hidden_bytes);
    append_bytes(&seg, &vec![0x5A_u8; CHEAP_TAIL]);
    let _ = std::fs::remove_file(dir.path().join("journal.meta"));

    // Декларация ВНУТРИ занятого диапазона: выше дешёвого префикса, но ниже скрытых seq.
    let bad_next = HIDDEN_FIRST - 1_000;
    assert!(bad_next > PREFIX, "setup-guard: декларация обязана быть выше дешёвого префикса");
    write_decl(dir.path(), bad_next, "ошибка оператора: seq внутри занятого диапазона");

    let outcome = open_with_deadline(dir.path(), cfg(), CEILING_SECS).unwrap_or_else(|| {
        panic!(
            "JR-I-10 НАРУШЕН: скан пола не уложился в {CEILING_SECS} s (замер этой формы — \
             384.94 s). Работа не ограничена ничем."
        )
    });

    match outcome {
        Err(e) => {
            let msg = e.to_lowercase();
            assert!(
                msg.contains("seq"),
                "отказ обязан объяснить причину (ожидается упоминание seq): «{e}»"
            );
            assert!(
                !ls(dir.path()).iter().any(|n| n == DECL_APPLIED),
                "отвергнутая декларация не должна помечаться применённой"
            );
        }
        Ok(next) => panic!(
            "JR-I-10 НАРУШЕН (fail-open): декларация next_seq={next} ПРИНЯТА при том, что \
             журнал содержит читаемые события вплоть до seq={hidden_max}. Так выглядит \
             «ответить тем, что успели до исчерпания бюджета»: пол занижен до {}, запись \
             пойдёт поверх занятого диапазона — seq-reuse, необратимая порча append-only \
             журнала. Исчерпание бюджета обязано давать `Unknown` (отказ), НИКОГДА — \
             `Known` по частично просмотренному каталогу.",
            PREFIX - 1
        ),
    }
}

// ═════════════════════════════════════════════════════════════════════════════════════
// WB-3 — ПАРНЫЙ VANTAGE (зелёный ДО и ПОСЛЕ): бюджет не имеет права убить escape-hatch
// ═════════════════════════════════════════════════════════════════════════════════════

/// Тривиальное «решение» TD-052 — вернуть `Unknown` немедленно (бюджет ≈ 0). Оно закрывает
/// время и не создаёт fail-open, но УБИВАЕТ операторский выход M-49, ради которого тот шёл
/// шесть кругов: recorder не стартует НИКОГДА, а единственное оставшееся действие оператора
/// — удалить каталог, то есть потерять историю (ровно то, от чего защищаемся).
///
/// Здесь порча ДЕШЁВАЯ (`0x5A`, как во всех фикстурах M-49): такой каталог обязан быть
/// разобран в рамках бюджета, честная декларация — принята, старт — разрешён.
#[test]
fn wb_3_honest_declaration_on_cheap_corruption_still_starts() {
    let dir = tempfile::tempdir().expect("dir");
    {
        let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
        for i in 0..200 {
            j.append(common::trade(i)).expect("append");
        }
        j.flush().expect("flush");
    }
    let seg = dir.path().join(SEG0);
    let max = max_seq_in(&std::fs::read(&seg).expect("read")).expect("читаемый префикс");
    append_bytes(&seg, &vec![0x5A_u8; CHEAP_TAIL]);
    let _ = std::fs::remove_file(dir.path().join("journal.meta"));

    write_decl(dir.path(), max + 1, "хвост невосстановим: холодной копии нет");
    let outcome = open_with_deadline(dir.path(), cfg(), CEILING_SECS)
        .expect("дешёвая порча обязана разбираться заведомо внутри бюджета");

    let next = outcome.unwrap_or_else(|e| {
        panic!(
            "ПАРНЫЙ VANTAGE ПРОВАЛЕН: честная декларация next_seq={} (строго больше \
             читаемого максимума {max}) на ДЕШЁВОЙ порче обязана разблокировать старт, \
             получено Err: {e}\nБюджет работы не имеет права стать «всегда Unknown» — это \
             убивает операторский выход M-49 (op_1) и оставляет оператору только удаление \
             каталога.",
            max + 1
        )
    });
    assert_eq!(next, max + 1, "запись обязана идти РОВНО с объявленной позиции");
    assert!(
        ls(dir.path()).iter().any(|n| n == DECL_APPLIED),
        "применённая декларация обязана быть помечена (одноразовость + аудит)"
    );
}

// ═════════════════════════════════════════════════════════════════════════════════════
// WB-4 — ГРАНИЦА «ОТСУТСТВИЕ»: здоровый каталог не платит за бюджет вообще
// ═════════════════════════════════════════════════════════════════════════════════════

/// Здоровый перезапуск — самый частый путь на проде (и единственный, который выполняется
/// 24/7). `readable_floor` на нём не вызывается вовсе (`op_3`: при читаемом хвосте
/// декларация даже не читается). Оракул пиннит, что бюджет не просочился в горячий путь:
/// старт на здоровом каталоге из НЕСКОЛЬКИХ сегментов укладывается в потолок и продолжает
/// `seq` без единого отказа.
#[test]
fn wb_4_healthy_restart_is_unaffected_by_the_budget() {
    let dir = tempfile::tempdir().expect("dir");
    let cfg_small = cfg_with(64 * 1024, "floor work-budget healthy fixture");
    let expect_next;
    {
        let mut j = Journal::open_with(dir.path(), cfg_small.clone()).expect("open_with");
        for i in 0..2_000 {
            j.append(common::trade(i)).expect("append");
        }
        j.flush().expect("flush");
        expect_next = j.next_seq();
    }
    assert!(
        ls(dir.path()).iter().filter(|n| n.ends_with(".jrnl")).count() >= 3,
        "setup-guard: фикстура обязана состоять из НЕСКОЛЬКИХ сегментов"
    );

    let next = open_with_deadline(dir.path(), cfg_small, CEILING_SECS)
        .expect("здоровый перезапуск обязан укладываться в потолок")
        .expect("здоровый перезапуск обязан быть разрешён");
    assert_eq!(
        next, expect_next,
        "здоровый перезапуск обязан продолжить seq без вмешательства бюджета"
    );
}
