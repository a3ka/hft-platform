//! RED `M-84` (sacred, architect-only) — **валидатор сессии судит НОРМАЛИЗОВАННЫЙ селектор.**
//!
//! COMPILE-RED: `gateway::CANONICAL_DEPTH_BANDS` ещё не существует.
//!
//! ## ЭТОТ ФАЙЛ ПЕРЕПИСАН ПО `C-221` B-1 — И ВОТ ЧТО БЫЛО НЕ ТАК
//!
//! Прежняя редакция требовала от `session::validate_selector` ОТВЕРГНУТЬ канонический
//! селектор (как «присланный клиентом»), а `red_fixed_bands_entrypoint.rs` требовал от
//! ТОГО ЖЕ вызова на ТОМ ЖЕ значении — ПРИНЯТЬ (селектор, собранный из кадра без поля,
//! несёт канонический набор). Детерминированная функция не может вернуть `Ok` и `Err`
//! на одно значение, и `Selector` не несёт поля «пришло от клиента»
//! (`crates/gateway-serve/src/wire_v1.rs:120-143` возвращает голый `Result<Selector, _>`).
//! Набор требовал от реализации ПРОВЕНАНС, который тип уже выбросил, — то есть был
//! невыполним, а не строг. Дефект мой, находка критика.
//!
//! ## КОНТРАКТ — ТРИ СЛОЯ, У КАЖДОГО СВОЙ ВОПРОС
//!
//! | слой | что видит | правило |
//! |---|---|---|
//! | разбор кадра `wire_v1::parse_selector` | JSON, то есть НАЛИЧИЕ ключа | ключ `bands` есть (любой: чужой, канонический, пустой) ⇒ `invalid_selector`; ключа нет ⇒ строится селектор с каноническим набором |
//! | валидатор сессии `session::validate_selector` (ЭТОТ ФАЙЛ) | уже нормализованный `Selector`, провенанса нет | канонический набор ⇒ `Ok`; любой другой ⇒ `Err` с названной причиной |
//! | гвард крейта `gateway::validate_selector` | `Selector` от ЛЮБОГО строителя, включая чекпоинтер | то же, и это последний рубеж для не-транспортных путей |
//!
//! Решение о том, ПРИСЫЛАЛ ли клиент сетку, принимается ровно там, где ещё видно ключ, —
//! на разборе. Ниже по течению провенанса нет и быть не может; требовать его от валидатора
//! значит требовать невозможного.
//!
//! ## ЧТО ЭТОТ ФАЙЛ НЕ ПРОВЕРЯЕТ — названо, чтобы следующий круг не искал здесь
//!
//! Отказ на ПРИСЛАННЫЙ клиентом набор живёт в `red_fixed_bands_entrypoint.rs` (настоящий
//! вход: байты → разбор → валидация). Здесь — только второй слой: сокет не поднимается,
//! состав кадра (14 строк) судит `red_fixed_bands_frame.rs`.
//!
//! ## `testing.md` чек-лист
//! - позитивный контроль ОБЯЗАТЕЛЕН: без него реализация, отвергающая всё подряд, зелена;
//! - п.4 **границы** — пустой набор отвергается отдельно от канонического;
//! - анти-плацебо: валидатор-заглушка `Ok(())` роняет `foreign_bands_rejected_by_session`.

use contracts::Venue;
use gateway::Selector;
use gateway_serve::session::validate_selector;

fn sel(bands: Vec<f64>) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands,
        window_ms: Some(60_000),
        depth_cadence_ms: None,
    }
}

#[test]
fn canonical_selector_is_accepted_by_session() {
    // ПОЗИТИВНЫЙ КОНТРОЛЬ и прямое следствие `C-221` B-1: именно это значение приходит
    // сюда после разбора кадра БЕЗ поля `bands`. Отказ здесь остановил бы нормальную
    // подписку — то есть закрыл бы продукт, а не чужую сетку.
    validate_selector(&sel(gateway::CANONICAL_DEPTH_BANDS.to_vec())).expect(
        "нормализованный серверный селектор обязан ПРОХОДИТЬ валидатор сессии: он и есть \
         то, что строит разбор кадра по П-029, когда клиент сетку не присылает",
    );
}

#[test]
fn foreign_bands_rejected_by_session() {
    // ГЛАВНЫЙ ФОРСИНГ второго слоя: селектор с чужим набором не проходит, откуда бы он
    // ни взялся. Это защита от строителей ВНУТРИ процесса, а не от клиента (клиента ловит
    // разбор кадра) — оба рубежа нужны, и ни один не заменяет другой.
    let err = validate_selector(&sel(vec![0.001, 0.002])).expect_err(
        "чужой набор обязан быть отвергнут валидатором сессии. Успех здесь означает, что \
         внутренний строитель может протащить произвольную сетку мимо решения П-029",
    );
    assert!(
        err.contains("bands") || err.contains("полос"),
        "отказ обязан НАЗЫВАТЬ причину. Получено: {err}"
    );
}

#[test]
fn legacy_single_band_is_rejected_by_session() {
    // Граница выкатки: сегодняшний прод живёт на `GATEWAY_BANDS=0.001`. После M-84 этот
    // набор — такой же чужой, как любой другой. Отдельный тест, потому что соблазн
    // «оставить старый набор работать» самый сильный именно здесь.
    validate_selector(&sel(vec![0.001])).expect_err(
        "легаси-набор из одной полосы обязан быть отвергнут наравне с чужими: иначе ось \
         отпечатка остаётся живой, и общий чекпоинт не получается",
    );
}

#[test]
fn empty_bands_rejected_by_session() {
    // Пустой набор — не «сервер сам подставит». Подстановка живёт на разборе кадра;
    // сюда пустой селектор может прийти только от сломанного строителя.
    validate_selector(&sel(Vec::new())).expect_err(
        "пустой набор обязан быть отвергнут: нормализация происходит на разборе кадра, и \
         сюда пустое значение приходит только если нормализация НЕ отработала",
    );
}

#[test]
fn rejection_message_points_at_the_decision() {
    // Отказ, который не объясняет, куда идти, порождает круг переписки. Сообщение обязано
    // называть предмет — иначе оператор кокпита увидит «invalid_selector» и всё.
    let err = validate_selector(&sel(vec![0.42])).expect_err("чужой набор отвергается");
    assert!(
        err.len() > 20,
        "сообщение об отказе обязано объяснять, а не только отказывать. Получено: {err:?}"
    );
}
