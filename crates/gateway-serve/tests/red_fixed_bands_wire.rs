//! RED `M-84` (sacred, architect-only) — **клиент НЕ задаёт сетку, и отказ ЯВНЫЙ, а не
//! молчаливая подмена.**
//!
//! COMPILE-RED: `gateway::CANONICAL_DEPTH_BANDS` ещё не существует.
//!
//! ## ГЛАВНОЕ СВОЙСТВО ФАЙЛА — РАЗЛИЧИТЬ ОТКАЗ И ПОДМЕНУ
//!
//! Самая вероятная «зелёная» реализация решения `П-029` — молча заменять присланный набор
//! каноническим. Она удовлетворяет и UX, и экономике, и НИ ОДИН тест про отпечаток её не
//! ловит: отпечаток-то будет правильный. Но клиент просит X, получает Y и об этом не знает —
//! это «выдать деградацию за норму», против чего стоит `PL-I-7`, и прямой запрет спеки
//! `M-84` §«Запрещено / Почему».
//!
//! Поэтому здесь два ПАРНЫХ утверждения, и ни одно не достаточно в одиночку:
//!   1. присланный набор ⇒ ОТКАЗ (а не тихий успех с подменённым набором);
//!   2. отказ НАЗЫВАЕТ причину (а не «invalid_selector» без объяснения).
//!
//! ## ЧЕГО ЭТОТ ФАЙЛ НЕ ПРОВЕРЯЕТ — названо, чтобы следующий круг не искал здесь
//!
//! Он не поднимает сокет и не судит сериализацию кадра: `validate_selector` транспорта —
//! быстрый путь без I/O, и проверяется именно он. Состав кадра (14 строк) — предмет задачи 3
//! и отдельного шага гейта, а не этого файла.
//!
//! ## `testing.md` чек-лист
//! - п.3 **отсутствие** — селектор БЕЗ полос обязан приниматься (это и есть новая норма);
//! - п.4 **границы** — канонический набор, присланный клиентом ЯВНО, тоже отвергается:
//!   иначе остаётся путь «клиент угадал набор», и завтрашняя смена набора сломает его молча;
//! - анти-плацебо: реализация, подменяющая молча, роняет `foreign_bands_rejected_not_swapped`.

use contracts::Venue;
use gateway::Selector;
use gateway_serve::session::validate_selector;

fn sel(bands: Vec<f64>) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands,
        window_ms: Some(60_000),
        depth_cadence_ms: None,
    }
}

#[test]
fn selector_without_bands_is_accepted() {
    // НОВАЯ НОРМА и позитивный контроль: клиент сетку не присылает. Без этого теста
    // реализация, отвергающая всё подряд, прошла бы остальные проверки файла.
    validate_selector(&sel(Vec::new())).expect(
        "селектор БЕЗ полос — это и есть новая норма по П-029: сетку задаёт сервер. \
         Отказ здесь означал бы, что клиент по-прежнему обязан её присылать",
    );
}

#[test]
fn foreign_bands_rejected_not_swapped() {
    // ГЛАВНЫЙ ФОРСИНГ. Молчаливая подмена проходит все прочие тесты набора.
    let err = validate_selector(&sel(vec![0.001, 0.002])).expect_err(
        "присланный клиентом набор обязан давать ОТКАЗ. Молчаливая подмена каноническим \
         запрещена спекой M-84: клиент просит X, получает Y и не знает — PL-I-7",
    );
    assert!(
        err.contains("bands") || err.contains("полос"),
        "отказ обязан НАЗЫВАТЬ причину. Получено: {err}"
    );
}

#[test]
fn even_canonical_bands_from_client_are_rejected() {
    // Граница, которую легко пропустить: клиент прислал ИМЕННО канонический набор.
    // Принять — значит оставить путь «клиент знает сетку». Завтрашняя смена набора сломает
    // такого клиента МОЛЧА: он продолжит слать старое и получать отказ без объяснения,
    // либо (хуже) старый набор будет принят и даст свой отпечаток.
    validate_selector(&sel(gateway::CANONICAL_DEPTH_BANDS.to_vec())).expect_err(
        "даже КАНОНИЧЕСКИЙ набор, присланный клиентом, обязан быть отвергнут: сетку задаёт \
         сервер, и клиент не должен её знать вовсе",
    );
}

#[test]
fn rejection_message_points_at_the_decision() {
    // Отказ, который не объясняет, куда идти, порождает круг переписки. Сообщение обязано
    // называть предмет — иначе оператор кокпита увидит «invalid_selector» и всё.
    let err = validate_selector(&sel(vec![0.42])).expect_err("чужой набор отвергается");
    assert!(
        err.len() > 20,
        "сообщение об отказе обязано объяснять, а не только отказывать. Получено: {err:?}"
    );
}
