//! SACRED (architect-only) — `M-75` `H-2`: **`GATEWAY_HEATMAP_WINDOW` есть КОНФИГ, и
//! невалидное значение ОТКАЗЫВАЕТ СТАРТУ, а не подменяется дефолтом.**
//!
//! Закрывает `C-194` `B-1`. Предмет — `M-75` §5 «Env-контракт (fail-closed, `PL-I-5`)»:
//! «Задана и неразбираема, либо вне `(0, 1)` → ОТКАЗ СТАРТА, а не молчаливый дефолт».
//!
//! # ПОЧЕМУ ЭТО НЕ COMPILE-RED, ХОТЯ ВЕРДИКТ НАЗВАЛ COMPILE-RED — отклонение В СТОРОНУ УСИЛЕНИЯ
//!
//! `C-194` `B-1` предписал закоммитить `H-2` «against the literal §5 signature in its explicit
//! COMPILE-RED state». Буква вердикта исполнена НЕ БУКВАЛЬНО, и основание называется здесь,
//! чтобы следующий круг судил против записанного, а не против памяти.
//!
//! COMPILE-RED потребовался бы только для проверки, что значение ДОХОДИТ до
//! `gateway::effective_heatmap_window_frac()` — функции, которой ещё нет. Но проверяемое
//! вердиктом требование («both malformed and out-of-range values failing startup, rather than
//! a fallback default») наблюдаемо СЕГОДНЯ и БЕЗ единой новой сигнатуры: `serve_config_from_env`
//! уже возвращает `Result<ServeConfig, String>`, и отказ старта есть `Err`.
//!
//! Репозиторий этот выбор уже сделал, дважды и в этой же зоне:
//! `crates/gateway-serve/tests/red_grace_from_env.rs:12-15` и
//! `red_depth_cadence_from_env.rs:21-24` — дословно: «тест не скомпилировался бы до правки
//! прод-типа, и `cargo test --all` падал бы сломанным билдом всего workspace'а. **Это не RED,
//! а поломка сборки** (`M-67` §10 фиксирует ровно этот класс)».
//!
//! Разница практическая, а не стилистическая: COMPILE-RED-файл не даёт исполниться НИ ОДНОМУ
//! тесту workspace'а — включая `H-1`/`H-3`/`H-4` и `H-5` того же милестоуна, то есть лишает
//! круг наблюдаемости ровно там, где она нужна. Исполняемый RED строго сильнее: он не только
//! существует как текст (единственное, чего COMPILE-RED достигает), но и ПАДАЕТ по предмету,
//! предъявляя дефект прогоном.
//!
//! Оракул на само ЗНАЧЕНИЕ (цепь `env → effective_heatmap_window_frac`) добавляется после
//! появления сигнатуры — тем же порядком, что `red_grace_from_env.rs:19` объявляет для своего
//! поля. В `M-75` он назван задачей и не подразумевается.
//!
//! # RUNTIME-RED СЕЙЧАС
//!
//! Переменная не читается вовсе: `grep -c GATEWAY_HEATMAP_WINDOW crates/gateway-serve/src/lib.rs`
//! → `0`. Поэтому любое значение — включая мусор и заведомо разрушительное `2.0` — принимается
//! молча, и `invalid_heatmap_window_is_rejected` обязан падать против текущего кода.
//!
//! # ПАРНЫЙ VANTAGE — требование нельзя удовлетворить, сломав запуск
//!
//! `valid_heatmap_window_starts` и `absent_heatmap_window_starts` запрещают «фикс», отвергающий
//! всё подряд: §5 прямо задаёт дефолт `0.001` при отсутствии переменной. Без этой пары
//! реализация «всегда `Err`» удовлетворила бы ядро RED и убила бы сервис.
//!
//! # ГРАНИЦЫ ДИАПАЗОНА ПРОВЕРЯЮТСЯ С ОБЕИХ СТОРОН
//!
//! `testing.md` §«Дегенерированный вход» п.4: фикстура не должна стоять РОВНО на границе —
//! округление уводит её в соседний диапазон. Поэтому `0` и `1.0` (исключённые концы) судятся
//! как отказ, а `0.000_001` и `0.999` (внутренние соседи концов) — как законный старт.

use gateway_serve::serve_config_from_env;
use std::collections::HashMap;

const VAR: &str = "GATEWAY_HEATMAP_WINDOW";
/// Подписанный дефолт §5. Равен сегодняшнему эффективному окну (`GATEWAY_BANDS=0.001`):
/// расцепление не меняет данные ни на байт в момент внедрения.
const SIGNED_DEFAULT: f64 = 0.001;

fn getter(pairs: &[(&'static str, &'static str)]) -> impl Fn(&str) -> Option<String> {
    let map: HashMap<&'static str, &'static str> = pairs.iter().copied().collect();
    move |k| map.get(k).map(|s| s.to_string())
}

const BASE: &[(&str, &str)] = &[
    ("GATEWAY_JWT_SECRET", "test-secret"),
    ("GATEWAY_TIMEFRAME_MS", "1000"),
    ("GATEWAY_MAX_SUBSCRIPTIONS", "16"),
];

fn base_plus(extra: &[(&'static str, &'static str)]) -> Vec<(&'static str, &'static str)> {
    let mut v: Vec<(&'static str, &'static str)> = BASE.to_vec();
    v.extend_from_slice(extra);
    v
}

/// ЯДРО RED, половина 1 — **НЕРАЗБИРАЕМОЕ** значение отказывает старту.
#[test]
fn malformed_heatmap_window_is_rejected() {
    for bad in ["abc", "", " ", "0.001x", "1e", "NaN", "--0.5", "0,001"] {
        let env = base_plus(&[(VAR, bad)]);
        match serve_config_from_env(getter(&env)) {
            Err(msg) => assert!(
                msg.contains(VAR),
                "отказ обязан НАЗЫВАТЬ переменную — иначе оператор не найдёт причину в логе \
                 упавшего контейнера. Значение {bad:?}, отказ: {msg}"
            ),
            Ok(_) => panic!(
                "{VAR}={bad:?} принято молча. Значит переменная не читается вовсе либо \
                 подменяется дефолтом при ошибке разбора — прямое нарушение PL-I-5 \
                 («отсутствие/невалидность лимита = отказ, не unbounded») и повторение класса \
                 GW-I-14/TD-020, где parse-error давал тихую деградацию на проде"
            ),
        }
    }
}

/// ЯДРО RED, половина 2 — **ВНЕ ДИАПАЗОНА `(0, 1)`** отказывает старту.
///
/// Разбираемость и осмысленность — разные свойства, и вторая опаснее: `2.0` разбирается
/// прекрасно и означает окно ±200 % от mid, то есть карту во всю книгу. Именно это значение
/// `M-75` и существует, чтобы сделать невозможным по построению.
#[test]
fn out_of_range_heatmap_window_is_rejected() {
    for bad in ["0", "0.0", "-0.001", "-1", "1", "1.0", "2.0", "100", "inf"] {
        let env = base_plus(&[(VAR, bad)]);
        match serve_config_from_env(getter(&env)) {
            Err(msg) => assert!(
                msg.contains(VAR),
                "отказ обязан НАЗЫВАТЬ переменную. Значение {bad:?}, отказ: {msg}"
            ),
            Ok(_) => panic!(
                "{VAR}={bad:?} вне (0, 1) принято. Окно — ДОЛЯ от mid: 0 уничтожает карту \
                 (сторож H-4 ловит это на выдаче, но старт обязан не дать такому значению \
                 дожить до выдачи), значения ≥ 1 раздувают ответ на всю книгу — ровно то \
                 усиление ресурса, ради снятия которого M-75 и существует (PL-I-5)"
            ),
        }
    }
}

/// ПАРНЫЙ VANTAGE 1 — валидные значения стартуют; гвард не переширок.
///
/// `0.000_001` и `0.999` стоят ВНУТРИ диапазона рядом с концами, а не на них: фикстура на
/// самой границе падала бы от округления, а не от предмета (`testing.md` §«Границы»).
#[test]
fn valid_heatmap_window_starts() {
    for good in ["0.000001", "0.001", "0.013", "0.6", "0.999"] {
        let env = base_plus(&[(VAR, good)]);
        if let Err(msg) = serve_config_from_env(getter(&env)) {
            panic!(
                "валидное окно {good:?} обязано стартовать — иначе требование fail-closed \
                 удовлетворено ценой неработающего сервиса. Отказ: {msg}"
            );
        }
    }
}

/// ПАРНЫЙ VANTAGE 2 — отсутствие переменной ЗАКОННО: §5 задаёт дефолт `0.001`.
///
/// Отличие от `GATEWAY_JWT_SECRET`, где отсутствие есть отказ, намеренно: оракул обязан
/// различать два норматива, а не применять один ко всему (`red_grace_from_env.rs` — тот же
/// разбор для своего конфига).
#[test]
fn absent_heatmap_window_starts() {
    if let Err(msg) = serve_config_from_env(getter(&base_plus(&[]))) {
        panic!(
            "отсутствие {VAR} обязано быть законным — M-75 §5 задаёт дефолт {SIGNED_DEFAULT} \
             (равный сегодняшнему эффективному окну). Отказ: {msg}"
        );
    }
}

/// **КОМПОЗИЦИЯ ДОСТАВКИ** — ручка, живущая только в коде, при деплое, который её не
/// устанавливает, ИНЕРТНА (`testing.md` §«Механизм несущего пути… доставка»).
///
/// Это третья вещь, о которой забывают: юниты зелены, оператор по-прежнему ничего не может
/// задать. Тот же пункт, что `red_depth_cadence_from_env.rs` пиннит для своей переменной.
#[test]
fn heatmap_window_is_declared_in_compose() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("корень workspace");
    let compose = root.join("docker-compose.yml");
    let text = std::fs::read_to_string(&compose)
        .unwrap_or_else(|e| panic!("SETUP НЕ СОСТОЯЛСЯ: {} нечитаем: {e}", compose.display()));

    // Блок СЕРВИСА-ПОТРЕБИТЕЛЯ, а не файл целиком (`A-031` §1: предмет наблюдения обязан
    // совпадать с предметом требования). Требование — «оператор может задать окно У СЕРВИСА,
    // который его читает»; `text.contains(VAR)` был бы истинен и от закомментированной
    // строки, и от объявления у чужого сервиса. Окно читает только `gateway-serve`:
    // `gateway-checkpoint` хранит состояние, от окна не зависящее (окно применяется на
    // ПОСТРОЕНИИ, `crates/gateway/src/lib.rs:1557`, а `heatmap_buckets` несут полный снимок
    // книги, `:1182`).
    let block: String = text
        .lines()
        .skip_while(|l| *l != "  gateway-serve:")
        .take_while(|l| {
            *l == "  gateway-serve:"
                || !(l.starts_with("  ") && !l.starts_with("   ") && l.ends_with(':'))
        })
        .collect::<Vec<_>>()
        .join("\n");

    // SETUP-СТРАЖ: блок обязан содержать соседнюю gateway-переменную. Иначе отсутствие нашей
    // ничего не доказывает — мы могли прочитать не тот файл или не тот блок.
    assert!(
        block
            .lines()
            .any(|l| l.trim_start().starts_with("GATEWAY_BANDS:")),
        "SETUP НЕ СОСТОЯЛСЯ: в блоке gateway-serve файла {} нет даже записи GATEWAY_BANDS — \
         прочитан не тот файл или блок не извлечён, и вывод об отсутствии {VAR} был бы ложным \
         при любой реализации",
        compose.display()
    );

    let key = format!("{VAR}:");
    let decl = block
        .lines()
        .find(|l| l.trim_start().starts_with(&key))
        .unwrap_or_else(|| {
            panic!(
                "{VAR} не объявлен ЗАПИСЬЮ env в блоке gateway-serve ({}). Ручка, не доехавшая до \
             деплоя, инертна: оператор не может задать окно, а все юнит-проверки при этом \
             зелены — класс built-not-wired (gates.md §4 «Механизм на пути»). Упоминание в \
             комментарии записью НЕ является",
                compose.display()
            )
        });

    // ЗНАЧЕНИЕ, а не только ключ: задача 4 требует величину, РАВНУЮ сегодняшней эффективной —
    // расцепление не меняет данные ни на байт в момент внедрения (M-75 §5).
    //
    // Сравнивается ЧИСЛО, а не подстрока: `contains("0.001")` истинно и для `0.00105`, то есть
    // страж снова был бы ШИРЕ требования (`A-031` §1). Форма записи допускается любая из
    // принятых соседями (`GATEWAY_BANDS`): литерал либо `${VAR:-<значение>}`.
    let raw = decl.split_once(':').map(|(_, v)| v.trim()).unwrap_or("");
    let value_tok = raw
        .strip_prefix("${")
        .and_then(|s| s.strip_suffix('}'))
        .and_then(|s| s.split_once(":-").or_else(|| s.split_once('-')))
        .map(|(_, v)| v)
        .unwrap_or(raw);
    let parsed: f64 = value_tok.trim().parse().unwrap_or_else(|_| {
        panic!(
            "значение записи `{decl}` не разбирается как число (токен {value_tok:?}). Гейт и \
             оракул судят ЧИСЛО, а не подстроку: `contains` был бы истинен и для 0.00105"
        )
    });
    assert_eq!(
        parsed, SIGNED_DEFAULT,
        "запись `{decl}` объявляет {parsed}, а не сегодняшнее эффективное {SIGNED_DEFAULT}: \
         раскатка с иным значением меняет ВЫДАЧУ в момент внедрения, тогда как M-75 §5 обещает \
         нулевое изменение данных"
    );
}
