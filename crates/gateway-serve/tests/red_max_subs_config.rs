use gateway_serve::serve_config_from_env;
use std::collections::HashMap;
use std::sync::{Arc, Mutex, MutexGuard, OnceLock};
use tracing_subscriber::fmt::MakeWriter;

/// ПОДПИСАННАЯ НОРМА (founder, 2026-08-11, `CT-RFC-09` §6 п.2). Литерал, намеренно.
const SIGNED_DEFAULT: usize = 16;

/// Эффективный лимит живёт в ПРОЦЕССНОМ atomic'е (`server::EFFECTIVE_MAX_SUBS`,
/// `lib.rs:181`), а не в поле `ServeConfig` — значит тесты одного бинаря пишут в ОДНУ
/// ячейку. Без сериализации набор мерил бы порядок исполнения потоков, а не свой инвариант
/// (`testing.md` §«Целостность гейта», свойство 2: конфаундинг держится КОНСТАНТНЫМ).
fn serial() -> MutexGuard<'static, ()> {
    static L: OnceLock<Mutex<()>> = OnceLock::new();
    L.get_or_init(|| Mutex::new(()))
        .lock()
        .unwrap_or_else(|e| e.into_inner())
}

fn getter(pairs: &[(&'static str, &'static str)]) -> impl Fn(&str) -> Option<String> {
    let map: HashMap<&'static str, &'static str> = pairs.iter().copied().collect();
    move |k| map.get(k).map(|s| s.to_string())
}

/// Минимально валидное окружение БЕЗ лимита — база сценария «переменная отсутствует».
const BASE: &[(&str, &str)] = &[
    ("GATEWAY_JWT_SECRET", "test-secret"),
    ("GATEWAY_TIMEFRAME_MS", "1000"),
];

fn base_plus(extra: &[(&'static str, &'static str)]) -> Vec<(&'static str, &'static str)> {
    let mut v: Vec<(&'static str, &'static str)> = BASE.to_vec();
    v.extend_from_slice(extra);
    v
}

/// Прогон конфигурации + снятие ЭФФЕКТИВНОГО лимита. Возвращает `Err`, если старт отвергнут.
fn effective_after(env: &[(&'static str, &'static str)]) -> Result<usize, String> {
    serve_config_from_env(getter(env))?;
    Ok(gateway_serve::server::effective_max_subs())
}

/// ЯДРО `A-015` §3 п.1: отсутствие ⇒ подписанная норма, а не отказ.
///
/// Против сегодняшней реализации (`lib.rs:1882` — `None => return Err(...)`) тест ПАДАЕТ.
/// Это и есть требуемое RED-состояние: зелёный с первого прогона означал бы, что фикстура не
/// давит на инвариант.
#[test]
fn absent_var_yields_signed_default_16() {
    let _g = serial();
    match effective_after(&base_plus(&[])) {
        Ok(n) => assert_eq!(
            n, SIGNED_DEFAULT,
            "A-015 §3 п.1: при отсутствии GATEWAY_MAX_SUBSCRIPTIONS действует ПОДПИСАННАЯ \
             норма {SIGNED_DEFAULT} (founder, 11.08). Получено: {n}"
        ),
        Err(msg) => panic!(
            "A-015 §3 п.1: отсутствие переменной ⇒ старт РАЗРЕШЁН с нормой {SIGNED_DEFAULT}. \
             Отказ старта — снятая позиция Б: её основание («parse-error → unbounded», урок \
             R7) к отсутствию не относится, потому что отсутствие даёт величину ОГРАНИЧЕННУЮ \
             и равную подписанной. Дом-конвеншн бинаря (A-015 F10) дефолтит при отсутствии у \
             ВСЕХ переменных, кроме GATEWAY_JWT_SECRET, — у секрета безопасного дефолта не \
             существует, у лимита он существует и подписан. Отказ: {msg}"
        ),
    }
}

/// ЯДРО `A-015` §3 п.1, вторая половина: два неполных состояния ведут себя ОДИНАКОВО.
///
/// Проверяется не «оба ошибка / оба успех», а РАВЕНСТВО ИСХОДА ПО СУЩЕСТВУ — эффективный
/// лимит. Прежняя редакция сравнивала `is_err()` с `is_err()`, и это слабее: реализация
/// «пусто ⇒ 16, отсутствует ⇒ 64» проходила бы такое сравнение, оставаясь асимметричной
/// ровно в том, ради чего тест написан.
#[test]
fn empty_var_is_same_as_absent() {
    let _g = serial();
    let absent = effective_after(&base_plus(&[]));
    let empty = effective_after(&base_plus(&[("GATEWAY_MAX_SUBSCRIPTIONS", "")]));
    assert_eq!(
        absent, empty,
        "«переменная не задана» и «задана пустой» — оба неполные состояния конфигурации; \
         поведение прода не имеет права зависеть от того, КАК её забыли задать (A-015 §3 п.1)"
    );
    assert_eq!(
        empty,
        Ok(SIGNED_DEFAULT),
        "и общий исход — именно подписанная норма {SIGNED_DEFAULT}, а не любой совпавший: \
         равенство двух отказов тоже «одинаково», но решению A-015 противоречит"
    );
}

/// `A-015` §3 п.2 — БЕЗ ИЗМЕНЕНИЙ: невалидное ЗНАЧЕНИЕ роняет старт.
///
/// Это анти-бланкет к послаблению выше: разрешение, выданное ОТСУТСТВИЮ, не смеет
/// распространиться на мусор. Границы по `testing.md` п.4: `1` валиден (§2.6 «целое >= 1»),
/// `0` — нет; `" "` — пустая строка после `trim`, и она идёт по ветке дефолта, поэтому здесь
/// её НЕТ (её предмет — `empty_var_is_same_as_absent`).
#[test]
fn invalid_values_refuse_start() {
    let _g = serial();
    for bad in ["0", "-1", "abc", "1.5", "16x"] {
        match serve_config_from_env(getter(&base_plus(&[("GATEWAY_MAX_SUBSCRIPTIONS", bad)]))) {
            Err(msg) => assert!(
                msg.contains("GATEWAY_MAX_SUBSCRIPTIONS"),
                "{bad:?}: отказ обязан НАЗЫВАТЬ переменную — оператор чинит конфиг, не читая \
                 исходники. Получено: {msg}"
            ),
            Ok(_) => panic!(
                "{bad:?}: старт РАЗРЕШЁН при невалидном ЗНАЧЕНИИ. A-015 §3 п.2 оставляет здесь \
                 отказ старта: «parse-error → unbounded запрещено» (урок R7) — правило про \
                 НЕРАЗБИРАЕМЫЙ вход, и послабление для ОТСУТСТВИЯ его не отменяет"
            ),
        }
    }
}

/// ПАРНЫЙ VANTAGE к дефолту: переменная РЕАЛЬНО читается.
///
/// Без этого теста три предыдущих зелены против реализации, которая конфиг игнорирует и
/// всегда ставит 16. Значения выбраны по обе стороны от нормы — `1` (минимум §2.6) и `64`
/// (выше нормы): реализация, зажимающая лимит сверху нормой, пройдёт проверку только с `1`.
#[test]
fn explicit_value_overrides_default() {
    let _g = serial();
    for good in ["1", "64"] {
        let want: usize = good.parse().expect("литерал теста");
        match effective_after(&base_plus(&[("GATEWAY_MAX_SUBSCRIPTIONS", good)])) {
            Ok(n) => assert_eq!(
                n, want,
                "явное значение {good:?} обязано ДЕЙСТВОВАТЬ — иначе дефолт не «норма при \
                 молчании конфига», а игнорирование конфига. Получено: {n}"
            ),
            Err(msg) => panic!(
                "валидный лимит {good:?} обязан стартовать — иначе «отказ старта» \
                 удовлетворяется поломкой запуска вообще. Отказ: {msg}"
            ),
        }
    }
}

/// Буфер записи подписчика `tracing` — наблюдаем ЛОГ, а не внутренности реализации.
#[derive(Clone, Default)]
struct Captured(Arc<Mutex<Vec<u8>>>);

impl std::io::Write for Captured {
    fn write(&mut self, buf: &[u8]) -> std::io::Result<usize> {
        self.0
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .extend_from_slice(buf);
        Ok(buf.len())
    }
    fn flush(&mut self) -> std::io::Result<()> {
        Ok(())
    }
}

impl<'a> MakeWriter<'a> for Captured {
    type Writer = Captured;
    fn make_writer(&'a self) -> Self::Writer {
        self.clone()
    }
}

/// Прогон под ЛОКАЛЬНЫМ (thread-local) подписчиком: `with_default` не трогает глобальный
/// подписчик и потому не зависит от соседей по бинарю.
fn warn_log_of(env: &[(&'static str, &'static str)]) -> String {
    let cap = Captured::default();
    let sub = tracing_subscriber::fmt()
        .with_writer(cap.clone())
        .with_max_level(tracing::Level::WARN)
        .with_ansi(false)
        .finish();
    tracing::subscriber::with_default(sub, || {
        let _ = serve_config_from_env(getter(env));
    });
    let buf = cap.0.lock().unwrap_or_else(|e| e.into_inner()).clone();
    String::from_utf8_lossy(&buf).into_owned()
}

/// Значение, названное В СВЯЗКЕ С ПЕРЕМЕННОЙ: цифры, идущие сразу за `<KEY>=`.
///
/// # Зачем не `contains`, и почему это не косметика (`TD-166`, замер `R-129`)
///
/// Прежняя редакция сверяла `on_default.contains("16")` по ВСЕЙ строке лога, а строка несёт
/// wall-clock таймстамп. «16» встречается в таймстампе с частотой **96/2000 = 4.8 %** — и
/// ровно с этой частотой оракул оставался ЗЕЛЁНЫМ против сломанной подписи. Замер reviewer'а
/// под мутацией «константа = 32»: **3 ложно-зелёных из 60 прогонов**.
///
/// Это класс «оракул мерит ОКРУЖЕНИЕ, а не свой инвариант» (`testing.md`, целостность гейта,
/// свойство 2): красный исход зависел от текущего времени суток. Оракул, который краснеет
/// вероятностно, при первом же «мигает — выключи» перестаёт защищать что-либо.
///
/// Привязка структурная: берём цифры НЕПОСРЕДСТВЕННО после `<KEY>=`. Первое упоминание в
/// сообщении (`GATEWAY_MAX_SUBSCRIPTIONS not set`) образцу не удовлетворяет — знака `=` там
/// нет, — поэтому найдено будет именно объявление значения. Цифровой хвост читается ЦЕЛИКОМ,
/// иначе `16` совпало бы с префиксом `160`.
fn value_named_with(log: &str, key: &str) -> Option<String> {
    let needle = format!("{key}=");
    let idx = log.find(&needle)?;
    let digits: String = log[idx + needle.len()..]
        .chars()
        .take_while(|c| c.is_ascii_digit())
        .collect();
    if digits.is_empty() {
        None
    } else {
        Some(digits)
    }
}

/// `A-015` §3 п.1: уход на подписанную норму обязан быть НАБЛЮДАЕМЫМ.
///
/// Здесь держится вся цена решения в пользу дефолта. Арбитраж взвесил отказ старта против
/// тихого 16 и выбрал второе ИМЕННО потому, что `warn` делает «конфиг не доехал» видимым без
/// отказа в обслуживании (`A-015` §2.3 (iii)). Без записи в логе решение вырождается в ту
/// самую тихую ложь, против которой возражала позиция Б, — и тогда права была бы она.
///
/// АССЕРТ НА СУЩЕСТВО, НЕ НА ПРОЗУ: требуются ИМЯ переменной и ЗНАЧЕНИЕ. Формулировку
/// («продуктовая норма») оракул не пиннит намеренно — тест, требующий дословной фразы,
/// связывает реализацию текстом, а не инвариантом, и краснеет на переводе слова.
///
/// ПАРНЫЙ VANTAGE В ТОМ ЖЕ ТЕСТЕ: при ЯВНОМ значении такой записи быть НЕ ДОЛЖНО. Без него
/// реализация «warn всегда» проходит, и предупреждение перестаёт что-либо означать.
#[test]
fn warn_on_default() {
    let _g = serial();

    let on_default = warn_log_of(&base_plus(&[]));
    assert!(
        on_default.contains("GATEWAY_MAX_SUBSCRIPTIONS"),
        "уход на подписанную норму обязан быть НАБЛЮДАЕМЫМ и НАЗЫВАТЬ переменную — иначе \
         «конфиг не доехал» неотличимо от штатного запуска. Лог WARN: {on_default:?}"
    );
    assert_eq!(
        value_named_with(&on_default, "GATEWAY_MAX_SUBSCRIPTIONS").as_deref(),
        Some(SIGNED_DEFAULT.to_string().as_str()),
        "запись обязана называть ЗНАЧЕНИЕ, на которое ушли ({SIGNED_DEFAULT}), И называть его \
         В СВЯЗКЕ С ПЕРЕМЕННОЙ. Сверка идёт с цифрами сразу после `GATEWAY_MAX_SUBSCRIPTIONS=`, \
         а НЕ поиском числа по всей строке: строка несёт wall-clock таймстамп, в котором «16» \
         встречается в 4.8 % случаев, и прежний `contains` оставлял оракул зелёным против \
         сломанной подписи в 3 прогонах из 60 (TD-166). Лог WARN: {on_default:?}"
    );

    let on_explicit = warn_log_of(&base_plus(&[("GATEWAY_MAX_SUBSCRIPTIONS", "64")]));
    assert!(
        !on_explicit.contains("GATEWAY_MAX_SUBSCRIPTIONS"),
        "при ЯВНО заданной переменной предупреждения о дефолте быть не должно: «warn всегда» \
         проходит первую половину теста и обесценивает сигнал. Лог WARN: {on_explicit:?}"
    );
}
