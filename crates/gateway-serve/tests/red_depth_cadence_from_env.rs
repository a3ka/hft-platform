//! RED задачи 22 (sacred, architect-only) — **КАДЕНЦИЯ ДЕПТ-СЕРИИ ЕСТЬ КОНФИГ, А НЕ КОНСТАНТА
//! В КОДЕ.**
//!
//! Предмет: `R-138` Б-3 (built-not-wired). Решение founder'а 2026-08-27, дословно по существу:
//! «против вшивания в код того, что потом может меняться — выносить наружу». Разбор и
//! carve-out зоны — `milestones/M-68-depth-from-book.md` §3 и §0sexies.2quinquies.
//!
//! # Что сломано
//!
//! Задача 15 обещает «дефолт 1000 мс, значение настраивается» и стоит `✅ DONE`. Замер
//! architect'а: НЕ ВЫПОЛНЕНО НИ В ОДНОЙ ПОЛОВИНЕ.
//!   · `depth_cadence_ms: None` зашито в прод-инициализаторах —
//!     `crates/gateway-serve/src/lib.rs` (`build_selector`) и
//!     `crates/gateway/src/bin/gateway-checkpoint.rs`;
//!   · `GATEWAY_DEPTH_CADENCE_MS` не существует НИГДЕ: ноль совпадений в `crates/`,
//!     `deploy/`, `docker-compose.yml`.
//! Ручка объявлена спекой и не подключена ни к чему — ровно класс `R-133` B-1.
//!
//! # Почему этот оракул СУДИТ ЗНАЧЕНИЕ, а соседний `red_grace_from_env.rs` — нет
//!
//! Тот файл судит только ОТКАЗ и прямо объясняет почему: проверка значения потребовала бы
//! нового поля в `ServeConfig`, то есть тест не скомпилировался бы до правки прод-типа, и
//! `cargo test --all` падал бы сломанным билдом всего workspace'а (класс `M-67` §10). Здесь
//! этого препятствия НЕТ: поле `Selector::depth_cadence_ms` уже введено (`A-024` `O-1`), а
//! `ServeConfig::selector` публичен. Значит цепь `env → ServeConfig → Selector` проверяема
//! ЦЕЛИКОМ, и ограничиваться отказом было бы слабее без причины.
//!
//! # Оракул ТОЧКИ ВХОДА, а не описание намерения (`testing.md`)
//!
//! `test -f` и греп по имени — описания намерения: обе бывают зелёными, когда ручка не
//! доезжает. Здесь пиннятся ТРИ вещи, и третья — та, о которой забывают:
//!   1. значение из окружения ДОХОДИТ до селектора (цепь исполняется, а не описывается);
//!   2. невалидное значение ОТКАЗЫВАЕТ старту, называя переменную (fail-closed, класс
//!      `GW-I-14`: «parse-error → тихая деградация» запрещено);
//!   3. **КОМПОЗИЦИЯ ДОСТАВКИ** — переменная объявлена в `docker-compose.yml`. Ручка, живущая
//!      только в коде, при деплое, который её не устанавливает, ИНЕРТНА: оператор по-прежнему
//!      ничего не может задать, а все юнит-проверки при этом зелены.
//!
//! # Парный vantage
//!
//! `absent_cadence_yields_signed_default` не даёт удовлетворить требование, сломав запуск:
//! отсутствие переменной обязано давать ПОДПИСАННЫЙ дефолт 1000 мс, а не отказ и не `None`.
//! Без него набор был бы зелен против реализации, которая не стартует никогда.
//!
//! # Дефолт 1000 мс поведение прода НЕ меняет — замер, а не обещание
//!
//! Прод-таймфрейм 1000 мс (`docker-compose.yml`: `GATEWAY_TIMEFRAME_MS:-1000`). При нём
//! `cadence = 1000` пропускает РОВНО те же события и даёт РОВНО те же ключи `time_s`, что
//! сегодняшнее `None` (замер: 100 событий → 10 уникальных ключей в обоих случаях). То есть
//! включение ручки с этим дефолтом — операция, нейтральная по выдаче, и §8-риска не несёт.

use gateway_serve::serve_config_from_env;
use std::collections::HashMap;

const VAR: &str = "GATEWAY_DEPTH_CADENCE_MS";
/// Подписанный дефолт задачи 15.
const SIGNED_DEFAULT_MS: i64 = 1_000;

fn getter(pairs: &[(&'static str, &'static str)]) -> impl Fn(&str) -> Option<String> {
    let map: HashMap<&'static str, &'static str> = pairs.iter().copied().collect();
    move |k| map.get(k).map(|s| s.to_string())
}

const BASE: &[(&str, &str)] = &[
    ("GATEWAY_JWT_SECRET", "test-secret"),
    ("GATEWAY_TIMEFRAME_MS", "1000"),
    ("GATEWAY_MAX_SUBSCRIPTIONS", "16"),
];

fn base_plus(extra: &[(&'static str, &'static str)]) -> Vec<(&'static str, &'static str)> {
    let mut v: Vec<(&'static str, &'static str)> = BASE.to_vec();
    v.extend_from_slice(extra);
    v
}

/// **ЯДРО: значение из окружения ДОХОДИТ до селектора.**
#[test]
fn env_cadence_reaches_the_selector() {
    let cfg = serve_config_from_env(getter(&base_plus(&[(VAR, "60000")])))
        .unwrap_or_else(|e| panic!("SETUP: валидная каденция 60000 отвергла старт: {e}"));
    assert_eq!(
        cfg.selector.depth_cadence_ms,
        Some(60_000),
        "{VAR}=60000 задано оператором, а до селектора дошло {:?}. Ручка объявлена спекой \
         (задача 15: «значение настраивается») и не подключена: значение либо не читается, \
         либо теряется по дороге — built-not-wired, класс R-133 B-1",
        cfg.selector.depth_cadence_ms
    );
}

/// **ПАРНЫЙ VANTAGE: отсутствие переменной даёт ПОДПИСАННЫЙ ДЕФОЛТ, а не отказ и не `None`.**
///
/// Требование задачи 15 состоит из ДВУХ половин — «дефолт 1000 мс» И «настраивается».
/// Оракул выше пиннит вторую; эта — первую. Без неё реализация «читаю переменную, а без неё
/// оставляю `None`» прошла бы набор, и дефолт остался бы обещанием.
#[test]
fn absent_cadence_yields_signed_default() {
    let absent = serve_config_from_env(getter(BASE))
        .unwrap_or_else(|e| panic!("отсутствие {VAR} обязано давать старт, а не отказ: {e}"));
    assert_eq!(
        absent.selector.depth_cadence_ms,
        Some(SIGNED_DEFAULT_MS),
        "без {VAR} селектор несёт {:?}, а задача 15 требует дефолт {SIGNED_DEFAULT_MS} мс. \
         `None` — не дефолт, а «настройки нет вовсе»",
        absent.selector.depth_cadence_ms
    );

    // `A-026` §1 / `A-015` §3 п.1: пустое и пробельное — те же два неполных состояния ОДНОЙ
    // конфигурации, что и отсутствие. Исход обязан быть ОДИН, иначе поведение прода зависит
    // от того, КАК переменную забыли задать. Пробельная форма взята намеренно НЕ на границе
    // (`" "`, а не только `""`): реализация с `is_empty()` вместо `trim().is_empty()` зелена
    // против первой и красна против второй.
    for blank in ["", " ", "\t "] {
        let got = serve_config_from_env(getter(&base_plus(&[(VAR, blank)])));
        match got {
            Ok(cfg) => assert_eq!(
                cfg.selector.depth_cadence_ms, absent.selector.depth_cadence_ms,
                "{VAR}={blank:?} и ОТСУТСТВИЕ {VAR} обязаны давать ОДИН исход (A-015 §3 п.1, \
                 подтверждено A-026 §1 для соседней ручки того же сервиса). Получено {:?} \
                 против {:?}",
                cfg.selector.depth_cadence_ms, absent.selector.depth_cadence_ms
            ),
            Err(e) => panic!(
                "{VAR}={blank:?} ОТВЕРГЛО старт, а отсутствие переменной — нет. Это третья \
                 политика для четвёртой ручки одного сервиса; A-026 §1 её прямо запрещает. \
                 Отказ: {e}"
            ),
        }
    }
}

/// **FAIL-CLOSED: невалидное значение ОТКАЗЫВАЕТ старту и НАЗЫВАЕТ переменную.**
///
/// Класс `GW-I-14`: конфигурация, которую не разобрали, не смеет молча выродиться в
/// поведение по умолчанию — оператор должен узнать, что его ввод отвергнут.
/// `999` включён намеренно: его отвергает порог «>= 1000», и это ЕДИНСТВЕННАЯ причина —
/// кейс не краснеет по чужой (урок `A-025` §3).
///
/// **ПУСТОЕ И ПРОБЕЛЬНОЕ СЮДА НЕ ВХОДЯТ, и это не упущение.** Первая редакция включала `" "`
/// в список невалидных — и была НЕВЕРНА: `A-026` §1 постановил для соседней ручки того же
/// сервиса, что отсутствие и пустое/пробельное суть ДВА НЕПОЛНЫХ СОСТОЯНИЯ ОДНОЙ конфигурации
/// с ОДНИМ исходом (основание — `A-015` §3 п.1: «поведение прода не имеет права зависеть от
/// того, КАК её забыли задать»). Требовать здесь отказа значило бы завести ТРЕТЬЮ политику
/// для четвёртой ручки одного сервиса — ровно то, что `A-026` §1 осудил у оракула `D` в
/// `M-71`. Пустое и пробельное судятся вместе с отсутствием — см.
/// `absent_cadence_yields_signed_default`.
#[test]
fn invalid_cadence_is_rejected_naming_the_variable() {
    for bad in ["abc", "-1", "0", "1000.0", "1_000", "999"] {
        match serve_config_from_env(getter(&base_plus(&[(VAR, bad)]))) {
            Err(msg) => assert!(
                msg.contains(VAR),
                "отказ обязан НАЗЫВАТЬ переменную, иначе оператор не поймёт, что чинить. \
                 Значение {bad:?}, отказ: {msg}"
            ),
            Ok(cfg) => panic!(
                "{VAR}={bad:?} ПРИНЯТО молча, селектор несёт {:?}. Невалидная конфигурация \
                 обязана быть отказом СТАРТА — класс GW-I-14: тихая деградация даёт \
                 оператору поведение, о котором он не просил",
                cfg.selector.depth_cadence_ms
            ),
        }
    }
}

/// **КОМПОЗИЦИЯ ДОСТАВКИ: ручка объявлена в `docker-compose.yml`.**
///
/// `testing.md` §«Механизм несущего пути обязан иметь оракул точки входа», п.3: «дойти до
/// доставки — файл в репозитории при деплое, который его не устанавливает, инертен». Ручка,
/// живущая только в коде, оператору недоступна: все три оракула выше зелены, а задать
/// значение на проде по-прежнему нечем.
///
/// Предел проверки НАЗВАН: это ЛЕКСИЧЕСКИЙ поиск по compose. Он ловит отсутствие объявления
/// и не доказывает, что переменная доедет до процесса при любой форме запуска —
/// `COGNITIVE-ONLY` в этой части, и выдавать его за большее нельзя.
#[test]
fn knob_is_declared_in_compose() {
    let root = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(|p| p.parent())
        .expect("SETUP: корень репозитория не вычислен");
    let compose = root.join("docker-compose.yml");
    let text = std::fs::read_to_string(&compose)
        .unwrap_or_else(|e| panic!("SETUP: {} не прочитан: {e}", compose.display()));
    assert!(
        text.contains(VAR),
        "{VAR} не объявлена в {}. Ручка существует только в коде: юнит-оракулы выше зелены, \
         а оператор на проде задать значение НЕ МОЖЕТ — деплой её не устанавливает. Образец \
         объявления — соседняя GATEWAY_WINDOW_MS в том же файле",
        compose.display()
    );
}
