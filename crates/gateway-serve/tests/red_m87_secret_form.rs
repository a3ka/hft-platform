//! RED M-87 круг `R-196` (sacred, architect-only) — **НАПРАВЛЕНИЕ трактовки секрета.**
//!
//! Находка `R-196` B3. `TD-207` фиксирует прод-форму однозначно: **сервер** строит ключ из
//! СЫРЫХ байт строки (`DecodingKey::from_secret(secret.as_bytes())`), а `wsprobe` ошибочно
//! hex-декодирует 64-символьную строку в 32 байта. Долг заведён на ЗОНД, а не на сервер.
//!
//! Реализация свела ОБЕ стороны к поведению ЗОНДА: общая `auth::key_material` декодирует
//! «ровно 64 hex-символа» в 32 байта. Прод-секрет — ровно 64 hex-символа. Следствие: после
//! выкатки сервер проверяет подпись 32 байтами вместо 64, и КАЖДЫЙ токен, выписанный
//! подписывателем Next.js (общий секрет, HS256 по сырым байтам), становится невалидным.
//! Вход в кокпит перестаёт работать целиком — при живом контейнере и свежем heartbeat.
//! Это одностороннее изменение контракта между плоскостями, которое охраняет `VB-I-9`.
//!
//! **Спека §10 разрешала ровно одну общую функцию трактовки секрета — но не разрешала
//! менять СЕМАНТИКУ прод-стороны.** Общая функция обязана давать то, чем подписывает
//! внешний подписыватель; чинить следовало зонд.
//!
//! **Почему оракул нужен, а «поправить обратно» недостаточно.** Направление уже разъехалось
//! один раз, молча, и поймал его человек на PR-гейте. Без оракула та же правка вернётся при
//! следующем касании: в коде обе стороны выглядят одинаково разумно, и только ВНЕШНИЙ
//! подписыватель решает, какая верна. Оракул воспроизводит внешнюю сторону явно.
//!
//! **Анти-плацебо.** Сценарии судят не `key_material` саму по себе, а СХОДИМОСТЬ с внешним
//! подписывателем: `s1` падает, если сервер перестал принимать то, что подписано сырыми
//! байтами; `s2` падает, если сервер начал принимать то, что подписано hex-декодированными.
//! Обе стороны нужны: функция, возвращающая что угодно ОДНО, зелёной обе не сделает.

use gateway_serve::auth::{key_material, verify_token, Claims};
use jsonwebtoken::{encode, DecodingKey, EncodingKey, Header};

/// Прод-форма секрета: РОВНО 64 hex-символа (`TD-207`). Именно на ней сырые байты и
/// hex-декодирование расходятся; на любой другой строке `key_material` возвращает одно и
/// то же, и сценарий выродился бы в тавтологию.
const PROD_SHAPED_SECRET: &str = "0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef";

fn claims() -> Claims {
    Claims {
        sub: "cockpit".to_string(),
        exp: 9_999_999_999,
    }
}

/// ВНЕШНИЙ подписыватель (Next.js, D6): HS256 по СЫРЫМ байтам строки секрета.
/// Это не наша реализация, а воспроизведение чужой стороны контракта.
fn sign_as_external_signer(secret: &str) -> String {
    encode(
        &Header::default(),
        &claims(),
        &EncodingKey::from_secret(secret.as_bytes()),
    )
    .expect("encode raw")
}

/// Ошибочная сторона (`wsprobe` до `TD-207`): HS256 по hex-декодированным 32 байтам.
fn sign_as_hex_decoder(secret: &str) -> String {
    let bytes: Vec<u8> = secret
        .as_bytes()
        .chunks(2)
        .map(|c| {
            let hi = (c[0] as char).to_digit(16).expect("hex");
            let lo = (c[1] as char).to_digit(16).expect("hex");
            ((hi << 4) | lo) as u8
        })
        .collect();
    assert_eq!(
        bytes.len(),
        32,
        "setup-страж: hex-декодирование дало не 32 байта"
    );
    encode(
        &Header::default(),
        &claims(),
        &EncodingKey::from_secret(&bytes),
    )
    .expect("encode hex")
}

/// SETUP-СТРАЖ всего файла: две трактовки обязаны РАЗЛИЧАТЬСЯ на прод-форме секрета.
/// Если они совпали, оба сценария ниже зелены тривиально и не проверяют ничего.
#[test]
fn s0_two_interpretations_differ_on_prod_shaped_secret() {
    let raw = PROD_SHAPED_SECRET.as_bytes().to_vec();
    let material = key_material(PROD_SHAPED_SECRET);
    assert_eq!(raw.len(), 64, "setup-страж: прод-форма — 64 символа");
    assert_ne!(
        sign_as_external_signer(PROD_SHAPED_SECRET),
        sign_as_hex_decoder(PROD_SHAPED_SECRET),
        "setup-страж: две подписи совпали — трактовки не различаются, и сценарии ниже \
         проверяли бы пустоту"
    );
    // Значение `material` здесь НЕ судится — оно предмет сценариев s1/s2. Читаем только
    // затем, чтобы страж падал, если функция исчезла или сменила сигнатуру.
    assert!(
        !material.is_empty(),
        "setup-страж: key_material вернул пустой ключ"
    );
}

/// `VB-I-9`: то, что подписал ВНЕШНИЙ подписыватель, сервер обязан ПРИНЯТЬ.
#[test]
fn s1_server_accepts_token_signed_by_external_signer() {
    let token = sign_as_external_signer(PROD_SHAPED_SECRET);
    let key = DecodingKey::from_secret(&key_material(PROD_SHAPED_SECRET));
    let got = verify_token(&token, &key);
    assert!(
        got.is_ok(),
        "R-196 B3: сервер ОТВЕРГ токен, подписанный внешним подписывателем по СЫРЫМ байтам \
         64-символьного секрета. Прод-секрет имеет ровно эту форму, значит после выкатки \
         кокпит не войдёт ВООБЩЕ: каждый его токен станет невалидным. Направление починки \
         TD-207 обратное — общая функция обязана повторять подписывателя, а чинить следует \
         зонд. Исход: {got:?}"
    );
}

/// Обратная сторона: hex-декодированная трактовка обязана быть ОТВЕРГНУТА.
/// Без неё «починка» вида «принимать оба варианта» прошла бы гейт, а она означает, что
/// сервер принимает подпись, сделанную ЧУЖИМ ключом.
#[test]
fn s2_server_rejects_token_signed_over_hex_decoded_bytes() {
    let token = sign_as_hex_decoder(PROD_SHAPED_SECRET);
    let key = DecodingKey::from_secret(&key_material(PROD_SHAPED_SECRET));
    let got = verify_token(&token, &key);
    assert!(
        got.is_err(),
        "сервер ПРИНЯЛ токен, подписанный hex-декодированными байтами. Либо трактовка \
         по-прежнему зондовая (см. s1), либо принято «оба варианта» — а это значит, что \
         ключей у сервера два, и один из них никем не предполагался. Исход: {got:?}"
    );
}
