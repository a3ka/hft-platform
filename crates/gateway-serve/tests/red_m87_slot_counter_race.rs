//! RED M-87 круг `R-200` §B7 (sacred, architect-only) — **глобальный счётчик занятых слотов
//! не имеет права ТЕРЯТЬ декременты под гонкой.**
//!
//! ## Находка и её асимметрия
//!
//! Условие `R-196` №7 требовало `fetch_sub`. Исполнено НАПОЛОВИНУ: локальный счётчик
//! декрементируется атомарно, а глобальный — тот, что кормит `serving_counters()` и,
//! значит, наблюдаемость предохранителя, — читается и пишется ДВУМЯ операциями:
//!
//! ```text
//! взятие слота:    SLOTS_IN_FLIGHT_GLOBAL.fetch_add(1, SeqCst)        ← атомарно
//! освобождение:    let prev = SLOTS_IN_FLIGHT_GLOBAL.load(SeqCst);    ← читаем
//!                  SLOTS_IN_FLIGHT_GLOBAL.store(prev.saturating_sub(1), SeqCst);  ← пишем
//! ```
//!
//! Между `load` и `store` другой поток успевает сделать своё `store`, и один декремент
//! пропадает. Асимметрия сама по себе — признак: взятие уже написано правильно, освобождение
//! нет.
//!
//! ## Чем это опасно ИМЕННО в этом милестоуне
//!
//! Счётчик — не украшение отчёта. Предохранитель существует, чтобы «один запрос не клал
//! сервис», а `slots_in_flight` — единственная величина, по которой видно, сколько работы
//! идёт прямо сейчас. Потерянный декремент завышает её НАВСЕГДА: счётчик дрейфует вверх,
//! и наблюдатель видит занятость, которой нет. Дальше два исхода, оба плохие: оператор
//! перестаёт верить показанию, либо автоматика по нему отказывает в обслуживании исправному
//! серверу.
//!
//! ## Почему ОТДЕЛЬНЫЙ бинарь
//!
//! Счётчик ПРОЦЕССНЫЙ. В общем бинаре соседние тесты берут и отпускают слоты параллельно,
//! и замер стал бы флаком — исход зависел бы от соседей, а не от инварианта
//! (`testing.md` §«Целостность гейта», свойство 2: гейт меряет СВОЙ инвариант, не окружение).
//! Здесь один сценарий на бинарь, поэтому процессное состояние принадлежит ему целиком.
//!
//! ## Форма замера
//!
//! Гонка воспроизводится НАГРУЗКОЙ, а не удачей: `THREADS` потоков по `ROUNDS` циклов
//! «взять слот → отпустить». Каждый цикл оставляет счётчик в исходном состоянии, поэтому
//! ИТОГ обязан вернуться к нулю. Потерянный декремент виден как остаток > 0.
//!
//! Проба устроена так, что ложно-зелёной быть не может: `s0` доказывает, что нагрузка
//! РЕАЛЬНО шла (взятий было столько, сколько заказано) — без него сценарий, в котором слоты
//! не выдавались вовсе, дал бы нулевой остаток и выглядел успехом.
//!
//! RUNTIME-RED по построению: на ревизии находки остаток > 0.

use gateway_serve::admission::ServingSlots;
use gateway_serve::metrics::serving_counters;

const THREADS: usize = 8;
const ROUNDS: usize = 500;

/// **s0+s1 — SETUP-СТРАЖ и ЗАМЕР в одном сценарии.**
///
/// Разделять их нельзя: счётчик процессный, и второй тест в этом же бинаре наблюдал бы
/// последствия первого. Поэтому страж — первая половина тела, замер — вторая.
#[test]
fn s1_global_slot_counter_returns_to_zero_under_contention() {
    let before = serving_counters().slots_in_flight;

    // Ёмкость заведомо больше числа потоков: предмет замера — ОСВОБОЖДЕНИЕ, а не отказ
    // в выдаче. Если бы слотов не хватало, часть потоков получала бы `None`, и остаток
    // сошёлся бы по другой причине — замер судил бы не тот механизм.
    let slots = std::sync::Arc::new(ServingSlots::new(THREADS * 2));
    let acquired = std::sync::Arc::new(std::sync::atomic::AtomicUsize::new(0));

    let mut hs = Vec::with_capacity(THREADS);
    for _ in 0..THREADS {
        let slots = std::sync::Arc::clone(&slots);
        let acquired = std::sync::Arc::clone(&acquired);
        hs.push(std::thread::spawn(move || {
            for _ in 0..ROUNDS {
                if let Some(g) = slots.try_acquire() {
                    acquired.fetch_add(1, std::sync::atomic::Ordering::SeqCst);
                    drop(g);
                }
            }
        }));
    }
    for h in hs {
        h.join().expect("поток завершился");
    }

    // SETUP-СТРАЖ: нагрузка действительно была. Без него сценарий, в котором `try_acquire`
    // всегда возвращает `None`, дал бы идеальный ноль и выглядел бы успехом.
    let got = acquired.load(std::sync::atomic::Ordering::SeqCst);
    assert_eq!(
        got,
        THREADS * ROUNDS,
        "SETUP-СТРАЖ: слотов выдано {got} из {} заказанных — ёмкости не хватило, и замер \
         судил бы отказ в выдаче, а не потерю декремента",
        THREADS * ROUNDS
    );

    // Локальный счётчик экземпляра обязан вернуться к нулю — он написан правильно и служит
    // ПАРНЫМ ориентиром: если и он поехал, дефект шире одной строки.
    assert_eq!(
        slots.in_flight(),
        0,
        "локальный счётчик экземпляра не вернулся к нулю — дефект шире глобального счётчика"
    );

    let after = serving_counters().slots_in_flight;
    assert_eq!(
        after,
        before,
        "ГЛОБАЛЬНЫЙ счётчик занятых слотов не вернулся к исходному значению: было {before}, \
         стало {after}, потеряно {} декрементов из {} циклов. Причина — неатомарное \
         освобождение: между `load` и `store` соседний поток успевает записать своё \
         значение, и один декремент пропадает. Взятие слота при этом уже написано верно \
         (`fetch_add`) — асимметрия и есть признак дефекта.\n\
         Цена: `slots_in_flight` — единственная величина, по которой видно идущую работу \
         предохранителя. Потерянный декремент завышает её НАВСЕГДА, и наблюдатель видит \
         занятость, которой нет.",
        after.saturating_sub(before),
        THREADS * ROUNDS
    );
}
