//! `M-89` (sacred, architect-only) — **СТОРОЖ сериализации `red_m87_entrypoint.rs`**
//! (`TD-225`): пока в предмете существует `SERIAL`, КАЖДЫЙ асинхронный тест обязан брать его.
//!
//! # Почему отдельный бинарь, а не тест «в том же файле»
//!
//! `red_m87_registry.rs::r1` держит БИЕКЦИЮ реестра с перечнем сценариев
//! `red_m87_entrypoint.rs` (`A-040`); любой новый `#[test]` в предмете — строка реестра.
//! Сторож формы предмета реестру не принадлежит, и корпус уже решил этот случай той же
//! формой: `red_m87_registry.rs` судит предмет через `include_str!` из соседнего бинаря.
//! Здесь — то же самое.
//!
//! # Что считается
//!
//! `a` = число строк-атрибутов `#[tokio::test` (включая форму с параметрами flavor);
//! `b` = число строк `SERIAL.lock().await`. Равенство ЧИСЕЛ, а не наличие строки: токен
//! «мы сериализуемся» подделываем, счётчики — нет (`TD-225`). Сторож не считает сам себя:
//! шаблон строки собирается конкатенацией, чтобы литерал `SERIAL.lock().await` не
//! встречался в ЭТОМ файле, и предмет читается `include_str!`, а не `file!()`.
//!
//! # Условие снятия (спека `M-89` §Tasks, задача 7)
//!
//! Когда `SERIAL` исчезает из предмета (счётчики переведены на экземплярные, `I-5`), `a`
//! остаётся > 0, `b` = 0 — сторож ОБЯЗАН перестать требовать равенства. Поэтому он смотрит
//! на присутствие ОБЪЯВЛЕНИЯ `static SERIAL`: есть объявление — требуется равенство; нет —
//! требуется, чтобы и вызовов не осталось (мёртвый вызов без объявления не скомпилируется,
//! но сторож называет это явно, а не полагается на компилятор соседнего бинаря).
//!
//! Зелен на ревизии набора (14 == 14, замер `R-206`); мутация «снять одну блокировку» — красен.

const SUBJECT: &str = include_str!("red_m87_entrypoint.rs");

fn count_lines_with(src: &str, needle: &str) -> usize {
    src.lines()
        .filter(|l| !l.trim_start().starts_with("//"))
        .filter(|l| l.contains(needle))
        .count()
}

#[test]
fn every_async_test_of_the_subject_takes_serial_while_serial_exists() {
    // Шаблоны — конкатенацией: сторож не должен ловить собственные литералы.
    let attr = ["#[tokio", "::test"].concat();
    let lock = ["SERIAL", ".lock()", ".await"].concat();
    let decl = ["static ", "SERIAL", ":"].concat();

    let a = count_lines_with(SUBJECT, &attr);
    let b = count_lines_with(SUBJECT, &lock);
    let declared = count_lines_with(SUBJECT, &decl) > 0;

    assert!(
        a > 0,
        "SETUP-СТРАЖ: в предмете нет ни одного `#[tokio::test]` — читается не тот файл"
    );

    if declared {
        assert_eq!(
            a, b,
            "TD-225: асинхронных тестов {a}, блокировок SERIAL {b} — новый тест добавлен без \
             сериализации, и класс TD-224 вернётся МОЛЧА: ложный зелёный у `c6`/`u1` на \
             заимствованном приросте не виден ни одному прогону"
        );
    } else {
        assert_eq!(
            b, 0,
            "SERIAL объявления нет, а вызовов {b} — предмет не собирается либо сторож читает не то"
        );
    }
}
