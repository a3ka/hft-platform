//! SACRED (architect-only) — `M-75`: **окно heatmap/COB НЕ ЗАВИСИТ от `Selector.bands`.**
//!
//! ## Что пиннится и почему именно это
//!
//! Сегодня окно heatmap и COB выводится из клиентского селектора одной строкой:
//! `let w = selector.bands.iter().copied().fold(0.0_f64, f64::max)`
//! (`crates/gateway/src/lib.rs:1557`, функция `build_heatmap_and_cob`). Полосы — предмет
//! депт-серии (`П-014`), но через эту строку они управляют ещё и охватом карты.
//!
//! **Цена связки замерена и подписана.** `П-020` §«Шкала»: прод-дефолт `bands=[0.001]` даёт
//! ответ 62 688 Б; канонический набор `[0.015…0.60]` — **45 261 937 Б**, при подписанном
//! пределе 2 000 000 Б. Превышение 22.6×, помечено в записи дословно «отвергается — усиление
//! ×722». Разбор `docs/plans/depth-delivery-architecture-2026-08-31.md` §2 разложил эти
//! 45 МБ по составу: heatmap поячеечно ≈98 %, COB ≈2 %, а **сама депт-серия ≈25 КБ, 0.05 %**.
//!
//! Отсюда предмет `M-75`: `П-020` отвергла НЕ полосы глубины, а побочный эффект связки.
//! Расцепить окно — значит включить подписанные полосы, не задев предел.
//!
//! ## ВТОРОЕ, ЧТО ЗАКРЫВАЕТ РАСЦЕПЛЕНИЕ — усиление, управляемое клиентом
//!
//! `gateway::validate_selector` о `bands` не знает ни одной строкой (замер `M-70` §0.3:
//! `grep -ci bands` по её телу → `0`), а предел `M-71` срабатывает ПОСЛЕ построения ответа.
//! То есть клиент и сегодня вправе прислать широкую полосу и заставить сервер собрать
//! десятки мегабайт, чтобы затем получить отказ. Это `PL-I-5`-класс («усиление ресурса,
//! управляемое клиентом»). Server-side окно снимает усиление ПО ПОСТРОЕНИЮ: ширина карты
//! перестаёт быть клиентским входом.
//!
//! ## КАК ЭТОТ НАБОР ЗАЩИЩЁН ОТ СОБСТВЕННОЙ СЛЕПОТЫ (`A-029`, правило `Р-4`)
//!
//! Оракул утверждает «карта не изменилась» по признаку «байт столько же». Правило `Р-4`
//! требует предъявить, что мир БЕЗ события этого признака не несёт: если бы два селектора
//! на деле не различались, «байт столько же» было бы истинно и при живой связке, и оракул
//! был бы зелен ни о чём. Поэтому каждый сценарий несёт **положительный контроль
//! различающей силы**: депт-серия обязана ИЗМЕНИТЬСЯ на тех же двух селекторах. Полосы
//! влияют на неё по построению, и если она не меняется — селекторы не различаются, setup не
//! состоялся, и сценарий обязан упасть с этим диагнозом, а не зеленеть.
//!
//! Это прямое следствие сегодняшнего разбора: за одну сессию два оракула утверждали
//! тождество, которого не устанавливали (`C-191` — подделываемое свидетельство, `C-192` —
//! неразличимые кадры). Здесь признак проверяется на способность различать ДО того, как на
//! нём строится вывод.
//!
//! ## СОСТОЯНИЕ: КРАСНЫЙ ПО ПОСТРОЕНИЮ
//!
//! `H-1` и `H-3` падают на сегодняшнем коде: окно выводится из `bands`, поэтому карта
//! растёт вместе с ними, а канонический набор выносит ответ за предел. `H-2` (fail-closed
//! конфиг) — COMPILE-RED против объявленной спекой сигнатуры, которой ещё нет.

use contracts::{to_fixed, DataSource, EventKind, Level, MdPayload, Side, Venue};
use gateway::{Cursor, Selector};
use journal::{EpochFilter, Journal, WriterConfig};

const MID: f64 = 65_000.0;
const T0: i64 = 1_752_000_000_000;

/// Прод-дефолт (`docker-compose.yml`): узкая полоса ±0.1 %.
const BANDS_NARROW: &[f64] = &[0.001];
/// Канонический набор — предмет `П-014` п.4. Значения из `M-71` §2.2.
const BANDS_CANONICAL: &[f64] = &[0.015, 0.03, 0.06, 0.12, 0.25, 0.40, 0.60];

fn cfg() -> WriterConfig {
    WriterConfig {
        max_segment_bytes: 1 << 26,
        min_free_bytes: 0,
        source: DataSource::OwnCapture,
        provenance: "M-75 heatmap window fixture".to_string(),
        epoch_id: "own-test".to_string(),
    }
}

fn sel_with(bands: &[f64]) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands: bands.to_vec(),
        window_ms: None,
        depth_cadence_ms: None,
    }
}

fn lvls(v: &[(f64, f64)]) -> Vec<Level> {
    v.iter()
        .map(|(p, s)| Level {
            price: to_fixed(*p),
            size: to_fixed(*s),
        })
        .collect()
}

/// Книга ПРОД-ФОРМЫ: **густая у цены и глубокая в хвост**. Обе черты обязательны, и первая
/// редакция этой фикстуры не имела ни одной — она равномерно раскладывала 200 уровней на
/// ±60 %, то есть шаг цены выходил 0.3 %, ГРУБЕЕ узкой полосы ±0.1 %. Следствие: узкий
/// селектор давал НОЛЬ ячеек, а канонический — 12 000 и укладывался в предел. Оба сценария
/// судили не то: `H-1` сравнивал «12 000 против 0» вместо двух непустых карт, а `H-3`
/// проходил ВАКУУМНО, потому что фикстура была на два порядка легче прода.
///
/// Форма снята с замера прода (`П-020` §«Шкала», `M-71` §2.2): heatmap 359 880 ячеек при
/// 5 998 уровнях книги. Здесь шаг — 0.02 % от mid, то есть узкая полоса ±0.1 % ловит ~5
/// уровней на сторону (непустая карта), а канонический ±60 % — три тысячи. Отношение ~600×
/// воспроизводит прод-пропорцию, а не выдумывает её.
fn journal_deep_book(ticks: usize, levels_per_side: usize) -> tempfile::TempDir {
    // Шаг 0.02 % от mid: густо у touch. `levels_per_side` задаёт, докуда тянется хвост.
    const STEP_FRAC: f64 = 0.0002;
    let dir = tempfile::tempdir().expect("tempdir");
    let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
    for t in 0..ticks as i64 {
        let step = MID * STEP_FRAC;
        let bids: Vec<(f64, f64)> = (1..=levels_per_side)
            .map(|k| (MID - k as f64 * step, 1.0 + (k % 17) as f64))
            .collect();
        let asks: Vec<(f64, f64)> = (1..=levels_per_side)
            .map(|k| (MID + k as f64 * step, 1.0 + (k % 17) as f64))
            .collect();
        j.append(EventKind::md(
            Venue::Binance,
            "BTCUSDT",
            MdPayload::L2Snapshot {
                bids: lvls(&bids),
                asks: lvls(&asks),
                ts_exch_ms: T0 + t * 1_000,
            },
        ))
        .expect("append L2Snapshot");
        // Сделка в том же такте — профиль объёма и пузыри не пусты, ответ реалистичен.
        j.append(EventKind::md(
            Venue::Binance,
            "BTCUSDT",
            MdPayload::Trade {
                price: to_fixed(MID + t as f64 * 0.01),
                size: to_fixed(1.0),
                side: if t % 2 == 0 { Side::Buy } else { Side::Sell },
                ts_exch_ms: T0 + t * 1_000,
            },
        ))
        .expect("append Trade");
    }
    j.flush().expect("flush");
    dir
}

/// Число уровней на сторону, покрывающее ±60 % при шаге 0.02 %: `0.60 / 0.0002 = 3000`.
/// Названо константой, а не числом в вызове: связь «шаг × уровни = охват» обязана быть
/// видна, иначе следующая правка снова разъедет фикстуру с полосами.
const LEVELS_TO_60PCT: usize = 3_000;
/// Тактов достаточно, чтобы карта была многострочной, но прогон оставался быстрым.
/// 10 × 3000 × 2 стороны = 60 000 ячеек против 359 880 на проде — тот же порядок конструкции.
const TICKS: usize = 10;

/// Снимок по селектору. `Err` — отдельный исход (предел `M-71` отверг ответ).
fn snap(dir: &std::path::Path, bands: &[f64]) -> std::io::Result<gateway::Snapshot> {
    gateway::snapshot(
        dir,
        EpochFilter::OwnCaptureOnly,
        &sel_with(bands),
        Cursor::LATEST,
    )
}

/// Байты сериализованного снимка — РЕСУРС, которым платит сеть, а не прокси вроде числа
/// ячеек (`testing.md` §«Оракул обязан мерить ТО, ЧТО ОБЕЩАЕТ» п.2). Тот же объект
/// уровня 1, что судит `red_egress_cap_boundary`.
fn bytes_of(s: &gateway::Snapshot) -> usize {
    serde_json::to_vec(s).expect("сериализация Snapshot").len()
}

/// ПОЛОЖИТЕЛЬНЫЙ КОНТРОЛЬ РАЗЛИЧАЮЩЕЙ СИЛЫ (`Р-4`): два селектора обязаны РЕАЛЬНО
/// различаться, и различие обязано быть наблюдаемо там, где полосы работают по построению —
/// в депт-серии. Без этого «карта не изменилась» истинно и при живой связке.
fn assert_selectors_actually_differ(narrow: &gateway::Snapshot, wide: &gateway::Snapshot) {
    assert!(
        !narrow.series.heatmap.is_empty(),
        "SETUP НЕ СОСТОЯЛСЯ: узкий селектор даёт ПУСТУЮ карту — шаг цены фикстуры грубее \
         полосы ±0.1 %. Сравнение «сколько ячеек» вырождается в «12 000 против нуля», что \
         истинно и при связке, и без неё. Чинить фикстуру, а не реализацию"
    );
    let n = narrow.series.depth_series.len();
    let w = wide.series.depth_series.len();
    assert!(
        w > n,
        "SETUP НЕ СОСТОЯЛСЯ: депт-серия одинакова у узкого и канонического наборов \
         ({n} против {w} строк). Полосы влияют на неё ПО ПОСТРОЕНИЮ, значит селекторы не \
         различаются — и вывод «карта не изменилась» был бы истинен при ЛЮБОЙ реализации, \
         включая сегодняшнюю связку. Чинить фикстуру, а не реализацию (правило Р-4, A-029)"
    );
}

// ═══════════════════════════════════════════════════════════════════════════════════════════
// H-1 — ПРЕДМЕТ: ширина полос не меняет объём карты
// ═══════════════════════════════════════════════════════════════════════════════════════════

/// Инвариант `HW-I-1`. Один и тот же журнал, два селектора, отличающиеся ТОЛЬКО `bands`:
/// число ячеек heatmap и уровней COB обязано совпадать. Сегодня падает — окно выводится
/// из `max(bands)`, и канонический набор раздувает карту на два порядка.
#[test]
fn hw_i_1_heatmap_size_is_independent_of_bands() {
    let dir = journal_deep_book(TICKS, LEVELS_TO_60PCT);

    let narrow = snap(dir.path(), BANDS_NARROW).unwrap_or_else(|e| {
        panic!("SETUP НЕ СОСТОЯЛСЯ: узкий селектор обязан обслуживаться сегодня: {e}")
    });
    let wide = match snap(dir.path(), BANDS_CANONICAL) {
        Ok(s) => s,
        Err(e) => panic!(
            "HW-I-1 НАРУШЕН (форма отказа): канонический набор ОТВЕРГНУТ пределом — {e}. \
             Это и есть связка: полосы предназначены депт-серии (≈25 КБ по разбору), а через \
             `max(bands)` они раздувают карту до 45 МБ (П-020: усиление ×722). После \
             расцепления ответ обязан строиться и укладываться в предел"
        ),
    };

    assert_selectors_actually_differ(&narrow, &wide);

    assert_eq!(
        wide.series.heatmap.len(),
        narrow.series.heatmap.len(),
        "HW-I-1 НАРУШЕН: число ячеек heatmap ЗАВИСИТ от полос — {} против {}. Окно карты \
         выводится из `max(selector.bands)` (lib.rs:1557), тогда как полосы принадлежат \
         депт-серии. Клиент управляет охватом карты как побочным эффектом, и это же даёт \
         усиление ресурса, управляемое клиентом (PL-I-5)",
        wide.series.heatmap.len(),
        narrow.series.heatmap.len()
    );
    assert_eq!(
        wide.series.cob.len(),
        narrow.series.cob.len(),
        "HW-I-1 НАРУШЕН: число уровней COB зависит от полос — {} против {}. Та же связка: \
         COB строится тем же окном, что и heatmap",
        wide.series.cob.len(),
        narrow.series.cob.len()
    );
}

// ═══════════════════════════════════════════════════════════════════════════════════════════
// H-3 — СЛЕДСТВИЕ: канонический набор укладывается в подписанный предел
// ═══════════════════════════════════════════════════════════════════════════════════════════

/// Инвариант `HW-I-3`. Мера — БАЙТЫ, а не ячейки. Разбор предсказал ≈88 КБ после
/// расцепления против 45 261 937 Б сегодня; здесь фиксируется только то, что подписанный
/// предел не задет, а конкретное число печатается для внесения в спеку замером.
#[test]
fn hw_i_3_canonical_bands_fit_under_signed_cap() {
    let limit = gateway::DEFAULT_MAX_RESPONSE_BYTES;
    assert!(limit > 0, "SETUP: предел объявлен нулевым");

    let dir = journal_deep_book(TICKS, LEVELS_TO_60PCT);
    let narrow = snap(dir.path(), BANDS_NARROW)
        .unwrap_or_else(|e| panic!("SETUP НЕ СОСТОЯЛСЯ: узкий селектор обязан обслуживаться: {e}"));
    let wide = match snap(dir.path(), BANDS_CANONICAL) {
        Ok(s) => s,
        Err(e) => panic!(
            "HW-I-3 НАРУШЕН: канонический набор ОТВЕРГНУТ пределом — {e}. Подписанные полосы \
             (П-014 п.4) обязаны обслуживаться под подписанным пределом (П-020); сегодня они \
             не обслуживаются ТОЛЬКО из-за связки окна карты с полосами"
        ),
    };

    assert_selectors_actually_differ(&narrow, &wide);

    let bw = bytes_of(&wide);
    let bn = bytes_of(&narrow);
    println!("HW-I-3 ЗАМЕР: узкий {bn} Б · канонический {bw} Б · предел {limit} Б");
    assert!(
        bw <= limit,
        "HW-I-3 НАРУШЕН: канонический набор даёт {bw} Б при пределе {limit} Б \
         (превышение {:.1}×). Узкий набор — {bn} Б",
        bw as f64 / limit as f64
    );
}

// ═══════════════════════════════════════════════════════════════════════════════════════════
// H-4 — СТОРОЖ: расцепление не куплено ценой соседнего инварианта
// ═══════════════════════════════════════════════════════════════════════════════════════════

/// Обратная мутация (`testing.md` §«что пришлось ослабить рядом»): карта обязана остаться
/// НЕПУСТОЙ. Реализация «окно всегда нулевое» удовлетворила бы `H-1` и `H-3` идеально и
/// уничтожила бы продукт — heatmap исчез бы вовсе. Сторож стоит здесь, чтобы такой «фикс»
/// валился на гейте, а не в проде.
#[test]
fn hw_i_4_decoupling_does_not_empty_the_heatmap() {
    let dir = journal_deep_book(TICKS, LEVELS_TO_60PCT);
    let narrow =
        snap(dir.path(), BANDS_NARROW).unwrap_or_else(|e| panic!("SETUP НЕ СОСТОЯЛСЯ: {e}"));

    assert!(
        !narrow.series.heatmap.is_empty(),
        "HW-I-4 НАРУШЕН: heatmap ПУСТ при узком селекторе на плотной книге. Расцепление, \
         обнулившее окно, удовлетворяет H-1 и H-3 и уничтожает продукт — карты нет вовсе"
    );
    assert!(
        !narrow.series.cob.is_empty(),
        "HW-I-4 НАРУШЕН: COB пуст при узком селекторе на плотной книге — то же самое"
    );
    assert!(
        !narrow.series.depth_series.is_empty(),
        "HW-I-4 НАРУШЕН: депт-серия пуста — фикстура не даёт предмета П-014, и весь набор \
         судит не то"
    );
}
