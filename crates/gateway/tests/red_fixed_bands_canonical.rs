#[test]
fn crate_rejects_f32_rounded_lookalikes() {
    // ЗАВЕДЁН ЗАКРЫТИЕМ `C-220` B-2, и это не теоретический случай. Критик собрал гвард с
    // поэлементным допуском `1e-6` — вполне разумным на вид — и показал, что f32-представление
    // `0.015` отличается от него на `0.000000000335276126`. Такой набор проходил гвард,
    // получал СВОЙ отпечаток и СВОЙ слепок, а все двенадцать тестов оставались зелёными.
    //
    // Отсюда требование к реализации, а не только к тесту: сравнение ТОЧНОЕ (например,
    // `to_bits`), не по длине и не по допуску. Допуск здесь не «мягче», он НЕВЕРЕН: отпечаток
    // хеширует `to_bits` (crates/gateway/src/lib.rs:3461), значит два набора, «равных с
    // точностью до 1e-6», дают РАЗНЫЕ слепки — и переиспользования, ради которого всё
    // затевалось, не происходит.
    let lookalike: Vec<f64> = gateway::CANONICAL_DEPTH_BANDS
        .iter()
        .map(|b| *b as f32 as f64)
        .collect();
    assert_ne!(
        lookalike,
        gateway::CANONICAL_DEPTH_BANDS.to_vec(),
        "SETUP НЕ СОСТОЯЛСЯ: f32-округление не изменило ни одного значения — атака не \
         построена, и её отвержение ниже ничего не доказывало бы"
    );
    gateway::validate_selector(&sel_with(lookalike)).expect_err(
        "набор, отличающийся от канонического лишь f32-округлением, обязан быть ОТВЕРГНУТ. \
         Принять его — значит выдать ему собственный отпечаток и собственный слепок: \
         переиспользование, ради которого П-029 и принята, не состоится",
    );
}

