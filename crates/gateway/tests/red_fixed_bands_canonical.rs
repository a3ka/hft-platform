//! RED `M-84` (sacred, architect-only) — **канонический набор полос ОДИН, и он принадлежит
//! КРЕЙТУ, а не транспорту.**
//!
//! Дом решения — `П-029` (граница C, founder 2026-09-10): сервер ВСЕГДА считает продуктовый
//! набор `1.5/3/5/8/15/30/60 %`, клиент НЕ задаёт сетку.
//!
//! COMPILE-RED: `gateway::CANONICAL_DEPTH_BANDS` ещё не существует. Это ЗАЯВЛЕННОЕ состояние
//! (`A-028` §1), а не поломка.
//!
//! ## ПОЧЕМУ ГВАРД ЖИВЁТ ЗДЕСЬ, А НЕ ТОЛЬКО В `gateway-serve`
//!
//! `Selector` собирают НАПРЯМУЮ: `research-cli`, чекпоинтер (`M-38b`), `M-39`. Гвард только в
//! транспорте оставил бы байпас-поверхность — ровно тот довод, которым `GW-I-14` обосновал
//! своё место в крейте (`crates/gateway/src/lib.rs:2743-2750`, дословно: «гвард ТОЛЬКО в
//! транспорте оставил бы байпас-поверхность»). Повторяем установленное решение, а не изобретаем.
//!
//! ## ЧТО ЭТОТ НАБОР ОБЯЗАН ЛОВИТЬ — и чего он НЕ ловит
//!
//! Ловит: отсутствие канонического набора; набор не той длины; набор, разошедшийся с
//! продуктовым; ПРИЁМ чужого набора крейтом; молчаливую подмену вместо явного отказа.
//! НЕ ловит: проводную форму (это `red_fixed_bands_wire.rs`) и переиспользование слепка
//! (это `red_fixed_bands_fingerprint.rs`). Разделение намеренное: один файл — одно свойство.
//!
//! ## `testing.md` чек-лист
//! - п.2 **множественность** — проверяется ВЕСЬ набор поэлементно, не только длина;
//! - п.3 **отсутствие** — пустой набор и `None`-подобный вход отвергаются отдельно от «чужого»;
//! - п.4 **границы** — набор на единицу короче/длиннее канонического; набор с теми же
//!   значениями в ДРУГОМ порядке; набор с дублем;
//! - анти-плацебо: реализация, принимающая ЛЮБОЙ набор, обязана уронить `foreign_*`-тесты.

use contracts::Venue;
use gateway::Selector;

/// Продуктовый набор — `docs/fa/viz-backend.md:42`, включение подписано `П-014`.
/// Здесь он ЛИТЕРАЛ: оракул не имеет права вычислять эталон тем же кодом, который судит
/// (иначе ослабление реализации ослабит и проверку — класс `C-202` B-2 на `M-45`).
const PRODUCT_BANDS: [f64; 7] = [0.015, 0.03, 0.05, 0.08, 0.15, 0.30, 0.60];

fn sel_with(bands: Vec<f64>) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands,
        window_ms: Some(60_000),
        depth_cadence_ms: None,
    }
}

#[test]
fn canonical_set_exists_and_equals_product_set() {
    // Тип КОНСТАНТЫ не диктуется: массив `[f64; 7]` и срез `&'static [f64]` оба годятся,
    // и выбор — за реализацией. Прежняя редакция писала `let canon: &[f64] = …` и тем
    // самым молча требовала срез: массив давал dev'у E0308 вместо спецификации.
    let canon: Vec<f64> = gateway::CANONICAL_DEPTH_BANDS.to_vec();
    assert_eq!(
        canon.len(),
        PRODUCT_BANDS.len(),
        "канонический набор обязан нести РОВНО семь полос (docs/fa/viz-backend.md:42), \
         получено {}. Длина — не украшение: она входит в отпечаток селектора, и лишняя \
         полоса обесценит слепки всех сессий",
        canon.len()
    );
    for (i, (got, want)) in canon.iter().zip(PRODUCT_BANDS.iter()).enumerate() {
        assert!(
            (got - want).abs() < 1e-12,
            "полоса #{i} расходится с продуктовым набором: {got} против {want}. \
             Набор объявлен в docs/fa/viz-backend.md:42 и подписан П-014 — код обязан \
             совпадать с подписанным, а не наоборот"
        );
    }
}

#[test]
fn canonical_set_is_sorted_and_without_duplicates() {
    // Тип КОНСТАНТЫ не диктуется: массив `[f64; 7]` и срез `&'static [f64]` оба годятся,
    // и выбор — за реализацией. Прежняя редакция писала `let canon: &[f64] = …` и тем
    // самым молча требовала срез: массив давал dev'у E0308 вместо спецификации.
    let canon: Vec<f64> = gateway::CANONICAL_DEPTH_BANDS.to_vec();
    for w in canon.windows(2) {
        assert!(
            w[0] < w[1],
            "набор обязан быть строго возрастающим: {} не меньше {}. Порядок несёт смысл — \
             строки кадра раскладываются (band, side) лексикографически, и поиск band_idx \
             идёт позицией (crates/gateway/src/lib.rs:1433)",
            w[0],
            w[1]
        );
    }
}

#[test]
fn canonical_set_within_source_coverage() {
    // Эмиссия режется MAX_REL_DIST = 0.60 (crates/venue-binance/src/lib.rs:33). Полоса ШИРЕ
    // порога никогда не наполнится и молча отдаст заниженное число — ровно класс, против
    // которого подписана П-014 (PL-I-7).
    for b in gateway::CANONICAL_DEPTH_BANDS.to_vec() {
        assert!(
            b > 0.0 && b <= 0.60,
            "полоса {b} вне охвата источника (0, 0.60]: MAX_REL_DIST=0.60 режет эмиссию, \
             и такая полоса отдавала бы заниженное число под меткой достоверности"
        );
    }
}

#[test]
fn crate_rejects_foreign_band_set() {
    // ГЛАВНЫЙ форсинг файла. Реализация, принимающая любой набор, проходит все тесты выше.
    let foreign = sel_with(vec![0.001]);
    let err = gateway::validate_selector(&foreign)
        .expect_err("крейт ОБЯЗАН отвергнуть чужой набор полос, а не принять его молча");
    let msg = err.to_string();
    assert!(
        msg.contains("bands") || msg.contains("полос"),
        "отказ обязан НАЗЫВАТЬ причину (полосы), иначе оператор не поймёт, что произошло. \
         Получено: {msg}"
    );
}

#[test]
fn crate_rejects_subset_of_canonical() {
    // Граница: подмножество канонического — самый вероятный «почти правильный» вход.
    let mut short: Vec<f64> = gateway::CANONICAL_DEPTH_BANDS.to_vec();
    short.pop();
    let err = gateway::validate_selector(&sel_with(short)).expect_err(
        "подмножество канонического набора — тоже ЧУЖОЙ набор: отпечаток другой, \
                     слепок другой, переиспользования нет",
    );
    assert!(!err.to_string().is_empty());
}

#[test]
fn crate_rejects_same_values_in_other_order() {
    // Граница: те же значения, другой порядок. Отпечаток хеширует значения ПО ПОРЯДКУ
    // (crates/gateway/src/lib.rs:3460), значит переставленный набор даёт ДРУГОЙ слепок.
    let mut shuffled: Vec<f64> = gateway::CANONICAL_DEPTH_BANDS.to_vec();
    shuffled.swap(0, 1);
    gateway::validate_selector(&sel_with(shuffled))
        .expect_err("переставленный набор обязан быть отвергнут: он даёт другой отпечаток");
}

