//! RED `MD-I-8` `d12`/`d13` (sacred, architect-only) — **КАДЕНЦИЯ ЗАДАЁТСЯ НА СЕРИЮ И
//! ОБЪЯВЛЯЕТСЯ ПОТРЕБИТЕЛЮ.**
//!
//! Милестоун `milestones/M-68-depth-from-book.md` rev5, задачи 15 и 16. Исполнение решения
//! founder'а 2026-08-26 (§0sexies): «показатели на разных глубинах — не чаще секунды, для
//! исторического анализа достаточно раз в минуту; но для аналога букмап нужен хитмап,
//! обновляющийся с каждым тиком».
//!
//! # COMPILE-RED, отдельным файлом — НАМЕРЕННО
//!
//! Оба оракула ссылаются на форму, которой ещё нет: `Selector::depth_cadence_ms` и
//! `SeriesBundle::cadence_ms`. Оставленные в общем наборе, они ронят КОМПИЛЯЦИЮ соседей, и
//! `d1..d10` нельзя было бы предъявить красными: «не собралось» и «упало на ассерте» — разные
//! вещи, а RED-first требует второго. Тот же приём и по той же причине, что в
//! `red_egress_cap_boundary.rs` и `red_depth_recompute_cost.rs`.
//!
//! # Почему каденция — поле `Selector`, а не глобальная настройка процесса
//!
//! 1. Частота серии есть свойство ЗАПРОШЕННОГО ВИДА, а не процесса: два клиента вправе
//!    смотреть один инструмент с разной зернистостью (`DESIGN` §16: разрешение — тарифная
//!    ручка, «Free получает 1-секундные кадры, не 100 мс»).
//! 2. Процессный глобал невидим системе типов — ровно так `M-71` `B-1` и прожил мимо
//!    зелёного гейта (`R-133`: ручка разобрана, читателей ноль).
//! 3. Каденция ВХОДИТ в `selector_fingerprint`. Это не подгонка кэша под совместимость
//!    (спека §3.1 её запрещает), а обратное: смена смысла редьюсера ОБЯЗАНА
//!    инвалидировать чекпоинт ЯВНО.
//!
//! # Почему `None` означает «на каждом событии», а не число
//!
//! Магическое `0` пришлось бы всем потребителям читать как «делить нельзя, это особый
//! случай». `Option` называет особый случай типом, а не соглашением.
//!
//! # ПРЕДСТАВИМОСТЬ КАДЕНЦИИ — ограничение проводной формы, найденное `C-167`
//!
//! Первая редакция `d12` требовала каденции 100 мс. **Это непредставимо**, и оракул был
//! неудовлетворим по построению. Проводная форма обеих серий ключуется СЕКУНДАМИ:
//! `DepthRow.series: Vec<(time_s, …)>` (`lib.rs:262`), `HeatmapCell.time_s` (`:229`), а
//! `bucket_time_s` (`:824-830`) делит на 1000 целочисленно. Замер:
//!
//! ```text
//! timeframe_ms=1000 → 1 ключ time_s в секунду
//! timeframe_ms= 250 → 1 ключ time_s в секунду   (4 бакета схлопнулись)
//! timeframe_ms= 100 → 1 ключ time_s в секунду   (10 бакетов схлопнулись)
//! ```
//!
//! Поэтому `d12` судит ТОЛЬКО представимые каденции (≥ 1 с), а непредставимые обязаны
//! ОТВЕРГАТЬСЯ, а не схлопываться молча — это `d14`. Требование founder'а покрыто целиком:
//! «раз в секунду, для истории даже раз в минуту» лежит внутри представимого диапазона.
//!
//! # Ведётся ВРЕМЕНЕМ СОБЫТИЯ, не часами — и это судится
//!
//! `VB-I-2` («живое == перепроигранное») рушится немедленно, если каденция зависит от
//! wall-clock: одно и то же окно журнала при повторном проигрывании дало бы другие точки.
//! `d12` сравнивает ДВА независимых прогона по одному журналу — при wall-clock-каденции они
//! разойдутся.

use contracts::{to_fixed, DataSource, EventKind, Level, MdPayload, Venue};
use gateway::{Cursor, Selector};
use journal::{EpochFilter, Journal, WriterConfig};

const MID: f64 = 65_000.0;
const T0: i64 = 1_752_000_000_000;
const NEAR_BAND: f64 = 0.001;

/// Событий в журнале: по одному L2-снимку в секунду на протяжении 120 секунд. Шаг выбран
/// так, чтобы РАЗЛИЧАТЬ представимые каденции: 1 с → **119** точек, 10 с → **11**, 60 с → **1**.
///
/// ЧИСЛА НА ЕДИНИЦУ МЕНЬШЕ ОЖИДАЕМЫХ, И ЭТО ЗАКОННО (`R-141` `Б-2`): последний интервал на
/// момент конца журнала ещё НЕ ЗАКРЫТ, а незакрытый интервал не эмитится. Прежняя редакция
/// комментария называла 120/12/2 — числа, которых фикстура не производит НИ ПРИ КАКОМ
/// исходе. Поймано `R-154` `N-14`. Оставляю след: док-комментарий, расходящийся с
/// производимым выводом, есть то же ложное самоописание, что `TD-138`, только в тесте —
/// и читатель поверит ему раньше, чем прогонит.
const EVENTS: i64 = 120;
const EVENT_STEP_MS: i64 = 1_000;

fn cfg() -> WriterConfig {
    WriterConfig {
        max_segment_bytes: 1 << 20,
        min_free_bytes: 0,
        source: DataSource::OwnCapture,
        provenance: "MD-I-8 cadence fixture".to_string(),
        epoch_id: "own-test".to_string(),
    }
}

fn lvl(price: f64, size: f64) -> Level {
    Level {
        price: to_fixed(price),
        size: to_fixed(size),
    }
}

/// **COMPILE-RED:** поля `depth_cadence_ms` в `Selector` ещё нет — в этом предмет `d12`.
fn sel(depth_cadence_ms: Option<i64>) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands: vec![NEAR_BAND],
        window_ms: None,
        depth_cadence_ms,
    }
}

fn journal() -> tempfile::TempDir {
    let dir = tempfile::tempdir().expect("SETUP: tempdir");
    let mut j = Journal::open_with(dir.path(), cfg()).expect("SETUP: open_with");
    for i in 0..EVENTS {
        j.append(EventKind::md(
            Venue::Binance,
            "BTCUSDT",
            MdPayload::L2Snapshot {
                // A-025 §5.4 П-1(а): варьирует РАЗМЕР, а не только цену. Прежняя фикстура
                // двигала цены при size == 5.0, а значение депт-серии есть СУММА size в
                // полосе — она была КОНСТАНТНОЙ (замер A-025: 120 точек, distinct_values=1),
                // и ассерт значения не различал close от «первого события интервала».
                bids: vec![lvl(MID - 1.0 - i as f64 * 0.01, 5.0 + i as f64 * 0.01)],
                asks: vec![lvl(MID + 1.0 + i as f64 * 0.01, 5.0 + i as f64 * 0.01)],
                ts_exch_ms: T0 + i * EVENT_STEP_MS,
            },
        ))
        .expect("SETUP: append");
    }
    j.flush().expect("SETUP: flush");
    dir
}

fn snap(dir: &std::path::Path, cadence: Option<i64>) -> gateway::Snapshot {
    gateway::snapshot(
        dir,
        EpochFilter::OwnCaptureOnly,
        &sel(cadence),
        Cursor::LATEST,
    )
    .expect("SETUP: snapshot обязан строиться")
}

/// Диагностика несостоявшегося setup'а — ОТДЕЛЬНО от вердикта о семантике
/// (`testing.md` «Целостность гейта» св. 3: проба, молча тестирующая не тот сценарий, есть
/// плацебо самой себя).
fn setup_failed(what: &str) -> ! {
    panic!(
        "SETUP НЕ СОСТОЯЛСЯ: {what}. Это НЕ вердикт о каденции: фикстура не воспроизвела \
         сценарий, ради которого оракул написан."
    )
}

fn depth_points(s: &gateway::Snapshot) -> usize {
    s.series.depth_series.iter().map(|r| r.series.len()).sum()
}

/// **`d12` (задача 15) — каденция депт-серии СВОЯ, ведётся временем события, настраивается.**
///
/// Три утверждения в одном оракуле намеренно: они об одном свойстве и порознь не значат
/// ничего. «Настраивается» без «влияет» — ручка `M-71` `B-1`; «влияет» без «временем
/// события» — сломанный `VB-I-2`.
#[test]
fn md_i8_d12_depth_cadence_is_per_series_and_event_time_driven() {
    let dir = journal();

    let each_second = depth_points(&snap(dir.path(), Some(1_000)));
    let each_ten = depth_points(&snap(dir.path(), Some(10_000)));
    let each_minute = depth_points(&snap(dir.path(), Some(60_000)));

    assert!(
        each_second > each_ten && each_ten > each_minute,
        "MD-I-8 d12: каденция не УПРАВЛЯЕТ числом точек депт-серии. Точек при интервалах \
         1/10/60 с: {each_second}/{each_ten}/{each_minute}. Ожидалось строгое убывание: реже \
         тик — меньше точек. Настройка, которая не меняет поведения, есть ручка без \
         механизма (класс R-133 B-1)"
    );
    assert!(
        each_minute >= 1,
        "MD-I-8 d12: при интервале 60 с на окне 120 с не осталось НИ ОДНОЙ точки — каденция \
         не прореживает, а ГАСИТ серию. Требование founder'а «для исторического анализа \
         достаточно раз в минуту» обязано оставаться исполнимым"
    );

    // ── CLOSE-СЕМАНТИКА: перестроено по `A-025` §5.4 П-1 ────────────────────────────
    //
    // ПРЕЖНЯЯ РЕДАКЦИЯ ТРЕБОВАЛА НЕВЕРНОГО, и это стоило круга. Она брала эталоном
    // `fine_pts.filter(ft <= t).last()` — последнее наблюдение ДО начала интервала, то есть
    // ровно «первое событие интервала», против которого и написана. Плюс `flat_map` схлопывал
    // ВСЕ строки `(side, band)` в один список, теряя их различие. Оба дефекта названы
    // `C-170` O-3 и подтверждены `A-025` §1; реализация, честно делающая close, роняла бы
    // старый ассерт — поэтому оракул чинится ПЕРВЫМ, до кода.
    //
    // ЧТО ПИННИТСЯ ТЕПЕРЬ (`A-025` §5.4 П-1(в)/(г)):
    //   ключ  — НАЧАЛО каденс-интервала (конвенция `bucket_time_s`);
    //   значение — ПОСЛЕДНЕЕ тонкое наблюдение ЭТОЙ ЖЕ строки внутри `[t, t + cadence)`.
    // Сравнение идёт ПО СТРОКАМ `(side, band_pct_e8)`; `flat_map` не воспроизводится.
    const CADENCE_MS: i64 = 60_000;
    let cadence_s = CADENCE_MS / 1000;
    let coarse = snap(dir.path(), Some(CADENCE_MS));
    let fine = snap(dir.path(), Some(1_000));

    // ФОРМА АДДИТИВНАЯ (`M-70` §2bis.-1): `series` — кортежи, метки в параллельном
    // `series_provenance`. Сравнение сводится к
    // ПАРАМ `(time_s, depth_e8)`, потому что предмет этого сценария — КАДЕНЦИЯ (какие такты
    // попали в серию), а не провенанс. Брать `DepthPoint` целиком значило бы вплести сюда
    // чужой предмет и получить ложное красное при любой правке метки.
    let rows_of =
        |sn: &gateway::Snapshot| -> std::collections::BTreeMap<(String, i64), Vec<(i64, i64)>> {
            sn.series
                .depth_series
                .iter()
                .map(|r| ((r.side.clone(), r.band_pct_e8), r.series.clone()))
                .collect()
        };
    let coarse_rows = rows_of(&coarse);
    let fine_rows = rows_of(&fine);

    // SETUP-GUARD (`A-025` §5.4 П-1(б), `testing.md` «Целостность гейта» св. 3): тонкая серия
    // ВНУТРИ каждого сравниваемого интервала обязана быть НЕ константной. На константной
    // фикстуре close и «первое событие» дают одно число, и ассерт ниже зелен против обоих —
    // ровно тот вакуум, которым болела прежняя редакция.
    let mut compared = 0usize;
    for (key, c_pts) in &coarse_rows {
        let f_pts = fine_rows
            .get(key)
            .unwrap_or_else(|| setup_failed(&format!("строки {key:?} нет в тонкой серии")));
        for (t, v) in c_pts {
            let inside: Vec<i64> = f_pts
                .iter()
                .filter(|(ft, _)| *ft >= *t && *ft < *t + cadence_s)
                .map(|(_, fv)| *fv)
                .collect();
            if inside.len() < 2 {
                continue; // интервал не покрыт двумя тонкими точками — сравнивать нечего
            }
            if inside.first() == inside.last() {
                setup_failed(&format!(
                    "SETUP: в интервале t={t} строки {key:?} тонкая серия КОНСТАНТНА                      ({:?}) — close и «первое событие интервала» дают одно число, и ассерт                      ниже не различал бы их (A-025 §5.4 П-1(б))",
                    inside.first()
                ));
            }
            let expected = *inside.last().expect("len >= 2");
            assert_eq!(
                *v, expected,
                "MD-I-8 d12 (A-024 O-3 / A-025 §5.4 П-1): строка {key:?}, точка грубой серии                  на t={t} несёт {v}, а ПОСЛЕДНЕЕ наблюдение внутри [{t}, {}) — {expected}.                  Первое наблюдение интервала — {:?}. Значит взят СЪЁМ В НАЧАЛЕ, а спека                  §0sexies.2bis пиннит CLOSE: в интервале побеждает последнее наблюдение, как                  и в бакете heatmap (§3.1 запрещает разводить семантику двух серий одного окна)",
                *t + cadence_s,
                inside.first()
            );
            compared += 1;
        }
    }
    if compared == 0 {
        setup_failed(
            "SETUP: не сравнено НИ ОДНОЙ точки — фикстура не дала интервала с двумя тонкими              наблюдениями, и оракул зелен по ОТСУТСТВИЮ предмета",
        );
    }

    // Детерминизм: ДВА независимых прогона по одному журналу обязаны совпасть побайтно по
    // составу. При wall-clock-каденции они разойдутся — `VB-I-2` рушится немедленно.
    let a = snap(dir.path(), Some(1_000));
    let b = snap(dir.path(), Some(1_000));
    assert_eq!(
        a.series.depth_series, b.series.depth_series,
        "MD-I-8 d12 (VB-I-2): два прогона по ОДНОМУ журналу с одной каденцией дали разные \
         депт-серии. Значит тик ведётся часами, а не временем события, и живое перестало \
         быть равно перепроигранному"
    );
}

/// **`d13` (задача 16) — выдача НАЗЫВАЕТ каденцию каждой серии.**
///
/// `П-014` п.2 дословно: «выдача обязана ЭТО НАЗЫВАТЬ, а не умалчивать». В августе метка
/// прикрывала ДЕФЕКТ и была временной; после решения founder'а о разной каденции она
/// описывает НАМЕРЕННОЕ свойство и постоянна: две серии в одном кадре имеют разную частоту,
/// и потребитель обязан их различать, не догадываясь.
///
/// **COMPILE-RED:** поля `cadence_ms` в `SeriesBundle` ещё нет.
#[test]
fn md_i8_d13_output_declares_cadence_of_each_series() {
    let dir = journal();
    let s = snap(dir.path(), Some(1_000));

    let declared = &s.series.cadence_ms;
    let depth = declared
        .iter()
        .find(|(name, _)| name == "depth_series")
        .unwrap_or_else(|| {
            panic!(
                "MD-I-8 d13 (П-014 п.2): выдача не называет каденцию депт-серии. Объявлено: \
                 {declared:?}. Потребитель, сравнивающий полосу с ячейкой heatmap в одном \
                 кадре, обязан знать, что их частоты РАЗНЫЕ по решению продукта"
            )
        });
    assert_eq!(
        depth.1,
        Some(1_000),
        "MD-I-8 d13: объявленная каденция депт-серии {:?} не совпадает с запрошенной 1000 мс. \
         Метка, расходящаяся с поведением, хуже отсутствия метки: она врёт уверенно",
        depth.1
    );

    let heatmap = declared
        .iter()
        .find(|(name, _)| name == "heatmap")
        .unwrap_or_else(|| {
            panic!("MD-I-8 d13: выдача не называет каденцию heatmap. Объявлено: {declared:?}")
        });
    assert_eq!(
        heatmap.1, None,
        "MD-I-8 d13: heatmap обязан объявляться как пер-событийный (None), а не числом. \
         Магическое 0 пришлось бы каждому потребителю читать как особый случай; Option \
         называет особый случай типом, а не соглашением. Объявлено: {:?}",
        heatmap.1
    );
}

/// **`d14` (`C-167`) — НЕПРЕДСТАВИМАЯ каденция ОТВЕРГАЕТСЯ, а не схлопывается молча.**
///
/// Проводная форма ключуется секундами; подсекундный интервал не может дать больше одной
/// точки в секунду. Сегодня такая настройка НЕ ДАЁТ ОШИБКИ — она молча склеивает бакеты
/// (замер в шапке файла). Это тот же класс, что `GW-I-14` закрыл для `GATEWAY_WINDOW_MS`:
/// невалидная конфигурация обязана быть отказом, а не тихой деградацией (`PL-I-5` дословно:
/// «отсутствие/невалидность лимита = отказ, не unbounded»).
///
/// Развязка «версионированная подсекундная форма» ЗАКОННА, но она — ДРУГОЙ предмет и другой
/// bump. Пока формы нет, единственный честный исход — отказ.
#[test]
fn md_i8_d14_sub_second_cadence_is_refused_not_silently_collapsed() {
    let dir = journal();
    for bad in [100_i64, 250, 999] {
        let got = gateway::snapshot(
            dir.path(),
            EpochFilter::OwnCaptureOnly,
            &sel(Some(bad)),
            Cursor::LATEST,
        );
        assert!(
            got.is_err(),
            "MD-I-8 d14 (C-167): каденция {bad} мс ПРИНЯТА. Проводная форма ключуется \
             секундами (DepthRow.series — time_s, lib.rs:262), значит подсекундный интервал \
             не может дать больше одной точки в секунду: бакеты схлопываются МОЛЧА, и \
             оператор получает вчетверо-вдесятеро меньше данных, чем просил, без единого \
             сообщения. Невалидная конфигурация обязана быть ОТКАЗОМ — класс GW-I-14"
        );
    }
}

/// **`d15` (`C-167`) — смена каденции ИНВАЛИДИРУЕТ чекпоинт, а не переиспользует его.**
///
/// Каденция меняет СМЫСЛ редьюсера: та же история даёт другую депт-серию. Чекпоинт,
/// собранный при одной каденции, при другой описывает не то состояние. Спека §3.1 запрещает
/// «менять `selector_fingerprint` ради совместимости кэша» — здесь ОБРАТНОЕ требование:
/// отпечаток обязан РАЗЛИЧАТЬ каденции, иначе тёплый старт молча отдаст чужие числа.
///
/// `C-094` B3 назвал класс дословно: развязка обязана быть ЯВНОЙ инвалидацией, а не
/// подгонкой отпечатка.
#[test]
fn md_i8_d15_cadence_change_invalidates_the_checkpoint() {
    let a = gateway::checkpoint::selector_fingerprint(&sel(Some(1_000)));
    let b = gateway::checkpoint::selector_fingerprint(&sel(Some(10_000)));
    assert_ne!(
        a, b,
        "MD-I-8 d15 (C-167): отпечатки селекторов с каденцией 1 с и 10 с СОВПАЛИ ({a}). \
         Значит чекпоинт, собранный при одной каденции, будет переиспользован при другой, и \
         тёплый старт отдаст числа, которых при запрошенной каденции быть не может. \
         Каденция меняет СМЫСЛ редьюсера — отпечаток обязан её различать (C-094 B3: \
         развязка через ЯВНУЮ инвалидацию, не через подгонку)"
    );

    // Контроль: одинаковая каденция даёт одинаковый отпечаток — иначе кэш не работает вовсе.
    assert_eq!(
        gateway::checkpoint::selector_fingerprint(&sel(Some(1_000))),
        gateway::checkpoint::selector_fingerprint(&sel(Some(1_000))),
        "MD-I-8 d15-C: отпечаток НЕСТАБИЛЕН при одном и том же селекторе — чекпоинт не \
         переиспользуется никогда, и это не инвалидация, а поломка кэша"
    );
}

/// **`d16` (`A-024` `O-4`) — чекпоинт ПОСРЕДИ каденс-интервала: warm-путь == полный реплей.**
///
/// `d8b` соседнего набора проверяет то же на хвосте дельт при пер-событийной семантике. С
/// собственной каденцией появляется НОВОЕ состояние, которого там нет: чекпоинт, записанный
/// В СЕРЕДИНЕ интервала, когда точка ещё не закрыта. Тёплый старт обязан дать то же, что
/// полный реплей, иначе смена каденции тихо разошлась бы с кэшем.
///
/// Каденция 60 с на окне 120 с гарантирует, что курсор чекпоинта попадёт ВНУТРЬ интервала,
/// а не на его границу — иначе оракул проверял бы вырожденный случай.
///
/// # `d16` ЗЕЛЁН сегодня, и это объявлено, а не замаскировано
///
/// Каденция ещё не реализована, поэтому тёплый и полный пути совпадают ТРИВИАЛЬНО. Это
/// GREEN-ПИН: он сторожит расхождение, которое станет возможным ТОЛЬКО с задачей 15.
///
/// **Мутацию architect предъявить не смог, и это записано, а не обойдено.** Любая мутация
/// сегодня ломала бы warm-путь ВООБЩЕ, а не «под каденцией» — то есть проверяла бы другой
/// инвариант и давала ложное доказательство. **Обязанность переносится в Done Block dev'а:**
/// после реализации задачи 15 испортить `snapshot_from_checkpoint` так, чтобы тёплый путь
/// разошёлся с полным на каденс-интервале, и предъявить КРАСНЫЙ `d16`. Не покраснел ⇒ оракул
/// ничего не пиннит, и чинить надо оракул.
#[test]
fn md_i8_d16_checkpoint_mid_cadence_interval_equals_full_replay() {
    let dir = journal();
    let ckpt = tempfile::tempdir().expect("SETUP: ckpt tempdir");
    let sel60 = sel(Some(60_000));

    gateway::checkpoint::advance(dir.path(), ckpt.path(), &sel60, EpochFilter::OwnCaptureOnly)
        .expect("SETUP: advance");

    let (warm, _stats) = gateway::snapshot_from_checkpoint(
        dir.path(),
        EpochFilter::OwnCaptureOnly,
        &sel60,
        ckpt.path(),
        Cursor::LATEST,
    )
    .expect("SETUP: snapshot_from_checkpoint");

    let full = snap(dir.path(), Some(60_000));

    assert_eq!(
        warm.series.depth_series, full.series.depth_series,
        "MD-I-8 d16 (O-4): тёплый старт из чекпоинта, записанного ПОСРЕДИ каденс-интервала, \
         дал депт-серию, отличную от полного реплея. Смена каденции обязана быть согласована \
         с кэшем: либо отпечаток её различает и чекпоинт перестраивается (d15), либо warm и \
         full совпадают. Расхождение здесь — тихая порча тёплого пути (VB-I-2)"
    );
}

/// Селектор с ЗАДАННЫМ таймфреймом — для `d17`. `sel()` фиксирует `timeframe_ms: 1_000`, а
/// предмет `d17` живёт именно в отношении двух параметров.
fn sel_tf(timeframe_ms: i64, depth_cadence_ms: Option<i64>) -> Selector {
    Selector {
        timeframe_ms,
        ..sel(depth_cadence_ms)
    }
}

/// **`d17` (Б-2, `R-138`) — ВЫДАЧА НЕ СМЕЕТ ОБЪЯВЛЯТЬ КАДЕНЦИЮ, КОТОРОЙ НЕ ДАЁТ.**
///
/// # Дефект
///
/// Фильтр каденции работает по `time_s`, УЖЕ выровненному на `timeframe_ms`
/// (`recompute_depth_from_book`: `time_s % cadence_s != 0`). Поэтому эффективная частота есть
/// **НОК(timeframe_s, cadence_s)**, а не заявленная. Замер (арифметика по фикстуре):
///
/// ```text
/// timeframe_ms=1000 cadence_ms=60000 -> заявлено 60 с, ФАКТ 60 с   (совпало)
/// timeframe_ms=3000 cadence_ms=10000 -> заявлено 10 с, ФАКТ 30 с   ← ЛОЖЬ втрое
/// timeframe_ms=2000 cadence_ms=10000 -> заявлено 10 с, ФАКТ 10 с   (совпало)
/// ```
///
/// `validate_selector` (`crates/gateway/src/lib.rs`) проверяет только `ms >= 1000` и
/// `86_400_000 % ms == 0` — отношения двух параметров НЕ проверяет вовсе. А метка выдачи
/// объявляет значение СЕЛЕКТОРА (`("depth_series", self.selector.depth_cadence_ms)`), то есть
/// лжёт ровно на величину расхождения. Это тот же класс тихой деградации, ради которого
/// существуют задача 17 и `GW-I-14`: оператор получает втрое меньше данных, чем просил, без
/// единого сообщения.
///
/// # Конструкцию оракул НЕ выбирает
///
/// Допустимы ОБА исхода, и решает реализация:
///   · ОТКАЗ при валидации (гвард `cadence_ms % timeframe_ms == 0`) — путь `GW-I-14`,
///     согласный с уже существующим гвардом «делит сутки»;
///   · либо ЧЕСТНАЯ эффективная каденция в метке `cadence_ms` — тогда выдача говорит правду
///     о том, что реально отдаёт.
/// Запрещено ровно одно: объявлять одно, а давать другое (`PL-I-7` — деградация не выдаётся
/// за норму).
#[test]
fn md_i8_d17_declared_cadence_matches_what_is_delivered() {
    let dir = journal();

    // ── VANTAGE: согласованная пара обязана РАБОТАТЬ и объявлять СВОЁ значение ────────
    let ok = gateway::snapshot(
        dir.path(),
        EpochFilter::OwnCaptureOnly,
        &sel_tf(1_000, Some(10_000)),
        Cursor::LATEST,
    )
    .unwrap_or_else(|e| setup_failed(&format!("согласованная пара 1000/10000 отвергнута: {e}")));
    let declared_ok = ok
        .series
        .cadence_ms
        .iter()
        .find(|(k, _)| k == "depth_series")
        .and_then(|(_, v)| *v)
        .unwrap_or_else(|| setup_failed("метка depth_series отсутствует у согласованной пары"));
    assert_eq!(
        declared_ok, 10_000,
        "MD-I-8 d17 VANTAGE: согласованная пара (timeframe 1000, cadence 10000) обязана \
         объявлять 10000; объявлено {declared_ok}. Без этой половины предмет ниже был бы \
         неотличим от «метка сломана всегда»"
    );

    // ── ПРЕДМЕТ: РАССОГЛАСОВАННАЯ пара ───────────────────────────────────────────────
    // 86_400_000 % 3000 == 0 и % 10000 == 0 — оба параметра проходят СЕГОДНЯШНИЕ гварды по
    // отдельности, и суб-кейс не краснеет по ЧУЖОЙ причине (урок A-025 §3: 86400000 % 999).
    assert_eq!(
        86_400_000 % 3_000,
        0,
        "SETUP: timeframe 3000 обязан делить сутки"
    );
    assert_eq!(
        86_400_000 % 10_000,
        0,
        "SETUP: cadence 10000 обязана делить сутки"
    );

    let got = gateway::snapshot(
        dir.path(),
        EpochFilter::OwnCaptureOnly,
        &sel_tf(3_000, Some(10_000)),
        Cursor::LATEST,
    );

    let Ok(snap) = got else {
        return; // ОТКАЗ — законный исход (гвард отношения параметров). Предмет закрыт.
    };

    // Реализация приняла пару ⇒ обязана говорить правду о том, что отдаёт.
    let declared = snap
        .series
        .cadence_ms
        .iter()
        .find(|(k, _)| k == "depth_series")
        .and_then(|(_, v)| *v)
        .unwrap_or_else(|| setup_failed("метка depth_series отсутствует у принятой пары"));

    // ФАКТИЧЕСКИЙ шаг — из самой серии, а не из арифметики: оракул мерит ВЫДАЧУ.
    let stamps: Vec<i64> = snap
        .series
        .depth_series
        .first()
        .map(|r| r.series.iter().map(|(t, _)| *t).collect())
        .unwrap_or_default();
    if stamps.len() < 2 {
        setup_failed(&format!(
            "в депт-серии {} точек — шаг не вычислим, предмет не воспроизведён",
            stamps.len()
        ));
    }
    let actual_step_ms = (stamps[1] - stamps[0]) * 1000;

    assert_eq!(
        declared,
        actual_step_ms,
        "MD-I-8 d17 (R-138 Б-2): выдача ОБЪЯВЛЯЕТ каденцию {declared} мс, а РЕАЛЬНО отдаёт \
         точки раз в {actual_step_ms} мс. Фильтр каденции работает по time_s, уже выровненному \
         на timeframe_ms={}, поэтому эффективная частота есть НОК(timeframe, cadence) = \
         {actual_step_ms} мс. Оператор получает данных в {:.0}× реже, чем просил, и метка это \
         СКРЫВАЕТ (PL-I-7: деградация не выдаётся за норму). Допустимы два исхода — ОТКАЗ при \
         валидации либо ЧЕСТНОЕ эффективное значение в метке; запрещено объявлять одно, а \
         давать другое",
        3_000,
        actual_step_ms as f64 / declared.max(1) as f64
    );
}

/// **`d20` (Б-2, `R-141`) — `VB-I-2` ПРИ ЗАДАННОЙ КАДЕНЦИИ: живое == перепроигранное.**
///
/// # Дефект круга 3
///
/// Сброс незакрытого каденс-интервала висит на `finish(self)` → `flush_pending_depth_interval`
/// (`crates/gateway/src/lib.rs:1332`), а живой путь идёт `LiveReducer::snapshot(&self)` →
/// `finish_ref_with_at(&self)` → `finish_ref(&self)` и сбросить не может: `flush` требует
/// `&mut self`, у живого пути его нет. Итог: живой снимок теряет САМУЮ СВЕЖУЮ точку глубины,
/// реплей её отдаёт. Замер `R-141` на одной фикстуре: `None` — 240/240, `Some(1000)` — 240
/// против 238, `Some(10000)` — 24 против 22, `Some(60000)` — 4 против 2 (на минуте теряется
/// ПОЛОВИНА точек).
///
/// **Корень — в спеке.** §0sexies.2ter предписала «незакрытый последний интервал сбрасывается
/// на `finish`». `finish` берёт `self` и живёт ТОЛЬКО на replay-пути; я назвал точку, которой
/// у живого пути нет. Dev исполнил написанное буквально.
///
/// # Почему единственный существующий оракул `VB-I-2` этого не видит
///
/// `crates/gateway/tests/red_gateway_live_eq_replay.rs:120` задаёт `depth_cadence_ms: None` и
/// к предмету слеп по построению: без каденции незакрытых интервалов не бывает. Оракул на
/// инвариант обязан гонять РЕЖИМ, в котором инвариант может сломаться.
///
/// # Семантику оракул НЕ выбирает
///
/// Эмитить частичную точку на ОБОИХ путях либо не эмитить ни на одном — решает реализация
/// (§0sexies.2ter, переписан). Требование одно: **живое равно перепроигранному ПРИ ЛЮБОЙ
/// каденции.** Ассерт равенства ловит обе односторонние поломки; «не меньше» — только одну.
#[test]
fn md_i8_d20_live_equals_replay_under_cadence() {
    let dir = journal();

    for cadence in [1_000_i64, 10_000, 60_000] {
        let selector = sel(Some(cadence));

        // ЖИВОЙ путь: тот, которым ходит gateway-serve.
        let ckpt = tempfile::tempdir().expect("SETUP: ckpt tempdir");
        let (mut live, _) = gateway::LiveReducer::resume(
            dir.path(),
            EpochFilter::OwnCaptureOnly,
            &selector,
            ckpt.path(),
        )
        .unwrap_or_else(|e| setup_failed(&format!("resume при каденции {cadence}: {e}")));
        loop {
            match live.pump(dir.path(), EpochFilter::OwnCaptureOnly, 256) {
                Ok((frames, _, _)) if frames.is_empty() => break,
                Ok(_) => continue,
                Err(e) => setup_failed(&format!("pump при каденции {cadence}: {e}")),
            }
        }
        let live_series = live.snapshot().series.depth_series;

        // ПЕРЕПРОИГРАННЫЙ путь: независимый полный реплей того же окна.
        let replay_series = snap(dir.path(), Some(cadence)).series.depth_series;

        // SETUP-GUARD: без точек сравнивать нечего, и зелёное было бы вакуумом.
        let n_replay: usize = replay_series.iter().map(|r| r.series.len()).sum();
        if n_replay == 0 {
            setup_failed(&format!(
                "при каденции {cadence} реплей не дал НИ ОДНОЙ точки — предмет не воспроизведён"
            ));
        }

        let n_live: usize = live_series.iter().map(|r| r.series.len()).sum();
        assert_eq!(
            live_series, replay_series,
            "MD-I-8 d20 / VB-I-2 (R-141 Б-2): при каденции {cadence} мс живая депт-серия \
             НЕ РАВНА перепроигранной — точек {n_live} против {n_replay}. VB-I-2 \
             (docs/fa/viz-backend.md:189) требует БИТ-ИДЕНТИЧНОСТИ, а не «не хуже». \
             Сброс незакрытого каденс-интервала сделан только на пути, которым ходит \
             РЕПЛЕЙ (finish(self)); живой путь идёт finish_ref(&self) и сбросить не может. \
             Клиент кокпита теряет самую свежую точку глубины, а перепроигрывание её отдаёт"
        );
    }
}
