/// **V6.** Честная мелкая фикстура, где все цены УЖЕ кратны `W`, обязана пройти сквозь
/// огрубление БЕЗ изменения чисел: сколько корзин было — столько и осталось, объёмы те же,
/// POC тот же.
///
/// Это парный vantage к `V1`: заглушка «схлопнуть всё в одну корзину» проходит любой оракул
/// размера и валит этот. Без него набор был бы зелен против реализации, уничтожающей продукт
/// ради байтов.
#[test]
fn v6_grid_aligned_input_passes_through_unchanged() {
    let base = 77_000 * 100_000_000_i64;
    let events = vec![
        trade(base, 1.0, T),
        trade(base + W, 5.0, T + 1),
        trade(base + 2 * W, 2.0, T + 2),
        trade(base + 3 * W, 1.0, T + 3),
    ];
    let dir = journal_of(events);
    let s = snap(dir.path());
    let row = only_row(&s);

    assert_eq!(
        row.bins.len(),
        4,
        "V6 НАРУШЕН: четыре цены, уже стоящие на сетке, дали {} корзин — \
         огрубление схлопнуло то, что схлопывать не должно",
        row.bins.len()
    );
    assert_eq!(
        row.poc_e8,
        base + W,
        "V6 НАРУШЕН: POC съехал с корзины максимального объёма"
    );
    let got: i128 = row.bins.iter().map(|&(_, v)| i128::from(v)).sum();
    assert_eq!(
        got,
        i128::from(to_fixed(9.0)),
        "V6 НАРУШЕН: суммарный объём изменился на входе, не требующем огрубления"
    );
}

/// **V6-b.** Вырожденная ширина: весь диапазон сессии уже внутри ОДНОЙ корзины.
