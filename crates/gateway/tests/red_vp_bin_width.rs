//! Милестоун `milestones/M-86-vp-bin-width.md`, задачи 2-3. Оракулы `V2`, `V3`, `V4`, `V6`,
//! `V8`. Размер кадра на прод-масштабе (`V1`) живёт ОТДЕЛЬНО —
//! `red_vp_bin_width_size.rs`: он меняет процессный предел ответа и потому не смеет
//! делить бинарь с этими тестами (глобал — гонка внутри одного тестового бинаря).
//!
//! ## Почему набор существует
//!
//! Замер на проде 2026-09-18 (`docs/plans/vp-frame-size-measurement-2026-09-18.md`):
//! профиль объёма — 87.41 % кадра, 211 381 корзина, где корзина = одна торгованная цена с
//! точностью до тика. Кадр 5 533 287 Б против предела 2 000 000 Б (`П-020`) ⇒ выдача
//! отвергается fail-closed, клиент получает НОЛЬ байт.
//!
//! ## COMPILE-RED
//!
//! `gateway::DEFAULT_VP_BIN_WIDTH_E8` ещё не существует ⇒ набор не компилируется. Это
//! законная форма RED в этом проекте (прецеденты `M-24`, `M-71`): тип/константа, объявленные
//! спекой, вводятся dev'ом, и до того тест обязан быть красным, а не «условно зелёным».
//!
//! ## Анти-плацебо — набор держат ДВА взаимно-противоположных оракула
//!
//! * `V1` (соседний файл) валит заглушку «сетку не применять»;
//! * `V6` валит заглушку «схлопнуть всё в одну корзину» — она проходит по размеру и
//!   уничтожает продукт.
//!
//! Ни один из двух в одиночку не достаточен, и это сказано здесь, потому что именно такой
//! паре `M-71` обязан тем, что переширокая реализация не проехала гейт.

use contracts::{to_fixed, DataSource, EventKind, MdPayload, Side, Venue};
use gateway::{Cursor, Selector};
use journal::{EpochFilter, Journal, WriterConfig};

/// Ширина корзины, ОБЪЯВЛЕННАЯ спекой (`M-86` §2.1): 0.25 USD в единицах e8.
/// Тесты берут значение из кода, а не дублируют литерал: если dev поставит другое, набор
/// поедет за ним, и расхождение поймает шаг `D` гейта (ручка в `docker-compose.yml`), а не
/// молчаливое несовпадение двух литералов.
const W: i64 = gateway::DEFAULT_VP_BIN_WIDTH_E8;

const T: i64 = 1_752_000_010_000; // середина одного UTC-дня
const DAY_MS: i64 = 86_400_000;

fn cfg() -> WriterConfig {
    WriterConfig {
        max_segment_bytes: 1 << 26,
        min_free_bytes: 0,
        source: DataSource::OwnCapture,
        provenance: "test".to_string(),
        epoch_id: "own-test".to_string(),
    }
}

fn trade(price_e8: i64, size: f64, ts: i64) -> EventKind {
    EventKind::md(
        Venue::Binance,
        "BTCUSDT",
        MdPayload::Trade {
            price: price_e8,
            size: to_fixed(size),
            side: Side::Buy,
            ts_exch_ms: ts,
        },
    )
}

fn journal_of(events: Vec<EventKind>) -> tempfile::TempDir {
    let dir = tempfile::tempdir().expect("tempdir");
    {
        let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
        for e in events {
            j.append(e).expect("append");
        }
        j.flush().expect("flush");
    }
    dir
}

/// Селектор без окна — профиль сессионный, окно на него не влияет (`VB-I-10`), а
/// `window_ms = None` убирает из оракулов посторонний источник расхождения.
fn sel() -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands: vec![0.001],
        window_ms: None,
        depth_cadence_ms: None,
    }
}

fn snap(dir: &std::path::Path) -> gateway::Snapshot {
    gateway::snapshot(dir, EpochFilter::OwnCaptureOnly, &sel(), Cursor::LATEST).expect("snapshot")
}

fn only_row(s: &gateway::Snapshot) -> &gateway::VolumeProfileRow {
    assert_eq!(
        s.series.volume_profile.len(),
        1,
        "SETUP НЕ СОСТОЯЛСЯ: ожидалась ровно одна сессия в профиле, получено {}",
        s.series.volume_profile.len()
    );
    &s.series.volume_profile[0]
}

