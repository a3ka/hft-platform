/// **V3.** Сумма объёмов по корзинам равна сумме объёмов сделок: ничего не потеряно на
/// делении и ничего не удвоено на границе.
///
/// Это тот оракул, который ловит «починку», экономящую байты потерей данных: отбросить
/// хвост, взять только крупные корзины, округлить объём. Все три варианта зелены по размеру.
#[test]
fn v3_total_volume_is_preserved_by_binning() {
    let base = 77_000 * 100_000_000_i64;
    let sizes = [1.0_f64, 2.5, 0.25, 4.0, 3.5, 0.75];
    let events: Vec<EventKind> = sizes
        .iter()
        .enumerate()
        .map(|(i, &sz)| trade(base + (i as i64) * (W / 2), sz, T + i as i64))
        .collect();
    let dir = journal_of(events);
    let s = snap(dir.path());
    let row = only_row(&s);

    let expected: i128 = sizes.iter().map(|&x| i128::from(to_fixed(x))).sum();
    let got: i128 = row.bins.iter().map(|&(_, v)| i128::from(v)).sum();
    assert_eq!(
        got, expected,
        "V3 НАРУШЕН: сумма объёмов по корзинам {got} != сумме объёмов сделок {expected} — \
         огрубление обязано СКЛАДЫВАТЬ объёмы, а не терять и не дублировать их"
    );
}

// ─────────────────────────────────────────────────────────────────────────────────────────
// V4 — метрики принадлежат ОТДАННОЙ сетке
// ─────────────────────────────────────────────────────────────────────────────────────────

/// **V4.** `poc_e8`, `vah_e8`, `val_e8` обязаны быть ключами ОТДАННЫХ корзин.
///
/// Краснеет против расчёта метрик ДО огрубления — самой естественной реализации: тогда
/// главный уровень указывает на цену, которой в отданной гистограмме нет, и клиент рисует
/// линию мимо собственных столбиков. Дефект тихий: размер в норме, все прочие оракулы зелены.
#[test]
fn v4_poc_and_value_area_belong_to_emitted_bins() {
    let base = 77_000 * 100_000_000_i64;
    // Объём сосредоточен на цене, НЕ кратной W (base + W/2 + 7), чтобы POC «до огрубления»
    // и POC «после» физически различались.
    let events = vec![
        trade(base + W / 2 + 7, 10.0, T),
        trade(base + W + 3, 1.0, T + 1),
        trade(base + 2 * W + 5, 2.0, T + 2),
        trade(base + 3 * W + 1, 1.0, T + 3),
    ];
    let dir = journal_of(events);
    let s = snap(dir.path());
    let row = only_row(&s);

    let keys: Vec<i64> = row.bins.iter().map(|&(p, _)| p).collect();
    for (name, value) in [
        ("poc_e8", row.poc_e8),
        ("vah_e8", row.vah_e8),
        ("val_e8", row.val_e8),
    ] {
        assert!(
            keys.contains(&value),
            "V4 НАРУШЕН: {name} = {value} не является ключом ни одной отданной корзины \
             (ключи: {keys:?}) — метрики обязаны считаться ПОСЛЕ огрубления"
        );
        assert_eq!(
            value % W,
            0,
            "V4 НАРУШЕН: {name} = {value} не кратен ширине корзины {W}"
        );
    }
}

