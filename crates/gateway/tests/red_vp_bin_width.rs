/// **V2.** Ключ корзины = `(price / W) * W`, деление ВНИЗ, якорь ноль.
///
/// Краснеет против округления «к ближайшему»: оно даёт РАЗНЫЕ сетки в зависимости от того,
/// с какой стороны пришла цена, и тогда снапшот и дельта одного потока кладут одну и ту же
/// сделку в разные корзины — склейка у потребителя размазывает профиль (`V8` ловит это уже
/// как следствие, а здесь ловится причина).
///
/// Дегенерированный вход присутствует намеренно: цена РОВНО на границе корзины, цена на
/// единицу ниже границы и цена на единицу выше.
#[test]
fn v2_every_emitted_price_is_on_the_grid() {
    let base = 77_000 * 100_000_000_i64; // 77 000.00 USD
    let prices = vec![
        base,         // ровно на границе (кратна W при любом делителе 0.25)
        base + W - 1, // на единицу НИЖЕ следующей границы
        base + W,     // ровно следующая граница
        base + W + 1, // на единицу ВЫШЕ границы
        base + W / 2, // середина корзины
    ];
    let dir = journal_of(
        prices
            .iter()
            .enumerate()
            .map(|(i, &p)| trade(p, 1.0, T + i as i64))
            .collect(),
    );
    let s = snap(dir.path());
    let row = only_row(&s);

    assert!(
        !row.bins.is_empty(),
        "SETUP НЕ СОСТОЯЛСЯ: профиль пуст, сравнивать нечего"
    );
    for &(price, _) in &row.bins {
        assert_eq!(
            price % W,
            0,
            "V2 НАРУШЕН: отданная цена {price} не кратна ширине корзины {W} \
             (ключ обязан быть (price/W)*W, деление вниз, якорь 0)"
        );
    }
    // Анти-вырождение: пять входных цен обязаны схлопнуться в ДВЕ корзины, а не остаться
    // пятью и не слиться в одну. Без этой проверки тест зелен против «сетка = тик».
    assert_eq!(
        row.bins.len(),
        2,
        "V2 НАРУШЕН: пять цен в двух корзинах шириной {W} дали {} корзин — \
         сетка либо не применена (5), либо слишком груба (1)",
        row.bins.len()
    );
}

