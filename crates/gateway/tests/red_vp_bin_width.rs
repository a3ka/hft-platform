/// **V6-c.** Одна сделка — не крайний случай, а самый частый вход на старте сессии.
#[test]
fn v6c_single_trade_yields_single_bin_on_grid() {
    let base = 77_000 * 100_000_000_i64;
    let dir = journal_of(vec![trade(base + W / 3, 2.0, T)]);
    let s = snap(dir.path());
    let row = only_row(&s);

    assert_eq!(
        row.bins.len(),
        1,
        "V6-c НАРУШЕН: одна сделка — одна корзина"
    );
    assert_eq!(
        row.bins[0].0 % W,
        0,
        "V6-c НАРУШЕН: единственная корзина не на сетке"
    );
    assert_eq!(row.poc_e8, row.bins[0].0, "V6-c НАРУШЕН: POC != корзина");
    assert_eq!(row.val_e8, row.bins[0].0, "V6-c НАРУШЕН: VAL != корзина");
    assert_eq!(row.vah_e8, row.bins[0].0, "V6-c НАРУШЕН: VAH != корзина");
}

