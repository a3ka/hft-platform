/// **V8.** `snapshot(C)` + `frames_since(C..LATEST)`, склеенные `Snapshot::apply`, дают
/// ТОТ ЖЕ профиль, что полный `snapshot(LATEST)`.
///
/// Эталон строится НЕЗАВИСИМЫМ путём (полная свёртка), поэтому сверка нетавтологична
/// (`testing.md` §«Зависимый эталон мутация ловит плохо»).
///
/// Краснеет против реализации, применившей сетку на одном пути и не применившей на другом:
/// `merge_volume_profile` складывает по КЛЮЧУ цены
/// (`crates/gateway/src/lib.rs:761-779`), поэтому две разные сетки в одном потоке дают у
/// потребителя гистограмму-химеру, которую не ловит ни размер, ни `V2`.
///
/// Две ЖИЗНИ одной цены в фикстуре обязательны (`testing.md` п.2 «множественность»): цена
/// торгуется ДО среза и СНОВА после — наивная реализация склейки теряет одну из них.
#[test]
fn v8_snapshot_plus_frames_equals_full_replay() {
    let base = 77_000 * 100_000_000_i64;
    let mut events = Vec::new();
    for i in 0..12_i64 {
        // цены НЕ кратны W намеренно: склейка обязана совпасть именно на огрублённых ключах
        events.push(trade(base + i * (W / 3) + 11, 1.0, T + i));
    }
    // вторая жизнь той же цены — после будущего среза
    events.push(trade(base + 11, 4.0, T + 50));
    let dir = journal_of(events);

    // Срез посередине: берём курсор снапшота, построенного на префиксе.
    let full = snap(dir.path());
    let mid = Cursor::at(6);
    let mut merged = gateway::snapshot(dir.path(), EpochFilter::OwnCaptureOnly, &sel(), mid)
        .expect("snapshot(C)");
    let (frames, _cursor) = gateway::frames_since(
        dir.path(),
        EpochFilter::OwnCaptureOnly,
        &sel(),
        mid,
        usize::MAX,
    )
    .expect("frames_since");

    assert!(
        !frames.is_empty(),
        "SETUP НЕ СОСТОЯЛСЯ: дельта пуста — срез покрыл весь журнал, склейка не проверена"
    );
    for f in &frames {
        merged.apply(f);
    }

    assert_eq!(
        merged.series.volume_profile, full.series.volume_profile,
        "V8 НАРУШЕН: склейка снапшота с дельтой разошлась с полным реплеем — \
         сетка применена не на обоих путях"
    );
}

/// **V8-b.** Две сессии: прошлая и текущая. Сетка обязана применяться к КАЖДОЙ строке, а не
/// только к последней.
///
/// Множественность по `testing.md` п.2: реализация, огрубляющая «текущую» строку, зелена на
/// односессионной фикстуре и врёт на суточной границе.
#[test]
fn v8b_every_session_row_is_binned() {
    let base = 77_000 * 100_000_000_i64;
    let events = vec![
        trade(base + 3, 1.0, T - DAY_MS), // прошлая сессия
        trade(base + W + 9, 1.0, T - DAY_MS + 1),
        trade(base + 5, 1.0, T), // текущая
        trade(base + W + 7, 1.0, T + 1),
    ];
    let dir = journal_of(events);
    let s = snap(dir.path());

    assert_eq!(
        s.series.volume_profile.len(),
        2,
        "SETUP НЕ СОСТОЯЛСЯ: ожидались две сессии, получено {}",
        s.series.volume_profile.len()
    );
    for row in &s.series.volume_profile {
        for &(price, _) in &row.bins {
            assert_eq!(
                price % W,
                0,
                "V8-b НАРУШЕН: в сессии {} цена {price} не на сетке — \
                 огрубление применено не ко всем строкам",
                row.session_id
            );
        }
    }
}
