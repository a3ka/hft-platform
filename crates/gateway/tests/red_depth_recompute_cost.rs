//! RED `MD-I-8` `d6a`/`d6b` (sacred, architect-only) — **ЦЕНА ПЕРЕСЧЁТА ПОЛОС.**
//!
//! Милестоун `milestones/M-68-depth-from-book.md` rev3.1. Ресурсный контракт **ПЕРЕПИСАН**
//! по блокеру `C-156` F1 — не подкручен, а заменён, и вот почему.
//!
//! # Что было и почему было неверно (`C-156` F1, вердикт принят целиком)
//!
//! Прежний `d6` требовал `deep <= shallow * 4` при книге глубже в 40 раз, то есть **цена НЕ
//! РАСТЁТ с глубиной книги**. Критик предъявил, что это недостижимо в объявленной зоне:
//! `book::OrderBook::depth_within` считает сумму через `BTreeMap::range(..).sum()`
//! (`crates/book/src/lib.rs:199-212`), то есть обходит уровни полосы; полоса 60 % — это вся
//! книга; `crates/book/src/**` спекой ЗАПРЕЩЁН. Точные суммы полос без обхода уровней в
//! разрешённых путях не получить. Оракул требовал от dev'а выбора между нарушением спеки и
//! фиктивным счётчиком — а «ложное КРАСНОЕ на честной работе опаснее пропуска».
//!
//! Вторая половина находки: прежний `d6` **не проверял собственную метрику**. Содержательных
//! ассертов было два — `a > 0` и `b <= a * 4`; реализация, возвращающая любую постоянную
//! ненулевую величину, красила его зелёным, не посетив ни одного уровня.
//!
//! # Что стало: линейность по книге ЛЕГАЛИЗОВАНА, множитель по ПОЛОСАМ запрещён
//!
//! Риск, названный `C-094` B5 дословно, — «пересчёт всех 7 bands на каждый `L2Delta`
//! потенциально сканирует глубокую книгу **МНОГО РАЗ**». Опасен множитель ×N_полос, а не
//! линейность сама по себе:
//!
//! * **линейность неизбежна** — точная сумма полосы требует обхода её уровней;
//! * **и она дёшева.** Прод-форма: книга ±60 % бакетирована по 0.02 % ⇒ ≤ ~6000 уровней на
//!   сторону; дельты 100 мс ⇒ 10 тактов/с. Один проход = ~12 000 посещений на такт,
//!   ~120 000/с — величина, ничего не решающая. Семь проходов вместо одного — тоже не
//!   катастрофа по абсолютной величине, но это ровно та бесплатная семикратная трата,
//!   которую `C-094` B5 и потребовал не допустить, и она масштабируется вместе с числом
//!   полос при следующем расширении набора.
//!
//! Отсюда ДВА оракула вместо одного, и каждый закрывает свою половину находки:
//!
//! | ID | пиннит | краснеет против |
//! |---|---|---|
//! | `d6a` | **счётчик ЧЕСТЕН** — он действительно считает посещённые уровни: на книге в 40 раз глубже растёт кратно | реализации, возвращающей КОНСТАНТУ (вторая половина `C-156` F1) и счётчика, забытого на нуле |
//! | `d6b` | **цена не множится на число ПОЛОС** — семь полос обходят книгу столько же раз, сколько одна | наивного «на каждой дельте пройти книгу отдельно под каждую полосу» (`C-094` B5) |
//!
//! `d6a` и `d6b` требуют ПРОТИВОПОЛОЖНОГО поведения по двум РАЗНЫМ осям, и это не
//! противоречие, а разведение осей: по глубине книги цена расти обязана (иначе счётчик врёт),
//! по числу полос — не имеет права. Оракул, у которого обе оси спутаны, был первой редакцией.
//!
//! COMPILE-RED: поле `ReadStats::depth_levels_visited` вводится реализацией (задача 8).
//! Счётчик отдаёт САМ API — тот же приём, что `events_scanned` (M-57) и `segment_meta_ops`
//! (M-62). Глобальных счётчиков нет: процессный атомик делает замер зависимым от соседних
//! тестов, и `scripts/check_resource_oracles.sh` его запрещает.

use contracts::{to_fixed, DataSource, EventKind, Level, MdPayload, Venue};
use gateway::{Cursor, Selector};
use journal::{EpochFilter, Journal, WriterConfig};

const MID: f64 = 65_000.0;
const T0: i64 = 1_752_000_000_000;
const FAR_BAND: f64 = 0.60;
const NARROW_OFFSET: f64 = 0.0008;
const NARROW_SIZE: f64 = 300.0;

/// Канонический набор полос (`П-014` п.4) — тот, ради которого `C-094` B5 и поставил вопрос.
const CANONICAL_BANDS: [f64; 7] = [0.015, 0.03, 0.05, 0.08, 0.15, 0.30, FAR_BAND];

/// Столько дельт в КАЖДОМ прогоне — конфаундинг держится константным во всех сравнениях.
const N_DELTAS: i64 = 24;

fn cfg() -> WriterConfig {
    WriterConfig {
        max_segment_bytes: 1 << 20,
        min_free_bytes: 0,
        source: DataSource::OwnCapture,
        provenance: "MD-I-8 d6 depth-recompute-cost fixture".to_string(),
        epoch_id: "own-test".to_string(),
    }
}

fn lvl(price: f64, size: f64) -> Level {
    Level {
        price: to_fixed(price),
        size: to_fixed(size),
    }
}

fn sel(bands: Vec<f64>) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands,
        window_ms: None,
        depth_cadence_ms: None,
    }
}

/// Журнал: снимок книги заданной глубины + `N_DELTAS` дельт СТРОГО ВНУТРИ книги.
///
/// Дельты кладутся на 0.08 % от mid при лучшем уровне на 0.05 % — то есть НЕ трогают лучшие
/// цены. Это условие корректности обоих замеров: сдвиг mid смещает пороги всех полос, и
/// полный пересчёт становится законным; тогда красное сравнение означало бы не наивную
/// реализацию, а честный пересчёт по смещённым порогам (`testing.md`, «Целостность гейта»
/// свойство 2 — конфаундинг держать КОНСТАНТНЫМ).
fn journal_with_book_depth(levels: usize) -> tempfile::TempDir {
    let dir = tempfile::tempdir().expect("tempdir");
    let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
    let bids: Vec<Level> = (0..levels)
        .map(|k| lvl(MID * (1.0 - 0.0005 - 0.001 * k as f64), 1.0))
        .collect();
    let asks: Vec<Level> = (0..levels)
        .map(|k| lvl(MID * (1.0 + 0.0005 + 0.001 * k as f64), 1.0))
        .collect();
    j.append(EventKind::md(
        Venue::Binance,
        "BTCUSDT",
        MdPayload::L2Snapshot {
            bids,
            asks,
            ts_exch_ms: T0,
        },
    ))
    .expect("append snapshot");
    for i in 0..N_DELTAS {
        j.append(EventKind::md(
            Venue::Binance,
            "BTCUSDT",
            MdPayload::L2Delta {
                bids: vec![lvl(MID * (1.0 - NARROW_OFFSET), NARROW_SIZE)],
                asks: vec![lvl(MID * (1.0 + NARROW_OFFSET), NARROW_SIZE)],
                first_update_id: (i as u64) * 2 + 1,
                final_update_id: (i as u64) * 2 + 2,
                prev_final_update_id: if i == 0 { None } else { Some((i as u64) * 2) },
                ts_exch_ms: T0 + i * 100 + 10,
            },
        ))
        .expect("append delta");
    }
    j.flush().expect("flush");
    dir
}

/// Число посещённых уровней при полной свёртке журнала под данным набором полос,
/// плюс лучшие цены — свидетель неподвижности mid.
fn visited(dir: &std::path::Path, bands: Vec<f64>) -> (u64, (i64, i64)) {
    let ckpt = tempfile::tempdir().expect("ckpt tempdir");
    let (snap, stats) = gateway::snapshot_from_checkpoint(
        dir,
        EpochFilter::OwnCaptureOnly,
        &sel(bands),
        ckpt.path(),
        Cursor::LATEST,
    )
    .expect("snapshot_from_checkpoint обязан строиться");
    let best_bid = snap
        .series
        .cob
        .iter()
        .filter(|l| l.side == "bid")
        .map(|l| l.price_e8)
        .max()
        .unwrap_or(0);
    let best_ask = snap
        .series
        .cob
        .iter()
        .filter(|l| l.side == "ask")
        .map(|l| l.price_e8)
        .min()
        .unwrap_or(0);
    (stats.depth_levels_visited, (best_bid, best_ask))
}

/// **`d6a` — СЧЁТЧИК ЧЕСТЕН: он считает уровни, а не возвращает константу.**
///
/// Вторая половина блокера `C-156` F1: прежний оракул принимал любую постоянную ненулевую
/// величину. Здесь книга углубляется в 40 раз при неизменных числе дельт и наборе полос —
/// честный счётчик обязан вырасти кратно. Порог ×5 щедр намеренно: он пропускает любую
/// реализацию, чья цена растёт медленнее линейного (бакетирование, пропуск пустых
/// диапазонов), и ловит ровно две вещи — константу и молчащий ноль.
///
/// Это НЕ бюджет. Это валидация метрики, без которой `d6b` ниже был бы вакуумен: сравнивать
/// две величины имеет смысл только после того, как доказано, что величина что-то измеряет.
#[test]
fn md_i8_d6a_counter_actually_measures_visited_levels() {
    let shallow = journal_with_book_depth(10);
    let deep = journal_with_book_depth(400);

    let (a, mid_shallow) = visited(shallow.path(), CANONICAL_BANDS.to_vec());
    let (b, mid_deep) = visited(deep.path(), CANONICAL_BANDS.to_vec());

    assert!(
        a > 0,
        "MD-I-8 d6a SETUP НЕ СОСТОЯЛСЯ: depth_levels_visited = 0 на мелкой книге — счётчик \
         не наблюдает НИЧЕГО, и оба оракула этого файла вакуумны"
    );
    assert_eq!(
        mid_shallow, mid_deep,
        "MD-I-8 d6a SETUP НЕ СОСТОЯЛСЯ: лучшие цены разошлись ({mid_shallow:?} против \
         {mid_deep:?}) — mid уехал, пороги полос вместе с ним, и сравнение считает не то"
    );
    assert!(
        b >= a * 5,
        "MD-I-8 d6a: книга глубже в 40 раз дала {b} посещённых уровней против {a} на мелкой. \
         Счётчик почти не отреагировал на 40-кратное изменение предмета измерения — значит он \
         не считает посещённые уровни, а возвращает величину, от них не зависящую. Реализация, \
         отдающая КОНСТАНТУ, красила прежний оракул зелёным, ничего не измерив (C-156 F1). \
         Порог ×5 при 40-кратной книге щедр намеренно: он пропускает сублинейные конструкции \
         и ловит ровно константу."
    );
}

/// **`d6b` — ЦЕНА НЕ МНОЖИТСЯ НА ЧИСЛО ПОЛОС.**
///
/// Ровно риск `C-094` B5 («сканирует глубокую книгу МНОГО РАЗ»), и единственная его часть,
/// которая от реализации зависит. Книга и число дельт держатся КОНСТАНТНЫМИ; варьируется
/// ТОЛЬКО состав полос: одна самая широкая против канонических семи, ВКЛЮЧАЮЩИХ ту же самую
/// широкую. Обход, дающий все семь сумм за один проход, посетит столько же уровней; наивный
/// «проход под каждую полосу» — заметно больше.
///
/// # Порог назван арифметикой фикстуры, а не вкусом
///
/// Уровни лежат равномерно до ~40 % от mid при глубине 400. Наивная реализация обойдёт под
/// каждую полосу её долю книги: 0.015→~15, 0.03→~30, 0.05→~50, 0.08→~80, 0.15→~150,
/// 0.30→~300, 0.60→400 уровней, сумма ≈ 1025 против 400 у однопроходной — то есть ≈ ×2.56.
/// Порог ×1.5 лежит между: однопроходная (≈ ×1.0) проходит с запасом, наивная не проходит.
/// Запас в обе стороны назван, а не подразумевается.
///
/// **Чего этот оракул НЕ утверждает:** он не запрещает цене расти с ГЛУБИНОЙ книги. Точная
/// сумма полосы требует обхода её уровней, `crates/book/src/**` предмету запрещён, и
/// требовать постоянной цены значило бы требовать невозможного — блокер `C-156` F1.
#[test]
fn md_i8_d6b_cost_does_not_multiply_by_number_of_bands() {
    let dir = journal_with_book_depth(400);

    let (one, mid_one) = visited(dir.path(), vec![FAR_BAND]);
    let (seven, mid_seven) = visited(dir.path(), CANONICAL_BANDS.to_vec());

    assert!(
        one > 0,
        "MD-I-8 d6b SETUP НЕ СОСТОЯЛСЯ: под ОДНОЙ полосой 60 % посещено 0 уровней — считать \
         нечего, и сравнение ниже вакуумно"
    );
    assert_eq!(
        mid_one, mid_seven,
        "MD-I-8 d6b SETUP НЕ СОСТОЯЛСЯ: лучшие цены разошлись между прогонами \
         ({mid_one:?} против {mid_seven:?}) — варьируется не только состав полос"
    );
    // Самая широкая полоса ОДНА и та же в обоих прогонах: семь полос не могут требовать
    // МЕНЬШЕ работы, чем одна широкая. Ассерт снизу ловит подгонку счётчика под порог сверху.
    assert!(
        seven >= one,
        "MD-I-8 d6b: семь полос (включая ту же 60 %) дали {seven} посещений против {one} у \
         одной 60 % — меньше работы при большем запросе физически невозможно. Счётчик считает \
         не работу, а что-то другое."
    );
    let budget = one + one / 2; // ×1.5
    assert!(
        seven <= budget,
        "MD-I-8 d6b: семь полос дали {seven} посещённых уровней против {one} у одной полосы \
         60 % (бюджет {budget} = ×1.5). Книга и число дельт в обоих прогонах ОДИНАКОВЫ, \
         значит различие вносит только состав полос — это отдельный проход по книге под \
         каждую полосу. Наивная арифметика фикстуры даёт ≈ ×2.56; однопроходная ≈ ×1.0. \
         C-094 B5 дословно: «пересчёт всех 7 bands на каждый L2Delta потенциально сканирует \
         глубокую книгу много раз»."
    );
}
