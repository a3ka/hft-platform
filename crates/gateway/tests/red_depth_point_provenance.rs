//! SACRED (architect-only) — `M-70` `DB-I-4`: **метка достоверности принадлежит ТОЧКЕ, а не
//! ряду.** Закрывает `TD-159` (MAJOR, OPEN), который в `TECH-DEBT.md:100` объявлен блокером
//! `П-014` п.4 дословно: «дыра достижима ровно в момент включения полос».
//!
//! # Что сломано — форма, а не вычисление
//!
//! `DepthRow` несёт РЯД точек и ОДНУ метку на всех:
//!
//! ```text
//! pub struct DepthRow {              // crates/gateway/src/lib.rs:311-321
//!     pub series: Vec<(i64, i64)>,             // (time_s, depth) — МНОГО точек
//!     pub depth_band_provenance: Option<String>,  // ОДНА метка на весь ряд
//! }
//! ```
//!
//! Точки ряда снимаются в РАЗНЫЕ моменты и при РАЗНОМ охвате книги: после старта процесса и
//! после любого sequence-gap книга пересобирается REST-снимком с жёстким
//! `REST_DEPTH_LIMIT = "5000"` (~1.3 % на spot BTCUSDT), а затем дельты достраивают её вглубь
//! до `MAX_REL_DIST = 0.60`. Значит точка из окна ресинка описывает мелкую книгу, а метка
//! ряда — состояние ПОСЛЕДНЕГО наблюдения.
//!
//! Клиент получает ряд, где часть точек снята за пределами наблюдённого охвата, под меткой
//! `liveness=confirmed`. Это ровно `PL-I-7` наоборот: деградация выдана за норму.
//!
//! # Инвариант `DB-I-4`
//!
//! **Две точки одного ряда, снятые при РАЗНОМ охвате стороны, обязаны нести РАЗНЫЕ метки.**
//! Сегодня это невыразимо: место для второй метки в форме отсутствует. Поэтому оракул красен
//! ПО ПОСТРОЕНИЮ и требует смены формы выдачи — то есть задачи 4 и bump'а версии (задача 6).
//!
//! # Различающая сила признака (`Р-4`, `main` `af29452`)
//!
//! Признак: «метки двух точек различаются». Мир, где событие не произошло (метка по-прежнему
//! одна на ряд), этого признака не несёт по построению — различаться нечему.
//!
//! Обязанность (а) — мир ¬P не несёт признака — здесь выполняется КОНСТРУКЦИЕЙ ФОРМЫ, и это
//! названо, а не предположено: пока `depth_band_provenance` есть `Option<String>` на `DepthRow`,
//! двух значений в ряду не существует физически. Страж уникальности значения не нужен;
//! вместо него — страж СОСТОЯТЕЛЬНОСТИ фикстуры (ниже), который отвечает на другой вопрос:
//! действительно ли точки сняты при разном охвате, или сравнивать нечего.
//!
//! # Анти-плацебо: чего оракул НЕ примет
//!
//! 1. **«Пометить весь ряд `not-observed`»** — дешёвый способ позеленеть, обесценивающий
//!    метку: клиент, которому всё «не наблюдалось», не знает ничего. Ловится
//!    `db_i_4b_reachable_point_is_not_falsely_downgraded`.
//! 2. **«Метка на точку, но копирующая последнюю»** — форма сменена, смысл прежний. Ловится
//!    основным тестом: он требует РАЗЛИЧИЯ, а не наличия поля.
//! 3. **Вырожденная фикстура**, где охват на самом деле не менялся: тогда «метки одинаковы»
//!    истинно при ЛЮБОЙ реализации. Ловится стражем состоятельности.

use contracts::{to_fixed, DataSource, EventKind, Level, MdPayload, Venue};
use gateway::{Cursor, DepthRow, Selector};
use journal::{EpochFilter, Journal, WriterConfig};

const MID: f64 = 65_000.0;
const T0: i64 = 1_752_000_010_000;

/// Полоса ГЛУБЖЕ 1.3 % — только такие несут метку (`VB-I-5`: ≤1.3 % — валидированный эталон).
const DEEP_BAND: f64 = 0.03;
/// Узкий охват окна ресинка: REST отдаёт ~1.3 % на spot BTCUSDT (`depth-probe-binance.md:15-18`).
/// Он МЕНЬШЕ полосы 3 % — значит точка этого момента полосой не наблюдена.
const REACH_RESYNC: f64 = 0.013;
/// Установившийся охват: дельты достроили книгу вглубь. БОЛЬШЕ полосы 3 %.
const REACH_SETTLED: f64 = 0.05;

fn cfg() -> WriterConfig {
    WriterConfig {
        max_segment_bytes: 1 << 20,
        min_free_bytes: 0,
        source: DataSource::OwnCapture,
        provenance: "M-70 DB-I-4 point provenance".to_string(),
        epoch_id: "own-test".to_string(),
    }
}

fn lvls(v: &[(f64, f64)]) -> Vec<Level> {
    v.iter()
        .map(|&(p, s)| Level {
            price: to_fixed(p),
            size: to_fixed(s),
        })
        .collect()
}

/// Снимок книги, достающий до `reach_pct` по обеим сторонам, в бакете `ts`.
fn book_at(reach_pct: f64, ts: i64) -> EventKind {
    let mut bids = vec![(MID - 1.0, 5.0)];
    let mut asks = vec![(MID + 1.0, 5.0)];
    for k in [0.5_f64, 1.0_f64] {
        bids.push((MID * (1.0 - reach_pct * k), 1.0));
        asks.push((MID * (1.0 + reach_pct * k), 1.0));
    }
    EventKind::md(
        Venue::Binance,
        "BTCUSDT",
        MdPayload::L2Snapshot {
            bids: lvls(&bids),
            asks: lvls(&asks),
            ts_exch_ms: ts,
        },
    )
}

fn journal_of(events: Vec<EventKind>) -> tempfile::TempDir {
    let dir = tempfile::tempdir().expect("tempdir");
    let mut j = Journal::open_with(dir.path(), cfg()).expect("open_with");
    for e in events {
        j.append(e).expect("append");
    }
    j.flush().expect("flush");
    dir
}

fn sel() -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands: vec![DEEP_BAND],
        window_ms: None,
        depth_cadence_ms: None,
    }
}

/// Журнал ДВУХ бакетов: первый снят при охвате окна ресинка, второй — при установившемся.
/// Это прод-форма перехода, а не выдумка: `docs/fa/viz-backend.md` §4 описывает ровно её.
fn journal_reach_changes() -> tempfile::TempDir {
    journal_of(vec![
        book_at(REACH_RESYNC, T0),
        book_at(REACH_SETTLED, T0 + 1_000),
    ])
}

fn snap(dir: &std::path::Path) -> gateway::Snapshot {
    gateway::snapshot(dir, EpochFilter::OwnCaptureOnly, &sel(), Cursor::LATEST)
        .expect("SETUP: снимок обязан строиться")
}

fn deep_row(s: &gateway::Snapshot, side: &str) -> DepthRow {
    s.series
        .depth_series
        .iter()
        .find(|r| r.side == side && r.band_pct_e8 == to_fixed(DEEP_BAND))
        .unwrap_or_else(|| {
            panic!(
                "SETUP НЕ СОСТОЯЛСЯ: в выдаче нет строки {side} на полосе {DEEP_BAND}. \
                 Строк всего: {}",
                s.series.depth_series.len()
            )
        })
        .clone()
}

/// **СТРАЖ СОСТОЯТЕЛЬНОСТИ ФИКСТУРЫ.** Признак оракула — «метки точек различаются». Если бы
/// охват на деле не менялся, различия не требовалось бы, и «метки одинаковы» было бы истинно
/// при ЛЮБОЙ реализации — оракул зеленел бы ни о чём.
///
/// Страж считает по КОНСТАНТАМ фикстуры, а не по выдаче gateway: спрашивать у проверяемого,
/// состоятельна ли проверка, — та же ошибка, что признак без различающей силы.
fn assert_fixture_actually_changes_reach() {
    // Проверка вынесена в КОМПАЙЛ-ТАЙМ намеренно: обе величины — константы этого файла, и
    // правка, разъезжающая фикстуру с полосой, обязана НЕ СОБРАТЬСЯ, а не упасть в прогоне.
    // Рантайм-`assert!` здесь вдобавок отвергается clippy (`assertions_on_constants`) — тот
    // случай, когда диагностический шум указывает на верную конструкцию. Функция сохранена
    // как ТОЧКА ВЫЗОВА: она называет предмет в теле каждого теста и переживёт переход
    // фикстуры на вычисляемые величины.
}

const _: () = assert!(
    REACH_RESYNC < DEEP_BAND,
    "SETUP: охват окна ресинка обязан быть МЕНЬШЕ полосы — иначе первая точка наблюдена, и \
     различать метки было бы нечего"
);
const _: () = assert!(
    REACH_SETTLED > DEEP_BAND,
    "SETUP: установившийся охват обязан быть БОЛЬШЕ полосы — иначе вторая точка тоже не \
     наблюдена, и обе метки законно совпали бы"
);

// ═══════════════════════════════════════════════════════════════════════════════════════════
// DB-I-4 — ПРЕДМЕТ: две точки одного ряда, снятые при разном охвате, несут РАЗНЫЕ метки
// ═══════════════════════════════════════════════════════════════════════════════════════════

#[test]
fn db_i_4_two_points_of_one_row_carry_their_own_provenance() {
    assert_fixture_actually_changes_reach();

    let dir = journal_reach_changes();
    let s = snap(dir.path());
    let row = deep_row(&s, "bid");

    assert!(
        row.series.len() >= 2,
        "SETUP НЕ СОСТОЯЛСЯ: в ряду {} точек, а предмет требует ДВУХ — снятой в окне ресинка \
         и снятой в установившемся режиме. Фикстура не дала двух бакетов",
        row.series.len()
    );

    // ЗДЕСЬ ОРАКУЛ КРАСЕН ПО ПОСТРОЕНИЮ. `DepthRow` несёт ОДНУ метку на весь ряд
    // (`lib.rs:320`), поэтому у точек нет собственных меток — их негде взять. Требование
    // теста и есть требование СМЕНЫ ФОРМЫ: метка обязана принадлежать точке.
    //
    // Форма после задачи 4 объявляется dev'ом в рамках `T-designate` (`05-contract-layer.md`
    // §2, аддитивно, без contract-RFC) и обязана дать доступ к метке КАЖДОЙ точки. Оракул
    // намеренно не диктует имя поля: он диктует НАБЛЮДАЕМОСТЬ.
    let per_point: Vec<Option<String>> = point_provenances(&row);

    assert_eq!(
        per_point.len(),
        row.series.len(),
        "DB-I-4 НАРУШЕН: меток {} на {} точек. TD-159 в чистом виде: одна метка описывает ряд \
         точек РАЗНОГО качества. Точка из окна ресинка (охват {REACH_RESYNC} < полосы \
         {DEEP_BAND}) не наблюдалась вовсе, а несёт метку последнего наблюдения",
        per_point.len(),
        row.series.len()
    );

    let first = per_point.first().cloned().flatten();
    let last = per_point.last().cloned().flatten();
    assert_ne!(
        first, last,
        "DB-I-4 НАРУШЕН: метки первой и последней точки СОВПАДАЮТ ({first:?}), хотя первая \
         снята при охвате {REACH_RESYNC} (полоса {DEEP_BAND} НЕ наблюдена ⇒ ожидается \
         `not-observed`), а последняя — при {REACH_SETTLED} (наблюдена ⇒ ожидается \
         `liveness=`). Это либо метка на ряд, либо метка на точку, КОПИРУЮЩАЯ последнюю — \
         второе проходит проверку «поле есть» и потому проверяется различием, а не наличием"
    );
    assert!(
        first
            .as_deref()
            .is_some_and(|m| m.starts_with("not-observed")),
        "DB-I-4 НАРУШЕН: точка окна ресинка обязана нести `not-observed…`, а несёт {first:?}. \
         Полоса {DEEP_BAND} лежит ЗА охватом {REACH_RESYNC}: число этой точки не наблюдалось, \
         и ставить на него liveness — утверждать о наблюдении, которого не было"
    );
}

/// АНТИ-ПЛАЦЕБО: «пометить весь ряд `not-observed`» проходит основной тест, если тот требует
/// лишь различия по краям. Здесь наблюдённая точка обязана НЕ БЫТЬ понижена.
#[test]
fn db_i_4b_reachable_point_is_not_falsely_downgraded() {
    assert_fixture_actually_changes_reach();

    let dir = journal_reach_changes();
    let s = snap(dir.path());
    let row = deep_row(&s, "bid");
    let per_point = point_provenances(&row);
    let last = per_point.last().cloned().flatten();

    assert!(
        last.as_deref().is_some_and(|m| m.contains("liveness=")),
        "DB-I-4b НАРУШЕН: последняя точка снята при охвате {REACH_SETTLED} — полоса \
         {DEEP_BAND} наблюдена, и метка обязана нести `liveness=`. Получено {last:?}. \
         Реализация, метящая `not-observed` ВСЁ подряд, удовлетворяет основной тест и \
         обесценивает метку: клиент, которому всё «не наблюдалось», не знает ничего"
    );
}

/// Доступ к метке КАЖДОЙ точки ряда.
///
/// **Сегодня функция возвращает ОДНУ метку на весь ряд** — потому что взять больше неоткуда:
/// `DepthRow.depth_band_provenance` есть `Option<String>` на строку (`lib.rs:320`). Именно
/// это и делает оракул красным, и именно это чинит задача 4.
///
/// Функция живёт в тесте намеренно: она — АДАПТЕР к форме выдачи, и когда форма сменится,
/// правится ровно одно место, а смысл обоих тестов остаётся нетронутым.
///
/// **ФОРМА СМЕНИЛАСЬ (задача 4, `M-70` §2bis), адаптер обновлён (задача 4b).** Раньше здесь
/// стояло `vec![row.depth_band_provenance.clone()]` — «взять больше неоткуда», потому что
/// метка была ОДНА на строку. Теперь каждая точка несёт свою: возвращаем метку КАЖДОЙ.
/// Смысл обоих сценариев не тронут — они по-прежнему требуют РАЗЛИЧИЯ меток у точек,
/// снятых при разном охвате, и запрещают поголовное `not-observed`.
fn point_provenances(row: &DepthRow) -> Vec<Option<String>> {
    row.series_provenance.clone()
}

/// `DB-I-4c` — ЦЕНА АДДИТИВНОЙ ФОРМЫ, названная спекой §2bis.-1 и сторожимая здесь.
///
/// Прежняя форма (`Vec<DepthPoint>`) делала рассинхрон длин НЕВЫРАЗИМЫМ, но ломала `VB-I-4`:
/// v1-потребитель, читающий `series: Vec<(i64, i64)>`, переставал разбирать выдачу
/// (`R-171` Б-1, замер: `Error("trailing characters")`). Аддитивная форма инвариант `VB-I-4`
/// сохраняет и ВОЗВРАЩАЕТ выразимость рассинхрона — значит рассинхрон обязан сторожиться.
///
/// **Что ловит:** реализацию, наполняющую два массива ПОРОЗНЬ — например пишущую точку и
/// забывающую метку, или обрезающую один массив эвикцией окна, а второй нет. Такой ответ
/// внешне валиден: `series` полон, метки «есть». Клиент при этом сопоставит метку i-й точки
/// с ДРУГОЙ точкой — тихая ложь класса `PL-I-7`, худшая, чем отсутствие метки.
///
/// **Различающая сила (`Р-4`):** признак — равенство длин. Мир, где массивы наполняются
/// порознь, его не несёт: длины разойдутся на первом же расхождении путей. Признак
/// недоступен ¬P по построению, а не по совпадению.
/// Селектор с ОГРАНИЧЕННЫМ окном — тот, при котором прод исполняет ЭВИКЦИЮ (`VB-I-10`:
/// память удерживается окном `[at−W, at]`). `sel()` с `window_ms: None` — offline-режим, и
/// путь эвикции на нём НЕ РАБОТАЕТ ВООБЩЕ.
fn sel_windowed(window_ms: i64) -> Selector {
    Selector {
        venue: Venue::Binance,
        symbol: "BTCUSDT".to_string(),
        timeframe_ms: 1_000,
        bands: vec![DEEP_BAND],
        window_ms: Some(window_ms),
        depth_cadence_ms: None,
    }
}

/// `DB-I-4d` — СВЯЗКА «точка ↔ её метка» ПЕРЕЖИВАЕТ склейку и эвикцию. Закрывает `R-172` Б-1.
///
/// # Почему сторожить ДЛИНЫ на этом пути БЕСПОЛЕЗНО — установлено замером, а не рассуждением
///
/// Ревьюер предъявил, что `DB-I-4c` не сторожит путь эвикции: мутация «резать массивы
/// порознь» оставляла набор зелёным. Я написал сценарий на длины после склейки — и он тоже
/// остался зелёным против той же мутации. Инструментирование показало причину:
///
/// ```text
/// DEBUG кадр: at_ms=1752000012000 lo=Some(1752000011) depth_rows_в_кадре=2 точек_до_apply=[2, 2]
/// DEBUG после apply: точек=[2, 2] меток=[2, 2]     ← при ЖИВОЙ мутации
/// ```
///
/// **`zip` в merge-пути (`lib.rs:1990-2000`) МОЛЧА УСЕКАЕТ по кратчайшему.** Эвикция,
/// прошедшая массивы порознь, оставляет 1 точку и 2 метки — но следующий же merge сшивает их
/// `zip`'ом, отбрасывая лишнюю метку. Длины СРАВНИВАЮТСЯ РАВНЫМИ, а метка при этом уехала на
/// чужую точку либо пропала вместе со своей. То есть длина — признак, который код
/// САМОВОССТАНАВЛИВАЕТ, разрушая данные: сторожить его бессмысленно по построению.
///
/// Это ровно `R-172` Н-4 («zip усекает молча, теряет точки вместо отказа»), и он оказался не
/// наблюдением на полях, а причиной слепоты предложенного стража.
///
/// # Что сторожится вместо длин
///
/// СВЯЗКА: для каждой строки набор троек `(time_s, depth_e8, provenance)`, собранный клиентом
/// через `snapshot(C) + frames`, обязан совпасть с полным реплеем того же окна. Это `VB-I-2`
/// в применении к метке: живое и перепроигранное равны. Мир, где любой шаг прошёл массивы
/// порознь, признака не несёт — `zip` выровняет длины, но пары разъедутся, и сравнение с
/// реплеем это увидит.
///
/// # Различающая сила (`Р-4`)
///
/// Признак — совпадение ТРОЕК, а не количеств. Мир ¬P (шаг порознь) даёт другую тройку на
/// той же позиции: метка соседней точки либо `None` там, где реплей даёт метку. Ни одно из
/// этих различий не «чинится» усечением.
#[test]
fn db_i_4d_point_to_label_binding_survives_merge_and_eviction() {
    assert_fixture_actually_changes_reach();
    let dir = journal_of(vec![
        book_at(REACH_RESYNC, T0),
        book_at(REACH_SETTLED, T0 + 1_000),
        book_at(REACH_SETTLED, T0 + 2_000),
    ]);

    let sel_w = sel_windowed(1_000);
    let at_c = Cursor { upto_seq: Some(1) };

    // Клиентская сборка: снимок на курсоре C + кадры (C..LATEST].
    let mut merged = gateway::snapshot(dir.path(), EpochFilter::OwnCaptureOnly, &sel_w, at_c)
        .expect("SETUP: снимок на курсоре C");
    let (frames, _to) = gateway::frames_since(
        dir.path(),
        EpochFilter::OwnCaptureOnly,
        &sel_w,
        at_c,
        usize::MAX,
    )
    .expect("SETUP: кадры после C");
    assert!(
        !frames.is_empty(),
        "SETUP НЕ СОСТОЯЛСЯ: кадров после курсора C нет — путь склейки не исполнен, и \
         сценарий судил бы `snapshot`, где массивы рождаются одним проходом"
    );
    for f in &frames {
        merged.apply(f);
    }

    // Эталон: полный реплей того же окна.
    let full = gateway::snapshot(
        dir.path(),
        EpochFilter::OwnCaptureOnly,
        &sel_w,
        Cursor::LATEST,
    )
    .expect("SETUP: полный реплей");

    // SETUP-СТРАЖ: эталон непуст и МНОГОТОЧЕЧЕН — на одной точке рассинхрон ненаблюдаем.
    let full_pts: usize = full
        .series
        .depth_series
        .iter()
        .map(|r| r.series.len())
        .sum();
    assert!(
        full_pts >= 2,
        "SETUP НЕ СОСТОЯЛСЯ: эталон несёт {full_pts} точек. Связка «точка ↔ метка» на одной \
         точке не проверяется: любая перестановка тождественна"
    );

    let triples = |sn: &gateway::Snapshot| -> Vec<(String, i64, Vec<(i64, i64, Option<String>)>)> {
        sn.series
            .depth_series
            .iter()
            .map(|r| {
                (
                    r.side.clone(),
                    r.band_pct_e8,
                    r.series
                        .iter()
                        .zip(r.series_provenance.iter())
                        .map(|((t, v), p)| (*t, *v, p.clone()))
                        .collect(),
                )
            })
            .collect()
    };

    assert_eq!(
        triples(&merged),
        triples(&full),
        "DB-I-4d НАРУШЕН: связка «точка ↔ её метка» не пережила склейку и эвикцию. Клиент, \
         собравший состояние из `snapshot(C) + frames`, получил ДРУГИЕ пары, чем полный \
         реплей того же окна (`VB-I-2`). Длины при этом могут совпадать: `zip` в merge-пути \
         усекает молча (`R-172` Н-4) и ВЫРАВНИВАЕТ их, уводя метку на чужую точку — именно \
         поэтому сторожится СВЯЗКА, а не количество"
    );
}

