//! `DV-I-16` — жизнь, завершённая ДО атрибуции, не теряется (M-59, находка `R-038` F-2).
//!
//! ЗАЧЕМ. Фикс `TD-107` заменил накопление `Vec` инкрементом агрегатов — и на пути
//! «рождение → отмена → рождение той же цены ДО того, как полоса определена» стал терять
//! завершённую жизнь бесследно. Механизм: `depth_lifetime.rs:249` возвращает старое
//! `LevelState` в `states` для последующей атрибуции, а `:252` **безусловно затирает его**
//! новорождённым в том же вздохе. `bump_finished_fate` для потерянной жизни не случается
//! никогда.
//!
//! ПОЧЕМУ ЭТОГО НЕ ПОЙМАЛ НИ ОДИН СУЩЕСТВУЮЩИЙ ОРАКУЛ — и почему это опаснее обычного бага.
//! Баланс `lives_born == cancelled + frozen + censored` ОСТАЁТСЯ ВЕРНЫМ: падают оба
//! слагаемых сразу (замер `R-038`: 4/1 → 3/0). Поэтому `DV-I-1..14`, стерегущие баланс, не
//! краснеют. Тихо смещается ровно одна величина — `cancel_fraction`, и смещается ВНИЗ. Это
//! метрика под подписанным решением founder'а (`П-011`), то есть цена ошибки здесь не
//! инженерная, а решенческая: занижение доли отмен меняет вывод о живости полос.
//!
//! ДЕГРАДИРОВАННЫЙ ВХОД — пункт 2 нашего же чек-листа (`testing.md`): «несколько ЖИЗНЕЙ
//! одной сущности». Пункт существовал, был процитирован в шапке милестоуна — и не применён
//! к фикстуре. `DV-I-15` засевает обе стороны на первом тике, поэтому путь «до атрибуции»
//! в нём не возникает вовсе: та же слепота, что породила сам `TD-107` (`DV-I-7` не ловил
//! дефект, потому что в его фикстуре `finished` был пуст).
//!
//! ЧТО ЭТОТ ОРАКУЛ ПАДАЕТ ПРОТИВ: реализации, которая теряет завершённую жизнь при
//! перерождении цены до атрибуции. Он НЕ проверяет баланс — баланс тут верен и у
//! сломанного кода; он проверяет ЧИСЛА, которые баланс скрывает.

use contracts::{Level, Side};
use research_cli::depth_lifetime::{analyze, DeltaTick};

const UNIT: i64 = 100_000_000;
const MID: i64 = 64_000 * UNIT;
const FAR_PCT: f64 = 0.06;
const FAR_LO_BPS: i64 = 500;

fn lvl_at(mid_ref: i64, pct: f64, side: Side, size_units: i64) -> Level {
    let price = match side {
        Side::Buy => mid_ref as f64 * (1.0 - pct),
        Side::Sell => mid_ref as f64 * (1.0 + pct),
    };
    Level {
        price: price as i64,
        size: size_units * UNIT,
    }
}

fn lvl(pct: f64, side: Side, size_units: i64) -> Level {
    lvl_at(MID, pct, side, size_units)
}

fn tick(u: u64, bids: Vec<Level>, asks: Vec<Level>) -> DeltaTick {
    DeltaTick {
        bids,
        asks,
        first_update_id: u,
        final_update_id: u,
        prev_final_update_id: None,
        ts_exch_ms: 1_700_000_000_000,
    }
}

#[test]
fn dv_i_16_life_completed_before_attribution_is_counted() {
    // Тик 1 — ТОЛЬКО bid-якорь: mid ещё не определён (нет ask), поэтому полоса дальней
    // цены неизвестна и её жизни попадают в очередь «неатрибутированных». Именно этот
    // путь и теряет жизнь.
    //
    // Тик 2 — ТРИ обновления ОДНОЙ И ТОЙ ЖЕ цены подряд: рождение → отмена → рождение.
    // Это «несколько жизней одной сущности» из чек-листа: наивная реализация считает
    // «одну», затирая завершённую новорождённой.
    let ticks = vec![
        tick(1, vec![lvl_at(MID, 0.001, Side::Buy, 10)], vec![]),
        tick(
            2,
            vec![
                lvl(FAR_PCT, Side::Buy, 5), // жизнь 1 рождается
                lvl(FAR_PCT, Side::Buy, 0), // жизнь 1 ОТМЕНЕНА (до атрибуции)
                lvl(FAR_PCT, Side::Buy, 7), // жизнь 2 рождается на той же цене
            ],
            vec![],
        ),
        // Тик 3 — появляется ask: mid определяется, очередь атрибутируется.
        tick(3, vec![], vec![lvl_at(MID, 0.001, Side::Sell, 10)]),
    ];

    let rep = analyze(&ticks);
    let b = rep
        .band(Side::Buy, FAR_LO_BPS)
        .expect("полоса [500,800) bid обязана быть в отчёте");

    eprintln!(
        "DV-I-16: born={} cancelled={} frozen={} censored={} cancel_fraction={:?}",
        b.lives_born,
        b.lives_cancelled,
        b.lives_frozen,
        b.lives_censored,
        b.cancel_fraction()
    );

    // Две жизни на одной цене: первая ОТМЕНЕНА, вторая дожила до конца окна.
    assert_eq!(
        b.lives_born, 2,
        "DV-I-16: цена прожила ДВЕ жизни (рождение → отмена → рождение), учтено {}. \
         Завершённая до атрибуции жизнь затёрта новорождённой и потеряна бесследно \
         (depth_lifetime.rs: старое состояние возвращается в states и тут же \
         перезаписывается)",
        b.lives_born
    );
    assert_eq!(
        b.lives_cancelled, 1,
        "DV-I-16: отмена ДО атрибуции не учтена (cancelled={}). Баланс при этом остаётся \
         верным — падают оба слагаемых, — поэтому DV-I-1..14 молчат. Смещается ровно \
         cancel_fraction, и смещается ВНИЗ: метрика под founder-решением П-011",
        b.lives_cancelled
    );

    // Баланс проверяем ПОСЛЕДНИМ и отдельно: он верен и у сломанного кода, поэтому
    // ассерт на него ничего не доказывает — но его поломка означала бы новый дефект.
    assert_eq!(
        b.lives_born,
        b.lives_cancelled + b.lives_frozen + b.lives_censored,
        "баланс жизней нарушен"
    );
}
