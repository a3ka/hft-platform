#!/usr/bin/env bash
# Механический барьер M-61 — номер артефакта выдаётся механизмом, а не памятью (`TD-111`).
#
# ИНВАРИАНТ ОТ РЕЗУЛЬТАТА И ОТ ДИАПАЗОНА (`milestones/M-61-artifact-ids.md` §4.1):
#   ни один коммит проверяемого диапазона не вводит номер, обозначающий ВТОРОЙ ПРЕДМЕТ —
#   ни созданием артефакта, ни переименованием, ни записью в `TECH-DEBT.md`; «второй»
#   считается относительно объединения `refs/remotes/origin/*` и `refs/heads/*`,
#   независимо от того, в каком дереве номер был выдан и в каком классе артефакта живёт.
#
# ПОЧЕМУ ДИАПАЗОН, А НЕ ВСЯ ИСТОРИЯ (`C-069` F-1): семь коллизий уже существуют (§1
# спеки) и переименованию не подлежат. Абсолютный инвариант дал бы барьер, КРАСНЫЙ
# НАВСЕГДА, либо grandfather-список — то есть «мешок случаев», запрещённый `A-005` §2
# поправка 1. Диапазонная формулировка снимает обе беды: предсуществующая коллизия в
# диапазон не попадает и легитимна, а ТРЕТИЙ файл под `R-038` попадает и краснеет.
# Проводка та же, что у соседнего работающего барьера `check_protected_artifacts.sh`:
# база берётся ИЗ СОБЫТИЯ, недостоверная база → fail-closed.
#
# SUBJECT_ID — нормализованный идентификатор ПРЕДМЕТА (спека §3.1). Два артефакта с одним
# номером законны ⟺ их `subject_id` совпал. Порядок правил, первое сработавшее побеждает:
#   1. носитель предмета в шапке — первый путь в обратных кавычках внутри блока,
#      начатого `**Предмет:**` или `**Контекст**`/`**Контекст.**`; блок продолжается до
#      первой пустой строки, путь на строке-продолжении засчитывается;
#   2. для `TD` — слаг из записи `- **TD-NNN** 'slug'` в `TECH-DEBT.md`;
#   3. milestone с буквенным суффиксом — семья без буквы, но суффикс сам по себе НЕ
#      доказательство: для артефакта, появляющегося В ДИАПАЗОНЕ, требуется ещё и совпавший
#      предмет по правилу 1 (ссылка на зонт семьи либо тот же `Предмет`); без этого новый
#      `M-38c` о постороннем предмете заверял бы сам себя одной буквой;
#   4. слаг имени: часть после `<PREFIX>-<NNN>-` до `.md`, без суффиксов `-rev<N>` /
#      `-addendum*`;
#   5. слага нет вовсе — sentinel `<без-слага>`, который УЧАСТВУЕТ в сравнении, а не
#      пропускается (`C-070` F-1: `C-024.md` и `C-024-M-28.md` — РАЗНЫЕ предметы).

set -uo pipefail
ZERO=0000000000000000000000000000000000000000
CLASS_RE='^(milestones/M|research/reviews/R|research/critiques/C|research/arbitration/A)-[0-9]+'

# ─── Страж базы ────────────────────────────────────────────────────────────────────
# Тот же fail-closed паттерн, что в `check_protected_artifacts.sh` (блокер B1):
# пустое событие / zero-SHA (создание ветки, force-push) / база не предок HEAD ⇒
# «занятость перечислить нельзя» ⇒ отказ. Символическая ветка на push подменяет
# `origin/main` на ТОЛЬКО ЧТО запушенный коммит, делая диапазон пустым и гейт ложным.
die() { echo "FAIL  $*"; echo; echo "Барьер fail-closed: база сравнения не установлена достоверно."; exit 1; }

raw=""
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}";;
    pull_request) raw="${PR_BASE_SHA:-}";;
    "")           die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI";;
    *)            die "неизвестное событие '${EVENT_NAME}' — база сравнения не определена";;
  esac
fi
[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?})"
case "${raw}" in
  *[!0]*) : ;;
  *)      die "база = zero-SHA (создание ветки или force-push) — занятость не доказуема";;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || die "база '${raw}' отсутствует в истории (переписана force-push'ем / поверхностный клон)"
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || die "база '${raw}' НЕ предок HEAD — история переписана; что появилось, недоказуемо"
BASE="$(git rev-parse "${raw}^{commit}")"

# ─── Класс и номер из пути ──────────────────────────────────────────────────────────
# Буквенный суффикс milestone'а (M-80a) отбрасывается: семья определяется числом, а
# законность дробления решает ПРЕДМЕТ (правило 3 выше), а не буква.
cls_num() {
  case "$1" in
    milestones/M-*)            printf 'M %s\n' "$(basename "$1" | sed -E 's/^M-0*([0-9]+).*/\1/')";;
    research/reviews/R-*)      printf 'R %s\n' "$(basename "$1" | sed -E 's/^R-0*([0-9]+).*/\1/')";;
    research/critiques/C-*)    printf 'C %s\n' "$(basename "$1" | sed -E 's/^C-0*([0-9]+).*/\1/')";;
    research/arbitration/A-*)  printf 'A %s\n' "$(basename "$1" | sed -E 's/^A-0*([0-9]+).*/\1/')";;
    *) return 1;;
  esac
}

# ─── Нормализация слага имени ──────────────────────────────────────────────────────
# Имя файла без префикса класса и номера; `-rev<N>` и `-addendum*` отбрасываются (правило 4).
# Если слага нет (slugless), возвращается пустая строка — вызывающий обязан подставить
# sentinel `<без-слага>`, и это ДРУГОЙ предмет, чем слаг (правило 5).
slug_of() {
  basename "$1" .md | sed -E 's/^(M|R|C|A)-[0-9]+[a-z]?-?//; s/-rev[0-9]+$//; s/-addendum.*$//'
}

# ─── subject_id: носитель предмета (правила 1, 4, 5) ──────────────────────────────
# $1 = "rev:path" (для ref'ов) или "commit:path" (для коммитов).
# Возвращает строку-идентификатор предмета: header-путь из блока «Предмет»/«Контекст», либо
# нормализованный слаг, либо sentinel `<без-слага>`.
subject_of() {
  local body hdr s
  body="$(git show "$1" 2>/dev/null)" || return 1
  # Правило 1: первый backtick-путь в блоке, начатом `**Предмет:**` или `**Контекст**` /
  # `**Контекст.**`; блок продолжается до первой пустой строки — путь на строке-продолжении
  # засчитывается (`C-058-addendum-critic2.md` берёт предмет со ВТОРОЙ строки блока).
  hdr="$(printf '%s\n' "$body" \
          | awk '/^\*\*(Предмет:|Контекст)/{f=1} f{print} f&&/^$/{exit}' \
          | grep -oE '`[^`]+`' | head -1 | tr -d '`')"
  if [ -n "${hdr}" ]; then printf '%s\n' "${hdr}"; return 0; fi
  # Правила 4 + 5: слаг имени, sentinel для slugless.
  s="$(slug_of "${1#*:}")"
  [ -z "${s}" ] && s='<без-слага>'
  printf '%s\n' "${s}"
}

# ─── Источник занятости ────────────────────────────────────────────────────────────
# Объединение `refs/remotes/origin/*` ∪ `refs/heads/*` — спека §3.1. Число в (классе, номере)
# считается по файлам ref'ов; `TD` — по записям `TECH-DEBT.md` каждого ref'а.
refs_all() { git for-each-ref --format='%(refname)' refs/remotes/origin refs/heads 2>/dev/null; }

# Печатает строки `<КЛАСС> <НОМЕР> <SUBJECT>` для КАЖДОГО артефакта объединения ref'ов,
# плюс строки `<TD> <НОМЕР> <СЛАГ>` для записей `TECH-DEBT.md` каждого ref'а. Сортируется
# по (класс, номер) для детерминированной выдачи.
universe() {
  local ref f cn
  for ref in $(refs_all); do
    while IFS= read -r f; do
      # `git ls-tree` не цитирует имена, но `git show --name-only` оборачивает в `"…"` файлы
      # с не-ASCII (`git show` применяет C-quoting). Тривиальный `tr` снимает обёртку до
      # матча CLASS_RE; внутри файла кавычек не бывает (git так не квотит).
      f="${f%\"}"
      f="${f#\"}"
      [[ "${f}" =~ ${CLASS_RE} ]] || continue
      cn="$(cls_num "${f}")" || continue
      printf '%s %s\n' "${cn}" "$(subject_of "${ref}:${f}")"
    done < <(git ls-tree -r --name-only "${ref}" 2>/dev/null)
  done
  for ref in $(refs_all); do
    git show "${ref}:TECH-DEBT.md" 2>/dev/null \
      | sed -nE 's/^- \*\*TD-0*([0-9]+)\*\* `([^`]+)`.*/TD \1 \2/p'
  done
}

# Что ВВЕДЕНО диапазоном. `--no-renames` показывает переименование как пару `D old` + `A
# new` — добавление в занятый номер (ось 4 «переименование в занятый номер») ловится по
# новому имени. `-M` отключает rename detection в `--name-only`, и это сознательно: `git
# show --cc --name-only --no-renames --diff-filter=AM --format= …` выдаёт имена файлов в
# коммите в форме `Added/Modified`, а не в форме `R old new`, что упрощает сравнение.
introduced() {
  local c f cn
  for c in $(git rev-list "${BASE}..HEAD"); do
    while IFS= read -r f; do
      # см. примечание в `universe` — C-quoting у `git show --name-only`.
      f="${f%\"}"
      f="${f#\"}"
      [[ "${f}" =~ ${CLASS_RE} ]] || continue
      cn="$(cls_num "${f}")" || continue
      printf '%s %s\n' "${cn}" "$(subject_of "${c}:${f}")"
    done < <(git show --cc --name-only --no-renames --diff-filter=AM --format= "${c}" 2>/dev/null)
    # Новые записи `TECH-DEBT.md` (ось 2 + 4, носитель «запись», способ «новая запись»):
    # фильтр `^\+` оставляет только добавленные строки диффа.
    git show "${c}" -- TECH-DEBT.md 2>/dev/null \
      | sed -nE 's/^\+- \*\*TD-0*([0-9]+)\*\* `([^`]+)`.*/TD \1 \2/p'
  done
}

U="$(universe | sort -u)"
IN="$(introduced | sort -u)"
[ -z "${IN}" ] && { echo "OK: проверяемый диапазон ${BASE:0:7}..HEAD не вводит ни одного нового артефакта"; exit 0; }

# ─── Суждение: каждое ВВЕДЁННОЕ занято под тот же (класс, номер), но другим предметом? ─
violations=0
while read -r cls num subj; do
  [ -z "${cls:-}" ] && continue
  # Один и тот же subject не нарушение; разный subject под одним (класс, номер) — нарушение.
  if printf '%s\n' "${U}" | awk -v c="${cls}" -v n="${num}" -v s="${subj}" \
      '$1==c && $2==n && $3!=s {found=1} END{exit !found}'; then
    echo "FAIL  ${cls}-${num}: введён предмет '${subj}', но (${cls}, ${num}) уже занят ДРУГИМ предметом в объединении ref'ов"
    echo "      (предсуществующая коллизия вне диапазона легитимна; ЭТОТ — в диапазоне ⇒ §4.1)"
    violations=$((violations + 1))
  fi
done <<< "${IN}"

if [ "${violations}" -gt 0 ]; then
  echo
  echo "Артефакты гейтов — аудит-трейл. FAIL почти всегда означает:"
  echo "  • номер занят в соседней ветке — сверься с scripts/next_artifact_id.sh;"
  echo "  • дробление семьи без совпавшего предмета в шапке (правило 3)."
  exit 1
fi

echo "OK: проверяемый диапазон ${BASE:0:7}..HEAD не вводит коллизию номеров (${BASE}..HEAD; по предмету, не по способу)"