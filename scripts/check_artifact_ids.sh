#!/usr/bin/env bash
# check_artifact_ids.sh — механический барьер M-61 (`TD-111`), РЕШЕНИЕ Б (founder, 2026-08-12).
#
# ═══ ИНВАРИАНТ ОТ РЕЗУЛЬТАТА И ОТ ДИАПАЗОНА (спека §4.1) ═══════════════════════════════
#   Ни один коммит проверяемого диапазона не вводит НОСИТЕЛЯ идентификатора, который в
#   объединении `refs/remotes/origin/*` ∪ `refs/heads/*` уже несёт ДРУГОЙ НОСИТЕЛЬ.
#   Идентификатор — `КЛАСС-НОМЕР` с необязательной БУКВОЙ (`M-60`, `M-60a`, `C-058b`):
#     • НОМЕР нормализуется по ведущим нулям (`10#`),
#     • БУКВА сравнивается ЛИТЕРАЛЬНО и через арифметику не проходит НИКОГДА,
#     • буква стоит ВПЛОТНУЮ к цифрам, всё после первого дефиса — слаг.
#   ПРЕДМЕТ АРТЕФАКТА НЕ ЧИТАЕТСЯ: два разных носителя под одним идентификатором —
#   нарушение, об одном они предмете или о разных. Продолжение работы (второй критик,
#   ревизия, дробление милестоуна) берёт СВОЙ идентификатор.
#
# ═══ ЧЕТЫРЕ МЕСТА СРАВНЕНИЯ (§4.6) ═══════════════════════════════════════════════════════
#   P1 путь → класс-носитель                  карта каталогов в id_of
#   P2 basename → «КЛАСС НОМЕР БУКВА»         регексп `^([MRCA])-([0-9]+)([a-z])?(-.*)?$`,
#                                              различитель буквы и одно-буквенного слага —
#                                              ДЕФИС (замер: 5 имён с буквенным суффиксом,
#                                              0 имён вида `КЛАСС-НОМЕР-<одна буква>-…`)
#   P3 строка TECH-DEBT.md → номер/карточка   ОДИН `td_holder` на `universe()`, `introduced()`
#                                              и `next_artifact_id.sh` (§5 запретный список:
#                                              «держать ДВА разборщика строки долга — нельзя»)
#   P4 сверка идентичности без разбора        строки `cls.num.lt.car` посимвольно; «ID
#                                              совпал, носитель различается» — нарушение
#
# ═══ АСИММЕТРИЯ РАЗБОРА СТРОКИ ДОЛГА (§3.1(в)) — НАМЕРЕННАЯ ═══════════════════════════
#   ЗАНЯТОСТЬ широка — номер занимает ЛЮБАЯ строка-запись `^- **TD-` (fail-closed):
#     замер 9 из 11 неканонических номеров давали exit 0 на настоящем переиспользовании,
#     одна закрытая карточка `CLOSED` без слага, одна форма "(исходная формулировка)",
#     одна мультиномерная строка `TD-049 / TD-050 / TD-051 — CLOSED`.
#   ВВЕДЕНИЕ узкое — только ЗАВОДЯЩАЯ карточка `- **TD-NNN** `слаг``: реальная форма
#     close-out'а reviewer'а (`- **TD-061** ✅ CLOSED…`) под симметричным разбором краснеет
#     на каждом merge.
#   Шире брать нельзя: 72 из 126 номеров упомянуты в файле более одного раза перекрёстными
#   ссылками; узкий разбор на это не отвечает.

set -uo pipefail                                          # НЕ `-e`: `10#...` на арифметической ошибке
                                                         #  обязана МОЛЧА пропустить, не уронив барьер

ZERO=0000000000000000000000000000000000000000
SEP=$'\037'                                              # US: не IFS-пробельный, пустое поле БУКВЫ живёт

# ── P2: разбор идентификатора ───────────────────────────────────────────────────────
# Буква ВПЛОТНУЮ к цифрам входит в идентификатор. Всё после ПЕРВОГО дефиса — слаг. Никаких
# необязательных дефисов перед буквой (`-?([a-z])?`), никаких свободных хвостов
# (`-?([a-z])?.*$`): оба дают fail-OPEN/CLOSED (замер приёмки, §3.1 правило 2, §5 запретный
# список). Ведущие нули НЕ снимаются здесь — нормализация через `10#` в теле цикла.
ID_RE='^([MRCA])-([0-9]+)([a-z])?(-.*)?$'

# ── P1: путь → класс-носитель + `КЛАСС НОМЕР БУКВА` через SEP ───────────────────────
# Карта каталогов ОБЯЗАТЕЛЬНА (спека §3.1(б), §4.6 P1): класс берётся из каталога, а не из
# префикса имени — `research/reports/M-66-tester-report.md` лишь УПОМИНАЕТ M-66, носителем
# не является (8 таких отчётов в `research/reports/`). Привязка к `.md` обязательна:
# `docs/fa/research-cli.md` §7 предписывает отчёту идти ПАРОЙ `metrics.json + R-NNN.md`,
# и без `.md` `R-001-obi-trackA.json` разбирается как `R-001` (проверено прогоном).
id_of() {                                                # $1 = путь; печатает запись через SEP, иначе return 1
  case "$1" in
    milestones/M-*.md|research/reviews/R-*.md|research/reports/R-*.md|\
    research/critiques/C-*.md|research/arbitration/A-*.md) ;;
    *) return 1 ;;
  esac
  basename "$1" .md | sed -nE "s|${ID_RE}|\\1${SEP}\\2${SEP}\\3|p"
}

# ── P3: один и тот же разбор строки долга на `universe()`, `introduced()` и аллокатор ──
# Регекспы лежат в константах; `[*]` (а не `\*`) — POSIX awk СНИМАЕТ экранирование `\*` и
# читает `- **TD` как «дефис, ноль и более пробелов, квантор» (тихая порча ровно того
# класса, что стоила кругов 3 и 5). Скобочный класс однозначен во всех awk-ах.
#
# ══ TD-PARSER-BLOCK ═══════════════════════════════════════════════════════════════════
# НАЧАЛО общего блока — поддерживать В СИНХРОН с scripts/next_artifact_id.sh (там тот же
# блок, побайтово). Спека §5: «Держать ДВА разборщика строки долга (барьер отдельно,
# аллокатор отдельно) — ЗАПРЕЩЕНО». Зависимый эталон (`testing.md`) мутация ловит плохо:
# сломай обе половины одним дефектом, и `X == Y` покраснеет в обе стороны. Поэтому тест
# гоняет мутантов `tdregex`/`tdtrim`/`tdcanonical`/`tdanyline`/`namesonly` только на
# барьере — и обе копии обязаны давать ТОТ ЖЕ ОТВЕТ на ТЕХ ЖЕ входах.
TD_HOLD_RE='^- [*][*]TD-[0-9]+'                          # ЛЮБАЯ строка-запись (широкая занятость)
TD_CANON_RE='^- [*][*]TD-0*[0-9]+[*][*] `[^`]+`'         # ЗАВОДЯЩАЯ карточка (узкое введение)
TD_PAT='- \*\*TD-0*([0-9]+)\*\* `([^`]+)`.*'             # форма diff-строки для introduced()

# Занятость TD по всему репозиторию для одного ref'а. Принимает СОДЕРЖИМОЕ `TECH-DEBT.md`
# на stdin (НЕ путь), чтобы одинаково обслуживать и `git show $ref:TECH-DEBT.md`, и
# `git diff`. Носитель канонической карточки — `номер слаг`, носитель прочих форм — сама
# строка целиком. Мультиномерный пункт держит ВСЕ номера своего ведущего жирного поля, а
# не все номера строки (72 из 126 номеров в `origin/main` упомянуты более одного раза
# перекрёстными ссылками — `sub(/^- \*\*/, "", head); i=index(head,"**"); head=substr(...)`
# отсекает хвост после первого `**`).
td_holder() {                                            # stdin: содержимое TECH-DEBT.md; stdout: записи «TD<SEP>num<SEP><SEP>carrier»
  awk -v hold="$TD_HOLD_RE" -v canonre="$TD_CANON_RE" -v sep="$SEP" '
    $0 ~ hold {
      line = $0
      canon = (line ~ canonre)
      slug = line; sub(/^[^`]*`/, "", slug); sub(/`.*$/, "", slug)
      head = line; sub(/^- \*\*/, "", head)
      i = index(head, "**"); if (i > 0) head = substr(head, 1, i - 1)
      while (match(head, /TD-[0-9]+/)) {
        num = substr(head, RSTART + 3, RLENGTH - 3); sub(/^0+/, "", num); if (num == "") num = "0"
        car = canon ? num " " slug : line
        printf "TD%s%s%s%s%s\n", sep, num, sep, sep, car
        head = substr(head, RSTART + RLENGTH)
      }
    }'
}
# ══ КОНЕЦ TD-PARSER-BLOCK ════════════════════════════════════════════════════════════

die() { echo "FAIL  $*" >&2; echo "      ↳ Барьер fail-closed: база не установлена достоверно." >&2; exit 1; }

# ── база из СОБЫТИЯ (та же проводка, что check_protected_artifacts.sh) ────────────────
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}" ;;
    pull_request) raw="${PR_BASE_SHA:-}" ;;
    "")           die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *)            die "неизвестное событие '${EVENT_NAME}' — база не определена" ;;
  esac
fi
[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?})"
case "${raw}" in
  *[!0]*) : ;;                                           # есть ненулевой символ — не zero-SHA
  *)      die "база = zero-SHA (создание ветки / force-push) — целостность не доказуема" ;;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || die "база '${raw}' отсутствует в истории (force-push / поверхностный клон)"
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || die "база '${raw}' НЕ предок HEAD — история переписана (force-push); что введено, недоказуемо"

# ── refs (двойной охват обязателен: §3.1(а)) ────────────────────────────────────────
refs_all() { git for-each-ref --format='%(refname)' refs/remotes/origin refs/heads 2>/dev/null; }

# ── universe: всё, что ЗАНИМАЕТ идентификатор ────────────────────────────────────────
# Четвёрки «КЛАСС НОМЕР БУКВА НОСИТЕЛЬ» через SEP. Канал чтения имён — `-z` ОДИНАКОВО для
# файлов и для TD: при текстовом режиме git КВОТИРУЕТ не-ASCII имена (`R-046` Б-3), и
# артефакт под русским именем выпал бы из подсчёта занятости — коллизия проходит молча.
universe() {
  local ref f id
  for ref in $(refs_all); do
    while IFS= read -r -d '' f; do
      id="$(id_of "$f")" || continue
      [ -n "${id}" ] || continue
      printf '%s%s%s\n' "$id" "$SEP" "$f"
    done < <(git ls-tree -r --name-only -z "${ref}" 2>/dev/null)
  done
  for ref in $(refs_all); do
    git show "${ref}:TECH-DEBT.md" 2>/dev/null | td_holder
  done
  return 0
}

# ── introduced: что ВВЕДЕНО коммитами диапазона ──────────────────────────────────────
# «Введён» = появился в диапазоне И ДОЖИЛ ДО HEAD (§4.1 — инвариант от РЕЗУЛЬТАТА).
# Цена конкретна: ветка, исправившая СВОЮ ЖЕ ошибку перенумерацией (реальный коммит
# `f0e915b`: R-038-M-60a → R-042), блокировалась, хотя в результате коллизии нет.
# `cat-file -e HEAD:$f` снимает ложный красный, НЕ ослабляя ни одного нарушения: и пере-
# именование В занятый номер, и коллизия в не-вершинном коммите оставляют свой носитель в HEAD.
#
# `--no-renames` ломает rename-детект: переименование в занятый номер превращается в D + A
# и краснеет как «новый файл» (ось 4). `--diff-filter=A` — НЕ `AM`: правка существующего
# (M) не вводит носитель (`R-046` Б-2).
introduced() {
  local c f id head_td
  for c in $(git rev-list "${raw}..HEAD" 2>/dev/null); do
    while IFS= read -r -d '' f; do
      id="$(id_of "$f")" || continue
      [ -n "${id}" ] || continue
      git cat-file -e "HEAD:${f}" 2>/dev/null || continue
      printf '%s%s%s\n' "$id" "$SEP" "$f"
    done < <(git show --cc --name-only --no-renames --diff-filter=A -z --format= "${c}" 2>/dev/null || true)
    # TD — узко: только ЗАВОДЯЩИЕ карточки, И ТОЛЬКО те, что дожили до HEAD.
    #
    # СРАВНИВАЮТСЯ ДАННЫЕ, А НЕ ШАБЛОН (Б-6 `R-054`). Прежняя редакция подставляла слаг
    # долга в ERE (`grep -qE "…\`${tsubj}\`"`): слаг с метасимволом переставал совпадать
    # САМ С СОБОЙ, grep возвращал не-0, кандидат МОЛЧА выпадал — и барьер печатал «ни
    # один артефакт не введён», exit 0 на настоящей коллизии. Обе стороны проходят
    # ОДИН И ТОТ ЖЕ разбор `TD_PAT`, сверка по точной строке (`-qxF`).
    head_td="$(git show "HEAD:TECH-DEBT.md" 2>/dev/null | sed -nE "s|^${TD_PAT}\$|\\1 \\2|p")"
    git show "${c}" -- TECH-DEBT.md 2>/dev/null \
      | sed -nE "s|^\+${TD_PAT}\$|\\1 \\2|p" \
      | while IFS= read -r td_line; do
          [ -n "${td_line}" ] || continue
          if printf '%s\n' "$head_td" | grep -qxF -- "$td_line"; then
            # 4 поля «TD NUM LT CARRIER» через SEP. LT у TD всегда пустой; bash'евый printf
            # с `X%s%s%s%s%s\n` СЪЕДАЕТ пустой аргумент между двумя `printf SEP` (замер прямо
            # на этом файле, см. Н-фикс в логе работы). Подстановка `${SEP}${SEP}` — ДВА
            # разделителя одним аргументом, без пустых слотов.
            printf 'TD%s%s%s%s\n' "$SEP" "${td_line%% *}" "${SEP}${SEP}" "$td_line"
          fi
        done
  done
  return 0
}

# ── main ────────────────────────────────────────────────────────────────────────────
U=$(universe | sort -u)
IN=$(introduced | sort -u)
[ -z "${IN}" ] && { echo "OK: ни один новый артефакт не введён (диапазон ${raw:0:7}..HEAD)"; exit 0; }

# P4 — сверка БЕЗ разбора: ID совпал, носитель различается. Сравнение посимвольное; один
# и тот же файл, видимый в N ref'ах, даёт один и тот же носитель и нарушением не является.
# Номер нормализуется `10#` ПОСЛЕ `read` (отдельно от буквы — буква через арифметику не
# проходит НИКОГДА, §3.1 правило 1); под `set -uo pipefail` без `-e` арифметическая ошибка
# молча пропустит присваивание, и сравнение пройдёт на сырой строке — замер: `10#60a` не
# роняет барьер.
while IFS="$SEP" read -r cls num lt car; do
  [ -n "${cls:-}" ] || continue
  num=$((10#${num}))
  while IFS="$SEP" read -r c2 n2 l2 car2; do
    [ -n "${c2}" ] || continue
    n2=$((10#${n2}))
    if [ "${c2}" = "${cls}" ] && [ "${n2}" = "${num}" ] && [ "${l2}" = "${lt}" ] && [ "${car2}" != "${car}" ]; then
      echo "FAIL  ${cls}-${num}${lt:+${lt}}: второй носитель «${car}» под идентификатором, занятым «${car2}»"
      exit 1
    fi
  done <<< "${U}"
done <<< "${IN}"

echo "OK: ни один коммит диапазона ${raw:0:7}..HEAD не ввёл второй носитель под занятым идентификатором"
