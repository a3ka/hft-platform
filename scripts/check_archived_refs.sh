#!/usr/bin/env bash
# check_archived_refs.sh — ВИСЯЧИЕ ССЫЛКИ НА ВЫНЕСЕННЫЕ АРТЕФАКТЫ.
#
# ЗАЧЕМ. Норма Р-2 (`docs/04-workflow.md` §2) выносит гейт и спеку закрытого милестоуна в
# `docs/archive/`. Всё, что ссылалось на них по прежнему пути, после переезда указывает в
# пустоту — и это молчаливый дефект: код собирается, тесты зелены, а читатель идёт по
# ссылке и не находит ничего.
#
# ЗАМЕР, ИЗ-ЗА КОТОРОГО БАРЬЕР ЗАВЕДЁН (`R-198` §5, `TD-218`). Переезд `M-88` оставил
# ВОСЕМЬ висячих ссылок: шесть в `crates/gateway/src/lib.rs`, две в `crates/gateway/tests/`.
# Тело коммита переезда при этом утверждало «ссылок из чужих зон нет». Утверждение было
# ложно, и ложным его сделали ДВЕ независимые формы ошибки — обе воспроизведены:
#
#   1. искали имя ГЕЙТА (`verify_M-88`), а ссылки были на СПЕКУ (`milestones/M-88-*.md`).
#      Кандидат барьера, названный в `04-workflow.md`, ловил бы ровно ту же половину;
#   2. `git grep -- 'crates/*/src'` БЕЗ `**` молча возвращает ноль там, где правильная
#      форма даёт шесть попаданий. Пустой вывод прочли как «чисто».
#
# Поэтому здесь: ОБА имени (спека И гейт), pathspec с `**`, и ни одного места, где
# пустота могла бы означать успех по недосмотру, — множество кандидатов печатается.
#
# ЧТО СЧИТАЕТСЯ ЖИВЫМ ТЕКСТОМ. Висячая ссылка есть дефект там, где читатель идёт по ней
# ЗА ДЕЙСТВУЮЩИМ знанием: код, гейты, деплой, CI, действующие документы. В `research/**`
# (вердикты гейтов), `docs/archive/**` (сами вынесенные артефакты) и `docs/workflow/**`
# (записки передачи) старый путь — ИСТОРИЯ: вердикт круга судил предмет по тому пути, по
# которому он тогда лежал, и переписывать его задним числом значит подделывать аудит-след.
#
# ОГОВОРКА. Действующий документ вправе НАЗВАТЬ мёртвый путь — карточка долга описывает
# именно его. Для этого строка несёт маркер `ARCHIVED-REF-OK`; он аудит-след, а не
# доказательство (тот же предел, что у `FOUNDER-APPROVED`).
#
# ГРАНИЦА ИДЕНТИФИКАТОРА (`R-203` §5, харнесс-трек 2026-09-26). Первая редакция искала
# прежний путь ПОДСТРОКОЙ (`git grep -F 'milestones/M-60'`), и при вынесенном зонте `M-60`
# краснела на живой `milestones/M-60b-gate-mechanisms.md`: префикс `M-60` — начало `M-60b`.
# Ложное красное чинили не барьером, а базовой линией — девять строк амнистировали ссылки
# на ЖИВЫЕ файлы, и барьер слабел там, где должен был молчать сам. Поэтому после
# идентификатора требуется ГРАНИЦА: следующий символ — не буква и не цифра (или конец
# строки). `M-60` ≠ `M-60b` ≠ `M-600`. Та же граница — в проверке протухания базовой линии:
# строка, чей файл ссылается только на `M-60b`, ПРОТУХЛА, а не «всё ещё ссылается».
#
# СУФФИКС ГЕЙТА. Вынесенный гейт может нести пояснение после номера
# (`verify_M-60-umbrella-2026-08.sh`); прежний путь у него — `scripts/verify_M-60.sh`.
# Первая редакция такой файл не считала артефактом вовсе и его ссылки не проверяла.

set -uo pipefail
cd "$(dirname "$0")/.."

FAIL=0
pass() { printf 'PASS  %s\n' "$1"; }
fail() { printf 'FAIL  %s\n' "$1"; FAIL=$((FAIL + 1)); }

# ЖИВОЙ ТЕКСТ — pathspec'ы с `**` ВЕЗДЕ, где есть каталог (см. форму ошибки 2 в шапке).
LIVE=(
  'crates/**' 'scripts/**' 'deploy/**' '.github/**' '.claude/**'
  'docs/fa/**' 'docs/0*.md' 'docs/DESIGN.md' 'docs/ROADMAP.md' 'CLAUDE.md'
  # СОБСТВЕННАЯ ОСНАСТКА БАРЬЕРА ИСКЛЮЧЕНА, и это не поблажка себе. Базовая линия ПО
  # ОПРЕДЕЛЕНИЮ перечисляет мёртвые пути — она их и описывает; барьер и его проба называют
  # их в объяснении, зачем существуют. Считать это нарушением значит требовать от механизма
  # не называть предмет, против которого он заведён.
  #
  # Найдено ПРОГОНОМ В CI, а не рассуждением, и это важнее самой правки: локально барьер был
  # ЗЕЛЁН, потому что базовая линия ещё не была под git, а `git grep` видит только
  # отслеживаемые файлы. Зелёный цвет был артефактом того, что файл не закоммичен, — ровно
  # тот класс, за который этот милестоун получил восемь кругов гейта.
  ':!scripts/check_archived_refs.sh'
  ':!scripts/lib/archived_refs_baseline.txt'
  ':!scripts/tests/red_archived_refs.sh'
)
# `PROJECT-STATE.md` и `TECH-DEBT.md` В ЖИВОЙ НАБОР НЕ ВХОДЯТ, и это решение, а не пропуск.
# Оба — ЗАПИСИ О ПРОШЛОМ: «гейт прогнан ревьюером: bash scripts/verify_M-88.sh» описывает
# то, что произошло по тому пути, по которому гейт тогда лежал. Переписать такую строку
# задним числом значит подделать запись о прогоне. Замер при заведении барьера: включение
# этих двух файлов дало 23 срабатывания, из них исправными были ДВА, остальные — корректные
# исторические цитаты, часть с явной оговоркой «путь НА МОМЕНТ ПРОГОНА». Барьер, который
# на девяносто процентов кричит на правду, не читают вовсе.

# УНАСЛЕДОВАННЫЙ ДОЛГ — явным списком, и он имеет право только СОКРАЩАТЬСЯ.
# Каждая строка: `<файл>|<прежний путь>`. Починил ссылку — обязан убрать строку: протухшая
# строка базовой линии есть FAIL (иначе список превращается в вечную амнистию, и барьер
# тихо слабеет по мере того, как долг чинят).
BASELINE="$(dirname "$0")/lib/archived_refs_baseline.txt"
[ -f "$BASELINE" ] || { fail "нет базовой линии $BASELINE — барьер fail-closed"; echo "VERDICT: FAIL"; exit 1; }

# Вынесенные артефакты: спеки милестоунов и их гейты. ОТБОР И РАЗБОР — ОДНО ВЫРАЖЕНИЕ
# (`C-255` B-1): прежде грамматика жила двумя копиями (`grep` отбора и `grep -o` разбора), и
# страж «идентификатор не разобран» между ними был недостижим — мёртвый код, выдаваемый за
# защиту. Теперь имя, из которого номер не разобрался, не отбирается вовсе: расхождению
# копий негде возникнуть. Спека: `M-<id>-<слаг>.md`. Гейт: `verify_M-<id>[-<пояснение>].sh`.
ARCHIVED=(); OLDPATH=()
while IFS= read -r art; do
  if [[ "$art" =~ ^(M-[0-9]+[a-z]?)-.*\.md$ ]]; then
    ARCHIVED+=("$art"); OLDPATH+=("milestones/${BASH_REMATCH[1]}")
  elif [[ "$art" =~ ^verify_(M-[0-9]+[a-z]?)(-.*)?\.sh$ ]]; then
    ARCHIVED+=("$art"); OLDPATH+=("scripts/verify_${BASH_REMATCH[1]}")
  fi
done < <(ls docs/archive/ 2>/dev/null)

if [ "${#ARCHIVED[@]}" -eq 0 ]; then
  fail "в docs/archive/ не найдено НИ ОДНОГО вынесенного артефакта — барьер судил бы пустоту"
  echo "VERDICT: FAIL (провалов: $FAIL)"
  exit 1
fi
pass "вынесенных артефактов найдено: ${#ARCHIVED[@]}"

# Для каждого — ПРЕЖНИЙ путь. Ищем по ИДЕНТИФИКАТОРУ С ГРАНИЦЕЙ, а не по полному имени
# и не подстрокой: в коде ссылки живут в форме `milestones/M-88-*.md` (точное имя её не
# поймает), а подстрока `milestones/M-60` совпадает с живым `M-60b` (см. шапку).
# `boundary_re` — единственное место, где граница определена; поиск и проверка протухания
# берут её отсюда, иначе две проверки разошлись бы в понимании, что такое «ссылается».
boundary_re() { printf '%s([^a-z0-9]|$)' "$1"; }
DANGLING=0
for i in "${!ARCHIVED[@]}"; do
  art="${ARCHIVED[$i]}"; old="${OLDPATH[$i]}"

  hits=$(git grep -n -E "$(boundary_re "$old")" -- "${LIVE[@]}" 2>/dev/null | grep -v 'ARCHIVED-REF-OK' || true)
  # УНАСЛЕДОВАННОЕ отделяется от НОВОГО. Первый проход архива (26 гейтов, норма Р-2) прошёл
  # БЕЗ этого барьера и оставил висячие ссылки по всему дереву, часть — в чужих зонах
  # (`crates/signals`, `crates/journal`, `.claude/rules`). Барьер, красный на унаследованном
  # долге, не вливается никогда и потому не защищает ничего. Норма Р-2 говорит о себе то же
  # самое: «не ретроспективна сама по себе — она останавливает РОСТ».
  hits=$(printf '%s\n' "$hits" | while IFS= read -r h; do
    [ -n "$h" ] || continue
    f="${h%%:*}"
    grep -qxF "${f}|${old}" "$BASELINE" 2>/dev/null || printf '%s\n' "$h"
  done)
  if [ -n "$hits" ]; then
    fail "висячая ссылка на вынесенный артефакт «$art» (прежний путь «$old»):"
    # Строки печатаются УСЕЧЁННО: в роадмапе одна ячейка таблицы занимает килобайты, и
    # вывод барьера становился бы нечитаемым ровно там, где его читают.
    printf '%s\n' "$hits" | cut -c1-140 | sed 's/^/        /' | head -20
    DANGLING=$((DANGLING + 1))
  fi
done

if [ "$DANGLING" -eq 0 ]; then
  pass "НОВЫХ висячих ссылок нет (проверено ${#ARCHIVED[@]} артефактов)"
fi

# Базовая линия обязана СОКРАЩАТЬСЯ: строка, которой в дереве больше нет, — протухла.
STALE=0
while IFS='|' read -r bf bold; do
  [ -n "${bf:-}" ] || continue
  case "$bf" in \#*) continue ;; esac
  # Та же граница, что в поиске: файл, ссылающийся только на живой `M-60b`, на `M-60` НЕ
  # ссылается — строка протухла (или никогда не была нужна: ложная амнистия).
  if ! git grep -q -n -E "$(boundary_re "$bold")" -- "$bf" 2>/dev/null; then
    fail "базовая линия протухла: «$bf» больше не ссылается на «$bold» — убери строку из $BASELINE"
    STALE=$((STALE + 1))
  fi
done < "$BASELINE"
[ "$STALE" -eq 0 ] && pass "базовая линия актуальна (унаследованных ссылок: $(grep -cv '^#' "$BASELINE"))"

printf '\n'
if [ "$FAIL" -eq 0 ]; then
  echo "VERDICT: PASS"
  exit 0
fi
echo "VERDICT: FAIL (провалов: $FAIL)"
exit 1
