#!/usr/bin/env bash
# verify_M-73.sh — acceptance-гейт M-73 (офсайт-копия по расписанию + сторож кэша сборок).
#
# ЗАВЕДЁН РЕТРОАКТИВНО, И ЭТО НАЗВАНО, А НЕ ЗАМАСКИРОВАНО. `04-workflow.md` §2 требует
# acceptance-скрипт ДО диспетчеризации dev'а; здесь он появился ПОСЛЕ, по находке `R-151`
# `Н-6`. Вина не dev'а: `scripts/verify_*.sh` — sacred-зона architect'а. Цена пробела
# измерима: пять блокеров нашёл человек-ревьюер там, где обязан был краснеть механизм.
#
# ЧТО ЭТОТ ГЕЙТ МОЖЕТ И ЧЕГО НЕ МОЖЕТ. Он судит ARGV и тексты — то есть КОМПОЗИЦИЮ и
# ЗАПРЕТЫ, — но не поведение на реальном канале. Поведенческая часть (копия доехала,
# второй прогон идемпотентен, локально ничего не удалено) предъявляется ручным прогоном на
# проде в Done Block'е. Это остаточный риск, объявленный здесь, а не выданный за покрытие.
#
# Прецедент формы для cron-обёрток — `scripts/verify_M-48.sh` (прод-форма
# `HFT_CRON_PRINT_ARGV=1` плюс канарейка КОМПОЗИЦИИ). Повторяем приём, а не изобретаем.
set -uo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2
FAIL=0
step() { printf '\n── %s\n' "$*"; }
# ПРОВЕРКА ИСПОЛНЯЕТСЯ В ПОДОБОЛОЧКЕ, И ЭТО НЕ СТИЛЬ. Первая редакция звала `eval "$1"` в
# ТЕКУЩЕМ шелле; любая проверка, содержащая `exit 0` (а их здесь четыре — многострочные
# блоки с ранним выходом), УБИВАЛА весь гейт с нулевым кодом. Замер первой редакции:
# напечатано `FAIL:` — и `VERIFY_EXIT=0`. То есть гейт был ЛОЖНО-ЗЕЛЁНЫМ ровно того класса,
# который он призван ловить, и поймал его собственный прогон, а не рассуждение
# (`testing.md`: «Симптом: гейт зелёный, но ты не можешь предъявить, ЧТО он покраснеет
# против конкретного слома»). Подоболочка изолирует `exit` проверки от кода гейта.
#
# Имя проверки печатается ПЕРВОЙ СТРОКОЙ выражения: многострочные блоки иначе печатались
# пустыми, и вывод не позволял понять, что именно упало.
chk() {
  local name; name="$(printf '%s' "$1" | sed -n '1{s/^[[:space:]]*//;s/[[:space:]]*$//;p}')"
  [ -n "$name" ] || name="<многострочная проверка>"
  if ( eval "$1" ) >/dev/null 2>&1; then echo "PASS: ${name}"; else echo "FAIL: ${name}" >&2; FAIL=$((FAIL + 1)); fi
}
WRAP=deploy/bin/journal-offsite-cron.sh
PRUNE=deploy/bin/builder-prune-cron.sh
# БЛОК `RSYNC:` МНОГОСТРОЧНЫЙ, И ЭТО НЕ ДЕТАЛЬ. Первая редакция брала `grep -m1 "^RSYNC:"` —
# строку-ЗАГОЛОВОК, в которой нет ни одного флага. Три проверки (`--partial` и обе половины
# запрета `--delete`) оказывались ВАКУУМНЫМИ: смотрели в пустую строку и были зелены при любом
# содержимом команды. Поймала это мутационная половина — она честно сообщила «мутант не
# обнаружен», вместо того чтобы промолчать. Ровно та работа, ради которой анти-плацебо-пара и
# существует (`testing.md`: проверка, не падающая против слома, ничего не проверяет).
#
# Читаем ВЕСЬ блок: от `RSYNC:` до следующей секции вида `КАПС:` либо до конца вывода.
rsync_block() {
  local wrap="${1:-$WRAP}"
  HFT_CRON_PRINT_ARGV=1 "$wrap" 2>/dev/null \
    | awk '/^RSYNC:/{f=1;next} /^[A-Z_]+:$/{f=0} f'
}

step "паритет с CI — базовый job целиком (gates.md §3: гейт, который зеленее CI, не гейт)"
chk "cargo fmt --all -- --check"
chk "cargo clippy --all-targets --all-features -- -D warnings"
chk "cargo test --all --quiet"

step "task #0 — механизмы СУЩЕСТВУЮТ и ИСПОЛНЯЮТСЯ прод-формой вызова"
# `test -f` — описание намерения, а не проверка (`testing.md`): бинарь может не стартовать
# ни при какой форме argv. Исполняем ту же форму, какой обёртку зовёт cron.
chk "test -x $WRAP"
chk "test -x $PRUNE"
chk "HFT_CRON_PRINT_ARGV=1 $WRAP >/dev/null 2>&1"
chk "HFT_CRON_PRINT_ARGV=1 $PRUNE >/dev/null 2>&1"

step "task #0 — НАБЛЮДЕНИЕ ОТСУТСТВИЯ: обе записи есть в cron.d (иначе механизм инертен)"
chk "grep -rq 'journal-offsite-cron.sh' deploy/cron.d/"
chk "grep -rq 'builder-prune-cron.sh' deploy/cron.d/"

step "task #0 — КОМПОЗИЦИЯ: argv обёртки согласован с cron.d (рассогласование = тихий no-op)"
chk '
  dst_cron=$(sed -n "s/^JOURNAL_OFFSITE_DST=//p" deploy/cron.d/journal-offsite | head -1)
  dst_argv=$(HFT_CRON_PRINT_ARGV=1 deploy/bin/journal-offsite-cron.sh 2>/dev/null \
             | sed -n "s/^DST_URL=//p" | head -1)
  [ -n "$dst_cron" ] && [ -n "$dst_argv" ] && [ "$dst_cron" = "$dst_argv" ]'

step "task #1 (R-151 Б-1) — расписание копии НЕ совпадает с суточными заданиями журнала"
# Копия почасовая (`M * * * *`); ретеншен `7 4 * * *`, компакция `50 3 * * *`,
# уборка кэша сборок `30 4 * * *`. Если минута почасового задания равна минуте суточного,
# они сходятся КАЖДЫЕ СУТКИ. Допускается и другая развязка — ОБЩИЙ lock-файл; тогда
# пересечение сериализуется.
#
# ПЕРЕЧЕНЬ СОСЕДЕЙ ВЫПИСАН, И `builder-prune` В НЁМ ТЕПЕРЬ ЕСТЬ (`R-155` `Н-9`). Прежняя
# редакция сверяла копию только с `journal-retention` и `journal-compaction`. Сегодня
# коллизии нет (копия `:22`, уборка `:30`), но перевод копии на `30 * * * *` гейт не поймал
# бы — то есть проверка молчала бы о том, ради чего написана. Это ровно класс `Р-3`: группа
# соседей имела ТРИ члена, сверялись ДВА; опасна та часть группы, которая не выписана.
#
# ПЕРЕЧЕНЬ СЧИТАЕТСЯ, А НЕ ЗАЯВЛЯЕТСЯ. Литерал числа заданий проверяется отдельным шагом
# ниже: появление ЧЕТВЁРТОГО cron-файла обязано красить гейт, иначе следующий сосед снова
# окажется невыписанным, и мы вернёмся сюда третий раз.
chk '
  off_min=$(grep -hE "^[0-9*]+ .*journal-offsite-cron\.sh" deploy/cron.d/* 2>/dev/null | awk "{print \$1}" | head -1)
  off_hour=$(grep -hE "^[0-9*]+ .*journal-offsite-cron\.sh" deploy/cron.d/* 2>/dev/null | awk "{print \$2}" | head -1)
  clash=0
  for f in deploy/cron.d/journal-retention deploy/cron.d/journal-compaction deploy/cron.d/builder-prune; do
    [ -f "$f" ] || continue
    while read -r m h _rest; do
      case "$m" in ""|\#*) continue ;; esac
      [ "$m" = "$off_min" ] && { [ "$off_hour" = "*" ] || [ "$off_hour" = "$h" ]; } && clash=1
    done < <(grep -hE "^[0-9*]+ " "$f" 2>/dev/null)
  done
  if [ "$clash" -eq 0 ]; then exit 0; fi
  # развязка через ОБЩИЙ lock: lock-файл копии обязан совпасть с lock-файлом соседей
  lk_off=$(grep -hoE "/var/lock/[A-Za-z0-9._-]+" deploy/cron.d/journal-offsite deploy/bin/journal-offsite-cron.sh 2>/dev/null | sort -u | head -1)
  lk_ret=$(grep -hoE "/var/lock/[A-Za-z0-9._-]+" deploy/cron.d/journal-retention deploy/bin/journal-retention-cron.sh 2>/dev/null | sort -u | head -1)
  [ -n "$lk_off" ] && [ "$lk_off" = "$lk_ret" ]'

# Наблюдение ОТСУТСТВИЯ выписанного соседа (`testing.md`, целостность гейта, свойство 4).
# Шаг выше сверяет копию с ТРЕМЯ поимённо названными заданиями. Четвёртое, появившись,
# осталось бы вне сверки молча — поэтому число cron-файлов пиннится литералом, и рост
# требует осознанного расширения перечня, а не проходит незамеченным.
step "task #1bis (R-155 Н-9) — перечень соседей ПОЛОН: новый cron-файл красит гейт"
chk '
  n=$(ls -1 deploy/cron.d/ 2>/dev/null | wc -l)
  if [ "$n" -eq 3 ]; then exit 0; fi
  echo "cron-файлов ${n} при ожидаемых 3: перечень соседей в task #1 обязан быть расширен" >&2
  exit 1'

step "task #2 (R-151 Б-2) — --partial НЕ применяется без --partial-dir"
# Оборванная передача под ФИНАЛЬНЫМ именем — обрывок под видом целого файла, на приёмнике,
# у которого снапшоты выключены. Тот же класс, что запрещает копировать активный сегмент.
chk '
  line=$(rsync_block)
  [ -n "$line" ] || exit 1
  case "$line" in
    *--partial-dir*) exit 0 ;;
    *--partial*)     exit 1 ;;
    *)               exit 0 ;;
  esac'

step "task #3 (R-151 Б-3) — runbook НЕ предписывает сломанную форму ssh://…"
chk '! grep -nE "ssh://[A-Za-z0-9._-]+@" deploy/README.md'

step "task #4 (R-151 Н-1) — АНТИ-ПЛАЦЕБО запрета --delete: пара «чисто / мутант»"
# Половина 1: живой argv не несёт запрещённых флагов.
chk '! rsync_block \
      | grep -qE -- "--(delete|delete-[a-z]+|remove-source-files)"'
# Половина 2: та же проверка ОБЯЗАНА поймать мутанта. Без неё половина 1 зелена и против
# наблюдателя, который не наблюдает ничего (`R-151` Н-1: канарейка дева не краснела против
# файла с `--delete` в живых аргументах). Мутация — в ИЗОЛИРОВАННОЙ копии.
#
# МУТАЦИЯ ЦЕЛИТ В НАБЛЮДАЕМЫЙ КАНАЛ, А НЕ В ТЕКСТ ФАЙЛА, и это исправление собственной
# ошибки. Первая редакция подставляла `--delete` к ПЕРВОМУ вхождению слова `rsync` в файле —
# а первое вхождение стоит в ШАПКЕ-комментарии. `grep` по тексту подтверждал «мутация
# внеслась», печатаемый блок при этом не менялся, и проверка падала, сообщая о необнаружении
# мутанта, которого не было. Ложный якорь мутации в комментарии — тот же класс, что ловил
# автора этим же днём на соседнем предмете.
#
# Развязка: guard сравнивает ВЫВОД до и после. Мутация считается внесённой только если
# изменился тот самый блок, который читает проверка.
chk '
  d=$(mktemp -d /tmp/m73-mut-XXXXXX) || exit 1
  cp -r deploy "$d/deploy" || { rm -rf "$d"; exit 1; }
  before=$(rsync_block)
  # целим в флаг ВНУТРИ печатаемой команды, а не в слово из комментария
  perl -0pi -e "s/--archive/--archive --delete/ if !\$done++" "$d/deploy/bin/journal-offsite-cron.sh"
  after=$(cd "$d" && rsync_block deploy/bin/journal-offsite-cron.sh)
  rm -rf "$d"
  # SETUP-GUARD: мутация обязана быть видна В ТОМ ЖЕ КАНАЛЕ, который читает проверка
  [ "$before" != "$after" ] || exit 1
  printf "%s" "$after" | grep -qE -- "--delete"'

step "task #5 (R-151 Н-2) — предполётная проверка берёт хост из DST, а не из зашитого"
chk '
  host_dst=$(HFT_CRON_PRINT_ARGV=1 deploy/bin/journal-offsite-cron.sh 2>/dev/null \
             | sed -n "s/^DST_URL=//p" | head -1 | sed "s/:.*//")
  [ -n "$host_dst" ] || exit 1
  # зашитого литерала хоста вне строки DST_URL по умолчанию быть не должно
  n=$(grep -c "your-storagebox.de" deploy/bin/journal-offsite-cron.sh)
  [ "$n" -le 1 ]'

echo
if [ "$FAIL" -ne 0 ]; then
  echo "провалено проверок: $FAIL"
  echo "VERDICT: FAIL"
  exit 1
fi
echo "VERDICT: PASS"
exit 0
