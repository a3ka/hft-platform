#!/usr/bin/env bash
# Барьер диск-преамбулы verify — M-60b G6.2.
# Спецификация: scripts/tests/red_disk_budget.sh (DB-1..DB-8) + milestones/M-60b-gate-mechanisms.md §6.
#
# ЗАЧЕМ. 01.08: `verify_alerting.sh` дал FAIL `exit=101` от ENOSPC — ложный красный, который
# заставляет чинить ИСПРАВНОЕ; диск в тот период 83–85 %. Отдельно аудит §2.6: общий
# `CARGO_TARGET_DIR` ВНЕ дерева подменяет исполняемый бинарь — verify гоняет не тот код и
# зеленеет не о том. Преамбула делает красное НАЗВАННЫМ ДО старта прогона.
#
# ── ПРОД-ФОРМА ВЫЗОВА ─────────────────────────────────────────────────────────────────
#   bash scripts/check_disk_budget.sh          # первой строкой каждого verify_M-*.sh
#   MIN_FREE_KB=<число> bash scripts/check_disk_budget.sh
# Меряется ФС ТЕКУЩЕГО КАТАЛОГА (`df -Pk .` через PATH-резолв — DB-8 сторожит именно
# потребление PATH, иначе граница просто не исполняется) и `CARGO_TARGET_DIR` относительно
# него. В CI барьер НЕ ЗОВЁТСЯ джобом (спека §8): там он мерил бы диск раннера, а не наш;
# в CI идёт только его проба.
#
# ── КОНТРАКТ ──────────────────────────────────────────────────────────────────────────
#   exit 0  — свободно ≥ порога И (`CARGO_TARGET_DIR` не задан ИЛИ внутри дерева И доступен
#             как target: чтение+вход+запись);
#   exit≠0  — ПЕРВАЯ строка вывода НАЗЫВАЕТ отказавший ресурс: «диск: …» либо
#             «CARGO_TARGET_DIR …». При двух отказах названы ОБА — первый не маскирует
#             второй (DB-6);
#   негодный порог (пусто / нечисло / за пределами int64) ⇒ FAIL fail-closed: страж не
#   ОТКЛЮЧАЕТСЯ негодным параметром (урок `A-008`; валидация тем же парсером, который
#   значение и потребляет).
#
# ── ПРЕДЕЛЫ, НАЗВАННЫЕ ЧЕСТНО (спека §10) ─────────────────────────────────────────────
# 1. Срабатывает только при ЗАПУСКЕ verify: диск между прогонами не сторожит и ENOSPC
#    ПОСРЕДИ прогона не предотвращает — делает названным красное ДО старта.
# 2. Дефолт порога — 5 GiB. Замер 2026-08-15 на этом хосте: ПОЛНЫЙ `target/` рабочего
#    дерева — 15 208 076 KB (≈14.5 GB), свободно 136 578 496 KB (≈130 GB). То есть дефолт
#    покрывает ТЁПЛЫЙ прогон (инкрементальная пересборка + логи + фикстуры) и НЕ покрывает
#    ХОЛОДНУЮ сборку с нуля — это названный предел, а не изображённое покрытие: порог,
#    поднятый до 15 GB, краснел бы на здоровом хосте, порог ниже 1 GB не поймал бы класс
#    01.08. Прогон, которому нужна холодная сборка, поднимает `MIN_FREE_KB` явно.
# 3. Меряется ФС текущего каталога. Если `CARGO_TARGET_DIR` (физически внутри дерева) лежит
#    на ДРУГОЙ ФС через mount --bind, свободное место на ней не меряется.
# 4. Принадлежность дереву судится по ФИЗИЧЕСКОМУ пути (`F-089-2`): симлинк внутри дерева,
#    указывающий наружу, — это target ВНЕ дерева, и он отвергается. Обратное направление НЕ
#    запрещается: симлинк, разрешающийся ВНУТРЬ дерева, законен (DB-10) — инвариант про
#    физическое расположение сборки, а не про запрет симлинков как таковых.

set -uo pipefail

# `${VAR-default}` (без двоеточия) — НАМЕРЕННО: пустое значение обязано дойти до валидатора
# и упасть fail-closed (DB-3a), а не молча подмениться дефолтом.
MIN_FREE_KB="${MIN_FREE_KB-5242880}"

msgs=()
add() { msgs+=("$1"); }

# ── Порог: валидация тем же парсером, что его потребляет ──────────────────────────────
case "${MIN_FREE_KB}" in
  '' | *[!0-9]*)
    echo "порог негоден: «${MIN_FREE_KB}» — MIN_FREE_KB обязан быть целым числом KB"
    echo "fail-closed: страж не отключается негодным параметром (урок A-008)"
    exit 2
    ;;
esac
if [ "${#MIN_FREE_KB}" -gt 18 ]; then
  echo "порог негоден: «${MIN_FREE_KB}» — за пределами int64, сравнение недостоверно"
  echo "fail-closed: страж не отключается негодным параметром (урок A-008)"
  exit 2
fi

# ── 1. Диск ФС текущего дерева ────────────────────────────────────────────────────────
# `df` зовётся ПО ИМЕНИ (PATH-резолв), а не как /usr/bin/df: барьер обязан мерить ту же
# величину, что видит вызывающая среда. DB-8 — зеркальный страж этого: под df-shim'ом
# порог на 1 KB выше подставного free обязан дать отказ.
FREE_KB="$(df -Pk . 2>/dev/null | awk 'NR==2 {print $4}')"
case "${FREE_KB:-}" in
  '' | *[!0-9]*)
    echo "диск: df не дал числа свободных KB («${FREE_KB:-}») — состояние ФС недоказуемо"
    echo "fail-closed: неизмеренный ресурс не считается достаточным"
    exit 2
    ;;
esac
if [ "${FREE_KB}" -lt "${MIN_FREE_KB}" ]; then
  add "диск: свободно ${FREE_KB} KB < порога ${MIN_FREE_KB} KB на ФС $(pwd) — прогон упрётся в ENOSPC посреди себя"
fi

# ── 2. CARGO_TARGET_DIR ───────────────────────────────────────────────────────────────
# Второй инвариант ТОГО ЖЕ носителя: общий target вне дерева подменяет исполняемый бинарь
# (аудит §2.6) — verify зеленеет о чужой сборке.
normalize_path() { # абсолютизация + текстовое схлопывание «//», «/./», «/../» (без realpath:
  # каталога может ещё не существовать, а зависимость от внешнего бинаря — лишний класс отказа)
  local p="$1" out="" seg
  case "${p}" in /*) : ;; *) p="$(pwd)/${p}" ;; esac
  local IFS='/'
  for seg in ${p}; do
    case "${seg}" in
      '' | '.') continue ;;
      '..') out="${out%/*}" ;;
      *) out="${out}/${seg}" ;;
    esac
  done
  printf '%s' "${out:-/}"
}

# ФИЗИЧЕСКОЕ разрешение пути (F-089-2). Текстовой нормализации НЕДОСТАТОЧНО: симлинк
# `<дерево>/target` → `/tmp/чужой-кэш` текстуально лежит внутри дерева и проходил проверку,
# то есть инвариант обходился ФИЗИЧЕСКИ, а не формально (реплей — DB-9).
# Порядок: сначала `readlink -f` (разрешает и несуществующий последний сегмент), при его
# отсутствии/отказе — запасной путь на встроенных средствах bash: подняться до существующего
# предка, разрешить его `cd -P`, вернуть остаток. Пустой результат ⇒ судим логический путь
# (fail-closed: неразрешённый путь не становится «внутренним» по умолчанию).
physical_of() { # $1=абсолютный нормализованный путь → физический путь ("" если не разрешён)
  local p rest="" base d n
  p="$(readlink -f "$1" 2>/dev/null || true)"
  if [ -n "${p}" ]; then printf '%s' "${p}"; return 0; fi
  p="$1"
  while [ ! -e "${p}" ] && [ ! -L "${p}" ] && [ "${p}" != "/" ]; do
    base="${p##*/}"
    rest="/${base}${rest}"
    p="${p%/*}"
    [ -n "${p}" ] || p="/"
  done
  if [ -d "${p}" ] && [ ! -L "${p}" ]; then
    p="$(cd -P "${p}" 2>/dev/null && pwd)" || return 1
  else
    d="${p%/*}"; n="${p##*/}"; [ -n "${d}" ] || d="/"
    d="$(cd -P "${d}" 2>/dev/null && pwd)" || return 1
    p="${d%/}/${n}"
  fi
  printf '%s' "${p%/}${rest}"
}

if [ -n "${CARGO_TARGET_DIR:-}" ]; then
  HERE_LOGICAL="$(normalize_path "$(pwd)")"
  HERE_PHYS="$(pwd -P)"
  T="$(normalize_path "${CARGO_TARGET_DIR}")"
  T_PHYS="$(physical_of "${T}" || true)"
  [ -n "${T_PHYS}" ] || T_PHYS="${T}"
  # Судится ФИЗИЧЕСКИЙ путь: именно он говорит, где реально окажется сборка.
  inside=1
  case "${T_PHYS}/" in
    "${HERE_PHYS}"/*) inside=0 ;;
    "${HERE_LOGICAL}"/*) inside=0 ;;
  esac
  SHOWN="${T}"
  [ "${T_PHYS}" = "${T}" ] || SHOWN="${T} → физически ${T_PHYS}"
  if [ "${inside}" -ne 0 ]; then
    add "CARGO_TARGET_DIR вне дерева: ${SHOWN} (дерево ${HERE_PHYS}) — verify гонял бы не тот бинарь"
  elif [ -e "${T}" ]; then
    lack=""
    [ -d "${T}" ] || lack="${lack} не-каталог"
    [ -r "${T}" ] || lack="${lack} чтение"
    [ -x "${T}" ] || lack="${lack} вход"
    [ -w "${T}" ] || lack="${lack} запись"
    [ -z "${lack}" ] \
      || add "CARGO_TARGET_DIR внутри дерева, но носитель недоступен (${lack# }): ${SHOWN} — cargo упадёт позже и не назовёт причину"
  fi
fi

if [ "${#msgs[@]}" -gt 0 ]; then
  printf '%s\n' "${msgs[@]}"
  echo
  echo "Преамбула остановила прогон ДО старта: названный красный вместо ENOSPC-мистики"
  echo "(01.08: verify_alerting.sh exit=101 при диске 83–85 %)."
  exit 1
fi

echo "OK: свободно ${FREE_KB} KB ≥ порога ${MIN_FREE_KB} KB; CARGO_TARGET_DIR=${CARGO_TARGET_DIR:-<не задан>}"
