#!/usr/bin/env bash
# Барьер привязки вердикта к предмету — M-60b G3 (GATE-META + subject-lock + ОТСУТСТВИЕ).
# Спецификация: scripts/tests/red_gate_meta.sh (GM-1..GM-27, GM-16 СОЖЖЁН) +
# milestones/M-60b-gate-mechanisms.md §4/§5.
#
# ЗАЧЕМ — три наших инцидента:
#   1. `C-062` (04.08): критик отработал круг в дереве ЧУЖОГО репозитория; в шапке вердикта
#      `Base: origin/main @ 9a0e48f0` — ревизия, которой в НАШЕЙ истории нет. Заметил человек.
#   2. Подмена предмета ПОСЛЕ проходного вердикта: «критик смотрел это» и «reviewer одобряет
#      то же самое» перестают совпадать. Лечится subject-lock'ом.
#   3. `TD-105`: M-32/33/34 уехали в `main` без единого артефакта гейта — и это было
#      НЕНАБЛЮДАЕМО. Проверка того, что ПОПАЛО в диапазон, слепа к ОТСУТСТВИЮ (`testing.md`,
#      целостность гейта, свойство 4).
#
# ── ДО-НОРМАТИВНЫЙ АРТЕФАКТ: `ARCHIVED-VERDICT` (F-089-1) ─────────────────────────────
# Предмет барьера — вердикты, ДОБАВЛЕННЫЕ ИЛИ ИЗМЕНЁННЫЕ диапазоном события (GM-8: лежащие
# в дереве, но не тронутые, не судятся; мутация «судить весь `git ls-files`» роняет GM-8).
# Ретроактивным барьер не является — но у него не было пути ПРИЗЕМЛИТЬ артефакт, НАПИСАННЫЙ
# до введения нормы. Класс реален и повторится: `C-062` и `C-083` спасены с брошенной ветки
# коммитами `fda1a68`/`f87afdb` — в диапазоне они ДОБАВЛЕНЫ, шапки у них нет и быть не может.
# Для `C-062` она невозможна ПО СУЩЕСТВУ: его база `9a0e48f0` в нашей истории отсутствует
# (в том и был инцидент — критик работал в ЧУЖОМ репозитории), барьер такую шапку отвергнет
# сам, а выдуманная превратила бы аудит-трейл инцидента в ложную запись. Спека M-60b §8
# запрещает требовать GATE-META от до-нормативных вердиктов, §2 держит существующие вердикты
# в Forbidden.
# Путь: строка `ARCHIVED-VERDICT: <путь> — <причина>` в теле ЛЮБОГО коммита диапазона.
#   • ПОФАЙЛОВО: токен обязан НАЗЫВАТЬ путь. Бланкетного «всё в этом диапазоне» нет — иначе
#     первый артефакт закрывал бы собой остальные (класс GM-20).
#   • ТОЛЬКО для статуса `A` (приземление). ИЗМЕНЕНИЕ вердикта (`M`) — действие СЕГОДНЯШНЕЕ,
#     норма применяется полностью; исключения нет (GM-30).
#   • Причина ≥12 символов помимо пути — тот же порог, что у `FOUNDER-APPROVED`
#     (`check_docs_freeze.sh`): токен-ритуал не отличим от отсутствия токена (GM-31).
#   • Срабатывание ГРОМКОЕ: печатается `NOTE` с путём и коммитом-носителем.
# Предел назван честно: токен ПОДДЕЛЫВАЕМ — это аудит-след, а не доказательство древности
# артефакта (та же оговорка, что у `ALLOW-SUBJECT-CHANGE` и `FOUNDER-APPROVED`, `gates.md`
# §11). Альтернатива «grandfathering по дате/коммиту» ХУЖЕ: дата живёт ВНУТРИ файла, то есть
# такая же декларация, но невидимая в `git log` и растущая молча со временем; токен виден
# `git log --grep`, привязан к пушу и печатается барьером на каждом прогоне.
#
# ── ЧЕГО БАРЬЕР НЕ ДЕЛАЕТ (граница, спека §4) ─────────────────────────────────────────
# Он читает ДЕКЛАРАЦИИ автора (шапку GATE-META, литерал `M-NN` в subject'е merge) и сверяет
# их с ФАКТАМИ git: существует ли ревизия, предок ли она HEAD, какие пути тронуты, есть ли
# файл в дереве слияния. СООТВЕТСТВИЕ вердикта предмету он НЕ ВЫЧИСЛЯЕТ — это суждение
# критика/reviewer'а. Класс «барьер вычисляет предмет артефакта» упразднён решением
# founder'а 12.08 по M-61 (вариант Б): шесть блокеров M-61 подряд жили ровно в нём.
#
# ── ПРОД-ФОРМА ВЫЗОВА ─────────────────────────────────────────────────────────────────
#   EVENT_NAME=push         PUSH_BEFORE=<github.event.before>            bash scripts/check_gate_meta.sh
#   EVENT_NAME=pull_request PR_BASE_SHA=<event.pull_request.base.sha>    bash scripts/check_gate_meta.sh
#   (первый позиционный аргумент — ручной прогон: база сравнения явно)
# База берётся ИЗ СОБЫТИЯ, а не из `origin/main`: на push-событии `actions/checkout` ставит
# `origin/main` на ТОЛЬКО ЧТО ЗАПУШЕННЫЙ коммит, диапазон пуст и барьер зеленел бы ВСЕГДА
# (блокер B1 `C-006`, тот же дефект, что чинили в `check_protected_artifacts.sh`).
# Переменная своего события пуста ⇒ пробуем вторую (проводка бывает неполной), затем
# fail-closed. Требуется `fetch-depth: 0`: при depth=1 любой настоящий SHA нерезолвим и
# каждая честная шапка станет ложным FAIL.
#
# ── КОДЫ ВОЗВРАТА ─────────────────────────────────────────────────────────────────────
#   0 — все тронутые вердикты диапазона привязаны к предмету, лок не нарушен, merge'и
#       milestone'ов несут вердикт reviewer'а;
#   1 — есть нарушения (печатаются ВСЕ: ни первый файл, ни первый merge не закрывают собой
#       остальные — GM-20/GM-21);
#   2 — база события не установлена достоверно / origin неизвестен (fail-closed).

set -uo pipefail

ZERO=0000000000000000000000000000000000000000
VERDICT_ENUM="REJECT NOTE APPROVE PASS CONCERNS KILL ESCALATE DECISION"
# Проходные исходы — только они запирают предмет. После REJECT/KILL/CONCERNS/ESCALATE
# правки ШТАТНЫ, и лок, красящий нормальный круг исправлений, вреднее отсутствующего
# (GM-11; спека §8 «Запретный список»).
PASSING_VERDICTS="NOTE APPROVE PASS DECISION"

FAILED=0
bad() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
die() {
  echo "FAIL  $*"
  echo
  echo "Барьер fail-closed: диапазон события не установлен достоверно."
  exit 2
}

in_list() { # $1=игла $2=список через пробел
  case " $2 " in *" $1 "*) return 0 ;; *) return 1 ;; esac
}

# ── 1. База диапазона ─────────────────────────────────────────────────────────────────
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)
      raw="${PUSH_BEFORE:-}"
      [ -n "${raw}" ] || raw="${PR_BASE_SHA:-}"
      ;;
    pull_request)
      raw="${PR_BASE_SHA:-}"
      [ -n "${raw}" ] || raw="${PUSH_BEFORE:-}"
      ;;
    "") die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *) die "неизвестное событие «${EVENT_NAME}» — база сравнения не определена" ;;
  esac
fi

[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?}) — что вошло в push, недоказуемо"
case "${raw}" in
  *[!0]*) : ;;
  *) die "база = zero-SHA (создание ветки или force-push) — диапазон недоказуем" ;;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || die "база «${raw}» отсутствует в истории (force-push / поверхностный клон — нужен fetch-depth: 0)"
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || die "база «${raw}» НЕ предок HEAD — история переписана; что вошло в диапазон, недоказуемо"
BASE="$(git rev-parse "${raw}^{commit}")"

# ── 2. Наш ли это репозиторий: слаг из ORIGIN, а НЕ литерал ───────────────────────────
# Сверка с зашитой константой воспроизводит ровно `C-062`: барьер, не спрашивающий origin,
# проходит весь набор и при этом не отличает наш репозиторий от чужого (GM-24 это убивает).
slug_of() { # нормализация любой формы URL → owner/name, регистр не значим
  printf '%s' "$1" | sed -E 's#/+$##; s#\.git$##; s#^.*[:/]([^:/]+/[^:/]+)$#\1#' | tr 'A-Z' 'a-z'
}
ORIGIN_URL="$(git remote get-url origin 2>/dev/null || true)"
[ -n "${ORIGIN_URL}" ] || die "у репозитория нет remote «origin» — принадлежность вердикта проверить нечем"
ORIGIN_SLUG="$(slug_of "${ORIGIN_URL}")"
[ -n "${ORIGIN_SLUG}" ] || die "origin «${ORIGIN_URL}» не приводится к виду owner/name"

# ── 2bis. ДИАПАЗОН СОБСТВЕННОЙ РАБОТЫ ВЕТКИ ───────────────────────────────────────────
# Всё, что судит subject-lock, обязано быть работой ВЕТКИ, а не работой `main`а. Якорей два,
# и одного мало — это находка `C-128` Б-1, предъявленная реальными CI-прогонами:
#
#   · `BASE` (база СОБЫТИЯ) устаревает: `github.event.pull_request.base.sha` обновляется
#     ЛЕНИВО и расходится с main-стороной merge-ref. У долгоживущего PR (норма гейтовых
#     кругов — PR #56 прожил шесть) ложный красный возвращается, и токен чеканится снова;
#   · `HEAD^1` merge-ref'а — main-сторона ПО ПОСТРОЕНИЮ, ей лениться нечем.
#
# ЯКОРЬ ВКЛЮЧАЕТСЯ ПО ПОДТВЕРЖДЁННОЙ ПРОД-ФОРМЕ, А НЕ ПО ФОРМЕ КОММИТА (`C-130` Б-1).
# Прежняя редакция включала его по одному лишь СУЩЕСТВОВАНИЮ `HEAD^2` — то есть применяла
# предпосылку «`HEAD^1` = main-сторона» к ЛЮБОМУ коммиту с двумя родителями. Предпосылка верна
# ровно у двух строителей (merge-ref GitHub'а и `gh pr merge`), а у штатной sync-вершины ветки
# (`git merge main` последним коммитом — рутина долгоживущего PR) стороны ОБРАТНЫЕ: `^HEAD^1`
# исключал ветку, суд получал пустоту и печатал «вердиктов проверено: 0» — МОЛЧАЛИВОЕ ложное
# зелёное, неотличимое от честного «вердиктов в диапазоне нет». Обе прежние редакции барьера
# то же нарушение ловили, то есть это была регрессия, а не унаследованный предел.
#
# Ориентация не УГАДЫВАЕТСЯ и не выводится из истории: `BASE` — предок ОБЕИХ сторон и
# дискриминатором не является. Она БЕРЁТСЯ ИЗ ТОГО ЖЕ КОНТРАКТА СОБЫТИЯ, что и сама база:
# на `pull_request` GitHub кладёт в `GITHUB_SHA` именно merge-ref, и совпадение с `HEAD`
# доказывает, что чекаут — merge-ref, а не вершина ветки. Нет доказательства ⇒ якорь НЕ
# применяется, судится весь диапазон: fail-closed, то есть в сторону ложного КРАСНОГО.
#
# На `push` якорь не применяется вовсе. Прежний комментарий утверждал «на push второго родителя
# нет» — это ЛОЖЬ для push-в-`main`: КАЖДЫЙ `gh pr merge --merge` даёт HEAD с `HEAD^2`
# (`C-130` N-4). Отказ от якоря на push безопасен и по существу: там `PUSH_BEFORE` не ленив,
# а исключать main-сторону незачем — она и есть база.
#
# ЧЕСТНО О ПРЕДЕЛЕ ПРОБЫ: конъюнкт `EVENT_NAME = pull_request` ОТДЕЛЬНЫМ сценарием НЕ запиннен,
# и декоративного сценария под него здесь нет. Причина названа, а не умолчана: единственный
# вред от якоря на push — батч из ≥2 merge'ей в одном push'е (`^HEAD^1` съел бы работу первого
# PR), а он недостижим при включённой защите ветки, требующей зелёного чека на каждый merge.
# Фикстура на недостижимое состояние пиннила бы воображение. Остальные два конъюнкта
# (`GITHUB_SHA == HEAD` и существование `HEAD^2`) запиннены `GM-16g`: прод-форма не
# подтверждена ⇒ якорь выключен ⇒ нарушение ловится.
EXCL_MAIN=()
ANCHOR_NOTE="якорь main-стороны НЕ применён (прод-форма merge-ref не подтверждена) — судится весь диапазон"
TOUCH_TIP="HEAD"
if [ "${EVENT_NAME:-}" = "pull_request" ] \
   && [ -n "${GITHUB_SHA:-}" ] \
   && [ "${GITHUB_SHA}" = "$(git rev-parse HEAD)" ] \
   && git rev-parse -q --verify 'HEAD^2' >/dev/null 2>&1; then
  EXCL_MAIN=( "^HEAD^1" )
  # КОНЕЧНАЯ ТОЧКА — ВЕРШИНА ВЕТКИ, а не синтезированный merge-ref. Комбинированный диф на
  # merge-ref печатает и файл, который слияние РЕАЛЬНО СЛИЛО из обеих сторон: замер на
  # merge-ref PR #60 давал лишний `scripts/verify_design_claims.sh` (его правили и #56 в
  # `main`, и #60) — ложный красный. Merge-ref строит GitHub механически, контрабанды в нём
  # быть не может; человеческий evil merge живёт НИЖЕ, внутри истории ветки, и `cc` его там
  # по-прежнему видит.
  TOUCH_TIP="HEAD^2"
  ANCHOR_NOTE="якорь main-стороны ПРИМЕНЁН (merge-ref подтверждён: GITHUB_SHA == HEAD, HEAD^2 есть); исключена сторона HEAD^1, судится HEAD^2"
fi

# `--diff-merges=cc` вместо `--no-merges` — это ЗАКРЫТИЕ дыры, а не смена флага (`C-128` M-3).
# Комбинированный диф печатает у merge-коммита только то, что отличается от ВСЕХ родителей, то
# есть содержимое EVIL MERGE (`git merge --no-commit` + правка + `commit` — две команды, без
# всякого конфликта), и НЕ печатает того, что merge просто принёс из другой ветки. Замер:
#   фикстура (main-коммит + ветка + evil-merge, правящий gate.sh)
#   --no-merges        → b.txt                 ← правка гейта НЕВИДИМА
#   --diff-merges=cc   → b.txt gate.sh         ← видима, работа main'а (a.txt) не втянута
# Прежняя редакция объявляла эту дыру «названным пределом» и приписывала невидимость флагу
# `--no-merges`; на деле её давал молчаливый дефолт `diff-merges=off`, не запиннутый ничем.
# СУДЯТСЯ КОММИТЫ, А НЕ ИТОГОВОЕ ДЕРЕВО (`C-130` N-3). Ветка, вливающая носитель правки гейта
# через `git merge -s ours`, итоговое дерево не меняет (`git diff --quiet` чист) — и всё же
# краснеет, потому что коммиты диапазона гейт трогали. Сторона ошибки защитная, семантика
# намеренная, но прежде она нигде не была названа.
own_touched() { # $1 = дополнительное исключение (`^<sha>`) либо пусто
  if [ -n "${1:-}" ]; then
    git log --format='' --name-only --diff-merges=cc "${BASE}..${TOUCH_TIP}" "$1" \
      ${EXCL_MAIN[@]+"${EXCL_MAIN[@]}"} 2>/dev/null | sort -u
  else
    git log --format='' --name-only --diff-merges=cc "${BASE}..${TOUCH_TIP}" \
      ${EXCL_MAIN[@]+"${EXCL_MAIN[@]}"} 2>/dev/null | sort -u
  fi
}
own_bodies() { # тела коммитов ТОГО ЖЕ диапазона — токен ищется там же, где найдено нарушение
  git log --format='%B' "${BASE}..${TOUCH_TIP}" "$1" ${EXCL_MAIN[@]+"${EXCL_MAIN[@]}"} 2>/dev/null || true
}
OWN_FILES="$(own_touched '')"

echo "── GATE-META: диапазон ${BASE:0:8}..HEAD, origin=${ORIGIN_SLUG}"
# Активация якоря ПЕЧАТАЕТСЯ всегда (`C-130` Б-1 п.4): «вердиктов проверено: 0» не должно быть
# молчанием — читатель обязан видеть, судился ли весь диапазон или одна его сторона.
echo "   ${ANCHOR_NOTE}"

# ── 3. Форма шапки, принадлежность предмету, subject-lock ─────────────────────────────
meta_of() { # $1=содержимое файла → строки ВНУТРИ блока GATE-META
  printf '%s\n' "$1" | awk '
    /<!-- GATE-META/ { inb = 1; next }
    inb && /-->/     { exit }
    inb              { print }'
}
field_of() { # $1=имя поля $2=блок шапки
  printf '%s\n' "$2" \
    | sed -n "s/^[[:space:]]*$1:[[:space:]]*//p" \
    | sed -n '1p' | sed 's/[[:space:]]*$//'
}
# Классы путей, запираемые проходным вердиктом (спека §10 — предел: только эти классы).
is_gate_class() {
  case "$1" in
    .claude/rules/*) return 0 ;;
    .github/workflows/*) return 0 ;;
    scripts/verify_*.sh) return 0 ;;
    scripts/check_*.sh) return 0 ;;
    scripts/tests/red_*.sh) return 0 ;;
    *) return 1 ;;
  esac
}

# Токен до-нормативного приземления: ищем в телах коммитов диапазона строку, НАЗЫВАЮЩУЮ этот
# путь. Тело читается `git log -1 --format='%B'`, а не `git show`: последний отдал бы и текст
# ДИФФА, и файл, ЦИТИРУЮЩИЙ токен, открывал бы лок сам себе (класс, названный в
# `check_docs_freeze.sh`).
archived_token_for() { # $1=путь → SHA коммита-носителя; 1, если токена нет
  local c line rest reason
  while IFS= read -r c; do
    [ -n "${c}" ] || continue
    while IFS= read -r line; do
      case "${line}" in "ARCHIVED-VERDICT: "*) : ;; *) continue ;; esac
      rest="${line#ARCHIVED-VERDICT: }"
      case "${rest}" in *"$1"*) : ;; *) continue ;; esac
      reason="${rest//"$1"/}"
      # причина — то, что осталось помимо пути; пробелы не считаются (порог 12 — как у
      # FOUNDER-APPROVED в check_docs_freeze.sh)
      __r="${reason//[[:space:]]/}"
      [ "${#__r}" -ge 12 ] || continue
      printf '%s' "${c}"
      return 0
    done < <(git log -1 --format='%B' "${c}" 2>/dev/null || true)
  done < <(git rev-list "${BASE}..HEAD" 2>/dev/null || true)
  return 1
}

# Вердикты, ВВЕДЁННЫЕ САМОЙ ВЕТКОЙ. Прежде бралось всё из `BASE..HEAD` двухточечным дифом —
# и при устаревшей базе в суд попадали вердикты ЧУЖИХ, уже влитых предметов. Именно так
# `R-108` (вердикт PR #56) запер PR #60: файл в дереве есть, к предмету ветки отношения не
# имеет (`C-128` Б-1).
verdict_changes="$(git diff --name-status --diff-filter=AM "${BASE}" HEAD -- \
  research/critiques research/reviews research/arbitration 2>/dev/null \
  | while IFS="$(printf '\t')" read -r __st __f; do
      [ -n "${__f}" ] || continue
      printf '%s\n' "${OWN_FILES}" | grep -qxF -- "${__f}" || continue
      printf '%s\t%s\n' "${__st}" "${__f}"
    done || true)"

checked=0
exempt=0
while IFS="$(printf '\t')" read -r st f; do
  [ -n "${f}" ] || continue
  case "${f}" in *.md) ;; *) continue ;; esac

  body="$(git show "HEAD:${f}" 2>/dev/null || true)"
  if ! grep -q '<!-- GATE-META' <<<"${body}"; then
    if [ "${st}" = "A" ] && tok="$(archived_token_for "${f}")"; then
      echo "NOTE  ${f}: до-нормативный артефакт приземлён явным ARCHIVED-VERDICT в ${tok:0:8} (аудит-след, НЕ доказательство — F-089-1)"
      exempt=$((exempt + 1))
      continue
    fi
    checked=$((checked + 1))
    bad "${f}: нет шапки GATE-META — вердикт ничем не привязан к предмету"
    [ "${st}" = "A" ] || echo "      статус ${st}: вердикт ИЗМЕНЁН этим диапазоном — приземление до-нормативного артефакта (ARCHIVED-VERDICT) сюда не относится"
    continue
  fi
  checked=$((checked + 1))
  meta="$(meta_of "${body}")"
  ms="$(field_of milestone "${meta}")"
  ar="$(field_of audited_repo "${meta}")"
  ab="$(field_of audited_base "${meta}")"
  ah="$(field_of audited_head "${meta}")"
  vd="$(field_of verdict "${meta}")"

  empty=""
  [ -n "${ms}" ] || empty="${empty} milestone"
  [ -n "${ar}" ] || empty="${empty} audited_repo"
  [ -n "${ab}" ] || empty="${empty} audited_base"
  [ -n "${ah}" ] || empty="${empty} audited_head"
  [ -n "${vd}" ] || empty="${empty} verdict"
  if [ -n "${empty}" ]; then
    bad "${f}: пустые поля шапки:${empty} — шапка стала ритуалом"
    continue
  fi

  # `milestone:` — ДЕКЛАРАЦИЯ (спека §4): против диффа она НЕ валидируется. Машинно —
  # непустота и форма идентификатора артефакта `КЛАСС-НОМЕР[буква]` (`gates.md` §12).
  # Форма НАМЕРЕННО шире буквального «M-NN[буква]» из спеки §4: вердикты пишутся и по
  # карточкам долга (`R-077` аудировал `TD-141`), и сузить её значило бы завести ложный
  # красный там, где предмет назван честно. Отступление названо, а не сделано молча.
  case "${ms}" in
    [A-Za-z]*-[0-9]*)
      grep -qE '^[A-Za-z]+-[0-9]+[a-z]?$' <<<"${ms}" \
        || bad "${f}: milestone «${ms}» не похож на идентификатор артефакта (КЛАСС-НОМЕР[буква])"
      ;;
    *) bad "${f}: milestone «${ms}» не похож на идентификатор артефакта (КЛАСС-НОМЕР[буква])" ;;
  esac

  if ! in_list "${vd}" "${VERDICT_ENUM}"; then
    bad "${f}: verdict «${vd}» вне перечня (${VERDICT_ENUM})"
    continue
  fi

  if [ "$(printf '%s' "${ar}" | tr 'A-Z' 'a-z')" != "${ORIGIN_SLUG}" ]; then
    bad "${f}: audited_repo «${ar}» ≠ origin этого репозитория «${ORIGIN_SLUG}» (класс C-062)"
    continue
  fi

  git rev-parse -q --verify "${ab}^{commit}" >/dev/null 2>&1 \
    || { bad "${f}: audited_base «${ab}» не существует в этой истории (класс C-062)"; continue; }
  git rev-parse -q --verify "${ah}^{commit}" >/dev/null 2>&1 \
    || { bad "${f}: audited_head «${ah}» не существует в этой истории (класс C-062)"; continue; }
  git merge-base --is-ancestor "${ah}" HEAD 2>/dev/null \
    || { bad "${f}: audited_head «${ah}» НЕ предок HEAD — аудировалась другая линия истории"; continue; }

  # ЧТО СДЕЛАЛА ВЕТКА ПОСЛЕ ВЕРДИКТА — а не «что изменилось в дереве». Разница практическая:
  # на событии `pull_request` CI берёт `HEAD`ом MERGE-REF, и прежний двухточечный
  # `git diff "${ah}" HEAD` включал в «тронутое» всё, что приехало в `main` за время кругов
  # гейта. Замер 2026-08-23, два ложных красных за сессию: PR #28 заперт на файлах PR #56,
  # PR #60 — по вердикту `R-108` того же чужого предмета. Диапазон и его якоря — `own_touched`
  # (см. §2bis выше); там же названо, почему якорей ДВА и почему `--diff-merges=cc`.
  if in_list "${vd}" "${PASSING_VERDICTS}"; then
    touched=""
    while IFS= read -r t; do
      [ -n "${t}" ] || continue
      is_gate_class "${t}" && touched="${touched} ${t}"
    done < <(own_touched "^${ah}")
    if [ -n "${touched}" ]; then
      # ТОКЕН ИЩЕТСЯ В ТОМ ЖЕ ДИАПАЗОНЕ, что и нарушение (`C-128` Б-2). Прежде «тронутое»
      # сузили до работы ветки, а поиск токена оставили на широком `${ah}..HEAD` — и ЧУЖОЙ
      # токен, приехавший из `main`, открывал лок на РЕАЛЬНОЕ нарушение ветки. Канал был не
      # теоретическим: `893ead1` (обход, выданный PR #28) влит в `main` и в живом прогоне
      # PR #60 открыл локи `C-123` и `R-108`. Деградация самоусиливающаяся — каждый ложный
      # красный чеканит токен, токен вливается в `main` и гасит локи соседних PR.
      if grep -q 'ALLOW-SUBJECT-CHANGE:' <<<"$(own_bodies "^${ah}")"; then
        echo "NOTE  ${f}: subject-lock открыт явным ALLOW-SUBJECT-CHANGE (аудит-след, НЕ доказательство — F-064-6):${touched}"
      else
        bad "${f}: subject-lock — после проходного вердикта (${vd}) тронут класс «гейт»:${touched}"
        echo "      выход из лока — строка «ALLOW-SUBJECT-CHANGE: <причина>» в теле коммита диапазона"
      fi
    fi
  fi
done <<EOF
${verdict_changes}
EOF

# ── 4. ОТСУТСТВИЕ вердикта (К-4): merge, называющий M-NN, обязан нести R-* в СВОЁМ дереве ─
# ЯКОРИ ЗДЕСЬ СОЗНАТЕЛЬНО НЕ ПРИМЕНЯЮТСЯ (`C-130` N-5). Раздел §2bis говорит «всё, что судит
# subject-lock, обязано быть работой ветки» — про subject-lock; absence-проверка живёт на
# ШИРОКОМ диапазоне намеренно. При устаревшей базе в суд попадут и чужие main-merge'и, но их
# вердикты лежат в их же деревьях, и повторный суд над ними зелен: цена — лишний обход, а не
# ложный исход. Сужать было бы хуже: пропустить merge БЕЗ вердикта дороже, чем пересудить
# merge с вердиктом.
# Судятся ВСЕ merge-коммиты диапазона, а не первый (GM-21). Не-merge коммиты не судятся:
# иначе каждый рабочий коммит потребует вердикта, и лок станет вреднее отсутствующего (GM-19).
# ПРЕДЕЛ (спека §5): merge, НЕ называющий milestone в subject'е, не покрыт — `TD-105`
# закрывается ЧАСТИЧНО, и это говорится, а не подразумевается.
merges=0
while IFS= read -r c; do
  [ -n "${c}" ] || continue
  git rev-parse -q --verify "${c}^2" >/dev/null 2>&1 || continue
  subj="$(git log -1 --format='%s' "${c}")"
  mid="$(grep -oE 'M-[0-9]+[a-z]?' <<<"${subj}" | sed -n '1p' || true)"
  [ -n "${mid}" ] || continue
  merges=$((merges + 1))
  found=""
  while IFS= read -r rf; do
    [ -n "${rf}" ] || continue
    if grep -qE -- "${mid}([^0-9a-z]|$)" <<<"$(git show "${c}:${rf}" 2>/dev/null || true)"; then
      found="${rf}"
      break
    fi
  done < <(git ls-tree -r --name-only "${c}" -- research/reviews 2>/dev/null \
    | grep -E '^research/reviews/R-.*\.md$' || true)
  if [ -n "${found}" ]; then
    echo "OK    merge ${c:0:8} «${subj}» — вердикт ${found} в дереве слияния"
  else
    bad "merge ${c:0:8} называет ${mid}, но research/reviews/R-*.md с этим литералом в дереве слияния НЕТ (класс TD-105)"
  fi
done < <(git rev-list "${BASE}..HEAD" 2>/dev/null || true)

echo
if [ "${FAILED}" -gt 0 ]; then
  echo "VERDICT: FAIL (${FAILED}) — вердикт не привязан к предмету либо merge прошёл без вердикта."
  echo "Шаблон шапки — .claude/rules/gates.md §4; проба контракта — scripts/tests/red_gate_meta.sh."
  exit 1
fi
echo "VERDICT: PASS — вердиктов проверено: ${checked}, до-нормативных приземлений: ${exempt}, merge'ей с milestone в subject'е: ${merges}"
