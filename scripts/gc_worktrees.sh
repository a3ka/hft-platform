#!/usr/bin/env bash
# gc_worktrees.sh — безопасная рекультивация git-worktree'ов (branch-hygiene.md §Worktree lifecycle).
#
# ПРОБЛЕМА: правило «worktree на роль/задачу» кодифицировано, «освободи после» — нет. Каждый worktree
# компилирует свой multi-GB `target/`; никто не сносит → дисковая протечка (инцидент: 61 worktree × ~3.5 GB).
#
# ГАРАНТИЯ БЕЗОПАСНОСТИ (не теряем работу): worktree удаляется ТОЛЬКО если ВСЕ ЧЕТЫРЕ условия:
#   (1) рабочее дерево ЧИСТОЕ (`git status --porcelain` пусто) — иначе возможна активная сессия;
#   (2) НЕТ только-локальных коммитов (`git rev-list HEAD --not --remotes` == 0) — всё на origin;
#   (3) HEAD ПОЛНОСТЬЮ на `origin/main` (`git merge-base --is-ancestor HEAD origin/main`) — милстоун смержен;
#   (4) НИ ОДИН живой процесс не держит `cwd` в дереве (`/proc/*/cwd`) — см. блок ниже.
# НИКОГДА не `--force`, НИКОГДА не `rm -rf` вслепую. Активные (dirty/unpushed/не-смерженные) — не трогаются.
#
# ── УСЛОВИЕ (4): ПОЧЕМУ ТРЁХ GIT-УСЛОВИЙ ОКАЗАЛОСЬ МАЛО (инцидент 2026-08-24) ──────────
# Условия (1)-(3) описывают состояние ГИТА, а не состояние МИРА. Агент, который только что
# забутстрапился в свежем дереве и ещё не написал ни строки, проходит все три идеально:
# дерево чистое (вердикт не написан), локальных коммитов нет, HEAD — ровно `origin/main`.
# Ровно так 24.08 `--reclaim` снёс `/tmp/hft-codex-critic-1787600196` — рабочий каталог
# ЖИВОГО критика, стоявшего на бутстрапе. Работа не пропала только потому, что транскрипт
# codex пишется вне дерева; `cwd` четырёх процессов превратился в удалённый inode, и сессия
# стала нерабочей. Оператор, снёсший дерево, за сорок минут до этого сам перечислял его
# среди живых — и всё равно отдал решение инструменту, у которого понятия «живой процесс»
# нет. Это не ошибка оператора поверх исправного стража, а отсутствующий страж.
#
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ: есть ли процесс, чей `cwd` равен пути дерева или лежит внутри него.
# Удалённый каталог `readlink` отдаёт как `<путь> (deleted)` — суффикс снимается, иначе
# сторож ослеп бы ровно на те процессы, которым уже навредили.
# FAIL-CLOSED: `/proc` недоступен или нечитаем ⇒ ответ «НЕ ЗНАЮ», и он трактуется как
# «держит». «Спросить не смогли» и «никто не держит» — разные состояния (`testing.md`,
# целостность гейта, свойство 3); разрушительный путь при неизвестности обязан отказывать.
# ГАРАНТИЯ СФОРМУЛИРОВАНА УЗКО (`C-140`, условие снятия REJECT'а). Сторож обещает ровно
# следующее и ни слова больше:
#
#   «Ни один процесс, чей `cwd` мы СМОГЛИ прочитать, не находится в дереве или под ним;
#    плюс ни один процесс НАШЕГО uid не остался неопрошенным.»
#
# Что в гарантию НЕ входит — перечислено поимённо, потому что широкое обещание на
# разрушительном пути хуже узкого:
#   1. **Открытые файлы.** Сторож видит `cwd`, а не `/proc/*/fd`. Процесс, работающий в
#      дереве по АБСОЛЮТНЫМ путям из другого `cwd`, не ловится. Обход `fd` на порядок
#      дороже и на больших `target/` даёт секунды на прогон — сознательный выбор.
#   2. **Чужие процессы с нечитаемым `cwd`.** Их число ПЕЧАТАЕТСЯ отдельной строкой
#      («N чужих процессов не опрошено»), но они не блокируют: замер 2026-08-24 даёт 590 из
#      817 нечитаемых, из них 483 root. Блокировать на них — значит не удалять никогда, то
#      есть вернуться к отсутствующему сторожу через его же выключение.
#   3. **Подкаталог под АЛИАСОМ дерева.** Сравнение `dev:inode` закрывает алиас САМОГО
#      корня (bind-mount, путь через симлинк — `C-140-2`). Для `cwd` вида
#      `<алиас>/подкаталог` текст не совпадёт префиксом, а инод у подкаталога свой —
#      такой случай сторож пропустит. Закрывается разбором `/proc/<pid>/mountinfo`; не
#      сделано и не изображается сделанным.
#
# Пункты 1-3 — `COGNITIVE-ONLY` в том смысле, что механизма у них нет; но они НАЗВАНЫ, и
# именно поэтому строка вывода отличает «никто не держит» от «спросить не смогли».
#
# ПОЧЕМУ ОДНОГО СНОСА ДЕРЕВЬЕВ НЕ ХВАТИЛО (инцидент 2026-08-12, диск 100 %):
# правило требовало запускать GC «в close-out после merge», а мусор производит ИМЕННО длинная
# НЕСЛИТАЯ работа: за неделю не смержено ничего, значит триггер не сработал ни разу. Плюс сам
# скрипт удаляет только ПОЛНОСТЬЮ смерженные деревья — при отсутствии merge он не удаляет
# ничего. Замер того дня: все 165 каталогов работы весили 782 MB, а `target/` — 105 GB.
# То есть механизм не покрывал 99 % объёма и не мог сработать в своём худшем случае.
# Отсюда режим `--reclaim`: он забирает КЭШ, не трогая работу, и не зависит ни от merge,
# ни от чистоты дерева — `target/` не работа ни при каком состоянии ветки.
#
# ЧЕГО ЭТОТ СКРИПТ НЕ ДЕЛАЕТ (названо явно, чтобы не подразумевалось):
#   • не трогает `target/` каталогов, не числящихся в `git worktree list` (осиротевшие после
#     `worktree remove`/`prune` деревья). Замер 2026-08-12: 19 таких каталогов, 13.9 GB —
#     видимого механизма для них нет, убираются руками;
#   • не убирает СВОЙ кэш агента в момент сдачи работы: свежий кэш по определению не «молчит»
#     (см. `branch-hygiene.md` §Worktree lifecycle п.3 — там это отдельная команда).
set -uo pipefail

# Корень proc вынесен в переменную РАДИ ПРОБЫ: сценарий «/proc недоступен» иначе не
# воспроизвести без root. Прод-путь её не задаёт (`gates.md` §3: гейт гоняет прод-форму).
PROC_ROOT="${GC_PROC_ROOT:-/proc}"
# Число процессов ЧУЖОГО владельца, чей cwd прочитать не удалось. Не блокирует (иначе
# инструмент мёртв — 590 из 817 на живой машине), но ПЕЧАТАЕТСЯ: «спросить не смогли» и
# «никто не держит» обязаны различаться в выводе, даже когда решение одно и то же.
#
# СЧЁТЧИК — В ФАЙЛЕ, А НЕ В ПЕРЕМЕННОЙ. `holder_pids` зовётся из `$(…)`, то есть в
# ПОДОБОЛОЧКЕ, и любой инкремент снаружи теряется. Тот же класс уже стоил пробам барьеров
# потерянного реестра фикстур (`red_branch_health.sh`, шапка `mk_repo`).
UNINSPECT_FILE="$(mktemp "${TMPDIR:-/tmp}/gcwt-uninspect-XXXXXX")"
trap 'rm -f "${UNINSPECT_FILE}"' EXIT
MY_UID="$(id -u)"   # один раз: иначе `id` зовётся на КАЖДЫЙ из сотен PID'ов

# holder_pids <путь> — печатает PID'ы процессов, чей cwd равен пути или лежит внутри него.
# Код возврата: 0 — держат (или спросить не смогли, fail-closed), 1 — точно никто не держит.
holder_pids() {
  local wt="$1" p pid t found=0 readable=0 wtid="" cwdid=""
  # Отдельной проверки `[ -d "$PROC_ROOT" ]` здесь НЕТ намеренно. Она стояла и была снята
  # мутационным контролем: её случай целиком закрыт стражем `readable` ниже — при
  # отсутствующем, нечитаемом или пустом каталоге glob не раскрывается, `readable` остаётся
  # нулём, и ответ всё равно «не знаю» ⇒ «держит».
  wtid="$(stat -c '%d:%i' "$wt" 2>/dev/null || true)"
  for p in "$PROC_ROOT"/[0-9]*; do
    [ -e "$p" ] || continue
    readable=1
    pid="${p##*/}"
    if ! t="$(readlink "$p/cwd" 2>/dev/null)"; then
      # СНАЧАЛА — УМЕР ЛИ ПРОЦЕСС. Между раскрытием glob'а и `readlink` проходит время, и в
      # живом `/proc` доминирующая причина отказа — не права, а исчезнувший PID. Мёртвый
      # процесс держателем не является ни в каком смысле, и трактовать его как «не знаю»
      # значит блокировать всё на ровном месте: на runner'е GitHub это уронило соседнюю
      # пробу `red_gc_reclaim_args` целиком (PID 909/925, прогон 2026-08-24T23:04Z).
      [ -d "$p" ] || continue
      # C-140-1: НЕЧИТАЕМЫЙ cwd — ЭТО «НЕ ЗНАЮ», А НЕ «НЕ ДЕРЖИТ». Прежняя редакция делала
      # здесь `continue`, и разрушительный путь доходил до удаления; критик предъявил это
      # ИСПОЛНЕНИЕМ (`WOULD-REMOVE` при PID с permission-denied на cwd).
      #
      # Но «нечитаем ⇒ держит» ВСЛЕПУЮ убивает инструмент. Замер на живой машине
      # 2026-08-24: 817 PID-каталогов, cwd читается у 227, НЕ читается у 590 — из них 483
      # root. То есть безусловное правило означало бы «никогда ничего не удалять», а
      # сторож, блокирующий всё, снимут первым же «он мешает» — и мы вернёмся к нулю.
      #
      # РАЗЛИЧИТЕЛЬ — ВЛАДЕЛЕЦ. Наши агенты работают под нашим же uid, и их cwd читается:
      # тем же замером процессов НАШЕГО uid 228, нечитаемых среди них 0. Значит нечитаемый
      # cwd У СВОЕГО процесса — аномалия, и fail-closed на ней бесплатен сегодня и закрывает
      # ровно тот класс, который реально держит наши деревья. Чужой uid — считается и
      # ПЕЧАТАЕТСЯ (см. вызывающий код), но не блокирует; предел назван, а не умолчан.
      if [ "$(stat -c '%u' "$p" 2>/dev/null || echo -1)" = "${MY_UID}" ]; then
        echo "${pid}?"; found=1
      else
        printf 'x' >> "${UNINSPECT_FILE}"
      fi
      continue
    fi
    t="${t% (deleted)}"
    case "$t" in "$wt"|"$wt"/*) echo "$pid"; found=1; continue ;; esac
    # C-140-2: ТЕКСТОВОЕ сравнение слепо к АЛИАСУ каталога (bind-mount, симлинк-путь):
    # критик предъявил `WOULD-REMOVE` при cwd, указывающем на алиас того же дерева.
    # Идентичность каталога решается не строкой, а парой устройство:инод — она одна и та же
    # по любому пути, ведущему в тот же каталог (замер: алиас и оригинал дают `2306:24672828`).
    if [ -n "${wtid}" ]; then
      cwdid="$(stat -Lc '%d:%i' "$p/cwd" 2>/dev/null || true)"
      [ -n "${cwdid}" ] && [ "${cwdid}" = "${wtid}" ] && { echo "${pid}~"; found=1; }
    fi
  done
  [ "$readable" = "1" ] || { echo "?"; return 0; }    # proc пуст/нечитаем — тоже «не знаю»
  [ "$found" = "1" ]
}

usage() {
  cat <<'EOF'
Usage:
  scripts/gc_worktrees.sh                  # удалить все безопасно-рекультивируемые деревья
  scripts/gc_worktrees.sh --dry-run        # только показать, что было бы удалено
  scripts/gc_worktrees.sh --reclaim [N]    # снести target/ у деревьев, молчащих дольше N часов,
                                           # затем обычный безопасный GC
  scripts/gc_worktrees.sh --reclaim-dry [N]
  N — целое число часов, ТОЛЬКО цифры (0, 2, 24); по умолчанию 2.
EOF
}

# ─── РАЗБОР АРГУМЕНТОВ: fail-CLOSED ──────────────────────────────────────────────────────
# Почему это не формальность (R-055 Б-1, воспроизведено на живом репозитории). Страж режима
# reclaim стоит на `[ "$idle_h" -lt "$IDLE_H" ]`. Нечисловой порог роняет САМО сравнение: `[`
# возвращает не-ноль, ветка KEEP-CACHE не берётся, управление уходит прямо в `rm -rf`. То
# есть при опечатке страж не ужесточается, а ОТКЛЮЧАЕТСЯ — вместе с деревьями, где сборка
# шла минуту назад. Прежняя шапка сама печатала параметр как `[Ч]`, приглашая набрать `3ч`.
# Отрицательный порог даёт тот же исход без всякой ошибки: `[ 0 -lt -1 ]` просто ложно.
# Прежний `case "${1:-}"` разбирал ТОЛЬКО первый аргумент: `--dryrun` не совпадал ни с чем и
# молча означал БОЕВОЙ прогон, а `--dry-run --reclaim` терял reclaim. Оба — опечатки, ценой
# которых чужая работа. Отсюда: полный цикл по аргументам, неизвестное — отказ.
# Оракул — `scripts/tests/red_gc_reclaim_args.sh` (13 сценариев, в CI).
DRY=0
MODE=gc
IDLE_H=2
IDLE_SET=0

refuse() {
  echo "ОТКАЗ: $*" >&2
  usage >&2
  echo "VERDICT: GC REFUSED (аргументы)" >&2
  exit 2
}

# ПЕРВЫЙ БАРЬЕР. Валидация идёт ТЕМ ЖЕ парсером, который порог потом ПОТРЕБЛЯЕТ, — иначе
# множества допустимого расходятся, и дыра неизбежна (R-058 Б-1rev2: текстовая проверка
# `*[!0-9]*` пропускала любую строку цифр, а `[ -lt ]` парсит только до intmax; порог из
# 20 цифр проходил валидацию и ронял сравнение). Текстовая проверка оставлена первой лишь
# ради ВНЯТНОГО сообщения на `3ч`; решает вторая строка — сам shell.
validate_threshold() {
  case "$1" in '' | *[!0-9]*) return 1 ;; esac
  [ "$1" -ge 0 ] 2>/dev/null || return 1
  return 0
}

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run)     DRY=1 ;;
    --reclaim)     MODE=reclaim ;;
    --reclaim-dry) MODE=reclaim; DRY=1 ;;
    -h|--help)     usage; exit 0 ;;
    *)
      # Единственный допустимый позиционный аргумент — порог часов, и только в режиме reclaim.
      [ "$MODE" = "reclaim" ] || refuse "неизвестный аргумент «$1»"
      [ "$IDLE_SET" = "0" ] || refuse "порог задан дважды («$IDLE_H» и «$1»)"
      validate_threshold "$1" || refuse "порог «$1» негоден. Ожидается целое число часов ≥ 0,
       которое РАЗБИРАЕТ САМ shell (0, 2, 24). Негодный порог не делает страж строже — он
       его выключает, и rm -rf уходит по кэшу деревьев, где сборка шла минуту назад."
      IDLE_H="$1"; IDLE_SET=1 ;;
  esac
  shift
done

ROOT="$(git rev-parse --path-format=absolute --git-common-dir 2>/dev/null | sed 's#/\.git$##')"
git fetch origin --quiet 2>/dev/null || true

# Путь берётся ЦЕЛИКОМ, а не первым полем (A-008 §1.1). `awk '{print $2}'` резал путь по
# первому ПРОБЕЛЬНОМУ символу, и дальше `rm -rf` уходил по УСЕЧЁННОМУ префиксу — то есть по
# каталогу, которого в списке worktree'ов нет вовсе. Два круга держали это как NOTE на
# основании «практически прикрыто `[ -d "$wt/target" ]`»; арбитр основание опроверг: условию
# `[ -d ]` удовлетворяет ЛЮБОЙ каталог, случайно оказавшийся по усечённому пути.
# Здесь, в MAIN_CHECKOUT, парсинг чинится ЗА КОМПАНИЮ и ради консистентности: сравнение
# `[ "$wt" = "$MAIN_CHECKOUT" ]` усекает обе стороны ОДИНАКОВО, поэтому иммунитет главного
# чекаута усечением не терялся. Утверждать обратное было бы переобещанием.
# Пути с `\n` вне модели угроз: git таких worktree'ов не создаёт.
MAIN_CHECKOUT="$(git worktree list --porcelain | sed -n 's/^worktree //p' | head -1)"

# ─── РЕЖИМ RECLAIM: забрать кэш сборки, работу не трогать ────────────────────────────────
if [ "$MODE" = "reclaim" ]; then
  # FAIL-CLOSED: если где-то идёт сборка, её кэш сносить нельзя — прогон упадёт с невнятной
  # ошибкой компоновки, и причину будут искать в коде. Лучше отказаться и сказать почему.
  # Отказ касается ТОЛЬКО реального сноса: сухой прогон ничего не удаляет, и запрещать его
  # при живой сборке значит приучать обходить страж ради простого «посмотреть».
  if [ "$DRY" = "0" ] && { pgrep -x cargo >/dev/null 2>&1 || pgrep -x rustc >/dev/null 2>&1; }; then
    echo "ОТКАЗ: идёт сборка (cargo/rustc). Кэш сносить нельзя — прогон упадёт, и причину"
    echo "       будут искать в коде. Дождись окончания либо снеси target/ вручную у молчащих."
    echo "VERDICT: GC REFUSED (активная сборка)"
    exit 1
  fi
  # Счётчиков «освобождено всего» здесь нет НАМЕРЕННО: цикл живёт в подоболочке пайпа, и
  # любая сумма, накопленная внутри, снаружи теряется. Итог показывает `df -h` ниже — он
  # меряет диск, а не наши намерения.
  now=$(date +%s)
  git worktree list --porcelain | sed -n 's/^worktree //p' | while IFS= read -r wt; do
    [ "$wt" = "$MAIN_CHECKOUT" ] && continue
    [ -d "$wt/target" ] || continue
    m=$(stat -c %Y "$wt/target" 2>/dev/null || echo "$now")
    idle_h=$(( (now - m) / 3600 ))
    # `du` считается и для KEEP-CACHE сознательно: строка «оставил 9 GB» — единственное, что
    # объясняет, куда делся диск, когда порог никого не отпустил.
    sz=$(du -sm "$wt/target" 2>/dev/null | cut -f1)
    # Тот же сторож, что в цикле сноса: `rm -rf target/` под живой сборкой рушит её на
    # середине. Порог молчания это НЕ ловит — процесс может держать дерево и молчать
    # (агент на бутстрапе, ожидание ввода, пауза между шагами).
    : > "${UNINSPECT_FILE}"
    if hp="$(holder_pids "$wt")"; then
      echo "KEEP-CACHE  $(basename "$wt") — ЖИВОЙ процесс держит cwd (PID: $(tr '\n' ' ' <<<"$hp")), ${sz}MB"
      continue
    fi
    un="$(wc -c < "${UNINSPECT_FILE}" | tr -d ' ')"
    [ "${un}" != "0" ] && echo "      ($(basename "$wt"): ${un} чужих процессов не опрошено — cwd нечитаем)"
    # ВТОРОЙ БАРЬЕР, независимый от первого, — и он же ответ на КЛАСС, а не на два его
    # экземпляра (R-055 Б-1 «3ч», R-058 Б-1rev2 «20 цифр»: оба входа роняли САМО сравнение,
    # и управление проваливалось в удаление). Условие переписано с отрицательного на
    # положительное: удаление требует УТВЕРДИТЕЛЬНОГО «да» (`-ge` истинно), а не ОТСУТСТВИЯ
    # «нет». Любая неудача вычисления — переполнение, порча переменной, будущая правка,
    # ослабившая валидацию, — даёт не-ноль и уходит в KEEP-CACHE.
    # ЧЕСТНО О ГРАНИЦЕ: два барьера закрывают РАЗНЫЕ подмножества и оба несущие. Инверсия
    # ловит «сравнение не состоялось» (нецифровой ввод, переполнение) при любом входе, но
    # НЕ ловит вход, который разбирается корректно и просто неверен по смыслу: `-1`
    # сравнивается прекрасно и означает «снести всё». Против него работает только
    # `validate_threshold`. Утверждение «инверсия закрывает класс целиком» было бы тем же
    # переобещанием, за которое этот скрипт уже получил два REJECT'а.
    if [ "$idle_h" -ge "$IDLE_H" ] 2>/dev/null; then
      if [ "$DRY" = "1" ]; then
        echo "WOULD-RECLAIM  $(basename "$wt") — ${sz}MB, молчит ${idle_h}ч"
      else
        rm -rf "$wt/target" && echo "RECLAIMED  $(basename "$wt") — ${sz}MB (кэш; cargo пересоберёт)"
      fi
    else
      echo "KEEP-CACHE  $(basename "$wt") — молчит ${idle_h}ч (порог ${IDLE_H}ч), ${sz}MB"
    fi
  done
  echo "-----"
  df -h / | tail -1
  echo
fi

# Счётчиков нет по той же причине, что и в блоке reclaim: цикл — подоболочка пайпа.
# Список путей worktree'ов (кроме основного чекаута).
git worktree list --porcelain | sed -n 's/^worktree //p' | while IFS= read -r wt; do
  [ "$wt" = "$MAIN_CHECKOUT" ] && continue
  name="$(basename "$wt")"

  # Условие (4) проверяется ПЕРВЫМ и намеренно: остальные три описывают состояние гита, а
  # живой агент в свежем дереве проходит их все (инцидент 24.08, шапка).
  : > "${UNINSPECT_FILE}"
  if hp="$(holder_pids "$wt")"; then
    echo "KEEP  $name — ЖИВОЙ процесс держит cwd в дереве (PID: $(tr '\n' ' ' <<<"$hp"))"; continue
  fi
  un="$(wc -c < "${UNINSPECT_FILE}" | tr -d ' ')"
  [ "${un}" != "0" ] && echo "      ($name: ${un} чужих процессов не опрошено — cwd нечитаем; гарантия сторожа их НЕ покрывает)"

  dirty="$(git -C "$wt" status --porcelain 2>/dev/null | wc -l | tr -d ' ')"
  if [ "$dirty" != "0" ]; then
    echo "KEEP  $name — dirty ($dirty файл(ов); возможна активная сессия / несохранённое)"; continue
  fi
  local_only="$(git -C "$wt" rev-list HEAD --not --remotes 2>/dev/null | wc -l | tr -d ' ')"
  if [ "$local_only" != "0" ]; then
    echo "KEEP  $name — $local_only только-локальных коммит(ов) (сначала push, потом GC)"; continue
  fi
  if ! git -C "$wt" merge-base --is-ancestor HEAD origin/main 2>/dev/null; then
    echo "KEEP  $name — не смержен в origin/main (активный/запаркованный feat)"; continue
  fi

  if [ "$DRY" = "1" ]; then
    echo "WOULD-REMOVE  $name (чист, на origin, смержен)"
  else
    if git worktree remove "$wt" 2>/dev/null; then echo "REMOVED  $name"; else echo "KEEP  $name — git worktree remove отказал"; fi
  fi
done

if [ "$DRY" = "0" ]; then
  git worktree prune
  echo "-----"
  echo "worktree'ов осталось: $(git worktree list | wc -l | tr -d ' ')"
fi
echo "VERDICT: GC $([ "$DRY" = "1" ] && echo "DRY-RUN" || echo "DONE")"
