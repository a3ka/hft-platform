#!/usr/bin/env bash
# Механический барьер: СПЕКА НЕ УЕЗЖАЕТ В АРХИВ, ПОКА `PROJECT-STATE.md` НЕ НАЗВАЛ МИЛЕСТОУН ЗАКРЫТЫМ.
#
# ── ЗАМЕР, ИЗ-ЗА КОТОРОГО БАРЬЕР СУЩЕСТВУЕТ ─────────────────────────────────────────
# `R-213` §3/§6 (Ф-2): у ПЯТИ вынесенных в `docs/archive/` милестоунов раздел
# `PROJECT-STATE.md` продолжал утверждать «НЕ ЗАКРЫТ — close-out за architect'ом»:
#   M-69 636a3ec 2026-08-24 (38 суток) · M-75 70ca5c8 · M-77 a9058d3 · M-85 c576514 · M-87 8d81b44.
# Пять из пяти — ОДНА И ТА ЖЕ фраза, записанная reviewer'ом ДО переезда. Причина — разрыв
# зависимости в норме `docs/04-workflow.md` §Close-out: закрытость называет reviewer, переезд
# делает architect, а шага «реестр отражает закрытие» нет ни у одной роли. Architect
# `PROJECT-STATE.md` писать не вправе (reviewer-owned), reviewer о переезде не узнаёт.
# Разбор и решение — `docs/plans/ps-on-archive-2026-10-02.md`.
#
# ── ЗАЩИЩАЕМЫЙ ИНВАРИАНТ ─────────────────────────────────────────────────────────────
# В дереве, где спека милестоуна лежит в `docs/archive/`, `PROJECT-STATE.md` несёт
# машинный маркер закрытия этого милестоуна и НЕ несёт маркера «открыт».
#
# Маркер — строка целиком, вне блока кода:   <!-- MS-STATE: M-NN CLOSED -->   (или OPEN)
# Ставит его reviewer — тем же движением, которым называет милестоун закрытым.
# Почему маркер, а не проза: закрытость по прозе НЕ ВЫВОДИТСЯ (`R-098` §3.1 — три ревизии
# критерия, три ответа). Замер на дереве 2026-10-02 подтверждает: наивный греп «НЕ ЗАКРЫТ»
# по заголовкам разделов краснеет на ДВУХ честно закрытых милестоунах — у M-69 эта фраза
# стоит в цитате («стояла здесь 38 суток»), у M-88 «НЕ ЗАКРЫТ» относится к предмету `P0-CORR`,
# а не к милестоуну. Суждение reviewer'а записывается им самим в форме, которую машина
# читает однозначно; барьер его НЕ вычисляет, а лишь требует, чтобы оно было записано.
#
# ── ЧТО ПРОВЕРЯЕТСЯ ─────────────────────────────────────────────────────────────────
# 1. Триггер — диапазон добавляет `docs/archive/M-*.md` (тот же, что у `check_roadmap_sync.sh`).
#    Для каждого такого M-NN на вершине (`HEAD`, в PR — дерево слияния) обязан стоять
#    маркер `CLOSED`. Маркер может прийти из `main` (reviewer закрыл раньше) ИЛИ коммитом
#    reviewer'а в том же диапазоне — architect'у правка `PROJECT-STATE.md` не нужна и не
#    разрешена; барьер ТРЕБУЕТ ПОРЯДКА «назвал закрытым → переезд», а не правки переезжающим.
# 2. При сработавшем триггере `## `-заголовок раздела M-NN не смеет нести фразу
#    «close-out за architect» вне цитаты «…» и вне `кода` — ровно ту формулировку, которой
#    реестр лгал все пять раз. Узко по замыслу: общее «НЕ ЗАКРЫТ» законно (M-88).
# 3. ВСЕГДА (без триггера): маркер `OPEN` у милестоуна, чья спека лежит в архиве, — FAIL.
#    Ловит обратный дрейф: реестр, переписанный в «открыт» после переезда.
# 4. Строка, начинающаяся с `<!-- MS-STATE:`, но не по форме, — FAIL (опечатка иначе молча
#    равнялась бы отсутствию маркера).
#
# ── ПРЕДЕЛ НАЗВАН, А НЕ ИЗОБРАЖЁН ────────────────────────────────────────────────────
# · Барьер видит НАЛИЧИЕ маркера, а не его ИСТИННОСТЬ и не автора: git-личность в проекте
#   единая (`branch-hygiene.md` п.6), поставил ли маркер reviewer — не проверяемо.
# · Согласованность прозы раздела с маркером проверяется ТОЛЬКО по фразе п.2; прочие
#   формулировки «не закрыт» в прозе — суждение reviewer'а.
# · Удаление маркера `CLOSED` у уже вынесенного милестоуна не ловится (п.3 видит только `OPEN`).
# · 33 милестоуна, вынесенные ДО барьера, маркеров не несут и не обязаны: барьер срабатывает
#   на переезде, а не на состоянии архива целиком (ретро-заполнение — зона reviewer'а).
# · Заброшенный милестоун, уезжающий в архив без закрытия, барьер не различает: reviewer
#   записывает `CLOSED` и объясняет прозой — либо спека не переезжает.
#
# Проба: `scripts/tests/red_ps_on_archive.sh` — анти-плацебо в обе стороны + реплей реальных
# переездов M-69/M-75/M-77/M-85/M-87 (барьер обязан покраснеть на каждом).
set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.." || { echo "FAIL  не удалось встать в корень репозитория"; exit 1; }

PS="PROJECT-STATE.md"

die() { echo "FAIL  $*"; echo; echo "Барьер fail-closed: база сравнения не установлена достоверно."; echo "VERDICT: FAIL"; exit 1; }

# ── БАЗА СРАВНЕНИЯ = СОСТОЯНИЕ ДО СОБЫТИЯ (та же дисциплина, что у check_roadmap_sync.sh) ──
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}" ;;
    pull_request) raw="${PR_BASE_SHA:-}" ;;
    "")           die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *)            die "неизвестное событие '${EVENT_NAME}' — база сравнения не определена" ;;
  esac
fi
[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?})"
case "${raw}" in
  *[!0]*) : ;;
  *)      die "база = zero-SHA (создание ветки или force-push) — диапазон не определим" ;;
esac
git rev-parse --verify --quiet "${raw}^{commit}" >/dev/null || die "база ${raw} отсутствует в истории"
BASE="$(git rev-parse "${raw}^{commit}")"

# Состояние читается из КОММИТА `HEAD`, а не из рабочего дерева: незакоммиченная правка
# реестра не имеет права удовлетворить барьер.
if ! PS_TEXT="$(git show "HEAD:${PS}" 2>/dev/null)"; then
  echo "FAIL  ${PS} отсутствует в HEAD — реестр «что реализовано» снесён"
  echo "VERDICT: FAIL"
  exit 1
fi

FAILS=0
fail() { echo "FAIL  $*"; FAILS=$((FAILS+1)); }

# ── Разбор маркеров вне блоков кода ─────────────────────────────────────────────────
# Блок кода (``` или ~~~) — цитата, а не утверждение: маркер, процитированный в примере,
# не закрывает и не открывает ничего.
MARKERS="$(printf '%s\n' "$PS_TEXT" | awk '
  /^[ \t]*(```|~~~)/ { fence = !fence; next }
  fence { next }
  /^<!-- MS-STATE:/ {
    if ($0 ~ /^<!-- MS-STATE: M-[0-9]+[a-z]? (CLOSED|OPEN) -->[ \t]*$/) { print $3, $4 }
    else { print "MALFORMED", NR }
  }')"

while read -r a b; do
  [ -n "${a:-}" ] || continue
  [ "$a" = "MALFORMED" ] && fail "${PS}:${b}: строка маркера не по форме «<!-- MS-STATE: M-NN CLOSED|OPEN -->»"
done <<< "$MARKERS"

has_marker() { printf '%s\n' "$MARKERS" | awk -v id="$1" -v st="$2" '$1==id && $2==st {f=1} END {exit !f}'; }
archived_on_head() { git ls-tree -r --name-only HEAD -- docs/archive/ 2>/dev/null | awk -v id="$1" '{n=$0; sub(/^.*\//,"",n)} index(n, id"-")==1 {f=1} END {exit !f}'; }

# ── 3. ВСЕГДА: «открыт» у вынесенного ───────────────────────────────────────────────
while read -r id st; do
  [ "${st:-}" = "OPEN" ] || continue
  if archived_on_head "$id"; then
    fail "${PS} несёт «${id} OPEN», а спека ${id} лежит в docs/archive/ — реестр противоречит дереву"
  fi
done <<< "$MARKERS"

# ── 1-2. ТРИГГЕР: переезд в диапазоне ───────────────────────────────────────────────
mapfile -t ARCHIVED < <(git diff --no-renames --name-only --diff-filter=A "${BASE}..HEAD" -- 'docs/archive/M-*.md' 2>/dev/null || true)

N=0
for path in "${ARCHIVED[@]}"; do
  [ -n "$path" ] || continue
  base_name="${path##*/}"
  id="$(printf '%s' "$base_name" | sed -nE 's/^(M-[0-9]+[a-z]?)-.*/\1/p')"
  if [ -z "$id" ]; then fail "${path}: идентификатор милестоуна из имени не извлечён"; continue; fi
  N=$((N+1))
  if has_marker "$id" CLOSED; then
    echo "OK    ${id}: переезд, ${PS} несёт маркер CLOSED"
  else
    fail "${id} уехал в архив (${path}), а ${PS} НЕ несёт «<!-- MS-STATE: ${id} CLOSED -->»"
  fi
  # Заголовок раздела: только ## -строки вне блоков кода, называющие ровно этот id
  # (M-69 не совпадает с M-690 и M-69a); цитаты «…» и `код` вырезаются до поиска фразы.
  stale="$(printf '%s\n' "$PS_TEXT" | awk -v id="$id" '
    /^[ \t]*(```|~~~)/ { fence = !fence; next }
    fence { next }
    /^## / {
      line = $0
      if (match(line, "(^|[^0-9A-Za-z-])" id "([^0-9a-z]|$)") == 0) next
      # « и » сперва заменяются однобайтовыми метками: в байтовом awk (mawk) класс [^»]
      # исключал бы байт 0xBB, а он входит в кириллическую «л» (D0 BB) — цитата рвалась бы.
      gsub(/«/, "\001", line); gsub(/»/, "\002", line)
      gsub(/\001[^\002]*\002/, "", line); gsub(/`[^`]*`/, "", line)
      if (index(line, "close-out за architect") > 0) print NR
    }')"
  if [ -n "$stale" ]; then
    fail "${PS}:$(echo $stale | tr ' ' ','): заголовок раздела ${id} всё ещё утверждает «close-out за architect» — проза противоречит переезду"
  fi
done

echo
if [ "$FAILS" -eq 0 ]; then
  if [ "$N" -eq 0 ]; then
    echo "OK: переезд в диапазоне ${BASE:0:8}..HEAD не обнаружен; маркеров «OPEN» у вынесенных нет"
  else
    echo "OK: переездов ${N}, каждый сопровождён маркером закрытия в ${PS}"
  fi
  echo "VERDICT: PASS"
  exit 0
fi

echo "Порядок close-out'а: reviewer НАЗЫВАЕТ милестоун закрытым в ${PS} (маркер + проза «ЗАКРЫТ»),"
echo "затем architect переносит спеку и гейт. Architect ${PS} не пишет: маркер ставит reviewer"
echo "в main ЛИБО своим коммитом на ветке переезда (docs/04-workflow.md §Close-out)."
echo "нарушений: ${FAILS}"
echo "VERDICT: FAIL"
exit 1
