#!/usr/bin/env bash
# Проба бюджета обязательного чтения — `scripts/check_context_budgets.sh` (M-60 G1).
#
# ЗАЧЕМ. Аудит воркфлоу §1.4 замерил: startup-протокол стоит ~1068 KB на КАЖДУЮ роль при
# каждом старте. Протокол такого объёма не читается целиком — роли скимят, и что именно
# выпало при скиме, ненаблюдаемо. Это тот самый механизм потери правил, против которого
# написана шапка CLAUDE.md, и корневая причина A-003 (корпус вырос ×2.7 дневником инцидентов).
#
# Единственный механизм einhard, работающий БЕЗ участия агента, — размерный кап в CI
# (`architecture_lint.py` R10/R13, `smoke.yml:605`). Его и переносим. Но с поправкой,
# купленной их же опытом: их R13 прямо сейчас КРАСНЫЙ (80 KB против бюджета 20 KB) и это
# терпится. Бюджет работает, только пока красное чинится, а не пересиживается, — значит
# наш обязан жить в блокирующем пути.
#
# КОНТРАКТ ГЕЙТА (задаётся этой пробой, реализуется dev'ом):
#   BUDGET_TABLE=<файл>  строки вида `<путь-от-корня><TAB><лимит-в-байтах>`; по умолчанию —
#                        таблица, встроенная в сам скрипт (0 строк прозы в правилах);
#   ROOT=<каталог>       корень дерева, которое проверяется (по умолчанию — корень репо);
#   exit 0  — все файлы существуют И укладываются в лимит;
#   exit≠0  — превышение, ОТСУТСТВИЕ файла из таблицы, отсутствие/пустота таблицы.
#
# Почему отсутствие файла — FAIL, а не пропуск: «файла нет» даёт нулевой размер, то есть
# бесконечный запас бюджета. Гейт, зеленеющий от исчезновения предмета, — не гейт.

set -uo pipefail

ROOT_REPO="$(cd "$(dirname "$0")/../.." && pwd)"
BARRIER="${BARRIER:-${ROOT_REPO}/scripts/check_context_budgets.sh}"

FAILED=0
PASSED=0
pass() { echo "PASS  $*"; PASSED=$((PASSED + 1)); }
fail() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
die()  { echo "SETUP НЕ СОСТОЯЛСЯ: $*" >&2; exit 1; }

# ── Страж барьера. Пока гейта нет, bash вернёт 127, и негативные сценарии («ожидаю exit≠0»)
# позеленели бы на пустом месте — проба аттестовала бы несуществующий механизм.
[ -f "${BARRIER}" ] || die "барьера нет: ${BARRIER}. 127 от bash неотличим от честного отказа гейта."
bash -n "${BARRIER}" 2>/dev/null || die "барьер не парсится — сценарии мерили бы ошибку интерпретатора."

# ── Фикстура: дерево нужных размеров + своя таблица бюджетов ───────────────────────────
mk_tree() { # $1=байт в a.md  $2=байт в b.md → путь
  local d; d="$(mktemp -d /tmp/red-budget-XXXXXX)" || die mktemp
  mkdir -p "$d/rules" || die mkdir
  head -c "$1" /dev/zero | tr '\0' 'x' > "$d/rules/a.md" || die "создание a.md"
  head -c "$2" /dev/zero | tr '\0' 'x' > "$d/rules/b.md" || die "создание b.md"
  # страж: размеры действительно те, что заявлены — иначе сценарий тестирует не то
  [ "$(wc -c < "$d/rules/a.md")" -eq "$1" ] || die "a.md не $1 байт"
  [ "$(wc -c < "$d/rules/b.md")" -eq "$2" ] || die "b.md не $2 байт"
  echo "$d"
}
mk_table() { # $1=dir $2=лимит a $3=лимит b → путь к таблице
  local t="$1/budgets.tsv"
  printf 'rules/a.md\t%s\nrules/b.md\t%s\n' "$2" "$3" > "$t" || die "таблица"
  echo "$t"
}
run_barrier() { # $1=root $2=table
  ( ROOT="$1" BUDGET_TABLE="$2" bash "${BARRIER}" >/dev/null 2>&1 )
}

echo "── Бюджет обязательного чтения (M-60 G1): 6 сценариев ──"
echo "барьер: ${BARRIER}"
echo

# CB-1 — превышение ⇒ блок
D="$(mk_tree 2000 500)"; T="$(mk_table "$D" 1000 1000)"
run_barrier "$D" "$T" && fail "CB-1 файл 2000 B при лимите 1000 ПРОШЁЛ — бюджета нет" \
                     || pass "CB-1 превышение бюджета заблокировано"

# CB-2 — всё в пределах ⇒ проход (анти-ложноположительный)
D="$(mk_tree 800 500)"; T="$(mk_table "$D" 1000 1000)"
run_barrier "$D" "$T" && pass "CB-2 файлы в пределах бюджета проходят" \
                     || fail "CB-2 ложное срабатывание: всё в пределах, а гейт блокирует"

# CB-3 — РОВНО на границе ⇒ проход (граница включительна; фикстура не должна стоять на
# соседнем значении — иначе тест падал бы по неверной причине, testing.md «Границы»)
D="$(mk_tree 1000 1000)"; T="$(mk_table "$D" 1000 1000)"
run_barrier "$D" "$T" && pass "CB-3 ровно на границе — проход (лимит включителен)" \
                     || fail "CB-3 граница трактуется строго: ровный размер отвергнут"

# CB-4 — превышение на ОДИН байт ⇒ блок (чувствительность; «примерно в бюджете» не бывает)
D="$(mk_tree 1001 500)"; T="$(mk_table "$D" 1000 1000)"
run_barrier "$D" "$T" && fail "CB-4 превышение на 1 байт ПРОШЛО — бюджет декоративен" \
                     || pass "CB-4 превышение на 1 байт поймано"

# CB-5 — файл из таблицы ОТСУТСТВУЕТ ⇒ блок, а не «ноль байт, значит в бюджете»
D="$(mk_tree 800 500)"; T="$(mk_table "$D" 1000 1000)"; rm -f "$D/rules/b.md"
[ ! -e "$D/rules/b.md" ] || die "фикстура: b.md не удалён"
run_barrier "$D" "$T" && fail "CB-5 отсутствующий файл дал ПРОХОД — исчезновение предмета зеленит гейт" \
                     || pass "CB-5 отсутствующий файл: fail-closed"

# CB-6 — таблицы нет / она пуста ⇒ блок (гейт без предмета проверки не смеет быть зелёным)
D="$(mk_tree 800 500)"
run_barrier "$D" "$D/нет-такой-таблицы.tsv" && fail "CB-6 отсутствующая таблица дала ПРОХОД" \
                                            || pass "CB-6 отсутствующая таблица: fail-closed"
: > "$D/empty.tsv"
run_barrier "$D" "$D/empty.tsv" && fail "CB-6b пустая таблица дала ПРОХОД — гейт проверяет ничто" \
                                || pass "CB-6b пустая таблица: fail-closed"

echo
if [ "${FAILED}" -gt 0 ]; then
  echo "VERDICT: FAIL (${FAILED})"
  echo "Бюджет не даёт заявленной гарантии. Пока проба красная, обязательный протокол растёт"
  echo "молча — а именно молчаливый рост и сделал его нечитаемым (аудит §1.4)."
  exit 1
fi
echo "VERDICT: PASS (${PASSED}/${PASSED}) — бюджет держит и не даёт ложных срабатываний"
