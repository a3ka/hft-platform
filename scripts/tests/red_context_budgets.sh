#!/usr/bin/env bash
# Проба бюджета обязательного чтения — `scripts/check_context_budgets.sh` (M-60 G1).
#
# ЗАЧЕМ. Аудит воркфлоу §1.4 замерил: startup-протокол стоит ~1068 KB на КАЖДУЮ роль при
# каждом старте. Протокол такого объёма не читается целиком — роли скимят, и что именно
# выпало при скиме, ненаблюдаемо. Это тот самый механизм потери правил, против которого
# написана шапка CLAUDE.md, и корневая причина A-003 (корпус вырос ×2.7 дневником инцидентов).
#
# Единственный механизм einhard, работающий БЕЗ участия агента, — размерный кап в CI
# (`architecture_lint.py` R10/R13, `smoke.yml:605`). Его и переносим. Но с поправкой,
# купленной их же опытом: их R13 прямо сейчас КРАСНЫЙ (80 KB против бюджета 20 KB) и это
# терпится. Бюджет работает, только пока красное чинится, а не пересиживается, — значит
# наш обязан жить в блокирующем пути.
#
# КОНТРАКТ ГЕЙТА (задаётся этой пробой, реализуется dev'ом):
#   BUDGET_TABLE=<файл>  строки вида `<путь-от-корня><TAB><лимит-в-байтах>`; по умолчанию —
#                        таблица, встроенная в сам скрипт (0 строк прозы в правилах);
#   ROOT=<каталог>       корень дерева, которое проверяется (по умолчанию — корень репо);
#   exit 0  — все файлы существуют И укладываются в лимит;
#   exit≠0  — превышение, ОТСУТСТВИЕ файла из таблицы, нечитаемый файл/таблица,
#             отсутствие/пустота таблицы, дублирующиеся/конфликтующие строки таблицы.
#
# Почему отсутствие файла — FAIL, а не пропуск: «файла нет» даёт нулевой размер, то есть
# бесконечный запас бюджета. Гейт, зеленеющий от исчезновения предмета, — не гейт.
#
# Ось «число одновременных потребителей» из testing.md к этому механизму НЕПРИМЕНИМА:
# бюджетный парсер stateless, читает одну TSV-таблицу и набор файлов, не держит shared cursor
# или состояние на каталог между сессиями. Применимая форма carrier/shared-state здесь —
# права доступа к носителю и несколько жизней одной строки таблицы (дубликаты ниже).

set -uo pipefail

ROOT_REPO="$(cd "$(dirname "$0")/../.." && pwd)"
BARRIER="${BARRIER:-${ROOT_REPO}/scripts/check_context_budgets.sh}"

FAILED=0
PASSED=0
pass() { echo "PASS  $*"; PASSED=$((PASSED + 1)); }
fail() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
die()  { echo "SETUP НЕ СОСТОЯЛСЯ: $*" >&2; exit 1; }

# Реестр фикстур ведётся в ФАЙЛЕ, а не в переменной: фикстуры рождаются в подоболочках,
# где присваивание переменной теряется (класс, давший 10 400 каталогов /tmp у
# red_docs_freeze; эталон починки — scripts/tests/red_artifact_ids.sh).
FIXTURE_REG="$(mktemp /tmp/red-budget-reg-XXXXXX)"
reg_fixture() { printf '%s\n' "$1" >> "${FIXTURE_REG}"; }
cleanup_fixtures() {
  [ -n "${KEEP_FIXTURES:-}" ] && { echo "фикстуры оставлены (KEEP_FIXTURES): ${FIXTURE_REG}"; return 0; }
  while IFS= read -r d; do
    [ -n "$d" ] || continue
    case "$d" in /tmp/red-budget-*) chmod -R u+rwX "$d" 2>/dev/null; rm -rf "$d" ;; esac
  done < "${FIXTURE_REG}" 2>/dev/null
  rm -f "${FIXTURE_REG}"
}
trap cleanup_fixtures EXIT

# ── Страж барьера. Пока гейта нет, bash вернёт 127, и негативные сценарии («ожидаю exit≠0»)
# позеленели бы на пустом месте — проба аттестовала бы несуществующий механизм.
[ -f "${BARRIER}" ] || die "барьера нет: ${BARRIER}. 127 от bash неотличим от честного отказа гейта."
bash -n "${BARRIER}" 2>/dev/null || die "барьер не парсится — сценарии мерили бы ошибку интерпретатора."

# ── Фикстура: дерево нужных размеров + своя таблица бюджетов ───────────────────────────
# Результат — ЧЕРЕЗ ИМЯ ПЕРЕМЕННОЙ ($1), а не через stdout: при форме `mk_tree D ...`
# тело исполняется в ПОДОБОЛОЧКЕ, и `die` завершает только её — проба идёт дальше с пустым
# путём и печатает PASS против несозданной фикстуры (замер: 11/11 на пустом месте).
# Внутренние локальные названы `__fx_*` НАМЕРЕННО: в bash динамическая область видимости, и
# `local d` внутри функции ЗАТЕНЯЕТ переменную `d` вызывающего — `printf -v "$1"` записал бы
# в локальную копию, а вызывающий получил бы unbound. Префикс исключает класс, а не случай.
mk_tree() { # $1=имя переменной, $2=байт в a.md, $3=байт в b.md
  local __fx_d; __fx_d="$(mktemp -d /tmp/red-budget-XXXXXX)" || die mktemp
  mkdir -p "$__fx_d/rules" || die mkdir
  head -c "$2" /dev/zero | tr '\0' 'x' > "$__fx_d/rules/a.md" || die "создание a.md"
  head -c "$3" /dev/zero | tr '\0' 'x' > "$__fx_d/rules/b.md" || die "создание b.md"
  # страж: размеры действительно те, что заявлены — иначе сценарий тестирует не то
  [ "$(wc -c < "$__fx_d/rules/a.md")" -eq "$2" ] || die "a.md не $2 байт"
  [ "$(wc -c < "$__fx_d/rules/b.md")" -eq "$3" ] || die "b.md не $3 байт"
  reg_fixture "$__fx_d"
  printf -v "$1" '%s' "$__fx_d"
}
mk_table() { # $1=имя переменной, $2=dir, $3=лимит a, $4=лимит b
  [ -n "${2:-}" ] && [ -d "${2:-}" ] || die "mk_table получил пустой каталог — фикстура не создана"
  local __fx_t="$2/budgets.tsv"
  printf 'rules/a.md\t%s\nrules/b.md\t%s\n' "$3" "$4" > "$__fx_t" || die "таблица"
  printf -v "$1" '%s' "$__fx_t"
}
run_barrier() { # $1=root $2=table
  [ -n "${1:-}" ] && [ -d "${1:-}" ] || die "run_barrier получил пустой/несуществующий ROOT «${1:-}» — фикстура не создана"
  local st
  ( ROOT="$1" BUDGET_TABLE="$2" bash "${BARRIER}" >/dev/null 2>&1 )
  st=$?
  # 126/127 — отказ СРЕДЫ, а не вердикт гейта. positive_control этот класс НЕ ловит: он
  # проверяет только ГОДНУЮ ветку, а падать может ОТКАЗНАЯ (барьер зовёт отсутствующий в CI
  # `jq`). Тогда каждый сценарий «ожидаю отказ» зеленеет против механизма, который не
  # отказывает, а падает (C-086 F-086-1 требовал именно этого различения).
  case $st in
    126|127) die "барьер вернул ${st} (не найден / не исполняется) — это отказ СРЕДЫ, а не отказ гейта; сценарий засчитал бы падение за срабатывание" ;;
  esac
  return $st
}
positive_control() {
  local d t
  mk_tree d 64 32
  mk_table t "$d" 128 128
  ( ROOT="$d" BUDGET_TABLE="$t" bash "${BARRIER}" >/dev/null 2>&1 ) \
    || die "барьер не проходит заведомо годную фикстуру (64/32 B при лимите 128 B); setup не состоялся"
}

echo "── Бюджет обязательного чтения (M-60 G1): сценарии CB-1..CB-9b ──"
echo "барьер: ${BARRIER}"
echo
positive_control
echo "SETUP positive-control: барьер принимает заведомо годную фикстуру"
echo

# CB-1 — превышение ⇒ блок
mk_tree D 2000 500; mk_table T "$D" 1000 1000
run_barrier "$D" "$T" && fail "CB-1 файл 2000 B при лимите 1000 ПРОШЁЛ — бюджета нет" \
                     || pass "CB-1 превышение бюджета заблокировано"

# CB-2 — всё в пределах ⇒ проход (анти-ложноположительный)
mk_tree D 800 500; mk_table T "$D" 1000 1000
run_barrier "$D" "$T" && pass "CB-2 файлы в пределах бюджета проходят" \
                     || fail "CB-2 ложное срабатывание: всё в пределах, а гейт блокирует"

# CB-3 — РОВНО на границе ⇒ проход (граница включительна; фикстура не должна стоять на
# соседнем значении — иначе тест падал бы по неверной причине, testing.md «Границы»)
mk_tree D 1000 1000; mk_table T "$D" 1000 1000
run_barrier "$D" "$T" && pass "CB-3 ровно на границе — проход (лимит включителен)" \
                     || fail "CB-3 граница трактуется строго: ровный размер отвергнут"

# CB-4 — превышение на ОДИН байт ⇒ блок (чувствительность; «примерно в бюджете» не бывает)
mk_tree D 1001 500; mk_table T "$D" 1000 1000
run_barrier "$D" "$T" && fail "CB-4 превышение на 1 байт ПРОШЛО — бюджет декоративен" \
                     || pass "CB-4 превышение на 1 байт поймано"

# CB-5 — файл из таблицы ОТСУТСТВУЕТ ⇒ блок, а не «ноль байт, значит в бюджете»
mk_tree D 800 500; mk_table T "$D" 1000 1000; rm -f "$D/rules/b.md"
[ ! -e "$D/rules/b.md" ] || die "фикстура: b.md не удалён"
run_barrier "$D" "$T" && fail "CB-5 отсутствующий файл дал ПРОХОД — исчезновение предмета зеленит гейт" \
                     || pass "CB-5 отсутствующий файл: fail-closed"

# CB-6 — таблицы нет / она пуста ⇒ блок (гейт без предмета проверки не смеет быть зелёным)
mk_tree D 800 500
run_barrier "$D" "$D/нет-такой-таблицы.tsv" && fail "CB-6 отсутствующая таблица дала ПРОХОД" \
                                            || pass "CB-6 отсутствующая таблица: fail-closed"
: > "$D/empty.tsv"
run_barrier "$D" "$D/empty.tsv" && fail "CB-6b пустая таблица дала ПРОХОД — гейт проверяет ничто" \
                                || pass "CB-6b пустая таблица: fail-closed"

# CB-7 — файл из таблицы есть, но НЕЧИТАЕМ ⇒ блок, а не «нулевой размер»/молчаливый skip
mk_tree D 800 500; mk_table T "$D" 1000 1000
chmod a-r "$D/rules/a.md" || die "CB-7 chmod a-r"
[ ! -r "$D/rules/a.md" ] || die "CB-7: chmod не сделал файл нечитаемым — сценарий тестировал бы не права"
run_barrier "$D" "$T" && fail "CB-7 нечитаемый файл дал ПРОХОД — carrier-permission отказ проглочен" \
                     || pass "CB-7 нечитаемый файл: fail-closed"
chmod u+r "$D/rules/a.md" 2>/dev/null || true

# CB-8 — таблица бюджетов есть, но НЕЧИТАЕМА ⇒ блок
mk_tree D 800 500; mk_table T "$D" 1000 1000
chmod a-r "$T" || die "CB-8 chmod a-r"
[ ! -r "$T" ] || die "CB-8: chmod не сделал таблицу нечитаемой — сценарий тестировал бы не права"
run_barrier "$D" "$T" && fail "CB-8 нечитаемая таблица дала ПРОХОД — гейт проверяет ничто" \
                     || pass "CB-8 нечитаемая таблица: fail-closed"
chmod u+r "$T" 2>/dev/null || true

# CB-9 — дублирующиеся/конфликтующие строки: fail-closed. Две стороны ловят и first-wins,
# и last-wins парсеры; корректный барьер не выбирает «одну жизнь» пути молча.
mk_tree D 800 500
T="$D/budgets.tsv"
printf 'rules/a.md\t1000\nrules/a.md\t100\nrules/b.md\t1000\n' > "$T" || die "CB-9a таблица"
run_barrier "$D" "$T" && fail "CB-9a конфликт first-pass/last-fail ПРОШЁЛ — parser взял первое вхождение" \
                     || pass "CB-9a конфликтующие дубли: fail-closed"

mk_tree D 800 500
T="$D/budgets.tsv"
printf 'rules/a.md\t100\nrules/a.md\t1000\nrules/b.md\t1000\n' > "$T" || die "CB-9b таблица"
run_barrier "$D" "$T" && fail "CB-9b конфликт first-fail/last-pass ПРОШЁЛ — parser взял последнее вхождение" \
                     || pass "CB-9b конфликтующие дубли обратного порядка: fail-closed"

# CB-10a/CB-10b — лимит БЕРЁТСЯ ИЗ ТАБЛИЦЫ, а не зашит в барьер.
# Все сценарии выше держат лимит 1000, поэтому реализация с зашитой константой 1000 проходит
# их все (замер: обманный стаб «игнорирует колонку лимита» → PASS 11/11). Колонка лимита не
# несла нагрузки. Две стороны обязательны: одна ловит зашитый лимит СНИЗУ, другая СВЕРХУ.
mk_tree D 2000 500; mk_table T "$D" 5000 5000
run_barrier "$D" "$T" && pass "CB-10a лимит 5000 из таблицы принят: файл 2000 B прошёл" \
                      || fail "CB-10a файл 2000 B при лимите 5000 ОТВЕРГНУТ — лимит зашит в барьер, а не прочитан"

mk_tree D 500 100; mk_table T "$D" 100 100
run_barrier "$D" "$T" && fail "CB-10b файл 500 B при лимите 100 ПРОШЁЛ — лимит зашит в барьер, а не прочитан" \
                      || pass "CB-10b лимит 100 из таблицы применён: файл 500 B отвергнут"

echo
if [ "${FAILED}" -gt 0 ]; then
  echo "VERDICT: FAIL (${FAILED})"
  echo "Бюджет не даёт заявленной гарантии. Пока проба красная, обязательный протокол растёт"
  echo "молча — а именно молчаливый рост и сделал его нечитаемым (аудит §1.4)."
  exit 1
fi
echo "VERDICT: PASS (${PASSED}/${PASSED}) — бюджет держит и не даёт ложных срабатываний"
