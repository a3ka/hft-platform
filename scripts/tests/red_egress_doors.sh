#!/usr/bin/env bash
# Проба-ИНВЕНТАРИЗАЦИЯ дверей выдачи — M-71, исполнение `A-021` Вопрос 3, Правка B.
#
# ЗАЧЕМ. Два круга гейта подряд находили дверь, которую оракул не звал: `C-157` R2 — живой
# WS-путь, `C-158` R1 — serve-обёртки и v1-конверт. Перечень «по построению» покрывает лишь
# то, о чём вспомнил автор. Правило границы `A-020` требует смены КОНСТРУКЦИИ, а не третьей
# двери: **список дверей проверяет машина.**
#
# ЧЕМ ЭТО ОТЛИЧАЕТСЯ ОТ КАНАРЕЙКИ, ЗАПРЕЩЁННОЙ `A-020`. Там лексический инструмент судил
# ПРОВЕНАНС ЗНАЧЕНИЯ в языке с открытым множеством каналов (`local X="$X"`, nameref, `eval`) —
# и не мог сойтись в принципе. Здесь греп ИНВЕНТАРИЗУЕТ закрытую синтаксически регулярную
# поверхность (сигнатуры Rust), а его отказ — не суждение о данных, а требование «дверь не
# названа в оракуле, допиши». Разница названа арбитром и записана здесь, чтобы следующий круг
# не спорил о ней заново.
#
# ИМЕНОВАННЫЙ ОСТАТОК (`COGNITIVE-ONLY`): двери, порождённые макросами или приходящие через
# трейт-объекты, лексический перебор НЕ ВИДИТ. Находки этого рода — NOTE, не REJECT (`A-021`).
set -uo pipefail
cd "$(dirname "$0")/../.." || exit 2

L1=crates/gateway/tests/red_egress_cap.rs
L2=crates/gateway-serve/tests/red_egress_cap_wire.rs
FAIL=0

for f in "${L1}" "${L2}"; do
  [ -f "${f}" ] || { echo "FAIL: SETUP — нет файла оракула ${f}"; exit 1; }
done

echo "=== УРОВЕНЬ 1: публичные строители gateway, принимающие &Selector ==="
# Свободные функции крейта + методы `LiveReducer`. Имя двери — то, чем её зовут из оракула.
DOORS1=$(grep -hoE '^pub fn [a-z_]+\(' crates/gateway/src/lib.rs | sed 's/^pub fn //; s/($//; s/(//' | sort -u)
LIVE=$(grep -hoE '^    pub fn (resume|pump)\(' crates/gateway/src/lib.rs | sed 's/^ *pub fn //; s/(//' | sort -u)

# ИСКЛЮЧЕНИЯ — список ЯВНЫЙ и с причиной, а не молчаливый фильтр. Дверь, выведенная отсюда,
# видна читателю: если причина перестанет быть верной, это заметят, а не пропустят.
#   validate_selector — САМ ГВАРД, а не строитель ответа: он принимает `&Selector`, но ничего
#                       не строит и ничего не отдаёт клиенту. Звать его из оракула предела
#                       нечего; его собственные инварианты — `GW-I-10`/`GW-I-14`.
EXCLUDE="validate_selector"

for d in ${DOORS1}; do
  case " ${EXCLUDE} " in *" ${d} "*) echo "SKIP: ${d} — в явных исключениях (см. EXCLUDE)"; continue;; esac
  # Строителем ответа считаем функцию, чья СИГНАТУРА принимает `&Selector`.
  #
  # ГРАНИЦА СКАНИРОВАНИЯ ОБЯЗАТЕЛЬНА, и её отсутствие было латентным дефектом (найден пробой
  # достижимости 2026-08-26, M-71 rev8). Прежняя редакция сканировала ВПЕРЁД без условия
  # остановки: от строки объявления до первого `&Selector` в ФАЙЛЕ. Для функции без
  # `&Selector` поиск уходил в СЛЕДУЮЩУЮ функцию и находил его там — и барьер объявлял
  # дверью то, что дверью не является. Дефект не проявлялся, пока все `pub fn` крейта
  # случайно были строителями; первая же не-строитель (`effective_max_response_bytes`,
  # мост предела M-71) дала ЛОЖНОЕ КРАСНОЕ на честной реализации.
  # Теперь сканируем ровно сигнатуру: от объявления до открывающей `{` тела.
  if ! awk -v fn="pub fn ${d}(" '
        index($0,fn){f=1}
        f{ sig = sig $0; if (index($0,"{")) { exit } }
        END{ if (index(sig,"&Selector")) print "yes" }
      ' crates/gateway/src/lib.rs | grep -q yes; then
    continue
  fi
  if grep -q "gateway::${d}(" "${L1}"; then
    echo "PASS: дверь L1 ${d} — названа в оракуле"
  else
    echo "FAIL: дверь L1 ${d} принимает &Selector, но оракул ${L1} её НЕ ЗОВЁТ"
    FAIL=$((FAIL + 1))
  fi
done

for d in ${LIVE}; do
  if grep -q "\.${d}(\|LiveReducer::${d}(" "${L1}"; then
    echo "PASS: дверь L1 LiveReducer::${d} — названа в оракуле"
  else
    echo "FAIL: дверь L1 LiveReducer::${d} не названа в оракуле ${L1}"
    FAIL=$((FAIL + 1))
  fi
done

echo "=== УРОВЕНЬ 2: НЕГАТИВНЫЙ чек + сверка с таблицей сценариев (A-022) ==="
# `C-161` показал предел ПОЛОЖИТЕЛЬНОГО чека: оракул звал строитель — проба была довольна, а
# оракул при этом строил судимую величину САМ и не исполнял прод-путь. Поэтому теперь чек
# ОБРАТНЫЙ: cap-оракул уровня 2 НЕ ИМЕЕТ ПРАВА звать строители исходящих форм — он обязан
# снимать байты с сокета. Покрытие дверей держится таблицей «дверь → сценарий» В ФАЙЛЕ оракула.
# ЛОВУШКА, на которой этот шаг уже споткнулся: `grep -c` при НУЛЕ совпадений печатает «0»
# И возвращает 1, поэтому `|| echo 0` дописывает ВТОРОЙ ноль и сравнение `-eq 0` ломается.
# Семейство то же, что у `git grep -c` (профиль architect'а, §«Форма показа»): показанный
# вывод обязан производиться показанной командой. Отсюда `|| true` вместо `|| echo`.
BUILDER_CALLS=$(grep -cE 'wire_v1::[a-z_]+_msg\(' "${L2}" || true)
BUILDER_CALLS=${BUILDER_CALLS:-0}
if [ "${BUILDER_CALLS}" -eq 0 ]; then
  echo "PASS: L2 cap-оракул НЕ строит исходящий текст сам (${BUILDER_CALLS} вызовов строителей)"
else
  echo "FAIL: L2 cap-оракул зовёт строители исходящих форм ${BUILDER_CALLS} раз — он обязан"
  echo "      судить байты, ПРИШЕДШИЕ В СОКЕТ, а не собранные им самим (C-161, A-022)"
  FAIL=$((FAIL + 1))
fi

# Оракул обязан реально ходить через сокет, иначе «не строит сам» выполняется вакуумно.
for token in 'connect_async' 'local_addr' 'Message::Text'; do
  if grep -q "${token}" "${L2}"; then
    echo "PASS: L2 оракул исполняет прод-границу (${token})"
  else
    echo "FAIL: L2 оракул не содержит '${token}' — сокетного прогона нет, и негативный чек выше вакуумен"
    FAIL=$((FAIL + 1))
  fi
done

DOORS_WIRE=$(grep -hoE '^pub fn [a-z_]+_msg\(' crates/gateway-serve/src/wire_v1.rs | sed 's/^pub fn //; s/(//' | sort -u)
DOORS_SERVE=$(awk '/^pub mod serve \{/{m=1} m&&/^    pub fn /{sub(/\(.*/,"");sub(/^    pub fn /,"");print} m&&/^\}/{m=0}' crates/gateway-serve/src/lib.rs | sort -u)

if [ -z "${DOORS_WIRE}" ] || [ -z "${DOORS_SERVE}" ]; then
  echo "FAIL: SETUP — перебор дверей уровня 2 не нашёл НИ ОДНОЙ. Пустой перебор зелен по построению."
  FAIL=$((FAIL + 1))
fi

for d in ${DOORS_WIRE} ${DOORS_SERVE}; do
  if grep -q "${d}" "${L2}"; then
    echo "PASS: дверь L2 ${d} — названа в таблице сценариев оракула"
  else
    echo "FAIL: дверь L2 ${d} существует, но в таблице «дверь → сценарий» файла ${L2} её НЕТ"
    FAIL=$((FAIL + 1))
  fi
done

# ПРЕДЕЛ ТАБЛИЦЫ НАЗВАН: присутствие ИМЕНИ в файле не доказывает, что сценарий действительно
# эту дверь исполняет. Зубы этому даёт МУТАЦИЯ НАБЛЮДАЕМОСТИ (`A-022` Вопрос 3), которую
# architect обязан прогнать до запроса критика и предъявить таблицей чувствительности.
# Здесь — COGNITIVE-ONLY, и это не изображается гейтом.

# ОСТАТОК, названный честно: точка отправки, которая строит текст МИМО `*_msg`-строителя,
# этому перебору не видна. Числом она наблюдаема — печатаем её, чтобы расхождение бросалось
# в глаза при ревизии, но НЕ роняем шаг: это `COGNITIVE-ONLY` (`A-021` Правка B).
N_SEND=$(grep -c 'Message::Text(' crates/gateway-serve/src/lib.rs || echo 0)
echo "NOTE: точек Message::Text( в lib.rs — ${N_SEND} (приём и отправка вместе). Текст, собранный"
echo "      МИМО *_msg-строителя, лексическому перебору не виден — COGNITIVE-ONLY, не гейт."

echo
echo "=== УРОВЕНЬ 3: ВЫЗЫВАТЕЛИ МОСТА (A-026 O-7, часть «б» требования моста) ==="
# ЧТО ЭТО ПИННИТ. Спека §4bis.2 требует: в проде эффективный предел ставит РОВНО ОДИН
# вызыватель — `serve_config_from_env`. Оракулом это не пиннится (см. ниже), инвентарём —
# пиннится: новый call-site в `crates/*/src` виден греп-перебором.
#
# ПОЧЕМУ НЕ ОРАКУЛОМ. Внутрипроцессный запрет рантайм-переустановки в этой конструкции
# НЕПИННИМ, и контрпример — сам sacred-набор: `N1-C`/`N1a`/`N1b`/`N1-D`/`N1-E`
# переустанавливают значение под `serial()` по построению. Жёсткий «один раз» типом
# (`OnceLock`, `Err` на второй вызов) ломает все пять и оба домашних набора той же формы.
# Решение — `A-026` §2; непокрытая часть «в» вынесена ЗАПИСЬЮ ДОЛГА (`A-026` §3bis), а не
# изображена закрытой.
#
# ПРЕДЕЛ ЭТОГО ШАГА НАЗВАН: барьер ТЕКСТОВЫЙ. Он ловит НОВЫЙ вызыватель, написанный
# литералом в `crates/*/src`, и СЛЕП к динамическому вызову существующего `pub`-сеттера
# (через указатель на функцию, реэкспорт под другим именем, макрос). `COGNITIVE-ONLY` в
# этой части — и это здесь сказано, а не подразумевается.
SETTER='set_effective_max_response_bytes'
OWNER='crates/gateway-serve/src/lib.rs'

# Определение самого сеттера исключается из перебора вызовов явно: `pub fn <имя>(` — это
# объявление двери, а не её употребление.
CALLS=$(grep -rnE "${SETTER}\(" crates/*/src 2>/dev/null | grep -vE "(pub )?fn ${SETTER}\(" || true)
N_CALLS=$(printf '%s' "${CALLS}" | grep -c . || true)

if [ "${N_CALLS}" -eq 0 ]; then
  # SETUP-GUARD (`testing.md` §«Целостность гейта» св. 3/4): барьер, молчащий при ОТСУТСТВИИ
  # предмета, есть плацебо самого себя. Ноль вызывателей = мост не подключён ИЛИ переименован;
  # оба случая обязаны быть красными, а не «претензий нет».
  echo "FAIL: L3 SETUP НЕ СОСТОЯЛСЯ — вызывателей ${SETTER}( в crates/*/src не найдено НИ ОДНОГО."
  echo "      Мост не подключён либо сеттер переименован. Молчание здесь неотличимо от порядка."
  FAIL=$((FAIL + 1))
else
  echo "${CALLS}" | while IFS= read -r line; do echo "      вызыватель: ${line}"; done
  N_OWNER=$(printf '%s\n' "${CALLS}" | grep -c "^${OWNER}:" || true)

  # СОДЕРЖАНИЕ, а не только файл: вызов обязан лежать ВНУТРИ `serve_config_from_env`.
  # Проверка по файлу его не даёт — вызов в соседней функции того же файла прошёл бы.
  IN_FN=$(awk '/^pub fn serve_config_from_env/{f=1} f{print} f && /^\}/{exit}' "${OWNER}" \
            | grep -cE "${SETTER}\(" || true)

  if [ "${N_CALLS}" -eq 1 ] && [ "${N_OWNER}" -eq 1 ] && [ "${IN_FN}" -eq 1 ]; then
    echo "PASS: L3 ${SETTER} — ровно один вызыватель, и он внутри serve_config_from_env"
  else
    echo "FAIL: L3 вызывателей ${SETTER}( — ${N_CALLS} (в ${OWNER}: ${N_OWNER}; внутри"
    echo "      serve_config_from_env: ${IN_FN}); обязан быть РОВНО ОДИН и именно там."
    echo "      Второй вызыватель молча меняет эффективный предел мимо старта (спека"
    echo "      §4bis.2, часть «б»)."
    echo "      ЧАСТЫЙ СЛУЧАЙ ДВОЙКИ — не новый call-site, а НЕСНЕСЁННАЯ мёртвая пара"
    echo "      gateway_serve::server::{effective,set_effective}_max_response_bytes: после"
    echo "      переезда значения в crates/gateway у неё ноль читателей, и спека §4bis.2 п.4"
    echo "      требует снести её ТЕМ ЖЕ коммитом. Найдено пробой достижимости: барьер давал"
    echo "      ложное КРАСНОЕ против правильной реализации, пока пара оставалась на месте."
    FAIL=$((FAIL + 1))
  fi
fi

echo
if [ "${FAIL}" -eq 0 ]; then echo "VERDICT: PASS — все найденные двери названы в оракулах"; exit 0; fi
echo "VERDICT: FAIL (${FAIL}) — дверь существует, а оракул её не зовёт"; exit 1
