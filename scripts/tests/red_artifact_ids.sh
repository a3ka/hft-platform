td_raw() { ( cd "$1" && printf '%s\n' "$2" >> TECH-DEBT.md ) || die td_raw; }

# ПРОД-ФОРМА ВЫЗОВА, а не удобная (testing.md, целостность гейта, свойство 1: «гейт,
