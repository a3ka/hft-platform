FIXTURES_REG="$(mktemp /tmp/red-ids-reg-XXXXXX)" || { echo "не создан реестр фикстур" >&2; exit 1; }
pass() { echo "PASS  $*"; PASSED=$((PASSED + 1)); }
fail() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
