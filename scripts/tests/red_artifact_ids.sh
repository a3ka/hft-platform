# ═══ СВЕРКА 4 — §4.3(4): у каждого МЕСТА СРАВНЕНИЯ §4.6 есть ИСПОЛНЕННЫЙ сценарий ═══
# Полнота набора объявляется относительно ДВУХ конечных перечней — осей (§4.2) и МЕСТ
# СРАВНЕНИЯ (§4.6, `A-007` §5(4)). Сверялся только первый, при том что §4.3 усл. 4 и шаг F
# гейта обещают проверку обоих. Место сравнения, живущее в спеке без единого давящего на него
# сценария, — то же «обещание несуществующего механизма», которое §6 шаг G запрещает норме.
places="$(awk -F'|' '
  function names(cell,   n, p, i, out) {
    n = split(cell, p, "`"); for (i = 2; i <= n; i += 2) if (p[i] != "") out = out " " p[i]; return out }
  /^#/ { inside = ($0 ~ /^### 4\.6/); next }
  inside && $2 ~ /\*\*P[0-9]+\*\*/ { pl = $2; gsub(/[^P0-9]/, "", pl); print pl "|" names($7) }
' "${SPEC}")"
[ -n "$(printf '%s' "${places}" | grep .)" ] \
  || die "таблица §4.6 в ${SPEC} не разобрана — места сравнения сверять не с чем.
  Setup-guard обязателен: сверка пустого с пустым была бы зелёной всегда."
BADP=""
while IFS='|' read -r pl scen; do
  [ -z "${pl}" ] && continue
  hit=0
  for s in ${scen}; do
    printf '%s\n' "${DECL}" | grep -qx -- "${s}" || { BADP="${BADP} ${pl}:${s}-НЕТ-В-МАНИФЕСТЕ"; continue; }
    printf '%s\n' "${RUN}"  | grep -qx -- "${s}" || { BADP="${BADP} ${pl}:${s}-НЕ-ИСПОЛНЕН"; continue; }
    hit=1
  done
  [ "${hit}" -eq 1 ] || BADP="${BADP} ${pl}:НИ-ОДНОГО-СЦЕНАРИЯ"
done <<< "${places}"
if [ -n "${BADP// /}" ]; then
  echo "FAIL  §4.3(4): места сравнения §4.6 не покрыты исполнением:${BADP}"
  FAILED=$((FAILED+1))
else
  echo "PASS  §4.3(4): у каждого из $(printf '%s\n' "${places}" | grep -c .) мест сравнения §4.6 есть исполненный сценарий"
fi

echo
if [ "${FAILED}" -gt 0 ]; then
  echo "VERDICT: FAIL (${FAILED})"
  echo "Полнота заявлена ОТНОСИТЕЛЬНО семи осей (спека §4.2);"
  echo "опровержение обязано называть ОСЬ и ЗНАЧЕНИЕ (§4.4)."
  exit 1
fi
echo "VERDICT: PASS (${PASSED}/${PASSED}) — все значения семи осей покрыты, состав сверен со спекой"
