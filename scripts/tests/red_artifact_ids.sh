# `- **TD-NNN** `слаг`` — форму «счастливого пути», и до круга 5 весь набор состоял из неё
# одной. Замер прод-корпуса (`origin/main:TECH-DEBT.md`, 124 строки-записи): каноническая
# форма — 111, закрытая без слага — 10, скобочная «(исходная формулировка)» — 2,
