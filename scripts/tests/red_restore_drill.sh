# ── RW — коробка только ЧИТАЕТСЯ, копия целиком НЕ КАЧАЕТСЯ (`M-99` §7, `R-263` Б-1, `C-311` Б-1) ──
# Судится ВЕСЬ транскрипт удалённых команд, а не наличие разрешённых: круг 2 требовал «хотя бы
# один листинг и одну выборку» и принимал `rm -rf cold` после честной выборки (`C-311` Б-1).
# Белый список — ровно две формы, по одной на операцию шва:
#   листинг  — `ls cold`;
#   выборка  — `rsync --server --sender <короткие флаги> . cold/<ОДИН файл>`: `--sender` значит,
#              что коробка ОТДАЁТ (без него rsync пишет НА коробку); имя — сегмент выбранной
#              формы или sidecar `*.json` корня, без масок и без каталога.
# Любая иная строка — нарушение. Вторая, независимая половина — дерево `cold` побайтно то же до
# и после прогона: ловит изменение копии, каким бы путём оно ни случилось.
rw_judge() { # $1=файл удалённых команд → 0, если транскрипт допустим; RW_LIST/RW_FETCH/RW_BAD
  RW_LIST=0; RW_FETCH=0; RW_BAD=""
  local line tok good
  while IFS= read -r line || [ -n "${line}" ]; do
    [ -n "${line}" ] || continue
    if [ "${line}" = "ls cold" ]; then RW_LIST=$((RW_LIST + 1)); continue; fi
    good=0
    if [[ "${line}" =~ ^rsync\ --server\ --sender\ (.+)\ \.\ cold/(segment-[0-9]{8}\.jrnl(\.zst)?|[A-Za-z0-9_.-]+\.json)$ ]]; then
      good=1
      for tok in ${BASH_REMATCH[1]}; do
        case "${tok}" in
          -[A-Za-z.]*) ;;          # кластер коротких флагов (`-logDtpre.iLsfxCIvu`)
          *) good=0 ;;             # длинные опции (`--delete`, `--remove-source-files`, …) — нет
        esac
      done
    fi
    if [ "${good}" -eq 1 ]; then RW_FETCH=$((RW_FETCH + 1)); else RW_BAD="${RW_BAD}${line} | "; fi
  done < "$1"
  [ "${RW_LIST}" -ge 1 ] && [ "${RW_FETCH}" -ge 1 ] && [ -z "${RW_BAD}" ]
}

# ── Конечная точка (`A-055` §3, `C-313` F-1). Заглушка ЗАПИСЫВАЕТ хост в `ssh-argv.txt`, но
# отбрасывает его перед `ssh-cmd.txt`; судить только команды — значит доказать «КАКАЯ-ТО коробка
# только читалась», а не «читалась НАША». Каждая строка argv нормализуется в `пользователь@хост`
# (`-l U хост` у `rsync -e`, `U@хост` у листинга — обе формы законны) и обязана побайтно равняться
# `${COLD%%:*}`. Хост без пользователя, расхождение `-l` и `U@`, любая опция, способная сменить
# точку соединения (`-J`, `-F`, `-o ProxyCommand=…`, `-o HostName=…`) — отказ.
ssh_endpoint() { # $1=строка argv заглушки → печатает пользователь@хост; 1 при недопустимой форме
  local -a a; read -r -a a <<<"$1"
  local i=0 user="" host=""
  while [ "${i}" -lt "${#a[@]}" ]; do
    case "${a[$i]}" in
      -l) user="${a[$((i + 1))]:-}"; i=$((i + 2)) ;;
      -p|-i) i=$((i + 2)) ;;
      -o) case "${a[$((i + 1))]:-}" in
            IdentitiesOnly=*|BatchMode=*|ConnectTimeout=*) i=$((i + 2)) ;;
            *) return 1 ;;
          esac ;;
      -[46ACKNTVXYakqstvxy]) i=$((i + 1)) ;;   # флаги ssh без аргумента, точки не меняют
      -*) return 1 ;;                          # -J, -F, -W, -b, … — точка могла смениться
      *) host="${a[$i]}"; break ;;
    esac
  done
  [ -n "${host}" ] || return 1
  if [[ "${host}" == *@* ]]; then
    [ -z "${user}" ] || [ "${user}" = "${host%%@*}" ] || return 1
    printf '%s' "${host}"
  else
    [ -n "${user}" ] || return 1
    printf '%s@%s' "${user}" "${host}"
  fi
}
ep_judge() { # $1=ssh-argv.txt $2=ssh-cmd.txt $3=ожидаемая точка → 0, если КАЖДЫЙ вызов — к ней; EP_BAD
  EP_BAD=""
  local na nc line ep
  na="$(grep -c . "$1" 2>/dev/null)"; na="${na:-0}"
  nc="$(grep -c . "$2" 2>/dev/null)"; nc="${nc:-0}"
  [ "${na}" -eq "${nc}" ] || EP_BAD="транскрипты рассогласованы (argv ${na}, команд ${nc}) | "
  [ "${na}" -gt 0 ] || EP_BAD="${EP_BAD}argv пуст | "
  while IFS= read -r line || [ -n "${line}" ]; do
    [ -n "${line}" ] || continue
    if ! ep="$(ssh_endpoint "${line}")"; then EP_BAD="${EP_BAD}недопустимая форма: ${line:0:80} | "
    elif [ "${ep}" != "$3" ]; then EP_BAD="${EP_BAD}точка ${ep} вместо $3 | "
    fi
  done < "$1"
  [ -z "${EP_BAD}" ]
}
