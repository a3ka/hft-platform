# ── ШОВ ТРАНСПОРТА — ЗАГЛУШКА `ssh`, ИСПОЛНЯЮЩАЯ УДАЛЁННУЮ КОМАНДУ ЛОКАЛЬНО (`R-263` Г-1) ─────
# Круг 1 гонял ветку `remote` только на ОТКАЗЕ транспорта, и ветка, которая не могла закончиться
# успехом ни при каком транспорте (`R-263` Б-1: чтение пустого каталога, локальный `ls`
# удалённого адреса, доставка копии целиком), прошла весь набор. Заглушка подменяет ТОЛЬКО
# сеть: обёртка зовёт её ровно теми командами, что на проде (`ssh … ls <путь>`, `rsync -e ssh`),
# а заглушка исполняет удалённую часть в каталоге песочницы — `cold` там играет роль `journal/`
# на коробке. Всё, что обёртка делает ПОСЛЕ доставки, судится тем же кодом, что на проде.
# Чего это НЕ доказывает — сеть, ключ и rsync-сервер коробки: это первый живой прогон (задача 8).
make_ssh_stub() { # $1=песочница → путь к заглушке; журнал вызовов — $1/ssh-argv.txt
  local st="$1/ssh-stub.sh"
  cat > "${st}" <<'STUB'
#!/usr/bin/env bash
# Заглушка ssh: argv = [опции] ХОСТ КОМАНДА… (так зовут и обёртка, и `rsync -e`).
printf '%s\n' "$*" >> "${DRILL_SSH_STUB_BOX}/ssh-argv.txt"
while [ $# -gt 0 ]; do
  case "$1" in
    -l|-p|-i|-o) shift 2 ;;
    -*) shift ;;
    *) break ;;
  esac
done
shift   # ХОСТ
# Удалённая команда — то, что ИСПОЛНИЛА БЫ коробка. Её и судит RW по белому списку (`C-311` Б-1).
printf '%s\n' "$*" >> "${DRILL_SSH_STUB_BOX}/ssh-cmd.txt"
[ "${DRILL_SSH_STUB_RC:-0}" = "0" ] || exit "${DRILL_SSH_STUB_RC}"
# Выборочный отказ (`A-055` §5.2): отказывает РОВНО ОДНА — первая — удалённая команда с этим
# первым словом (`rsync` — выборка); листинг и остальные выборки проходят. Отказ ВСЕХ выборок не
# годится: обёртка, глотающая отказ, упала бы позже на другом шаге с другой причиной, и мутант
# «отказ проглочен» прошёл бы (замер круга 4: прошёл).
if [ -n "${DRILL_SSH_STUB_FAIL_ON:-}" ] && [ "${1:-}" = "${DRILL_SSH_STUB_FAIL_ON}" ] \
   && [ ! -e "${DRILL_SSH_STUB_BOX}/stub-failed-once" ]; then
  : > "${DRILL_SSH_STUB_BOX}/stub-failed-once"
  exit 255
fi
cd "${DRILL_SSH_STUB_BOX}" || exit 255
exec "$@"
STUB
  chmod +x "${st}"
  : > "$1/ssh-argv.txt"; : > "$1/ssh-cmd.txt"
  printf '%s' "${st}"
}

tree_sum() { # $1=каталог → имена, типы, режимы и sha256 всего содержимого (пусто, если каталога нет)
  [ -d "$1" ] || return 0
  ( cd "$1" && find . -printf '%y %m %p\n' | LC_ALL=C sort \
      && find . -type f -print0 | LC_ALL=C sort -z | xargs -0 -r sha256sum )
}

run_drill_remote() { # $1=песочница $2=код заглушки [$3=первое слово команды, которой отказать] → код возврата
  local stub wrapper
  stub="$(make_ssh_stub "$1")"
  snapshot_source "$1"
  tree_sum "$1/cold" > "$1/cold.before"
