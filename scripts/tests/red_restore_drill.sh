# ЭТАЛОННАЯ ОБЁРТКА — ЗАКРЫТИЕ КОРНЯ ВСЕЙ СЕРИИ ОТКАЗОВ (`C-216`, решение founder'а 08.09)
#
# ЧТО БЫЛО НЕ ТАК, И ЭТО ГЛАВНОЕ. Девять сценариев из четырнадцати (`S N P H C E F A T`)
# включались ТОЛЬКО при наличии прод-обёртки, которой ещё нет. То есть две трети пробы
# НИКОГДА НЕ ИСПОЛНЯЛИСЬ, а сдавались как «красная фаза по построению». Это не RED-first:
# RED-first — когда тест падает по ВЕРНОЙ причине, а не когда половина файла недостижима.
#
# Цена измерена: `C-216` нашёл, что `h_verdict` был определён НИЖЕ места вызова в `H` — в
# bash это мгновенный отказ при исполнении. Дефект пролежал круг гейта только потому, что
# `H` ни разу не запускался. Тем же корнем объясняются и «закрытие класса грепом вместо
# прогона», и «назвал остаточный риск вместо того, чтобы закрыть».
#
# ЧТО ЗДЕСЬ. Честная эталонная реализация контракта §«Контракт обёртки» — ТЕСТОВАЯ, а не
# прод: прод-обёртку вносит engine-dev задачей 2 в `deploy/bin/**`, это его зона. Эталон
# живёт в `scripts/tests/**` (зона architect'а) и нужен ровно для одного: чтобы КАЖДЫЙ
# сценарий исполнялся УЖЕ СЕЙЧАС и позитивный контроль был настоящим.
#
# ПОЧЕМУ ЭТО НЕ ПОДМЕНА ПРЕДМЕТА. Милестоун остаётся КРАСНЫМ: отсутствие прод-обёртки
# объявляется отдельной строкой отказа, и `VERDICT` красен, пока задача 2 не исполнена.
# Меняется одно — набор перестаёт быть непроверенным кодом и начинает предъявлять, что он
# ловит. Если эталон проходит все сценарии, а атаки краснеют, значит различающая сила есть;
# если нет — дефект в наборе, и его видно ЗДЕСЬ, а не кругом гейта.
make_reference_wrapper() { # $1=песочница → путь к эталонной обёртке
  local w="$1/reference-drill.sh"
  cat > "${w}" <<'REF'
#!/usr/bin/env bash
# ЭТАЛОННАЯ (тестовая) реализация контракта обёртки. Не идёт в прод.
set -uo pipefail
COLD="${JOURNAL_DRILL_COLD:?}"; RESTORE="${JOURNAL_DRILL_RESTORE:?}"
STATE="${JOURNAL_DRILL_STATE:?}"; READER="${JOURNAL_DRILL_READER:?}"
TRANSPORT="${JOURNAL_DRILL_TRANSPORT:-remote}"

if [ "${HFT_CRON_PRINT_ARGV:-0}" = "1" ]; then
  # Печать argv ДО побочных эффектов — обязанность контракта (сценарий `P`).
  printf 'RESTORE_DIR=%s
READER_DIR=%s
COLD=%s
TRANSPORT=%s
' \
    "${RESTORE}" "${RESTORE}" "${COLD}" "${TRANSPORT}"
  exit 0
fi

write_state() { # $1=ok $2=events $3=digest $4=reason $5=checked
  mkdir -p "$(dirname "${STATE}")"
  local tmp="${STATE}.tmp.$$"
  # `ts_wall_ms` — ОБЯЗАТЕЛЬНОЕ поле контракта (i64, ms since epoch); `ts` — необязательный
  # человекочитаемый дубль. Первая редакция эталона писала `"ts":0`, то есть необязательное
  # поле ВМЕСТО обязательного, и сценарий `A` краснел. Контракт предъявил себя исполнением —
  # ровно то, ради чего эталонная обёртка и заведена.
  printf '{"ok":%s,"ts_wall_ms":%s,"checked":%s,"events_read":%s,"digest":"%s","reason":"%s"}\n' \
    "$1" "$(date +%s)000" "$5" "$2" "$3" "$4" > "${tmp}"
  mv "${tmp}" "${STATE}"          # атомарно: обрывок не должен читаться как успех
}

rm -rf "${RESTORE}"; mkdir -p "${RESTORE}"
# Каталог восстановления ПУСТ перед первой выборкой — проверено НАБЛЮДЕНИЕМ, а не кодом возврата
# очистки (`M-99` §4 стр.12 (д), `C-318` B-1): иначе байты ПРОШЛОГО прогона засчитываются как
# доставленные этим. Неочищенный каталог — неполная доставка, `transport-failed`/5, читатель не зовётся.
if [ ! -d "${RESTORE}" ] || [ -n "$(ls -A "${RESTORE}" 2>/dev/null)" ]; then
  echo "ALERT transport-failed (каталог восстановления ${RESTORE} не очищен)" >&2
  write_state 0 0 "" "transport-failed" 0; exit 5
fi

# ── ДОСТАВКА: ДВЕ операции шва — листинг и выборка ОДНОГО файла (`M-99` §4 п.7, `R-263` Б-1) ─
# Ветки `local`/`remote` различаются ТОЛЬКО этими двумя функциями; всё после доставки — один
# код. Копия целиком не качается никогда: выборка зовётся по имени файла.
SSH="${JOURNAL_DRILL_SSH:-ssh -i /root/.ssh/storagebox -o IdentitiesOnly=yes -o BatchMode=yes -o ConnectTimeout=10 -p 23}"
if [ "${TRANSPORT}" = "remote" ]; then
  HOSTPART="${COLD%%:*}"; RPATH="${COLD#*:}"
  list_cold()  { ${SSH} "${HOSTPART}" ls "${RPATH}"; }
  fetch_one()  { rsync --archive -e "${SSH}" "${HOSTPART}:${RPATH}/$1" "${RESTORE}/"; }
else
  list_cold()  { ls "${COLD}"; }
  fetch_one()  { cp -p -- "${COLD}/$1" "${RESTORE}/"; }
fi
LISTING="$(list_cold)" || { write_state 0 0 "" "transport-failed" 0; exit 5; }
# ОТБОР ПО ИНДЕКСАМ, как предписан спекой §«Алгоритм отбора»: индексы извлекаются из ОБЕИХ
# форм имени, сортируются и ДЕДУПЛИЦИРУЮТСЯ, затем берутся ПЕРВЫЙ, СРЕДНИЙ и ПОСЛЕДНИЙ.
# НЕ «три свежих»: первая редакция этого эталона брала `tail -3`, и сценарий порчи стал
# ВАКУУМНЫМ — фикстура портит САМЫЙ СТАРЫЙ сегмент, он в выборку не попадал, и `C` зеленел
# на копии, которую никто не проверял. Эталон обязан реализовать ОБЪЯВЛЕННЫЙ контракт, иначе
# он проверяет не тот предмет.
ALL="$(printf '%s\n' "${LISTING}" | sed -n 's/^segment-\([0-9]\{8\}\)\.jrnl\(\.zst\)\?$/\1/p' | sort -u)"
N="$(printf '%s\n' "${ALL}" | grep -c .)"
if [ "${N}" -ge 3 ]; then
  MID=$(( (N + 1) / 2 ))
  IDX="$(printf '%s\n' "${ALL}" | sed -n "1p;${MID}p;${N}p" | sort -u)"
else
  IDX="${ALL}"
fi
# `checked` СЛЕДУЕТ ЗА ДОСТАВКОЙ (`M-99` §4 стр.12, `R-268` Б-1): членство — НЕ конвейером с ранним
# выходом (под `pipefail` `printf | grep -q` ложно проваливается на листинге за буфером канала),
# индекс засчитывается, только когда КАЖДАЯ его форма из листинга лежит в `RESTORE`; выбранный
# индекс без форм или с недоставленной формой — неполная доставка, `transport-failed`/5.
CHECKED=0
for i in ${IDX}; do
  want=0; got=0
  for f in "segment-${i}.jrnl" "segment-${i}.jrnl.zst"; do
    if grep -qx -- "$f" <<<"${LISTING}"; then
      want=$((want + 1))
      fetch_one "$f" || { write_state 0 0 "" "transport-failed" "${CHECKED}"; exit 5; }
      [ -f "${RESTORE}/$f" ] && got=$((got + 1))
    fi
  done
  if [ "${want}" -eq 0 ] || [ "${got}" -ne "${want}" ]; then
    echo "ALERT transport-failed (индекс ${i}: в листинге форм ${want}, доставлено ${got})" >&2
    write_state 0 0 "" "transport-failed" "${CHECKED}"; exit 5
  fi
  CHECKED=$((CHECKED + 1))
done
for side in $(printf '%s\n' "${LISTING}" | grep -E '^[^/]+\.json$'); do
  fetch_one "${side}" || { write_state 0 0 "" "transport-failed" 0; exit 5; }
done

if [ "${CHECKED}" -eq 0 ]; then write_state 0 0 "" "cold-empty" 0; exit 5; fi

# ── ЧТЕНИЕ: исход берётся У ЧИТАТЕЛЯ, а не сочиняется ────────────────────────────
OUT="$(${READER} --dir "${RESTORE}" --min-events 1 2>&1)"; RC=$?
EV="$(printf '%s' "${OUT}" | sed -n 's/.*"events_read":\([0-9]*\).*/\1/p' | head -1)"
# Отпечаток берётся СЫРЫМ (любое содержимое кавычек) и судится целиком ниже: выборка «только
# 64 строчных hex» превращала заглавный/короткий отпечаток в пустой — и обёртка не могла
# отличить «читатель не дал отпечаток» от «дал не тот» (`A-056` §3).
DG="$(printf '%s' "${OUT}" | sed -n 's/.*"digest"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1)"
INTRA="$(printf '%s' "${OUT}" | sed -n 's/.*"intra_segment_continuous":[[:space:]]*\(true\|false\).*/\1/p' | head -1)"
if [ "${RC}" -ne 0 ]; then
  write_state 0 "${EV:-0}" "" "reader-rc-${RC}" "${CHECKED}"; exit "${RC}"
fi
# Читатель НАШЁЛ дыру внутри сегмента — его собственный диагноз (`M-74` «Дополнительный fail-closed»).
if [ "${INTRA}" = "false" ]; then
  write_state 0 "${EV:-0}" "" "intra-segment-gap" "${CHECKED}"; exit 4
fi
# ВОРОТА ПРОТОКОЛА УСПЕХА (`M-99` §4 стр.11, `A-056` §4.1): `ok=1` — ТОЛЬКО при `rc=0` И полном
# протоколе: отпечаток ровно 64 строчных hex, `events_read` ≥ 1, `intra_segment_continuous=true`.
# Иное при `rc=0` — противоречие читателя: ни успех, ни чужой класс сочинять нельзя.
if ! printf '%s' "${DG}" | grep -qxE '[0-9a-f]{64}' \
   || [ -z "${EV}" ] || [ "${EV}" -lt 1 ] || [ "${INTRA}" != "true" ]; then
  write_state 0 "${EV:-0}" "" "reader-protocol-violation" "${CHECKED}"; exit 7
fi
write_state 1 "${EV}" "${DG}" "" "${CHECKED}"
exit 0
REF
  chmod +x "${w}"
  printf '%s' "${w}"
}

# ЭТАЛОННЫЙ ЧИТАТЕЛЬ — по той же причине, что и эталонная обёртка. Прод-бинарь
# `journal-drill-read` вносит engine-dev задачей 2b; пока его нет, обёртке НЕКОГО звать, и
# сценарии `H`/`C`/`F`/`A`/`T` не исполняются вовсе. Эталон говорит на объявленном контракте
# читателя (коды `0`/`4`/`5`, та же формула отпечатка) и живёт в зоне architect'а
# (`crates/journal/tests/**`). В прод не идёт и прод-бинарь не заменяет: сценарий `N` отдельно
# краснеет, пока настоящего читателя нет, — чтобы подмена не стала незаметной.
make_reference_reader() { # $1=песочница → команда читателя
  local r="$1/reference-reader.sh"
  cat > "${r}" <<REFR
#!/usr/bin/env bash
DIR=""; MIN=1; prev=""
for a in "\$@"; do
  [ "\${prev}" = "--dir" ] && DIR="\$a"
  [ "\${prev}" = "--min-events" ] && MIN="\$a"
  prev="\$a"
done
OUT="\$(cd '${ROOT}' && DRILL_READER_DIR="\${DIR}" DRILL_READER_MIN_EVENTS="\${MIN}" \\
  cargo test -p journal --test fixture_restore_drill_cold --quiet -- --exact \\
  reference_reader_for_shell_probe --nocapture 2>/dev/null)"
L="\$(printf '%s' "\${OUT}" | sed -n 's/^DRILL_READER //p' | head -1)"
[ -z "\${L}" ] && { echo '{"error":"reference reader failed"}'; exit 3; }
fld() { printf '%s' "\${L}" | sed -n "s/.*[ ]\$1=\\([^ ]*\\).*/\\1/p" | head -1; }
RC="\$(printf '%s' "\${L}" | sed -n 's/.*rc=\\([0-9]*\\).*/\\1/p')"
SR="\$(fld segments_read)"; EV="\$(fld events_read)"
SF="\$(fld seq_first)";     SL="\$(fld seq_last)"
IC="\$(fld intra_segment_continuous)"; DG="\$(fld digest)"
# ПОЛНЫЙ объявленный протокол успеха (C-217 N-1): шесть полей, а не два. Обратные кавычки
# здесь ЗАПРЕЩЕНЫ: этот текст живёт внутри НЕэкранированного heredoc и подставляется как
# команда — прежняя редакция печатала «C-217: command not found» посреди прогона. Прежде эталон
