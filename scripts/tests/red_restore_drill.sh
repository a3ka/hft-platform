# ══════════════════════════════════════════════════════════════════════════════════════
# D и R — САМОПРОВЕРКА РАЗЛИЧАЮЩЕЙ СИЛЫ. Подставляют ЖУЛЬНИЧЕСКУЮ обёртку и требуют, чтобы
# набор её поймал. Без них «зелёный на честной обёртке» не отличим от «зелёный на любой» —
# состояние, в котором проба четырежды прошла собственный прогон и четырежды была отвергнута
# гейтом. Проверка идёт по ТЕМ ЖЕ предикатам, что и `H`: если поймать не удалось, дефект в
# предикате, а не в сценарии.
# ══════════════════════════════════════════════════════════════════════════════════════

# Предикат `H` в отдельной функции — чтобы D/R судили ТО ЖЕ САМОЕ, а не свою копию правила.
# Редекларация предиката была бы тем же классом, что `C-202` B-2 на `M-45`: ослабь один —
# второй останется зелёным.
# ── ДОСТАВКА СОСТОЯЛАСЬ, А НЕ БЫЛА ПОДМЕНЕНА (закрытие `C-214` B-1) ──────────────────
#
# ЧТО СЛОМАЛОСЬ. rev 5 доказала ЧТЕНИЕ и на этом остановилась: `H` сверял отпечаток
# состояния с отпечатком каталога восстановления — а `truth_digest` ИДЁТ ПО ССЫЛКЕ. Обёртка,
# сделавшая `ln -s cold restore`, ничего не доставляет, читает холодную копию и проходит
# `H/C/E/F/A`. Проверено воспроизведением: `readlink -f` обоих каталогов даёт ОДИН путь.
#
# ПОЧЕМУ МОЙ СОБСТВЕННЫЙ «НАЗВАННЫЙ ОСТАТОК» БЫЛ НЕВЕРЕН. Я писал, что доставку сторожит
# сценарий `F`. `F` моделирует НЕЧИТАЕМЫЕ файлы холодной копии (`chmod 000`); при подмене
# ссылкой всё читается, и `F` молчит. Назвать предел — не то же самое, что закрыть его, и
# ошибка была именно в оценке, а не в умолчании.
#
# ЧТО ПРОВЕРЯЕТСЯ. Доставка — это ОТДЕЛЬНО МАТЕРИАЛИЗОВАННЫЙ результат:
#   · `restore` не символическая ссылка;
#   · `realpath(restore) != realpath(cold)` — не тот же каталог под другим именем;
#   · файлы восстановления не делят inode с холодной копией — жёсткая ссылка данных не
#     переносит, а на проде доставка идёт по сети, где `ln` невозможен в принципе.
# Проверка СТРУКТУРНАЯ (свойства файловой системы), а не текстовая: она не читает обёртку и
# не верит её полям — ровно то, чего требует условие снятия `C-214`.
#
# ТРИ СТРАЖА — ГРУППА, И КАЖДЫЙ ПРЕДЪЯВЛЕН ОТДЕЛЬНО (`Р-3`: мутация снимает РОВНО ОДНО
# свойство; опасна группа, которая не выписана). Замер по каждому:
#   атака ССЫЛКОЙ (`ln -s cold restore`)   → ловят ВСЕ ТРИ независимо;
#   атака ЖЁСТКИМИ ССЫЛКАМИ (`cp -al`)     → каталог настоящий, `-L` и `realpath` МОЛЧАТ,
#                                             ловит ТОЛЬКО пересечение inode'ов.
# Отсюда следствие для мутационного контроля, найденное собственным прогоном: снятие двух
# первых стражей НЕ роняет сценарий `X`, потому что третий ловит ту же атаку. Это
# избыточность, а не инертность — но проверять группу одной мутацией нельзя, и вывод
# «страж не нужен» из такого прогона был бы ложным якорем.
#
# ОСТАТОК, ТЕПЕРЬ НАЗВАННЫЙ ТОЧНО. Обёртка, которая ЧЕСТНО скопировала сегменты, а отпечаток
# посчитала по холодной копии, пройдёт. Но она ДОСТАВИЛА, и доставленное побайтно равно
# тому, что оцифровано, — свойство «доставленная копия читаема» установлено. Не покрыт
# только случай, где доставленное отличается от оцифрованного, и его держит равенство
# отпечатка каталогу восстановления, а не холодному.
delivery_ok() { # $1=песочница → 0, если восстановление РЕАЛЬНО материализовано
  local c r
  [ -L "$1/restore" ] && return 1
  [ -d "$1/restore" ] || return 1
  c="$(readlink -f "$1/cold" 2>/dev/null)"; r="$(readlink -f "$1/restore" 2>/dev/null)"
  [ -n "${c}" ] && [ -n "${r}" ] && [ "${c}" != "${r}" ] || return 1
  # Жёсткие ссылки: пересечение inode'ов означает, что байты не переносились.
  local shared
  shared="$(comm -12 \
    <(find "${r}" -maxdepth 1 -type f -printf '%i\n' 2>/dev/null | sort -u) \
    <(find "${c}" -maxdepth 1 -type f -printf '%i\n' 2>/dev/null | sort -u) | wc -l)"
  [ "${shared:-0}" -eq 0 ]
}

h_verdict() { # $1=песочница → 0, если состояние ДОКАЗЫВАЕТ чтение И доставку
  local ok ev d_state d_truth
  ok="$(state_field "$1" ok)"; ev="$(state_field "$1" events_read)"
  d_state="$(state_field "$1" digest)"; d_truth="$(truth_digest "$1/restore")"
  delivery_ok "$1" && [ "${ok}" = "1" ] && [ "${ev:-0}" -gt 0 ] \
    && [ -n "${d_truth}" ] && [ "${d_state}" = "${d_truth}" ]
}

# ── D — АТАКА `C-191`, ПОВТОРЁННАЯ ДОСЛОВНО ────────────────────────────────────────────
# Обёртка НЕ вызывает читателя и НЕ восстанавливает. Она делает ровно то, что делала
# жульническая обёртка критика: узнаёт каталоги из окружения и пишет правдоподобное
# состояние. В rev 4 этого хватало для `PASS (9/9)`.
make_fixture BOX_D healthy
FAKE_D="${BOX_D}/fake-drill.sh"
# ВОССТАНАВЛИВАЕТ ЧЕСТНО, но отпечаток ВЫДУМЫВАЕТ. Так проверяется именно то свойство,
# ради которого rev 5 существует: «назвать величину, не посчитав её». Обёртка, которая
# вдобавок ничего не восстановила, ловилась бы по пустому каталогу — то есть по другому
# признаку, и сценарий был бы зелен по слабой причине.
cat > "${FAKE_D}" <<'FAKE'
#!/usr/bin/env bash
mkdir -p "${JOURNAL_DRILL_RESTORE}" "$(dirname "${JOURNAL_DRILL_STATE}")"
cp "${JOURNAL_DRILL_COLD}"/* "${JOURNAL_DRILL_RESTORE}/" 2>/dev/null
printf '{"ok":1,"ts":0,"checked":3,"events_read":41213,"digest":"%s","reason":""}\n' \
  "$(printf 'выдуманный-отпечаток-без-чтения' | sha256sum | cut -c1-64)" > "${JOURNAL_DRILL_STATE}"
exit 0
FAKE
chmod +x "${FAKE_D}"
run_drill "${BOX_D}" "${FAKE_D}" || true
D_TRUTH="$(truth_digest "${BOX_D}/restore")"
if h_verdict "${BOX_D}"; then
  fail "D обёртка, восстановившая копию, но ВЫДУМАВШАЯ отпечаток, признана честной. Это класс
атаки C-191, сломавшей rev 4. Набор не имеет различающей силы, и его зелёный ничего не значит"
elif [ -z "${D_TRUTH}" ]; then
  fail "D поймана НЕ ПО ТОЙ ПРИЧИНЕ: восстановленный каталог пуст, и предикат отверг обёртку
по отсутствию данных, а не по расхождению отпечатков. Сценарий обязан судить подделку
ВЕЛИЧИНЫ; иначе он зелен по слабому признаку и не доказывает свойства rev 5"
else
  pass "D выдуманный отпечаток ПОЙМАН при ЧЕСТНО восстановленном каталоге (эталон ${D_TRUTH:0:12}… \
против объявленного обёрткой) — тем же предикатом, что судит честный прогон"
fi

# ── X — АТАКА `C-214`: ПОДМЕНА КАТАЛОГА ВОССТАНОВЛЕНИЯ ────────────────────────────────
# Обёртка НЕ доставляет ничего: делает `restore` ссылкой на `cold`, и отпечаток сходится
# сам собой, потому что читается та же холодная копия. rev 5 это принимала — `H/C/E/F/A`
# зелены. Сценарий требует, чтобы набор поймал подмену, и отдельно предъявляет, что поймал
# он её ПО ДОСТАВКЕ, а не по расхождению отпечатков: иначе он был бы зелен по чужой причине.
make_fixture BOX_X healthy
FAKE_X="${BOX_X}/fake-drill.sh"
cat > "${FAKE_X}" <<'FAKE'
#!/usr/bin/env bash
# Ничего не доставляет: подменяет каталог восстановления ссылкой на холодную копию.
rm -rf "${JOURNAL_DRILL_RESTORE}"
ln -s "${JOURNAL_DRILL_COLD}" "${JOURNAL_DRILL_RESTORE}"
mkdir -p "$(dirname "${JOURNAL_DRILL_STATE}")"
printf '{"ok":1,"ts":0,"checked":3,"events_read":41213,"digest":"__D__","reason":""}\n' \
  > "${JOURNAL_DRILL_STATE}"
exit 0
FAKE
# Отпечаток подставляется ПОДЛИННЫЙ — тот, что даст чтение подменённого каталога. Иначе
# сценарий ловил бы подделку величины (это уже делает `D`), а не подмену доставки.
X_TRUE="$(truth_digest "${BOX_X}/cold")"
sed -i "s/__D__/${X_TRUE}/" "${FAKE_X}"
chmod +x "${FAKE_X}"
run_drill "${BOX_X}" "${FAKE_X}" || true
X_DSTATE="$(state_field "${BOX_X}" digest)"
X_DTRUTH="$(truth_digest "${BOX_X}/restore")"
if h_verdict "${BOX_X}"; then
  fail "X обёртка, подменившая каталог восстановления ССЫЛКОЙ на холодную копию, признана
честной. Она НИЧЕГО НЕ ДОСТАВИЛА: доказана читаемость холодных данных, а не восстановленных.
Это находка C-214 B-1, и именно так rev 5 проходила H/C/E/F/A"
elif [ -z "${X_DTRUTH}" ] || [ "${X_DSTATE}" != "${X_DTRUTH}" ]; then
  fail "X поймана НЕ ПО ТОЙ ПРИЧИНЕ: отпечатки разошлись (состояние ${X_DSTATE:0:12}…,
каталог ${X_DTRUTH:0:12}…), то есть сработал предикат величины, а не проверка ДОСТАВКИ.
Сценарий обязан ловить подмену каталога даже при СОВПАДАЮЩИХ отпечатках"
else
  pass "X подмена каталога восстановления ПОЙМАНА при СОВПАВШЕМ отпечатке (${X_DSTATE:0:12}…) — \
сработала проверка доставки, а не величины"
fi

# ── R — ОТПЕЧАТОК ПРОШЛОГО ПРОГОНА ─────────────────────────────────────────────────────
# Ловушка, названная разведкой задачи 6b: обёртка, однажды увидевшая правильное значение,
# подставит его константой. Здесь берётся ПОДЛИННЫЙ отпечаток ДРУГОЙ фикстуры (другой нонс)
# и предъявляется как свой. Значение настоящее — но не этого прогона.
make_fixture BOX_R healthy
STALE_DIGEST="$(truth_digest "${BOX_D}/cold")"
if [ -z "${STALE_DIGEST}" ] || [ "${STALE_DIGEST}" = "$(truth_digest "${BOX_R}/cold")" ]; then
  die "две фикстуры дали ОДИН отпечаток (или ни одного) — одноразовость не состоялась, и
сценарий R судил бы не тот предмет. Проверить нонс строителя (задача 6b)"
fi
FAKE_R="${BOX_R}/fake-drill.sh"
cat > "${FAKE_R}" <<FAKE
#!/usr/bin/env bash
# Восстанавливает ЧЕСТНО, но отпечаток берёт из ПРОШЛОГО прогона.
mkdir -p "\${JOURNAL_DRILL_RESTORE}" "\$(dirname "\${JOURNAL_DRILL_STATE}")"
cp "\${JOURNAL_DRILL_COLD}"/* "\${JOURNAL_DRILL_RESTORE}/" 2>/dev/null
printf '{"ok":1,"ts":0,"checked":3,"events_read":41213,"digest":"${STALE_DIGEST}","reason":""}\n' \
  > "\${JOURNAL_DRILL_STATE}"
exit 0
FAKE
chmod +x "${FAKE_R}"
run_drill "${BOX_R}" "${FAKE_R}" || true
if h_verdict "${BOX_R}"; then
  fail "R отпечаток ЧУЖОГО прогона принят как свой. Признак не различает миры: обёртка,
однажды увидевшая правильное значение, подставит его навсегда (Р-4 обязанность (а))"
else
  pass "R отпечаток прошлого прогона ОТВЕРГНУТ — фикстура одноразова, признак различает"
fi

echo
TOTAL=$((PASSED + FAILED))
if [ "${FAILED}" -eq 0 ]; then
  echo "VERDICT: PASS (${PASSED}/${TOTAL}) — копия читается прод-читателем, исходы различимы"
  exit 0
fi
echo "VERDICT: FAIL (${FAILED} из ${TOTAL})"
exit 1
