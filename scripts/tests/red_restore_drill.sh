printf '{"segments_read":%s,"events_read":%s,"seq_first":%s,"seq_last":%s,"intra_segment_continuous":%s,"digest":"%s"}\\n' \\
  "\${SR:-0}" "\${EV:-0}" "\${SF:-0}" "\${SL:-0}" "\${IC:-false}" "\${DG}"
exit "\${RC:-3}"
REFR
  chmod +x "${r}"
  printf 'bash %s' "${r}"
}

