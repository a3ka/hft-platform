# ═══ ФОРМА ПРОДА СНЯТА ЗАМЕРОМ 2026-08-31, А НЕ ВООБРАЖЕНА ═══
#
#   $ cat  <журнал>/journal.legacy.json          → {"declarations": []}    ← ПУСТ
#   $ ls   <журнал>/segment-* | head -1          → segment-00000001.jrnl.zst
#   $ ssh box 'ls journal/ | grep -v ^segment'   → journal.legacy.json, journal.replay-digest.json
#                                                  (journal.meta ОТСУТСТВУЕТ)
#   $ ssh box 'ls journal/ | wc -l'              → 501 = 478 .zst + 21 .jrnl + 2 sidecar
#   $ пар «и .jrnl, и .jrnl.zst» на один индекс  → 17
#
# Отсюда прямые следствия для сценариев ниже:
#  • сценарий `M` («sidecar'ов нет ⇒ legacy не читается») СНЯТ: на проде НОЛЬ legacy-деклараций,
#    отсутствие манифеста для наших данных безвредно, и сценарий был бы зелен по отсутствию
#    предмета. Его предмет — различение «нет контекста» и «порча» — перенесён в
#    `fixture_restore_drill_cold.rs::undeclared_legacy_is_a_context_error_not_a_corruption_error`,
#    где помечен FORWARD-GUARD'ом: он сторожит будущую декларацию, а не сегодняшний прод;
#  • вместо него введён сценарий `E` (ПУСТОТА), который на проде ДОСТИЖИМ и опасен: копия
#    «скачалась успешно» и не привезла ничего, а `journal::stream` на пустом каталоге
#    возвращает Ok с нулём событий — то есть drill, решающий по коду возврата читателя,
#    рапортует успех. Это ровно класс `R-157` `Б-5`;
#  • `H` обязан подтвердить, что прочитана И СЖАТАЯ форма: drill, умеющий только `.jrnl`,
#    молча пропустил бы 478 сегментов из 499 и был бы зелёным.
#
# ═══ ПОЧЕМУ rev 5: ЧЕТЫРЕ ОТКАЗА НА ОДНОМ КЛАССЕ ═══
#
# Круги 1-4 провалились на одном: набор судил ПОКАЗАНИЯ обёртки о самой себе. Круг 4
# (`C-189` B-1) закрывал это ПРОЗРАЧНЫМ НАБЛЮДАТЕЛЕМ над читателем, писавшим свидетельство
# в место, «обёртке не известное». Круг 5 (`C-191`) это сломал: путь к свидетельству лежал
# в скрипте наблюдателя, а скрипт проба сама же передавала обёртке в `JOURNAL_DRILL_READER`.
# Критик собрал обёртку, которая читателя НЕ ЗАПУСКАЛА, дописала строку свидетельства руками
# и получила `PASS (9/9)`.
#
# Арбитр (`A-028` §4) объявил предел кругов исчерпанным и вернул предмет founder'у. Решение
# founder'а 2026-09-07 — вариант A: ПЕРЕСБОРКА ДРУГОЙ КОНСТРУКЦИЕЙ, счёт кругов с нуля.
#
# Смена конструкции — не пятая заплатка на той же идее, и разница проверяема:
#   rev 4: свидетельство — ДЕКЛАРАЦИЯ О ДЕЙСТВИИ («читатель был вызван»). Декларацию
#          подделывает кто угодно, надо лишь найти, куда её писать. Критик нашёл.
#   rev 5: свидетельство — ПРОДУКТ ДЕЙСТВИЯ (`digest` по декодированным полям). Чтобы его
#          назвать, надо разобрать `postcard + crc32`, то есть выполнить работу, которую
#          drill и обязан выполнить. Прятать нечего — и находить нечего.
#
# Обе очевидные лазейки закрыты и предъявлены сценариями, а не обещаны:
#   `D` — обёртка, не читавшая копию, отпечаток назвать не может (атака `C-191` повторена);
#   `R` — отпечаток ПРОШЛОГО прогона не годится: фикстура одноразова (нонс из корневого
#         источника энтропии с самопроверкой на вырождение — задача 6b, образец взят у
#         `scripts/reserve_artifact_id.sh`, где решается структурно та же задача).
#
# ═══ СЦЕНАРИИ ═══
#   S  фикстура материализована                → SETUP-GUARD (иначе всё ниже вакуумно)
#   N  эталон считается, нонс одноразов        → SETUP-GUARD отпечатка (задача 6b, `Р-4` (а))
#   P  argv печатается ДО побочных эффектов    → путь записи fetch'а == путь чтения читателя
#   H  здоровая прод-форменная копия           → drill ПРОХОДИТ; отпечаток состояния РАВЕН
#                                                 отпечатку прод-читателя по восстановленному
#   C  один сжатый сегмент повреждён           → ОТКАЗ rc=4, отпечатка НЕТ
#   E  холодная копия ПУСТА                    → ОТКАЗ rc=5, причина ОТЛИЧНА от C
#   F  копия полна, доставка молча не сработала → ОТКАЗ rc=5, отпечатка НЕТ
#   A  оборванный файл состояния               → перезаписан целиком (канарейка обрывка исчезла)
#   D  обёртка НЕ читает и подделывает состояние → проба ОБЯЗАНА покраснеть (атака `C-191`)
#   X  обёртка подменяет каталог восстановления ССЫЛКОЙ → проба ОБЯЗАНА покраснеть (`C-214`)
#   A1 каталог настоящий, ФАЙЛЫ — ссылки на холодную копию → покраснеть (`C-215`)
#   A6 доставка пуста, отпечаток подлинный по холодной копии → покраснеть
#   A7 доставлен ОДИН индекс из трёх, отпечаток подлинный → покраснеть (`C-216`)
#   T  ветка `remote` идёт через ШОВ и падает закрыто (`A-032` §2.3; НЕ доказательство сети)
#   R  обёртка подставляет отпечаток ПРОШЛОГО прогона → проба ОБЯЗАНА покраснеть
#   A8 доставлены ТРИ настоящих, но НЕ ТЕ индекса → покраснеть (`C-217` B-2)
#   A9 выборка верна, отчёт `checked` лжив → покраснеть
#   Q  читатель говорит ПОЛНЫМ протоколом, непрерывность — ВНУТРИ сегмента (`C-218` B-1)
#   A10 не привезена одна форма выбранного индекса → покраснеть (`C-218` B-2)
#   A11 наблюдатель обёртки ВОЗВРАЩАЕТ источник в окне чтения → покраснеть (`C-219` B-1, `M-99`)
#   A12 sidecar НЕ привезён / A13 sidecar ПОДМЕНЁН → покраснеть (`C-219` B-2, `M-99`)
#
# `M-99` (2026-10-10): источник при проверке доставки УНИЧТОЖАЕТСЯ, а не прячется, и всё окно
# чтения наблюдается inotify; sidecar'ы сверяются побайтно со снимком копии, снятым ДО запуска
# обёртки. Разбор и таблица мутаций — `milestones/M-99-restore-drill-automation.md` §4, §8.
#
# `D` и `R` — самопроверка РАЗЛИЧАЮЩЕЙ СИЛЫ: они подставляют жульническую обёртку и требуют,
# чтобы набор её поймал. Без них «зелёный на честной обёртке» не отличим от «зелёный на
# любой» — ровно то состояние, в котором проба четырежды прошла гейт и четырежды была
# отвергнута.
#
# `H` — позитивный контроль. Без него `C` и `E` зелены против drill'а, который отказывает
# ВСЕГДА: «отказал на битой копии» верно и для процедуры, которая не работает никогда.
#
# ═══ ЧЕГО ПРОБА НЕ ЛОВИТ — названо ═══
#   • сеть и права Storage Box: `JOURNAL_DRILL_TRANSPORT=local`, то есть гоняется ЛОКАЛЬНАЯ
#     ветка доставки. Сетевая ветка проверяется только первым автопрогоном на VPS;
#   • порчу в НЕВЫБРАННОМ сегменте: принятый предел выборки, названный в спеке `M-74`;
#   • сценарий `E` (пустая холодная копия) свидетельства НЕ требует: обёртка вправе отсечь
#     пустую копию ДО вызова читателя, это дешевле и законно. Подделку на этом пути ловят
#     `H`/`C`/`F`, а не `E` — названо, чтобы следующий круг не искал здесь дыру.

set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
DRILL="${ROOT}/deploy/bin/journal-restore-drill-cron.sh"

PASSED=0; FAILED=0
pass() { echo "PASS  $*"; PASSED=$((PASSED + 1)); }
fail() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
die()  { echo "SETUP НЕ СОСТОЯЛСЯ: $*" >&2; exit 2; }

REG="$(mktemp /tmp/red-drill-reg-XXXXXX)" || die mktemp
cleanup() {
  # Наблюдатель атаки `A11` — фоновый процесс СУДИМОЙ (жульнической) обёртки; он обязан умереть
  # вместе с пробой при ЛЮБОМ исходе, включая `die` посреди сценария.
  if [ -n "${A11_PIDFILE:-}" ] && [ -s "${A11_PIDFILE}" ]; then
    kill -- "-$(cat "${A11_PIDFILE}")" 2>/dev/null || kill "$(cat "${A11_PIDFILE}")" 2>/dev/null || true
  fi
  if [ -n "${KEEP_FIXTURES:-}" ]; then echo "песочницы оставлены: ${REG}"; return 0; fi
  while IFS= read -r d; do
    case "$d" in /tmp/red-drill-*) [ -d "$d" ] && rm -rf "$d" ;; esac
  done < "${REG}" 2>/dev/null
  rm -f "${REG}"
}
trap cleanup EXIT

# ── ЗАЯВЛЕННОЕ КРАСНОЕ. Обёртки нет — это состояние задачи 2, а не сбой пробы. ───────────
#
# ПРЕЖНЯЯ РЕДАКЦИЯ ЗДЕСЬ ВЫХОДИЛА, И ЭТО БЫЛО ДЕФЕКТОМ. Сценарии `D`/`R` подставляют СВОЮ,
# жульническую обёртку и настоящей не требуют — то есть различающая сила набора проверяема
# УЖЕ СЕЙЧАС, до задачи 2. Ранний выход её не проверял, и получалось, что до появления
# обёртки набор не утверждал о себе НИЧЕГО. Именно это и вскрывалось потом на гейте: проба
# была зелена на честной обёртке и на любой другой одинаково, а узнавали об этом кругом
# критика, а не прогоном.
#
# `A-028` §1 требует полноты набора ДО диспетчеризации. Полнота — не «файлы на месте», а
# «набор предъявляет, что он ловит». Отсутствие прод-обёртки объявляется ОТДЕЛЬНОЙ строкой
# отказа, но НИ ОДИН сценарий из-за неё не пропускается: с `C-216` все они гоняются против
# ЭТАЛОННОЙ обёртки (см. ниже). Прежняя редакция здесь печатала «сценарии S/N/P/H/C/E/F/A
# объявлены RED» и это стало ложью в тот же коммит, которым эталон был внесён.
DRILL_PRESENT=1
if [ ! -f "${DRILL}" ]; then
  DRILL_PRESENT=0
  fail "обёртки ${DRILL#"${ROOT}"/} НЕ СУЩЕСТВУЕТ — RED задачи 1 (её вносит engine-dev задачей 2)"
fi

# ── Фикстура строится ПРОД-ПИСАТЕЛЕМ, а не printf'ом ────────────────────────────────────
# Единственный строитель — тест-таргет крейта `journal`. Здесь только вызов и СТРАЖ того,
# что вызов дал результат: `cargo test` возвращает 0 и когда фильтр не нашёл ни одного теста.
make_fixture() { # $1=имя переменной под каталог; $2=healthy|corrupt|empty
  local d out
  d="$(mktemp -d /tmp/red-drill-XXXXXX)" || die mktemp
  printf '%s\n' "${d}" >> "${REG}"
  out="$(cd "${ROOT}" && DRILL_FIXTURE_OUT="${d}" DRILL_FIXTURE_VARIANT="$2" \
        cargo test -p journal --test fixture_restore_drill_cold --quiet \
        -- --exact materialize_for_shell_probe --nocapture 2>&1)" \
    || die "строитель фикстуры не собрался/упал (вариант $2):"$'\n'"${out}"
  printf '%s\n' "${out}" | grep -q 'DRILL_FIXTURE_READY' \
    || die "строитель НЕ отчитался о материализации (вариант $2) — шаг был бы вакуумным:"$'\n'"${out}"
  # Нонс ПРОГОНА (задача 6b) объявляется строителем в stdout и НЕ кладётся в каталог: лёжа
  # в каталоге, он был бы доступен обёртке до чтения и перестал бы различать миры.
  printf -v "FIX_NONCE_${1#BOX_}" '%s' \
    "$(printf '%s\n' "${out}" | sed -n 's/.*DRILL_FIXTURE_READY variant=[a-z]* nonce=\([0-9]*\).*/\1/p' | head -1)"
  [ -d "${d}/cold" ] || die "каталог холодной копии не создан (вариант $2)"
  printf -v "$1" '%s' "${d}"
}

# Число РАЗЛИЧНЫХ индексов сегментов в каталоге (дубли raw+zst считаются один раз).
seg_indices() { ls "$1" 2>/dev/null | sed -n 's/^segment-\([0-9]\{8\}\)\.jrnl\(\.zst\)\?$/\1/p' | sort -u | wc -l; }

# ══════════════════════════════════════════════════════════════════════════════════════
# ОТПЕЧАТОК ПРОЧИТАННОГО — ЯДРО rev 5, закрытие `C-191`.
#
# ЧТО СЛОМАЛОСЬ В rev 4. Свидетельство о вызове читателя писал ПРОЗРАЧНЫЙ НАБЛЮДАТЕЛЬ, и
# проба прятала от обёртки путь к нему. Критик путь НАШЁЛ — прочитав скрипт наблюдателя,
# который проба сама же и передавала обёртке в `JOURNAL_DRILL_READER`. Собрал обёртку, которая
# НЕ ВЫЗЫВАЛА читателя, дописала строку `DIR/RC/EV` руками, и получил `PASS (9/9)`.
# Корень: свидетельство было ДЕКЛАРАЦИЕЙ О ДЕЙСТВИИ, а декларацию подделывает кто угодно.
#
# ЧТО ЗДЕСЬ ВМЕСТО НЕГО. Доказательством становится `digest` — свёртка по ДЕКОДИРОВАННЫМ
# полям событий (`sha256(Σ "<seq>:<ts_exch_ms>:<price_e8>\n")`, спека §«Поле digest»).
# Это ПРОДУКТ ДЕЙСТВИЯ, а не рассказ о нём: чтобы назвать `seq`/`ts`/`price`, надо разобрать
# `postcard + crc32`, то есть выполнить ровно ту работу, доказательством которой drill и
# является. Прятать больше нечего — и потому нечего найти.
#
# ЭТАЛОН БЕРЁТСЯ НА ГРАНИЦЕ ПОТРЕБИТЕЛЯ (`Р-1`), А НЕ ПЕРЕПИСЫВАНИЕМ ЛОГИКИ. Проба НЕ
# повторяет правило отбора сегментов, которое реализует обёртка: она зовёт ПРОД-ЧИТАТЕЛЯ на
# том каталоге, который обёртка РЕАЛЬНО наполнила, и берёт его отпечаток. Редекларация
# судимой логики — отдельный класс дефекта, на котором уже краснел `M-45` (`C-202` B-2):
# ослабь реализацию — проба, повторяющая её, останется зелёной.
#
# ПРЕЖНЯЯ РЕДАКЦИЯ ЗДЕСЬ НАЗЫВАЛА ОСТАТОК НЕВЕРНО, и это стоило двух кругов. Стояло:
# «обёртка, посчитавшая отпечаток по холодной копии, доставку не доказывает — доставку
# сторожит сценарий `F`». Оба утверждения ложны. `F` моделирует НЕЧИТАЕМЫЕ файлы
# (`chmod 000`); при любой подмене каталога всё читается, и `F` молчит — `C-214` и `C-215`
# предъявили это дважды. Назвать предел не значит закрыть его: названный неверно предел
# опаснее умолчания, потому что читается как покрытие.
#
# ЧТО ДЕРЖИТ ДОСТАВКУ СЕЙЧАС — `INV-DELIVERY` (см. ниже, `A-032` §2.2): формулировка ОТ
# РЕЗУЛЬТАТА вместо перечисления форм подмены. ЧЕГО ПРОБА НЕ ДОКАЗЫВАЕТ — перенос байтов по
# сети; это `Р-2`, а не остаток, и разбор там же.
#
# ДВА ИСТОЧНИКА ЭТАЛОНА, И ЭТО НЕ ДУБЛИРОВАНИЕ.
#  · `truth_digest` — НЕЗАВИСИМЫЙ путь: свёртка считается прямо библиотекой `journal`
#    (`crates/journal/tests/fixture_restore_drill_cold.rs::digest_for_shell_probe`). Не
#    зависит от бинаря, который зовёт судимая обёртка, и потому доступен УЖЕ СЕЙЧАС —
#    благодаря чему самопроверка `D`/`R` исполняется до задачи 2b, а не печатает вакуумный
#    зелёный. `testing.md`: эталон берётся из независимого пути, не из судимого источника.
#  · `reader_digest` — ПРОД-ПУТЬ: тот самый бинарь, которым обёртка обязана читать. Нужен
#    сценарию `N`, чтобы предъявить, что прод-читатель вообще способен выдать отпечаток.
# Совпадение двух источников на здоровой копии — отдельное утверждение (сценарий `N`):
# расхождение означало бы, что формула у сторон разная, и тогда все сравнения ниже мерят
# не то. Один источник вместо двух этого не поймал бы.
truth_digest() { # $1=каталог → отпечаток НЕЗАВИСИМОГО пути; пусто, если не вышло
  local out
  out="$(cd "${ROOT}" && DRILL_DIGEST_DIR="$1" cargo test -p journal \
          --test fixture_restore_drill_cold --quiet -- --exact digest_for_shell_probe \
          --nocapture 2>/dev/null)" || true
  printf '%s' "${out}" | sed -n 's/.*DRILL_DIGEST events=[0-9]* digest=\([0-9a-f]\{64\}\).*/\1/p' | head -1
}

reader_digest() { # $1=каталог → отпечаток ПРОД-ЧИТАТЕЛЯ; пусто, если бинаря нет
  local out
  out="$(cd "${ROOT}" && cargo run -q -p journal --bin journal-drill-read -- \
          --dir "$1" --min-events 0 2>/dev/null)" || true
  printf '%s' "${out}" | sed -n 's/.*"digest"[[:space:]]*:[[:space:]]*"\([0-9a-f]\{64\}\)".*/\1/p' | head -1
}

# `$2` — необязательная ПОДМЕНА обёртки: сценарии `D`/`R` подставляют жульническую, чтобы
# проба предъявила СВОЮ различающую силу исполнением, а не обещанием.
run_drill() { # $1=песочница [$2=путь к обёртке] → код возврата
  # Судимая обёртка: явно переданная (сценарии-атаки) → прод → ЭТАЛОН в этой песочнице.
  # Эталон строится ПОД КАЖДУЮ песочницу: он обязан быть тем же кодом, но не делить
  # состояние между сценариями.
  local wrapper="${2:-}" READER_CMD
  snapshot_source "$1"
  if [ -n "$(reader_digest "$1/cold" 2>/dev/null)" ] || [ -f "${ROOT}/crates/journal/src/bin/journal-drill-read.rs" ]; then
    READER_CMD="cargo run -q --manifest-path ${ROOT}/Cargo.toml -p journal --bin journal-drill-read --"
  else
    READER_CMD="$(make_reference_reader "$1")"
  fi
  if [ -z "${wrapper}" ]; then
    if [ "${DRILL_PRESENT}" -eq 1 ]; then wrapper="${DRILL}"
    else wrapper="$(make_reference_wrapper "$1")"; fi
  fi
  ( cd "$1" \
    && JOURNAL_DRILL_COLD="$1/cold" \
       JOURNAL_DRILL_RESTORE="$1/restore" \
       JOURNAL_DRILL_STATE="$1/state/journal-restore-drill.json" \
       JOURNAL_DRILL_TRANSPORT="local" \
       JOURNAL_DRILL_READER="${READER_CMD}" \
       bash "${wrapper}" >"$1/drill.log" 2>&1 )
  local rc=$?
  printf '%s' "${rc}" > "$1/drill.rc"
  return "${rc}"
}

drill_rc()      { cat "$1/drill.rc" 2>/dev/null; }
state_field() { # $1=песочница $2=имя поля → значение или пусто
  sed -n "s/.*\"$2\"[[:space:]]*:[[:space:]]*\"\{0,1\}\([^,\"}]*\)\"\{0,1\}.*/\1/p" \
    "$1/state/journal-restore-drill.json" 2>/dev/null | head -1
}

# ── INV-DELIVERY: ДОСТАВКА ДОКАЗЫВАЕТСЯ НЕЗАВИСИМОСТЬЮ ОТ ИСТОЧНИКА (`A-032` §2.2) ────
#
# ТРИ КРУГА ЛОВИЛИ СПОСОБ, А НАДО БЫЛО РЕЗУЛЬТАТ. Прежняя `delivery_ok` перечисляла формы
# подмены: символическая ссылка на каталог (`C-214`), жёсткие ссылки, ссылки на файлы
# (`C-215`). Каждый круг находил следующую форму — ровно та траектория, которую корпус уже
# прошёл на `check_protected_artifacts.sh` и назвала бесполезной: «латать частные случаи
# бесполезно; инвариант формулируется от РЕЗУЛЬТАТА, а не от способа» (шапка того файла).
#
# ФОРМУЛИРОВКА ОТ РЕЗУЛЬТАТА, постановленная арбитром `A-032` §2.2:
#
#   > После завершения обёртки восстановленный каталог обязан читаться НЕЗАВИСИМЫМ
#   > читателем в тот же отпечаток, что назван в состоянии, — ПРИ НЕДОСТУПНОМ ИСТОЧНИКЕ
#   > (холодная копия убирается ДО повторного чтения).
#
# Она не называет ни одной формы подмены и потому ловит их все: ссылка на каталог, ссылки
# на файлы, bind-mount, ленивый passthrough — у всех ОДИН результат: без источника читать
# нечего. Ловля форм этим решением ЗАКРЫТА как класс; REJECT за непокрытую форму псевдонима
# кругом не считается (`A-032` §4).
#
# ЖЁСТКИЕ ССЫЛКИ ПРОХОДЯТ, И ЭТО ПРАВИЛЬНО, А НЕ ПРОБЕЛ (`A-032` §2.2). Инвариант про
# РЕЗУЛЬТАТ: каталог держит СВОЮ ссылку на байты, и они читаются без холодной копии. Отказ
# по inode был бы требованием к СПОСОБУ. На проде жёсткая ссылка через сеть невозможна, в
# локальной заглушке безвредна. Названо, а не умолчано.
#
# ЧЕГО ЭТА ПРОБА НЕ ДОКАЗЫВАЕТ — предел назван как `Р-2`, а не как «остаток»: проба пиннит
# `JOURNAL_DRILL_TRANSPORT=local` и НИ РАЗУ не гоняет `remote`, то есть ПЕРЕНОС БАЙТОВ ПО
# СЕТИ здесь недоказуем в принципе — оракул судил бы ветку-заглушку. Это перенесено на
# первый живой прогон на VPS с `TRANSPORT=remote` и на деплой-гейт `gates.md` §8
# (`A-032` §2.4). Сам ШОВ транспорта проба покрывает — сценарий `T` ниже.
# ═══ РАЗЛОЖЕНИЕ НА ПЕР-ЧЛЕННО МУТИРУЕМЫЕ СТРАЖИ (`Р-3`) — И ПОЧЕМУ ОНО ПОТРЕБОВАЛОСЬ ═══
#
# ЗАМЕР, А НЕ СООБРАЖЕНИЕ. Редакция `ab803d2` держала в `h_verdict` сравнение
# `d_state = d_truth` И вызывала `inv_delivery`, который сравнивал `d_after` С ТЕМ ЖЕ
# `state.digest`. Мутация «снять сравнение отпечатков в `h_verdict`» дала прогон,
# ПОБУКВЕННО РАВНЫЙ немутированному: 18 из 18 строк те же. Страж был ИНЕРТЕН — а спека
# при этом утверждала, что его снятие роняет `D` и `R`. Утверждение было ложным.
#
# Корень нашёлся во ВТОРОМ вопросе мутационного контроля (`testing.md`: «что пришлось
# ослабить рядом»): проверка ПОЛНОТЫ, внесённая закрытием `C-216`, объявляла `checked=3`
# при восьми реально доставленных индексах у ЖУЛЬНИЧЕСКИХ обёрток `D`/`R` — и ловила их
# ПЕРВОЙ. Обе атаки были переопределены, а страж отпечатка не нёс ничего.
#
# РАЗВЯЗКА — три НАЗВАННЫХ стража, каждый со своим членом, и фикстуры атак, устроенные так,
# чтобы КАЖДАЯ проходила все стражи, кроме СВОЕГО:
#
#   digest_matches_state  объявленный отпечаток == прочитанный ПРИ ЖИВОМ источнике  → `D`, `R`
#   delivery_complete     заявленное `checked` == доставленным индексам, и их ≥ 3    → `A7`
#   inv_delivery          при УБРАННОМ источнике каталог читается В ТО ЖЕ            → `X`, `A1`
#
# `A-032` §2.2 п.1 («решающий предикат — ОДНА функция») НЕ нарушен: единственной судящей
# функцией остаётся `h_verdict`, и её зовут все сценарии. Разложение ВНУТРИ неё.
#
# ИНВАРИАНТ АРБИТРА НЕ ОСЛАБЛЕН, А УСИЛЕН. `A-032` требует `d_after = state.digest`. Здесь
# требуется `state.digest = d_live` И `d_after = d_live`, откуда требование арбитра следует.
# Пара строго сильнее одиночного условия и не может пропустить того, что пропускал бы он.
#
# `A6` (пустая доставка) переопределена ПО ПОСТРОЕНИЮ и это названо, а не замолчано: пустой
# каталог нарушает и величину, и полноту одновременно; объявить `checked=0` она не может —
# контрактный минимум три. Её свойство порознь держат `D` (величина) и `A7` (полнота).
digest_matches_state() { # $1=песочница $2=отпечаток каталога ПРИ ЖИВОМ источнике
  [ -n "$2" ] && [ "$(state_field "$1" digest)" = "$2" ]
}

# ═══ ТОЖДЕСТВО ЧЛЕНОВ ВЫБОРКИ — ЗАКРЫТИЕ `C-217` B-2 ═══
#
# ЧТО ПРОПУСКАЛА ПРЕЖНЯЯ `delivery_complete`. Она проверяла ЧИСЛО («доставлено == заявлено,
# и их ≥3») и не проверяла, КАКИЕ. Обёртка, доставившая три НАСТОЯЩИХ, читаемых без
# источника сегмента `00/01/02` вместо предписанных `00/03/07`, проходила ВЕСЬ набор:
# отпечаток подлинный, независимость от источника держится, счёт сходится.
#
# ПОЧЕМУ ЭТО НЕ ПЕДАНТИЗМ. Смысл правила «первый / floor(N/2) / последний» — проверить копию
# ПО ВСЕЙ ЕЁ ДЛИНЕ. Три подряд идущих свежих сегмента проверяют узкую полоску и объявляют,
# что копия читается целиком, — то есть drill отвечает на другой вопрос, чем задан.
#
# КАК ЭТО ПРОВЕРЯЕТСЯ, НЕ РЕДЕКЛАРИРУЯ АЛГОРИТМ. Ожидаемый состав — ЛИТЕРАЛ, выведенный из
# спеки ОДИН РАЗ для ЭТОЙ фикстуры, а не пересчёт правила отбора рядом с судимой обёрткой.
# Редекларация судимой логики уже стоила круга на `M-45` (`C-202` B-2): ослабь реализацию —
# и проба, её повторяющая, ослабнет вместе с ней. Литерал так не умеет.
# Литерал держится SETUP-GUARD'ом на ФОРМУ фикстуры (сценарий `S`): восемь индексов
# `00000000`..`00000007`. Изменится фикстура — сценарий `S` умрёт с «setup не состоялся», а
# не соврёт зелёным.
EXPECTED_MEMBERS="00000000 00000003 00000007"

delivered_members() { # $1=песочница → доставленные ИНДЕКСЫ одной строкой
  ls "$1/restore" 2>/dev/null | sed -n 's/^segment-\([0-9]\{8\}\)\.jrnl\(\.zst\)\?$/\1/p' \
    | sort -u | tr '\n' ' ' | sed 's/ *$//'
}

delivery_matches_selection() { # $1=песочница → 0, если доставлен РОВНО объявленный состав
  local ck got n
  ck="$(state_field "$1" checked)"
  got="$(delivered_members "$1")"
  n="$(printf '%s\n' ${got} | grep -c .)"
  # ДВЕ обязанности, и каждая со своим членом в наборе:
  #  (1) ТОЖДЕСТВО состава объявленной выборке — сценарии `A7` (недодал) и `A8` (не те);
  #  (2) согласие заявленного `checked` с доставленным — сценарий `A9` (соврал в отчёте).
  # Третьей обязанности «не меньше трёх» здесь НЕТ намеренно: при тождестве трёхчленной
  # выборке она истинна всегда, то есть была бы ИНЕРТНА. Замер её инертность и показал —
  # мутация «снять согласие и минимум» не роняла ни одного сценария (`Р-3`).
  [ "${got}" = "${EXPECTED_MEMBERS}" ] && [ "${ck:-0}" -eq "${n:-0}" ]
}

# ═══ ФОРМЫ ФАЙЛА НА ВЫБРАННЫЙ ИНДЕКС — ЗАКРЫТИЕ `C-218` B-2 ═══
#
# Спека §«Правило выборки»: «для каждого выбранного индекса восстанавливаются ОБЕ формы, если
# обе есть в копии, — прод-читатель сам предпочтёт сырую (D-COMP-1)». На проде таких пар 17.
#
# ЧЕМУ ЭТА ОБЯЗАННОСТЬ БЫЛА РАВНА ДО СЕЙЧАС: НИЧЕМУ. Единственный дубль фикстуры лежал на
# индексе `00000001`, которого выборка НЕ БЕРЁТ. Ни один ВЫБРАННЫЙ индекс двух форм не имел,
# значит обёртку, роняющую одну из них, отвергнуть было нечем — обязанность вакуумна. Дубль
# перенесён на `00000003` (средний член выборки) в строителе фикстуры; страж `S` это
# утверждает исполнением, а сценарий `A10` предъявляет отвержение.
#
# ПОЧЕМУ ЭТО НЕ ПЕДАНТИЗМ: сырая и сжатая формы одного индекса — РАЗНЫЕ носители одних байт.
# Обёртка, привёзшая только сжатую, не доказала читаемость сырой; на проде их 21 против 478,
# и именно сырые — самые свежие, то есть ровно те, где живёт регресс последнего деплоя.
# ФОРМЫ СЧИТАЮТСЯ ПО ДОСТАВЛЕННЫМ ИНДЕКСАМ, А НЕ ПО ОЖИДАЕМЫМ — И ЭТО НЕ ДЕТАЛЬ.
# Первая редакция этого стража перебирала `EXPECTED_MEMBERS`, то есть ПРЕДПОЛАГАЛА тождество
# состава и потому ловила ВСЁ, что ловит страж тождества: сценарий `A8` (не те члены) не
# привозит форм ожидаемого индекса `00000003` и краснел ЗДЕСЬ. Мутация это и показала —
# снятие тождества не роняло ничего, страж тождества стал ИНЕРТЕН. Тот же класс сработал на
# предмете ТРЕТИЙ раз подряд: закрытие находки обесценивает соседнего стража, и видно это
# только прогоном. Перебор по ДОСТАВЛЕННЫМ разводит обязанности: тождество отвечает за то,
# ЧТО привезено, формы — за ПОЛНОТУ КАЖДОГО привезённого.
delivery_forms_complete() { # $1=песочница → 0, если для КАЖДОГО ДОСТАВЛЕННОГО индекса
                            # привезены все формы, что есть в холодной копии
  # Что есть «в копии» — берётся из СНИМКА, снятого ДО запуска обёртки (`snapshot_source`), а не
  # из живого `cold`: источник к этому моменту может быть уже уничтожен `retire_source`, а
  # жульническая обёртка могла сама удалить из `cold` форму, которую не привезла (`M-99` §4).
  local i f base
  [ -n "${SRC_FORMS[$1]+x}" ] || return 1
  for i in $(delivered_members "$1"); do
    for f in "jrnl" "jrnl.zst"; do
      base="segment-${i}.${f}"
      case " ${SRC_FORMS[$1]} " in
        *" ${base} "*) [ -f "$1/restore/${base}" ] || return 1 ;;
      esac
    done
  done
  return 0
}

# ═══ `M-99`: ЗАКРЫТИЕ `C-219` B-1 — ИСТОЧНИК УНИЧТОЖАЕТСЯ, ОКНО ЧТЕНИЯ НАБЛЮДАЕТСЯ ═══
#
# ЧТО ПРОПУСКАЛА РЕДАКЦИЯ `85ae7de`. `inv_delivery` прятала источник ПЕРЕИМЕНОВАНИЕМ
# (`cold` → `cold-hidden-$$`), читала восстановленное и возвращала имя. Критик (`C-219` B-1)
# оставил после обёртки фонового наблюдателя: увидев исчезновение `cold`, тот создавал `cold`
# заново — ссылкой на спрятанный источник. Ссылки в `restore` снова разрешались, чтение
# проходило, и доставка, не содержащая ни одного своего байта, признавалась честной. Утверждение
# «источник недоступен» проверялось ОДИН РАЗ — в момент `mv`, а не на всё время чтения.
#
# ЧТО ЗДЕСЬ ВМЕСТО ЭТОГО — две меры, и роли у них разные.
#  1. `retire_source` — источник УНИЧТОЖАЕТСЯ (`rm -rf`), а не прячется: спрятанного источника,
#     к которому можно привязаться, больше не существует. Фикстура ОДНОРАЗОВА (нонс задачи 6b),
#     всё, что пробе нужно знать о копии после этого, снято ДО запуска обёртки в
#     `snapshot_source`. Это мера ПО ПОСТРОЕНИЮ, а не страж; эксклюзивного члена у неё нет и он
#     здесь не изображается (мутация «переименование вместо удаления» оставляет `A11` пойманным —
#     его ловит мера 2).
#  2. `source_stayed_absent` — СТРАЖ: всё окно независимого чтения каталог песочницы наблюдается
#     inotify (`IN_CREATE|IN_MOVED_TO`); появление имени `cold` в окне — отказ. Так проверяется
#     требование `C-219` B-1 «источник недоступен ВСЁ время чтения», а не в один момент. Член —
#     сценарий `A11` (наблюдатель обёртки пере-создаёт `cold` ссылкой на свой тайник).
#
# ЧЕГО ЭТО НЕ ЗАКРЫВАЕТ — названо (`A-032` §2.2/§4). Обёртка, положившая в `restore` ссылки
# ПРЯМО на свой тайник (не через имя `cold`), байты по сути доставила — в другое место; это
# форма псевдонима, и требовать её покрытия решением арбитра запрещено.
declare -A SRC_FORMS SRC_SIDECARS RETIRED

snapshot_source() { # $1=песочница — что лежит в копии ДО запуска обёртки (формы, sidecar'ы)
  [ -d "$1/cold" ] || return 0
  SRC_FORMS[$1]="$(ls "$1/cold" 2>/dev/null | grep -E '^segment-[0-9]{8}\.jrnl(\.zst)?$' | sort | tr '\n' ' ')"
  local j acc=""
  for j in "$1/cold"/*.json; do
    [ -f "$j" ] || continue
    acc="${acc} $(basename "$j"):$(sha256sum < "$j" | cut -c1-64)"
  done
  SRC_SIDECARS[$1]="${acc# }"
}

retire_source() { # $1=песочница → источник уничтожен (идемпотентно)
  case "$1" in /tmp/red-drill-*) ;; *) return 1 ;; esac
  [ -n "${RETIRED[$1]:-}" ] && return 0
  rm -rf -- "$1/cold" || return 1
  RETIRED[$1]=1
}

source_absent() { [ ! -e "$1/cold" ] && [ ! -L "$1/cold" ]; }

# Наблюдатель окна — тот же приём, что в оракулах `M-95` (`inotify` через `ctypes`). Setup-страж
# на КАЖДЫЙ запуск: канарейка, созданная пробой, обязана попасть в журнал наблюдателя — иначе
# страж вакуумен (`testing.md` «Целостность гейта» св. 3).
INOTIFY_PY='
import ctypes, os, struct, sys, select
libc = ctypes.CDLL("libc.so.6", use_errno=True)
d, out, ready = sys.argv[1], sys.argv[2], sys.argv[3]
fd = libc.inotify_init1(0)
if fd < 0: sys.exit(3)
if libc.inotify_add_watch(fd, d.encode(), 0x100 | 0x80) < 0: sys.exit(3)
f = open(out, "w", buffering=1); open(ready, "w").close()
while True:
    r, _, _ = select.select([fd], [], [], 0.02)
    if not r:
        if os.path.exists(ready + ".stop"): break
        continue
    buf = os.read(fd, 65536); i = 0
    while i < len(buf):
        wd, mask, cookie, ln = struct.unpack_from("iIII", buf, i)
        f.write(buf[i+16:i+16+ln].rstrip(b"\0").decode() + "\n"); i += 16 + ln
'

# $1=песочница; УНИЧТОЖАЕТ источник и читает восстановленное, наблюдая ВСЁ окно
# [уничтожение источника, конец чтения]: наблюдатель поднимается ДО `retire_source`, поэтому
# возврат имени `cold` в любой момент окна попадает в журнал. Печатает «отпечаток_после».
# Код: 0 — имя `cold` в окне не появлялось и в конце его нет; 1 — появлялось (или есть);
# 2 — наблюдатель не поднялся/вакуумен (SETUP).
retire_and_read_watched() {
  local w log ready pid t0 d_after canary
  w="$(mktemp -d /tmp/red-drill-watch-XXXXXX)" || return 2
  printf '%s\n' "${w}" >> "${REG}"
  log="${w}/events"; ready="${w}/ready"
  python3 -c "${INOTIFY_PY}" "$1" "${log}" "${ready}" >/dev/null 2>&1 &
  pid=$!
  t0=$SECONDS
  while [ ! -f "${ready}" ]; do
    [ $((SECONDS - t0)) -lt 10 ] || { kill "${pid}" 2>/dev/null; return 2; }
    sleep 0.05
  done
  canary="inotify-canary-$$-${RANDOM}"
  : > "$1/${canary}"; rm -f "$1/${canary}"
  t0=$SECONDS
  until grep -qx "${canary}" "${log}" 2>/dev/null; do
    [ $((SECONDS - t0)) -lt 5 ] || { touch "${ready}.stop"; wait "${pid}" 2>/dev/null; return 2; }
    sleep 0.05
  done
  retire_source "$1" || { touch "${ready}.stop"; wait "${pid}" 2>/dev/null; return 2; }
  d_after="$(truth_digest "$1/restore")"
  touch "${ready}.stop"; wait "${pid}" 2>/dev/null
  printf '%s' "${d_after}"
  if grep -qx 'cold' "${log}" 2>/dev/null || ! source_absent "$1"; then return 1; fi
  return 0
}

source_stayed_absent() { # $1=песочница → 0, если в окне чтения источник НЕ возвращался
  [ -n "${WATCH_RC[$1]+x}" ] && [ "${WATCH_RC[$1]}" = "0" ]
}
declare -A WATCH_RC D_AFTER

inv_delivery() { # $1=песочница $2=отпечаток ПРИ ЖИВОМ источнике → 0, если читается БЕЗ него
  local rc
  [ -d "$1/restore" ] || return 1
  if [ -z "${D_AFTER[$1]+x}" ]; then
    D_AFTER[$1]="$(retire_and_read_watched "$1")"; rc=$?
    RETIRED[$1]=1   # `retire_source` исполнен в подоболочке `$( )` — отметка ставится здесь
    [ "${rc}" -eq 2 ] && die "наблюдатель окна чтения (inotify) не поднялся или вакуумен в $1 — страж source_stayed_absent судил бы пустоту"
    WATCH_RC[$1]="${rc}"
  fi
  [ -n "${D_AFTER[$1]}" ] && [ -n "$2" ] && [ "${D_AFTER[$1]}" = "$2" ]
}

# ═══ `M-99`: ЗАКРЫТИЕ `C-219` B-2 — SIDECAR'Ы ВОССТАНАВЛИВАЮТСЯ ПОБАЙТНО ═══
#
# Контракт (`M-99` §4 п.2): каждый sidecar (`*.json` в корне холодной копии) восстанавливается
# ПОБАЙТНО — sha256 восстановленного равен sha256 копии. Прежде правило выборки говорило «берётся
# то, что в копии ЕСТЬ», а решающий предикат sidecar'ов не смотрел вовсе: прод-читатель на пустом
# манифесте читает и без него, и пропуск/подмена проходили набор (`C-219` B-2).
# Судится В СОСТОЯНИИ «ИСТОЧНИКА НЕТ» (`retire_source` уже исполнен): ссылка на sidecar копии
# тогда не разрешается, и форма подмены значения не имеет. Эталон — снимок ДО запуска обёртки.
delivery_sidecars_identical() { # $1=песочница
  local e name sha got
  [ -n "${SRC_SIDECARS[$1]+x}" ] || return 1
  retire_source "$1" || return 1
  for e in ${SRC_SIDECARS[$1]}; do
    name="${e%%:*}"; sha="${e##*:}"
    got="$(sha256sum < "$1/restore/${name}" 2>/dev/null | cut -c1-64)"
    [ -n "${got}" ] && [ "${got}" = "${sha}" ] || return 1
  done
  return 0
}

# ЕДИНСТВЕННЫЙ РЕШАЮЩИЙ ПРЕДИКАТ. `A-032` §2.2 п.1: `H` инлайнил надмножество `h_verdict`
# — та самая редекларация судимого правила, которую проба сама запрещает соседним
# комментарием. Теперь `H` и все самопроверки судят ОДНОЙ функцией: ослабь её — покраснеет
# и позитивный контроль, и атаки.
h_verdict() { # $1=песочница → 0, если состояние ДОКАЗЫВАЕТ и чтение, и доставку
  local ok ev d_live
  ok="$(state_field "$1" ok)"; ev="$(state_field "$1" events_read)"
  d_live="$(truth_digest "$1/restore")"
  [ "${ok}" = "1" ] && [ "${ev:-0}" -gt 0 ] \
    && digest_matches_state "$1" "${d_live}" \
    && delivery_matches_selection "$1" \
    && delivery_forms_complete "$1" \
    && inv_delivery "$1" "${d_live}" \
    && source_stayed_absent "$1" \
    && delivery_sidecars_identical "$1"
}

