# Предикат `H` в отдельной функции — чтобы D/R судили ТО ЖЕ САМОЕ, а не свою копию правила.
# Редекларация предиката была бы тем же классом, что `C-202` B-2 на `M-45`: ослабь один —
# второй останется зелёным.
# ── D — АТАКА `C-191`, ПОВТОРЁННАЯ ДОСЛОВНО ────────────────────────────────────────────
# Обёртка НЕ вызывает читателя и НЕ восстанавливает. Она делает ровно то, что делала
# жульническая обёртка критика: узнаёт каталоги из окружения и пишет правдоподобное
# состояние. В rev 4 этого хватало для `PASS (9/9)`.
make_fixture BOX_D healthy
# Отпечаток копии D снимается СЕЙЧАС: `h_verdict` ниже УНИЧТОЖАЕТ источник (`retire_source`,
# `M-99`), а сценарий `R` берёт именно его как «отпечаток прошлого прогона».
D_COLD_DIGEST="$(truth_digest "${BOX_D}/cold")"
FAKE_D="${BOX_D}/fake-drill.sh"
# ВОССТАНАВЛИВАЕТ ЧЕСТНО, но отпечаток ВЫДУМЫВАЕТ. Так проверяется именно то свойство,
# ради которого rev 5 существует: «назвать величину, не посчитав её». Обёртка, которая
# вдобавок ничего не восстановила, ловилась бы по пустому каталогу — то есть по другому
# признаку, и сценарий был бы зелен по слабой причине.
cat > "${FAKE_D}" <<'FAKE'
#!/usr/bin/env bash
rm -rf "${JOURNAL_DRILL_RESTORE}"; mkdir -p "${JOURNAL_DRILL_RESTORE}" "$(dirname "${JOURNAL_DRILL_STATE}")"
# ОТБОР по объявленному правилу: первый / floor(N/2) / последний ИНДЕКС. Жульничество этой
# обёртки лежит НЕ здесь — доставку она делает честную, чтобы сценарий судил РОВНО СВОЙ класс.
ALL="$(ls "${JOURNAL_DRILL_COLD}" 2>/dev/null | sed -n 's/^segment-\([0-9]\{8\}\)\.jrnl\(\.zst\)\?$/\1/p' | sort -u)"
N="$(printf '%s\n' "${ALL}" | grep -c .)"; MID=$(( (N + 1) / 2 ))
IDX="$(printf '%s\n' "${ALL}" | sed -n "1p;${MID}p;${N}p" | sort -u)"
CK=0
for i in ${IDX}; do
  for f in "${JOURNAL_DRILL_COLD}/segment-${i}.jrnl" "${JOURNAL_DRILL_COLD}/segment-${i}.jrnl.zst"; do
    [ -f "$f" ] && cp -- "$f" "${JOURNAL_DRILL_RESTORE}/" 2>/dev/null
  done
  CK=$((CK + 1))
done
for j in "${JOURNAL_DRILL_COLD}"/*.json; do [ -f "$j" ] && cp -- "$j" "${JOURNAL_DRILL_RESTORE}/" 2>/dev/null; done
printf '{"ok":1,"ts_wall_ms":0,"checked":%s,"events_read":41213,"digest":"%s","reason":""}\n' \
  "${CK}" "$(printf 'выдуманный-отпечаток-без-чтения' | sha256sum | cut -c1-64)" > "${JOURNAL_DRILL_STATE}"
exit 0
FAKE
chmod +x "${FAKE_D}"
run_drill "${BOX_D}" "${FAKE_D}" || true
D_TRUTH="$(truth_digest "${BOX_D}/restore")"
if h_verdict "${BOX_D}"; then
  fail "D обёртка, восстановившая копию, но ВЫДУМАВШАЯ отпечаток, признана честной. Это класс
атаки C-191, сломавшей rev 4. Набор не имеет различающей силы, и его зелёный ничего не значит"
elif [ -z "${D_TRUTH}" ]; then
