не из этого прогона. Это и есть тот класс, ради которого digest введён: продукт действия,
которого не было"
  else
    fail "F отказ есть, но не КОДОМ ПУСТОТЫ (rc=${rc_f:-∅}, ожидалось 5; ok=${ok_f:-∅})"
