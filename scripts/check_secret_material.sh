#!/usr/bin/env bash
# Механический барьер: КЛЮЧЕВОЙ МАТЕРИАЛ не живёт в репозитории.
#
# Требование founder'а 2026-09-07, дословно: «главное чтобы ключи не попадали в рипо».
# До этого барьера контур держался на внимательности: одиннадцать барьеров проекта не
# проверяли секреты НИ ОДНИМ (замер: `grep -l 'secret\|PRIVATE' scripts/check_*.sh` → пусто;
# `cargo audit` в CI смотрит уязвимости зависимостей, а не ключи).
#
# ── ИНВАРИАНТ ФОРМУЛИРУЕТСЯ ОТ РЕЗУЛЬТАТА, А НЕ ОТ СПОСОБА ───────────────────────────
# Судится СОСТОЯНИЕ ДЕРЕВА НА HEAD: «в отслеживаемых файлах нет ключевого материала».
# Не диапазон коммитов. Причина та же, по которой `check_protected_artifacts.sh` ушёл от
# погони за способом (там — D/R/evil merge/`-s ours`): секрет, внесённый месяц назад и с
# тех пор не тронутый, в диапазон push'а не попадает ВООБЩЕ, и диапазонный сканер его не
# увидит НИКОГДА. Полный скан дерева ловит его при каждом прогоне.
# Цена скана — один `git grep` по отслеживаемым файлам; она не зависит от длины истории.
#
# ── ЧЕСТНО НАЗВАННЫЙ ПРЕДЕЛ ──────────────────────────────────────────────────────────
# Барьер судит ТЕКУЩЕЕ ДЕРЕВО, а не ИСТОРИЮ. Секрет, внесённый и удалённый, остаётся в
# объектах git и здесь НЕ ловится — такой ключ обязан считаться скомпрометированным и
# отзываться, а не вычищаться из истории. Это ограничение принятое и названное, а не дыра,
# о которой умолчали: скан всей истории на каждом push'е стоил бы линейно её длине.
#
# ── ПРИЗНАК ОБЯЗАН БЫТЬ НЕДОСТУПЕН МИРУ БЕЗ СОБЫТИЯ (`Р-4`) ─────────────────────────
# Ловится ЗНАЧЕНИЕ ключа, а не его ИМЯ. Строки `TELEGRAM_BOT_TOKEN`, `authorized_keys`,
# `GITHUB_TOKEN` живут в документах и конфигурации законно — их сотни, и барьер на имя
# был бы шумом, который отключат первым же. Признаки ниже в мире без секрета не
# встречаются: заголовок PEM, тело публичного ключа base64, конкретные формы токенов
# известных сервисов.
#
# Проба: `scripts/tests/red_secret_material.sh` — анти-плацебо в ОБЕ стороны (краснеет
# против внесённого ключа каждого класса; НЕ краснеет против сегодняшнего корпуса, где
# имена секретов упоминаются свободно).
set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.." || { echo "FAIL  не удалось встать в корень репозитория"; exit 1; }

git rev-parse --git-dir >/dev/null 2>&1 || {
  echo "FAIL  не git-репозиторий — барьер не может перечислить отслеживаемые файлы"
  echo
  echo "Барьер fail-closed: «не могу перечислить» не значит «нечего проверять»."
  exit 1
}

FAILED=0
note() { printf 'NOTE  %s\n' "$*"; }
bad()  { printf 'FAIL  %s\n' "$*"; FAILED=$((FAILED + 1)); }

# Файлы, которым РАЗРЕШЕНО нести признаки: сам барьер и его проба. Список узкий и
# явный намеренно — у барьера про секреты не должно быть токена-исключения в теле
# коммита: именно так секреты и въезжают («один раз, по делу, с объяснением»).
# Расширение этого списка — видимая правка sacred-файла, а не строка в чужом коммите.
is_allowed() {
  case "$1" in
    scripts/check_secret_material.sh|scripts/tests/red_secret_material.sh) return 0 ;;
    *) return 1 ;;
  esac
}

# ── 1. ПУТИ: файлы, которые не имеют права быть отслеживаемыми ──────────────────────
# `.env.example`/`.env.sample` разрешены явно: это шаблоны БЕЗ значений, и их польза
# (показать состав переменных, не раскрывая их) превышает риск.
while IFS= read -r f; do
  [ -n "$f" ] || continue
  is_allowed "$f" && continue
  case "$f" in
    *.env.example|*.env.sample|.env.example|.env.sample) continue ;;
  esac
  bad "отслеживается файл-носитель секрета: $f"
done < <(git ls-files -- \
  '*.pem' '*.key' '*.p12' '*.pfx' '*.jks' '*.keystore' \
  'id_rsa*' 'id_ed25519*' 'id_ecdsa*' 'id_dsa*' \
  '*authorized_keys' '.env' '*/.env' '.env.*' '*/.env.*' 2>/dev/null)

# ── 2. СОДЕРЖИМОЕ: значения ключей и токенов ────────────────────────────────────────
# Каждый признак сопровождён тем, ЧТО он ловит, — иначе следующий читатель не отличит
# осмысленный признак от суеверия.
# СИНТЕТИЧЕСКАЯ ФИКСТУРА — ОБЪЯВЛЕННАЯ КОНВЕНЦИЯ, а не догадка барьера.
# Оракулам нужны строки РЕАЛИСТИЧНОЙ ФОРМЫ: тест редакции токена, проверяющий, что в лог
# не уходит секрет, обязан нести токен, неотличимый по форме от настоящего, — иначе он
# проверяет не то (`testing.md`: фикстура повторяет форму прода). Барьер, краснеющий на
# таких строках, — шум, а шумный барьер отключают первым.
# Различитель: тело фикстуры НЕСЁТ САМООПИСАНИЕ. Настоящий выданный сервисом токен слов
# `DO-NOT-SEND`/`FIXTURE`/`EXAMPLE` не содержит — их вписывает автор теста осознанно.
# ПРЕДЕЛ НАЗВАН: настоящий токен, помеченный таким словом, барьер пропустит. Остаток
# принят сознательно и он мал — вписать в живой ключ «DO-NOT-LOG» надо ещё захотеть.
FIXTURE_MARK='DO-NOT-(SEND|LOG|USE)|SECRET-FIXTURE|FIXTURE-SECRET|EXAMPLE|SAMPLE|FAKE|DUMMY|REDACTED|PLACEHOLDER|xxxx'

# Проверка ПОСТРОЧНАЯ, а не пофайловая: файл может нести и живой секрет, и фикстуру рядом,
# и пофайловое решение («в файле есть маркер ⇒ файл чист») спрятало бы первый за второй.
scan() {
  local label="$1" pattern="$2" hit file line
  # `-I` — не лезть в бинарные файлы; `-n` — номер строки; `-E` — расширенные регулярки.
  while IFS= read -r hit; do
    [ -n "$hit" ] || continue
    file="${hit%%:*}"
    is_allowed "$file" && continue
    line="${hit#*:}"          # строка вида `NN:текст`
    # Самоописанная фикстура — не находка. Решение принимается по САМОЙ строке.
    printf '%s' "${line#*:}" | grep -qiE "$FIXTURE_MARK" && continue
    bad "$label — $file:${line%%:*}"
  # `-e` ОБЯЗАТЕЛЕН, а не косметика: шаблон PEM начинается с дефисов, и без `-e`
  # `git grep` разбирает `-----BEGIN …` как набор флагов, молча ничего не находит и
  # возвращает «чисто». Дыру предъявила проба (сценарий «приватный ключ PEM»): барьер
  # пропускал самый однозначный класс ключа, оставаясь зелёным. Ровно тот случай, ради
  # которого анти-плацебо и требуется — «зелёный» без пробы не значит «работает».
  done < <(git grep -nIE -e "$pattern" -- . 2>/dev/null || true)
}

# Приватный ключ любого формата — заголовок PEM однозначен и в прозе не встречается.
scan "приватный ключ (PEM)" '-----BEGIN [A-Z ]*PRIVATE KEY-----'
# Тело публичного ключа SSH. Сам по себе не секрет, но его место — на сервере, а не в
# репозитории; отпечатки вида `SHA256:…`, которыми корпус оперирует законно, сюда НЕ
# попадают: у них другая форма.
scan "публичный ключ SSH (тело)" '(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp[0-9]+) AAAA[0-9A-Za-z+/]{40,}'
# Токены сервисов — формы конкретные, префикс несёт сам сервис.
scan "токен GitHub"        '(ghp|gho|ghu|ghs|ghr)_[0-9A-Za-z]{36}'
scan "токен GitHub (fine)" 'github_pat_[0-9A-Za-z_]{60,}'
scan "токен Slack"         'xox[baprs]-[0-9A-Za-z-]{10,}'
scan "ключ доступа AWS"    'AKIA[0-9A-Z]{16}'
# Бот-токен Telegram: номер бота, двоеточие, тело фиксированной длины. Имя переменной
# `TELEGRAM_BOT_TOKEN` этой формы НЕ имеет и ложного срабатывания не даёт.
scan "бот-токен Telegram"  '[0-9]{8,10}:AA[0-9A-Za-z_-]{33}'
# Приватный ключ Ed25519 в форме OpenSSH — отдельный заголовок.
scan "ключ OpenSSH"        'BEGIN OPENSSH PRIVATE KEY'

echo "---"
if [ "$FAILED" -eq 0 ]; then
  echo "OK: ключевого материала в отслеживаемых файлах нет"
  echo "VERDICT: PASS"
  exit 0
else
  echo
  echo "Найденный ключ считается СКОМПРОМЕТИРОВАННЫМ с момента попадания в репозиторий."
  echo "Порядок: отозвать и перевыпустить ключ, затем убрать файл. Вычистка истории"
  echo "БЕЗ отзыва — ложное успокоение: объект остаётся у всех, кто клонировал."
  echo "VERDICT: FAIL ($FAILED)"
  exit 1
fi
