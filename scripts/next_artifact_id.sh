#!/usr/bin/env bash
# next_artifact_id.sh — аллокатор следующего свободного номера (M-61, TD-111), РЕШЕНИЕ Б
# (founder, 2026-08-12). Барьер и аллокатор разделяют ОДИН разбор строки долга (§5 запретный
# список — «ДВА разборщика нельзя»), см. `scripts/check_artifact_ids.sh#td_holder`.
#
# Спека: milestones/M-61-artifact-ids.md §3 (задача 1) + §3.1 (объединение ref'ов,
# асимметрия «широкая занятость / узкое введение», буква как часть идентификатора).

set -uo pipefail
die() { echo "FAIL  $*" >&2; exit 1; }

CLS="${1:-}"
case "${CLS}" in
  TD|R|C|A|M) : ;;
  *) die "неизвестный класс '${CLS}' — допустимы: TD R C A M" ;;
esac

# ── fail-closed по origin (§3.1, ось 3) ────────────────────────────────────────────
if git remote get-url origin >/dev/null 2>&1; then
  n_origin=$(git for-each-ref --format='%(refname)' refs/remotes/origin 2>/dev/null \
             | wc -l | tr -d '[:space:]')
  [ "${n_origin:-0}" -gt 0 ] \
    || die "origin сконфигурирован, но ни одного его ref'а нет — занятость перечислить невозможно"
fi

# ── refs (одинаково с барьером) ─────────────────────────────────────────────────────
refs_all() { git for-each-ref --format='%(refname)' refs/remotes/origin refs/heads 2>/dev/null; }

# ══ TD-PARSER-BLOCK ═══════════════════════════════════════════════════════════════════
# НАЧАЛО общего блока — поддерживать В СИНХРОН с scripts/check_artifact_ids.sh (там тот же
# блок, побайтово). Спека §5: «Держать ДВА разборщика строки долга (барьер отдельно,
# аллокатор отдельно) — ЗАПРЕЩЕНО». Тест гоняет мутантов `tdregex`/`tdtrim`/`tdcanonical`/
# `tdanyline` только на барьере — и обе копии обязаны давать ТОТ ЖЕ ОТВЕТ на ТЕХ ЖЕ входах.
# Регекспы — в переменных (`[*]` вместо `\*` — gawk СНИМАЕТ экранирование `\*` и читает
# `- **TD` как «дефис, ноль и более пробелов, квантор»; тихая порча ровно того класса,
# что стоила кругов 3 и 5).
TD_HOLD_RE='^- [*][*]TD-[0-9]+'                           # широкая ЗАНЯТОСТЬ — ЛЮБАЯ запись
TD_PAT='- \*\*TD-0*([0-9]+)\*\* `([^`]+)`.*'             # форма для канонических карточек
# То же ядро awk, что и `td_holder` в барьере: регексп `hold` ОБЯЗАТЕЛЬНО привязан к
# `^- **TD-` (проза-упоминания «см. TD-NNN» не считаются занятостью: 72 из 126 номеров в
# `origin/main` упомянуты >1 раза). Все номера мультиномерной строки (`- **TD-049 /
# TD-050 / TD-051 — CLOSED`) считаются занятыми; берётся ВЕДУЩЕЕ жирное поле, а не вся
# строка — `sub(/^- \*\*/, "", head); i = index(head, "**"); if (i > 0) head = substr(head, 1, i - 1)`
# отсекает хвост.
td_awk_nums() {
  awk -v hold="$TD_HOLD_RE" '
    $0 ~ hold {
      head = $0; sub(/^- \*\*/, "", head)
      i = index(head, "**"); if (i > 0) head = substr(head, 1, i - 1)
      while (match(head, /TD-[0-9]+/)) {
        num = substr(head, RSTART + 3, RLENGTH - 3); sub(/^0+/, "", num); if (num == "") num = "0"
        print num
        head = substr(head, RSTART + RLENGTH)
      }
    }'
}
# ══ КОНЕЦ TD-PARSER-BLOCK ════════════════════════════════════════════════════════════

max=0
for ref in $(refs_all); do
  case "${CLS}" in
    TD)
      n="$(git show "${ref}:TECH-DEBT.md" 2>/dev/null | td_awk_nums)" ;;
    M|R|C|A)
      # Та же карта каталогов, что в `id_of` из `check_artifact_ids.sh` (§4.6 P1, §3.1(б)):
      # носитель — `*.md` в каталоге-носителе СВОЕГО класса. Без привязки к `.md`
      # `research/reports/R-001-obi-trackA.json` (пара к `R-NNN.md`, `docs/fa/research-cli.md`
      # §7) разбирался бы как `R-001` (проверено прогоном `id_of` — спека §0 отклонение 2).
      # Буква в идентификаторе `M-38a` НЕ отделяется: аллокатор не выдаёт букву (§12), и
      # присутствие `M-38a` ЗАНИМАЕТ числовую часть `M-38` с точки зрения выдачи следующего
      # свободного `M-NN`.
      # ЯКОРЬ `^каталог/CLS-` в sed-регекспе ОБЯЗАТЕЛЕН: без него регексп
      # `.*[/-][0]*([0-9]+)…` ЖАДНО съедает всё до ПОСЛЕДНЕГО `-`, и `M-33-depth-band-3060.md`
      # даёт `num=3060`, а не `33` (замер: 4 таких файла в `origin/main`, максимум
      # ломается до M-3061). Делимитр `#` — потому что `|` уже занят alternation у класса R.
      case "${CLS}" in
        M) _sed_re='^milestones/M-[0]*([0-9]+)([a-z])?(-.*)?\.md$'  _sed_cap='\1' ;;
        R) _sed_re='^research/(reviews|reports)/R-[0]*([0-9]+)([a-z])?(-.*)?\.md$'  _sed_cap='\2' ;;
        C) _sed_re='^research/critiques/C-[0]*([0-9]+)([a-z])?(-.*)?\.md$'  _sed_cap='\1' ;;
        A) _sed_re='^research/arbitration/A-[0]*([0-9]+)([a-z])?(-.*)?\.md$'  _sed_cap='\1' ;;
      esac
      n=""
      while IFS= read -r -d '' f; do
        num="$(printf '%s' "$f" | sed -nE "s#${_sed_re}#${_sed_cap}#p")"
        [ -n "$num" ] && n="${n} ${num}"
      done < <(git ls-tree -r -z --name-only "${ref}" 2>/dev/null || true)
      n="${n# }"
      ;;
  esac
  for x in ${n}; do
    x=$((10#$x))                                          # 10# снимает ведущие нули и НЕ падает на 0NN
    [ "${x}" -gt "${max}" ] && max="${x}"
  done
done

# Setup-guard (§6.1): если объединение пусто по классу, эталон не вычислим, и сравнивать
# в шаге N гейта нечего — лучше умереть, чем выдать «1» против пустого эталона.
[ "${max}" -gt 0 ] || die "класс ${CLS}: в объединении ref'ов нет ни одного номера — setup-guard"

# Формат печати — паритет с уже существующими в репозитории: M — двузначный (M-60),
# остальные — трёхзначные (R-001 и выше; верификатор ожидает ровно такую форму, §6.1).
case "${CLS}" in
  M) printf 'M-%02d\n' $((max + 1)) ;;
  *) printf '%s-%03d\n' "${CLS}" $((max + 1)) ;;
esac
