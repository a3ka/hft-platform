# shellcheck shell=bash
# runbook_markers.sh — строки-маркеры, которые runbook велит искать в логе, обязаны
# печататься КОДОМ (TD-243, решение арбитра A-047 §2 п.1).
#
# Зачем. Маркер в runbook'е существует, чтобы оператор скопировал его в `grep` по логу.
# Несуществующий маркер даёт пустой результат, и оператор читает его как «этого не
# случилось». Так начался TD-239 (маркер успеха, которого никто не печатал) и так же
# ошибся его второй фикс (R-231 N-1: обрезанная строка провала).
#
# Что проверяется. Каждый маркер вида `=== … ===` из runbook'а режется до ПРЕФИКСА — до
# первого места подстановки (многоточие, `<`, `$`); маркер без подстановки берётся целиком,
# вместе с закрывающими `===`. Префикс обязан ДОСЛОВНО встречаться хотя бы в одном
# ОТСЛЕЖИВАЕМОМ git'ом файле кода.
#
# Что НЕ считается кодом (иначе runbook подтверждал бы сам себя):
#   *.md где угодно, docs/**, research/**, */tests/* (тест проверяет печать, а не печатает),
#   сам этот файл.
#
# ПРЕДЕЛ, названный честно: проверяется СУЩЕСТВОВАНИЕ строки в коде, а не то, что код
# печатает её в описанной runbook'ом ситуации и в описанном порядке. Утверждения о порядке
# вывода, о форме вызова, о том, какая команда что пишет, механизмом не покрыты — это
# остаточный риск, записанный карточкой TD-243.
#
# Использование: runbook_markers_check <runbook> <корень репозитория>
# Печатает строку на маркер (`ok`/`miss`), итог; код возврата 0 — все маркеры найдены.
# Ноль маркеров в runbook'е — ОТКАЗ: извлечение, молча нашедшее пустоту, проверяет ничто.

runbook_markers_check() {
  local readme="$1" root="$2"
  if [ ! -f "${readme}" ]; then
    echo "runbook-markers: нет файла ${readme}"
    return 1
  fi
  if ! git -C "${root}" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    echo "runbook-markers: ${root} — не рабочее дерево git; искать маркеры негде"
    return 1
  fi
  local -a markers=()
  mapfile -t markers < <(grep -oE '===[^=]*===' "${readme}" | sort -u)
  if [ "${#markers[@]}" -eq 0 ]; then
    echo "runbook-markers: в ${readme} не найдено ни одного маркера — извлечение пусто, проверять нечего"
    return 1
  fi
  local m p body miss=0 where
  for m in "${markers[@]}"; do
    p="${m%%…*}"
    p="${p%%<*}"
    p="${p%%\$*}"
    body="${p#===}"
    body="${body#"${body%%[![:space:]]*}"}"
    if [ "${#body}" -lt 3 ]; then
      echo "miss  ${m}  — префикс до подстановки пуст, опознать маркер в логе нечем"
      miss=$((miss + 1))
      continue
    fi
    where=$(git -C "${root}" grep -lF -e "${p}" -- . \
              ':(exclude)*.md' ':(exclude)docs/**' ':(exclude)research/**' \
              ':(exclude)*/tests/*' ':(exclude)scripts/lib/runbook_markers.sh' 2>/dev/null \
            | head -1 || true)
    if [ -n "${where}" ]; then
      echo "ok    ${m}  ← ${where}"
    else
      echo "miss  ${m}  — префикс «${p}» не печатается ни одним файлом кода"
      miss=$((miss + 1))
    fi
  done
  echo "runbook-markers: маркеров ${#markers[@]}, не найдено в коде ${miss}"
  [ "${miss}" -eq 0 ]
}
