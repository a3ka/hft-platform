#!/usr/bin/env bash
# mutation_gate.sh — ОБЩИЙ исполнитель мутационного контроля для `scripts/verify_*.sh`.
#
# Введён решением арбитра `research/arbitration/A-035-m86-mutation-witness-and-route.md`
# §2.3 M1. С этого решения форма
#
#     if (cd "${MUT}" && cargo test …); then echo FAIL; else echo PASS; fi
#
# в `verify_*.sh` ЗАПРЕЩЕНА — мутационный шаг собирается только через этот helper.
#
# ─────────────────────────────────────────────────────────────────────────────────────────
# ПОЧЕМУ ОДНОГО КОДА ВОЗВРАТА НЕ ХВАТАЕТ — замер, а не рассуждение (`A-035` Ф-3)
# ─────────────────────────────────────────────────────────────────────────────────────────
#
#   $ (крейт-проба) assert!(false)     → cargo test exit=101
#   $ (крейт-проба) let x: i32 = "s";  → cargo test exit=101
#
# `cargo` возвращает ОДИН И ТОТ ЖЕ код, когда тест упал по нужному ассерту и когда он
# вообще не собрался. Значит в ОБРАТНОЙ проверке («мутант обязан упасть») ненулевой код
# физически не способен служить доказательством: внимательному автору нечего читать.
#
# Класс дефекта, который это породило, — «PASS по неспецифичному свидетелю» — в корпусе
# воспроизвёлся ТРИЖДЫ в трёх гейтах разных дат (`A-035` Ф-4): `verify_M-68.sh:94`,
# `verify_M-71.sh:219-221`, `verify_M-86.sh` H/H2. Экземпляр `M-86` поймал `C-231` B3:
# шаг печатал «PASS: мутация уронила V1», когда `V1` НЕ КОМПИЛИРОВАЛСЯ.
#
# ─────────────────────────────────────────────────────────────────────────────────────────
# РАЗВЯЗКА (`A-035` §2.2, BINDING): код возврата решает ОТКАЗ, успех — ТРИ СВИДЕТЕЛЯ
# ─────────────────────────────────────────────────────────────────────────────────────────
#
#   W0 — БАЗОВАЯ ЛИНИЯ: тот же именованный тест на НЕМУТИРОВАННОМ дереве ЗЕЛЁН.
#        Нет W0 ⇒ судить мутацию не по чему («baseline RED — мутация не судима»).
#   W1 — МУТАНТ СОБРАЛСЯ: `cargo test --no-run` в мутанте exit=0 (и, если заданы,
#        тесты-«должны остаться зелёными» в мутанте действительно зелены).
#   W2 — ИМЕНОВАННЫЙ ТЕСТ УПАЛ СВОИМ ДИАГНОЗОМ: в выводе есть `test result: FAILED`
#        И строка, совпадающая с переданным регэкспом диагноза.
#
# Отсутствие любого из трёх — FAIL с НАЗВАНИЕМ отсутствующего, а не общее «не прошло».
#
# Сверка W2 ПО ТЕКСТУ не нарушает `gates.md` §3 («решение по коду возврата, а не по тексту»).
# Та норма написана против случая, где текст ЗАМЕНЯЛ код и МАСКИРОВАЛ отказ
# (`cmd && echo PASS || echo FAIL`). Здесь текст — ДОПОЛНИТЕЛЬНОЕ необходимое условие
# ПОВЕРХ кода: PASS печатается, только если сошлись все три свидетеля, то есть решение
# остаётся fail-closed. Это сказано здесь явно, чтобы ремонт не был отклонён под §3
# (`A-035` §2.2, последний абзац).
#
# ─────────────────────────────────────────────────────────────────────────────────────────
# ИНТЕРФЕЙС
# ─────────────────────────────────────────────────────────────────────────────────────────
#
#   mutant_must_fail <mut_dir> <pkg> <test_bin> <test_name> <diag_regex> [<green_test>…]
#
#   mut_dir     — каталог мутантной копии (мутация УЖЕ внесена вызывающим)
#   pkg         — крейт (`-p`)
#   test_bin    — имя интеграционного набора (`--test`)
#   test_name   — ИМЕНОВАННЫЙ тест, который обязан упасть
#   diag_regex  — ERE, которым опознаётся СВОЙ диагноз в выводе упавшего теста
#   green_test… — 0..N именованных тестов, которые в мутанте обязаны остаться ЗЕЛЁНЫМИ
#                 (двойная польза: они же доказывают W1 — зелёный тест без сборки невозможен)
#
#   Печатает сырые строки по каждому свидетелю. Возвращает 0, только если сошлись все три.
#
# ПРЕДЕЛ, НАЗВАННЫЙ ЧЕСТНО: helper проверяет, что мутант СОБРАЛСЯ и что упал НУЖНЫЙ тест
# с НУЖНЫМ диагнозом. Он НЕ проверяет, что внесённая мутация осмысленна — за это отвечает
# setup-страж вызывающего (он обязан убедиться, что точка мутации существовала и изменилась).

# Прогон одного набора в каталоге; stdout+stderr в файл, возвращает код cargo.
_mg_run() {
  local dir="$1" pkg="$2" bin="$3" filter="$4" out="$5"
  (cd "${dir}" && cargo test -p "${pkg}" --test "${bin}" ${filter:+"${filter}"} -- --exact 2>&1) >"${out}"
}

mutant_must_fail() {
  local mut_dir="$1" pkg="$2" test_bin="$3" test_name="$4" diag_re="$5"
  shift 5
  local green_tests=("$@")
  local repo_root rc out_w0 out_w1 out_w2 ok=0

  repo_root="$(pwd)"
  out_w0=$(mktemp); out_w1=$(mktemp); out_w2=$(mktemp)

  # ── W0: базовая линия на НЕМУТИРОВАННОМ дереве ────────────────────────────────────────
  _mg_run "${repo_root}" "${pkg}" "${test_bin}" "${test_name}" "${out_w0}"
  rc=$?
  if [ "${rc}" -ne 0 ]; then
    echo "FAIL: [W0] baseline RED — мутация НЕ СУДИМА: ${pkg}/${test_bin}::${test_name} на"
    echo "      немутированном дереве не зелён (exit=${rc}). Это законное состояние на"
    echo "      plan-time RED-head: реализации ещё нет, доказывать мутацией нечего."
    echo "      Сырой хвост:"
    tail -3 "${out_w0}" | sed 's/^/      | /'
    rm -f "${out_w0}" "${out_w1}" "${out_w2}"
    return 1
  fi
  echo "  [W0] baseline GREEN: $(grep -m1 '^test result' "${out_w0}")"

  # ── W1: мутант СОБРАЛСЯ ───────────────────────────────────────────────────────────────
  (cd "${mut_dir}" && cargo test -p "${pkg}" --test "${test_bin}" --no-run 2>&1) >"${out_w1}"
  rc=$?
  if [ "${rc}" -ne 0 ]; then
    echo "FAIL: [W1] мутант НЕ СОБРАЛСЯ (exit=${rc}) — ненулевой код мутанта НЕ является"
    echo "      доказательством мутации: ровно так гейт печатал ложный PASS (C-231 B3)."
    grep -m2 -E '^error' "${out_w1}" | sed 's/^/      | /'
    rm -f "${out_w0}" "${out_w1}" "${out_w2}"
    return 1
  fi
  echo "  [W1] мутант собрался: $(grep -m1 -E 'Finished|Executable' "${out_w1}" | sed 's/^[[:space:]]*//')"

  # ── W1bis: названные соседи обязаны остаться ЗЕЛЁНЫМИ ────────────────────────────────
  for g in "${green_tests[@]}"; do
    local out_g; out_g=$(mktemp)
    _mg_run "${mut_dir}" "${pkg}" "${test_bin}" "${g}" "${out_g}"
    rc=$?
    if [ "${rc}" -ne 0 ]; then
      echo "FAIL: [W1bis] ${g} обязан остаться ЗЕЛЁНЫМ в мутанте, но упал (exit=${rc}):"
      grep -m1 -E '^test result|panicked at' "${out_g}" | sed 's/^/      | /'
      ok=1
    else
      echo "  [W1bis] ${g} в мутанте GREEN: $(grep -m1 '^test result' "${out_g}")"
    fi
    rm -f "${out_g}"
  done

  # ── W2: именованный тест упал СВОИМ диагнозом ─────────────────────────────────────────
  _mg_run "${mut_dir}" "${pkg}" "${test_bin}" "${test_name}" "${out_w2}"
  rc=$?
  if [ "${rc}" -eq 0 ]; then
    echo "FAIL: [W2] ${test_name} в мутанте ЗЕЛЁН — оракул не пиннит предмет мутации"
    ok=1
  elif ! grep -q 'test result: FAILED' "${out_w2}"; then
    echo "FAIL: [W2] ${test_name} завершился ненулевым кодом, но без 'test result: FAILED' —"
    echo "      это посторонний сбой (сборка/окружение), а не падение оракула"
    tail -3 "${out_w2}" | sed 's/^/      | /'
    ok=1
  elif ! grep -qE "${diag_re}" "${out_w2}"; then
    echo "FAIL: [W2] ${test_name} упал, но НЕ СВОИМ диагнозом: ожидался /${diag_re}/."
    echo "      Падение по чужой причине доказательством мутации не является."
    grep -m2 -E 'panicked at|assertion' "${out_w2}" | sed 's/^/      | /'
    ok=1
  else
    echo "  [W2] упал своим диагнозом: $(grep -m1 -E "${diag_re}" "${out_w2}" | cut -c1-140)"
  fi

  rm -f "${out_w0}" "${out_w1}" "${out_w2}"
  return "${ok}"
}
