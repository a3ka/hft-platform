#!/usr/bin/env bash
# ОБЩИЙ РАЗБОР ШАПКИ `GATE-META` — один парсер на всех потребителей.
#
# Извлечён из `scripts/check_gate_meta.sh` (M-60b G3) при постройке второго потребителя,
# `scripts/check_verdict_gate.sh`. Основание — `A-010` §G: новых скриптов не заводим там, где
# есть готовый разбор. Копия парсера была бы ТРЕТЬИМ местом, где живёт формат шапки: разошлись
# бы они не сразу, а на первой же правке формата — и разошлись бы МОЛЧА, потому что каждый
# потребитель зелен против своей копии.
#
# ЭТО БИБЛИОТЕКА, А НЕ БАРЬЕР. Она не печатает, не решает и не завершает процесс: только
# извлекает поля и отвечает на вопрос «этот исход проходной?». Всякое решение — у потребителя.
#
# ПОДКЛЮЧЕНИЕ (обязательно fail-closed — библиотека молча отсутствовать не смеет):
#   LIB="$(dirname "${BASH_SOURCE[0]}")/lib/gate_meta.sh"
#   . "${LIB}" || { echo "FAIL  библиотека разбора ${LIB} недоступна"; exit 2; }
# Потребитель, который source'ит её через `|| true`, превращает пропажу парсера в «шапок нет»
# — ровно тот класс, против которого написаны оба барьера.

# ── Перечень исходов ────────────────────────────────────────────────────────────────────
# Источник — `.claude/rules/gates.md` §4 (шаблон шапки). Значение ВНЕ перечня не «похоже на
# проходное» и не «похоже на отказ»: оно НЕИЗВЕСТНО, и потребитель обязан краснеть, а не
# угадывать. В `origin/main` такие значения РЕАЛЬНО лежат (замер 2026-08-20):
# `BLOCKED-ARBITER` (`R-042`) и `REJECT (docs/workflow-audit) / APPROVED (docs/retro-audit)`
# (`R-034`) — обе шапки написаны человеком мимо перечня.
GATE_META_VERDICT_ENUM="REJECT NOTE APPROVE PASS CONCERNS KILL ESCALATE DECISION"

# Проходные исходы. Дополнение до перечня — ОТКАЗНЫЕ: `REJECT CONCERNS KILL ESCALATE`.
# Множество отказных НЕ выписывается отдельным литералом намеренно: два независимых списка
# разошлись бы при добавлении исхода, и новый исход молча оказался бы «и не проходной, и не
# отказной». `CONCERNS` держит merge по `gates.md` §5 («KILL/CONCERNS блокирует merge до
# устранения находок или явного founder-override») — то есть он отказной по действующей норме,
# а не по нашему выбору.
GATE_META_PASSING_VERDICTS="NOTE APPROVE PASS DECISION"

# ── Примитивы ───────────────────────────────────────────────────────────────────────────
gate_meta_in_list() { # $1=игла $2=список через пробел
  case " $2 " in *" $1 "*) return 0 ;; *) return 1 ;; esac
}

# Блок шапки из содержимого файла. Пусто, если шапки нет.
gate_meta_block() { # $1=содержимое файла
  printf '%s\n' "$1" | awk '
    /<!-- GATE-META/ { inb = 1; next }
    inb && /-->/     { exit }
    inb              { print }'
}

# Значение поля из блока шапки. Берётся ПЕРВОЕ вхождение: повтор поля — не «уточнение», а
# неоднозначность, и разбор не смеет молча предпочесть последнее.
gate_meta_field() { # $1=имя поля $2=блок шапки
  printf '%s\n' "$2" \
    | sed -n "s/^[[:space:]]*$1:[[:space:]]*//p" \
    | sed -n '1p' | sed 's/[[:space:]]*$//'
}

# Проходной ли исход. НЕИЗВЕСТНОЕ значение проходным НЕ считается — но потребитель обязан
# отличать «отказ» от «неизвестно» сам (через gate_meta_in_list с перечнем), иначе
# опечатка в шапке станет неотличима от честного REJECT.
gate_meta_is_passing() { # $1=значение verdict
  gate_meta_in_list "$1" "${GATE_META_PASSING_VERDICTS}"
}

# Форма идентификатора артефакта `КЛАСС-НОМЕР[буква]` (`gates.md` §12). Шире буквального
# `M-NN`: вердикты пишутся и по карточкам долга (`R-077` аудировал `TD-141`), и по PR
# (`R-094` — ключ `PR-31`). Сузить значило бы завести ложный красный там, где предмет назван
# честно.
gate_meta_is_artifact_id() { # $1=значение milestone
  case "$1" in
    [A-Za-z]*-[0-9]*) grep -qE '^[A-Za-z]+-[0-9]+[a-z]?$' <<<"$1" ;;
    *) return 1 ;;
  esac
}
