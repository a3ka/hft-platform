#!/usr/bin/env bash
# Механический барьер: артефакт гейта, который СУЩЕСТВОВАЛ, обязан существовать на HEAD.
#
# Защищено:
#   research/critiques/*.md   — вердикты critic/risk-critic (аудит-трейл гейтов)
#   research/reviews/*.md     — вердикты reviewer'а (условие merge, gates.md §4)
#   research/arbitration/*.md — решения арбитра (обязательны к исполнению, gates.md §0)
#   milestones/*.md           — спеки, по которым исполняют dev-агенты
#   docs/rfc/**               — contract-RFC (КАНОН); docs/contract-rfc/** — исторический путь
#
# ── Почему критерий именно такой (эволюция после трёх итераций критика) ──────────────
# Прежние версии гонялись за СПОСОБОМ исчезновения (D в коммите, R в коммите, D в мерже…) —
# и каждый раз находился новый способ: `git mv` внутри merge-коммита (статус R, не D);
# `merge -s ours`, выбрасывающий файл, который жил только в side-ветке (относительно первого
# родителя удаления нет вовсе). Латать частные случаи бесполезно.
#
# Инвариант формулируется от РЕЗУЛЬТАТА, а не от способа:
#   если защищённый путь существовал (в базе ИЛИ был добавлен в этой ветке),
#   он ОБЯЗАН существовать на HEAD — либо под тем же именем, либо переехав в другой
#   защищённый путь, либо его удалил коммит с явным `ALLOW-ARTIFACT-DELETE:` в СВОЁМ теле.
# Любой способ исчезновения (delete, rename-out, evil merge, -s ours, add→delete) ловится
# автоматически, потому что все они дают один и тот же результат: файла нет на HEAD.
#
# ── БАЗА СРАВНЕНИЯ = СОСТОЯНИЕ ДО СОБЫТИЯ (блокер B1, reviewer, C-006) ────────────────
# Прежняя проводка (`check_protected_artifacts.sh origin/main`) делала гейт ЛОЖНЫМ: на
# `push`-событии `actions/checkout` ставит `origin/main` на ТОЛЬКО ЧТО ЗАПУШЕННЫЙ коммит,
# поэтому `merge-base(origin/main, HEAD) == HEAD`, диапазон пуст и скрипт печатал «OK»
# ВСЕГДА. PR в этом репо не используются (все прогоны — event=push на main), так что барьер
# не срабатывал ни разу: коммит, сносящий вердикт критика, проходил CI зелёным. Ложный гейт
# опаснее отсутствующего — он создаёт ощущение защиты.
#
# Правильная база берётся из САМОГО СОБЫТИЯ:
#   push         → `github.event.before` (состояние ветки ДО пуша);
#   pull_request → `github.event.pull_request.base.sha`.
# Всё, что мешает установить базу достоверно (пустое событие, zero-SHA при создании ветки
# или force-push, база отсутствует в истории, база не предок HEAD ⇒ история переписана),
# → **FAIL, а не пропуск**: «базы нет» не значит «проверять нечего», это значит «не могу
# гарантировать целостность». Fail-closed — та же дисциплина, что у риск-гейта.
#
# Проба: `scripts/tests/red_protected_artifacts.sh` (число сценариев — счётчик самой пробы,
# здесь намеренно не дублируется цифрой: она протухала. Зовёт барьер ТОЙ ЖЕ
# проводкой, какой его зовёт CI; каждая редакция барьера падала против пробы следующего витка).
set -uo pipefail

die() { echo "FAIL  $*"; echo; echo "Барьер fail-closed: база сравнения не установлена достоверно."; exit 1; }

raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}" ;;
    pull_request) raw="${PR_BASE_SHA:-}" ;;
    "")           die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *)            die "неизвестное событие '${EVENT_NAME}' — база сравнения не определена" ;;
  esac
fi

[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?})"
case "${raw}" in
  *[!0]*) : ;;  # есть хоть один ненулевой символ — не zero-SHA
  *)      die "база = zero-SHA (создание ветки или force-push) — целостность артефактов не доказуема" ;;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || die "база '${raw}' отсутствует в истории (переписана force-push'ем / поверхностный клон)"
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || die "база '${raw}' НЕ предок HEAD — история переписана (force-push); что исчезло, недоказуемо"

base=$(git rev-parse "${raw}^{commit}")

is_protected() {
  case "$1" in
    research/critiques/*.md|research/reviews/*.md|research/arbitration/*.md) return 0 ;;
    milestones/*.md|docs/rfc/*|docs/contract-rfc/*) return 0 ;;
    *) return 1 ;;
  esac
}

# 1) Защищённые пути, которые СУЩЕСТВОВАЛИ где-либо в диапазоне.
#
# ⚠ Первая редакция собирала это множество через `git log --diff-filter=AR --name-only`, и это
# была ДЫРА (блокер rev7, critic): **`git log` по умолчанию НЕ показывает диффы merge-коммитов**.
# Артефакт, пришедший в ветку через мерж (родился в side-ветке или прямо в теле мержа), в
# множество не попадал — и его последующее удаление барьер не замечал (exit=0).
# Это тот же самый способ-центричный подход, от которого мы уже дважды отказывались: мы снова
# спрашивали «КАК файл появился» вместо «БЫЛ ли он».
#
# Инвариант РЕЗУЛЬТАТА, доведённый до конца: путь СУЩЕСТВОВАЛ, если он есть в дереве ЛЮБОГО
# коммита диапазона (включая merge-коммиты и коммиты side-веток) либо в базе. Как он туда попал
# — неважно и спрашивать не нужно. `ls-tree` смотрит на СОСТОЯНИЕ, а не на дифф, поэтому
# слеп к способу по построению — ни один новый трюк с мержем сюда не пролезет.
PROTECTED_DIRS="research/critiques research/reviews research/arbitration milestones docs/rfc docs/contract-rfc"

# Перечень защищённых путей В ДЕРЕВЕ одной ревизии. Один помощник на все места, где нужен
# ответ «что там БЫЛО» — чтобы вопрос «состояние или дифф» нельзя было решить по-разному
# в двух соседних проверках (`R-118`-класс: согласованное изменение в двух местах).
tree_listing() { git ls-tree -r --name-only "$1" -- ${PROTECTED_DIRS} 2>/dev/null | grep -vE '^$' || true; }

existed=$(
  { tree_listing "${base}"
    for c in $(git rev-list "${base}..HEAD"); do tree_listing "${c}"; done
  } | sort -u || true
)

# ── РОЖДЁН ЛИ ПУТЬ В ДИАПАЗОНЕ — тем же вопросом о СОСТОЯНИИ, что и `existed` ─────────
#
# Это множество нужно ровно одному потребителю — fallback'у ниже, — и вычисляется здесь,
# ОДНИМ проходом по диапазону, а не запросом на каждый пропавший путь.
#
# ⚠ `TD-163` круг 2 отвечал на этот вопрос ДИФФОМ:
#   `git log --full-history --diff-filter=A ${base}..HEAD -- <путь>`
# и это была ТА ЖЕ асимметрия в третий раз. `git log` по умолчанию не показывает диффы
# merge-коммитов, а `--full-history` их НЕ включает (включает `--diff-merges`, которого там
# не было). Путь, воссозданный ПРЯМО В ТЕЛЕ merge'а, в такой запрос не попадал — `born_here`
# оставался пуст, fallback включался, и древний `ALLOW-ARTIFACT-DELETE` благословлял
# сегодняшнюю потерю. Замер (фикстура «путь рождён merge'ем, выброшен следующим merge'ем»):
#   барьер `origin/main` → exit=1 (ловил) · барьер круга 2 → NOTE + exit=0 (ЛОЖНОЕ ЗЕЛЁНОЕ)
# То есть круг 2 закрыл КЛЕТКУ (`C-136` строил рождение коммитом side-ветки), а не КЛАСС.
#
# Ответ по состоянию, слепой к способу по построению: путь РОДИЛСЯ в коммите `c`, если он
# есть в дереве `c` и его НЕТ в дереве НИ ОДНОГО родителя `c`. Merge-коммит здесь ничем не
# особен: у него просто два родителя, и «принёс путь, которого не было ни у кого из них» —
# это и есть рождение. Ни один трюк с мержем сюда не пролезет, потому что дифф не
# спрашивается вовсе. Комментарий круга 2 «это единственная проверка, смотрящая на ДИФФ —
# осознанное отступление» СНЯТ вместе с самой проверкой: отступления больше нет.
born_in_range=$(
  for c in $(git rev-list "${base}..HEAD"); do
    parents=$(git rev-parse "${c}^@" 2>/dev/null || true)
    if [ -z "${parents}" ]; then
      tree_listing "${c}"        # корневой коммит: всё, что в нём есть, здесь и родилось
      continue
    fi
    comm -23 <(tree_listing "${c}" | sort -u) \
             <(for p in ${parents}; do tree_listing "${p}"; done | sort -u)
  done | sort -u || true
)

# ── ВТОРОЕ УСЛОВИЕ: БЫЛ ЛИ ПУТЬ В МАГИСТРАЛИ ЭТОГО PUSH'А ────────────────────────────
#
# Рождения НЕ ДОСТАТОЧНО, и это ЗАМЕР, а не осторожность. Два сценария того же класса
# `C-136` Б-1 проходят проверку «рождён ли здесь» и всё равно дают ложное зелёное — оба
# воспроизведены, оба являются РЕГРЕССИЕЙ против барьера `origin/main` (он их валит):
#
#   • ВОЗВРАТ В МАГИСТРАЛЬ: ветка форкнута ДО архивного переезда и НАСЛЕДУЕТ путь (значит
#     не рождает его); первый merge возвращает путь в `main`, второй — молча выбрасывает.
#   • ПУТЬ ЕСТЬ В САМОЙ БАЗЕ: он был удалён с токеном, затем воссоздан в `main` ДО базы —
#     и evil merge выбрасывает его снова. Древнее удаление объясняет не это исчезновение.
#
# Общее у них: путь БЫЛ в магистрали push'а, а значит его отсутствие на HEAD произвёл
# ЭТОТ push, и прошлое к нему отношения не имеет. Магистраль — база плюс first-parent-цепочка
# `base..HEAD`: ровно те деревья, через которые `main` прошёл. Проверка снова по СОСТОЯНИЮ.
mainline=$(
  { tree_listing "${base}"
    for c in $(git rev-list --first-parent "${base}..HEAD"); do tree_listing "${c}"; done
  } | sort -u || true
)

# Fallback позволен ТОЛЬКО когда путь в этом push'е не появлялся НИ рождением (ни у одного
# родителя его не было), НИ в магистрали.
#
# ⚠ КЛАСС ЗАКРЫТ НЕ ПОЛНОСТЬЮ, И ЭТО НАЗВАНО, А НЕ ПОДРАЗУМЕВАЕТСЯ (`C-137` Б-1, `A-017`).
# Прежняя редакция этого комментария утверждала «остаётся ровно один случай» и «различить
# можно только СОДЕРЖИМЫМ». Оба утверждения ЛОЖНЫ, опровергнуты исполнением, и снимаются
# здесь потому, что комментарий барьера — основание чужих будущих решений:
#
#   1. «Ровно один случай» — нет. Путь может въехать в push РЕБРОМ ПРЕДКА: вложенный merge
#      старой ветки, форкнутой до архивного переезда, несёт путь ⇒ у коммита есть родитель
#      с этим путём ⇒ «не рождён»; на first-parent-цепочку он не попадает ⇒ «не в магистрали».
#      При этом и сохранение пути во вложенном мерже, и выброс финальным — РУКОТВОРНЫ.
#      Фикстуры: `C-137` §2 (F1a, носитель — второй родитель) и `A-017` Р-2 (F1a-swap,
#      носитель — ПЕРВЫЙ родитель; octopus). Барьер `origin/main` их ловит, этот — нет.
#   2. «Различает только содержимое» — нет, и это важнее первого. СОСТОЯНИЕ различает все
#      случаи: авто-резолюция дропающего мержа (`git merge-tree --write-tree p1 p2`) даёт
#      auto-DELETES для легитимного наследования (`TD-163`), auto-KEEPS для рукотворного
#      дропа и CONFLICT для рукотворной резолюции. Контентная ось на F1a вообще СЛЕПА:
#      blob идентичен состоянию до древнего удаления.
#
# ПОЧЕМУ ЭТО ВЛИТО ТАК. `A-017` Р-4: имя-уровневая семья предикатов НЕ сходится — четыре
# круга, пять дыр, каждая исполнена; «появился ли путь ПО ИМЕНИ» управляется автором через
# топологию мержей, а искомое свойство — «изготовлено ли исчезновение руками» — живёт в
# РЕЗОЛЮЦИЯХ. Пятое сужение по имени (в т.ч. `^1` вместо `^@`) арбитражем ЗАПРЕЩЕНО.
# Класс закрывает круг 4 — авто-воспроизводимость дропа (`A-017` Р-3, кандидат B).
# `A-017` Р-5: круг 3 влит до него сознательно — он строго сильнее `origin/main` по ложным
# КРАСНЫМ (снимает `TD-163`, сорвавший деплой дважды) и строго сильнее кругов 1-2 по ложным
# зелёным; остаточная дыра требует НАМЕРЕННОГО рукотворного акта внутри мержа, естественного
# инцидента этого класса не было, а простой всей доставки — цена реальная и растущая.
# Остаток ведётся карточкой `TD` (заводит reviewer; `TECH-DEBT.md` — его зона).
fallback_allowed() { # 0 — исчезновение НЕ дело этого push'а
  printf '%s\n' "${born_in_range}" | grep -Fxq -- "$1" && return 1
  printf '%s\n' "${mainline}"      | grep -Fxq -- "$1" && return 1
  return 0
}

violations=0
# Артефакт на HEAD обязан быть НОРМАЛЬНЫМ НЕПУСТЫМ ФАЙЛОМ, а не «каким-нибудь объектом по пути».
#
# ⚠ Прежняя проверка `git cat-file -e HEAD:${path}` отвечала «объект существует» для ЛЮБОГО
# объекта: дерева (на месте `C-006.md` создан КАТАЛОГ `C-006.md/`), симлинка (`C-006.md → /dev/null`),
# gitlink'а. Артефакт при этом уничтожен, а барьер молчал (блокер rev8, critic).
# Инвариант результата дочитан до конца: «артефакт существует» = по пути лежит blob с режимом
# обычного файла (100644/100755) и НЕНУЛЕВЫМ содержимым. Усечение в 0 байт — то же удаление,
# только вежливое: вердикт из нуля байт не аудирует ничего.
head_file_ok() { # 0 — на HEAD лежит нормальный непустой файл
  local p="$1" mode oid
  read -r mode _type oid _rest < <(git ls-tree HEAD -- "${p}" 2>/dev/null) || return 1
  [ -n "${mode:-}" ] || return 1
  case "${mode}" in
    100644 | 100755) : ;;                    # обычный файл — единственная легитимная форма
    120000) echo "      (по пути СИМЛИНК, не файл)" >&2; return 1 ;;
    040000) echo "      (по пути КАТАЛОГ, не файл)" >&2; return 1 ;;
    160000) echo "      (по пути SUBMODULE, не файл)" >&2; return 1 ;;
    *)      echo "      (по пути объект режима ${mode}, не обычный файл)" >&2; return 1 ;;
  esac
  [ "$(git cat-file -s "${oid}" 2>/dev/null || echo 0)" -gt 0 ] || return 1   # пустой = удалённый
}

for path in ${existed}; do
  is_protected "${path}" || continue
  head_file_ok "${path}" && continue     # цел — вопросов нет

  # Файла нет на HEAD. Ищем коммит(ы), которые его убрали.
  #
  # ⚠ `--full-history` ОБЯЗАТЕЛЕН (блокер rev9, инцидент 2026-08-03 — main покраснел).
  # `git log -- <path>` по умолчанию применяет **history simplification**: на merge-коммите он
  # идёт только по ТОМУ родителю, который объясняет итоговое состояние, и коммиты side-ветки в
  # вывод не попадают. Легитимное переименование `C-056-ct-rfc-09.md → C-057-ct-rfc-09.md`,
  # сделанное коммитом ВНУТРИ feat-ветки (`91530de`) и влитое merge'ем, стало невидимым:
  # `removed_by` пуст ⇒ барьер решал «файл исчез, и никто его не удалял ⇒ evil merge» и валил
  # main на КОРРЕКТНОЙ миграции.
  #
  # Это тот же самый класс, от которого барьер уже трижды уходил в `existed` (там ответ —
  # `ls-tree` по состоянию, слепой к способу). Но вторая половина проверки — «кто убрал» — так и
  # осталась на `git log`, то есть на упрощённой истории. Асимметрия и дала дыру: множество
  # «что существовало» собиралось честно, а множество «чем это объясняется» — нет.
  # Проверка: без флага `git log --diff-filter=DR -M 73d0c04..9f53e1d -- <путь>` пуст,
  # с флагом — находит `91530de`.
  removed_by=$(git log --full-history --diff-filter=DR -M --format='%H' "${base}..HEAD" -- "${path}" || true)

  # `TD-163` — ТРЕТИЙ вариант той же асимметрии, что уже дала `TD-092`. `existed` собирается по
  # СОСТОЯНИЮ деревьев ВСЕХ коммитов диапазона, включая унаследованные веткой файлы; объясняющий
  # коммит ищется ТОЛЬКО ВНУТРИ диапазона. Ветка, форкнутая ДО архивного переезда, приносит в
  # `existed` пути, удалённые в `main` ЗАДОЛГО до базы, — и барьер объявлял их «исчезли, и ни один
  # коммит их не удалял», то есть evil merge'ем.
  #
  # Замер (воспроизведено дважды, `R-118` §10): merge PR #29 → `main` красен, Deploy SKIPPED;
  # симуляция merge'а PR #66 в `main` → 24 FAIL, exit=1. Оба открытых PR форкнуты до `bd357df`
  # и попали бы туда же. Красное снялось СЛУЧАЙНЫМ следующим коммитом — это обход, не фикс.
  #
  # ПОЧЕМУ FALLBACK, А НЕ РАСШИРЕНИЕ ПОИСКА. Если диапазон СОДЕРЖИТ удаление — судим ЕГО и
  # только его: старое объяснённое удаление не смеет оправдывать новое неоправданное (файл
  # удалён с токеном, воссоздан, удалён снова молча — второе удаление в диапазоне и остаётся
  # FAIL). Историю спрашиваем ТОЛЬКО когда диапазон удаления не содержит вовсе, то есть когда
  # исчезновение произошло НЕ в этом push'е. Тогда ответ «кто убрал» лежит до базы — и он там
  # уже был отсужен своим собственным push'ем.
  #
  # ФОРМУЛИРОВКА ПРО EVIL MERGE ИСПРАВЛЕНА (`C-136` Б-1, условие 3). Первая редакция писала
  # «evil merge этим НЕ прощается» — и это было ЛОЖНО в общем виде: прощался evil merge пути,
  # который РАНЬШЕ удаляли с токеном, а потом воссоздали. Тогда удаление в истории есть, оно
  # объяснено древним токеном, а нынешнее исчезновение — дело merge'а, к тому токену отношения
  # не имеющего. Адверсарий предъявил это исполнением; моя проба `P22` дыру не видела, потому
  # что удаляла путь явным `git rm` — а он попадает в диапазон и fallback не включает.
  #
  # СУЖЕНИЕ: fallback НЕ применяется к пути, ПОЯВИВШЕМУСЯ в диапазоне. Появился здесь —
  # значит и исчезновение здешнее, и объяснять его прошлым нельзя. Инвариант «спрашиваем
  # историю только когда исчезновение произошло НЕ в этом push'е» этим и держится.
  #
  # МЕТОД: условие fallback'а задано СОСТОЯНИЮ (`born_in_range` + `mainline`, собраны выше),
  # а не диффу. Круг 2 задавал его диффом и промахивался мимо merge-рождения; разбор, замеры
  # и остаточный случай — в комментариях к обоим множествам. Отступления от правила `existed`
  # здесь больше нет: обе половины проверки — «что существовало» и «чем это объясняется» —
  # смотрят на деревья.
  if [ -z "${removed_by}" ] && fallback_allowed "${path}"; then
    removed_by=$(git log --full-history --diff-filter=DR -M --format='%H' HEAD -- "${path}" \
                 | head -1 || true)
  fi

  ok=0
  reason=""
  for c in ${removed_by}; do
    # (а) переезд в ДРУГОЙ защищённый путь — легитимная миграция (docs/contract-rfc → docs/rfc)
    newp=$(git show -M --name-status --format='' "${c}" \
             | awk -v p="${path}" '$1 ~ /^R/ && $2 == p {print $3}' | sed -n '1p')
    # Достаточно, чтобы новый путь тоже был ЗАЩИЩЁН: он сам проверяется этим же циклом
    # (цепочка переименований A→B→C внутри защиты легитимна; требовать существования B на
    # HEAD нельзя — он мог переехать дальше).
    if [ -n "${newp}" ] && is_protected "${newp}"; then
      ok=1; reason="переехал в ${newp} (остался под защитой)"; break
    fi
    # (б) осознанное удаление — override в ТЕЛЕ ЭТОГО коммита
    if grep -q '^ALLOW-ARTIFACT-DELETE:' <<<"$(git log -1 --format='%B' "${c}" 2>/dev/null || true)"; then
      ok=1; reason="ALLOW-ARTIFACT-DELETE в $(git log -1 --format='%h' "${c}")"; break
    fi
  done

  if [ "${ok}" -eq 1 ]; then
    echo "NOTE  ${path}: ${reason}"
  else
    violations=$((violations + 1))
    # Отличаем ПОДМЕНУ ТИПА от исчезновения: по пути что-то есть, но это не файл (или он пуст).
    if git cat-file -e "HEAD:${path}" 2>/dev/null; then
      echo "FAIL  ${path}: по пути на HEAD НЕ обычный непустой файл — артефакт подменён"
      echo "      (каталог / симлинк / submodule / пустой файл на месте артефакта = то же удаление)"
    elif [ -z "${removed_by}" ]; then
      echo "FAIL  ${path}: артефакт ИСЧЕЗ с HEAD, и ни один коммит его не удалял"
      echo "      (значит его выбросил MERGE — evil merge / -s ours / rename внутри мержа)"
    else
      echo "FAIL  ${path}: артефакт удалён без ALLOW-ARTIFACT-DELETE"
      for c in ${removed_by}; do echo "      $(git log -1 --format='%h %s' "${c}")"; done
    fi
  fi
done

if [ "${violations}" -gt 0 ]; then
  echo
  echo "Артефакты гейтов — аудит-трейл, а не черновики. Почти всегда FAIL означает:"
  echo "  • ты не на своей ветке (общий чекаут переключили), ЛИБО"
  echo "  • 'git commit -a' / 'git add -A' (запрещено, .claude/rules/branch-hygiene.md)."
  echo "Осознанное удаление — строкой в теле ТОГО ЖЕ коммита:"
  echo "  ALLOW-ARTIFACT-DELETE: <причина>"
  exit 1
fi

echo "OK: защищённые артефакты целы на HEAD (${base:0:7}..HEAD; проверка по РЕЗУЛЬТАТУ, не по способу)"
