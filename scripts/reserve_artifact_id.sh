#!/usr/bin/env bash
# reserve_artifact_id.sh — АТОМАРНЫЙ резерв номера артефакта CAS-пушем УНИКАЛЬНОГО SHA.
#
# Решение founder'а 2026-08-15 («применяй CAS-резерв»); разбор, замеры и альтернативы —
# `docs/plans/process-decisions-2026-08-14.md` §Р-1, вердикт критика — `research/critiques/
# C-084-process-decisions.md` (advisory N-1..N-3 закрыты ниже поимённо).
#
# ── ЧТО ЭТО РЕШАЕТ ───────────────────────────────────────────────────────────────────
# `scripts/next_artifact_id.sh` выдаёт max+1 по `refs/remotes/origin ∪ refs/heads`. Между
# выдачей номера и push'ем НОСИТЕЛЯ проходят минуты; параллельная роль в этом окне получает
# ТОТ ЖЕ номер. Замер: пять срабатываний за двое суток (`R-065` ×2, `TD-130`/`TD-131`,
# `R-069`/`R-067`), одно — прямо внутри выноса вердикта. Барьер `check_artifact_ids.sh`
# ловит это ПОСТФАКТУМ: работа уже сделана, файл переименовывается.
#
# ── ПОЧЕМУ SHA ОБЯЗАН БЫТЬ УНИКАЛЬНЫМ (несущий замер §Р-1 E1/E2/E3, воспроизведён C-084) ──
#   E1  push ДРУГОГО SHA в занятое имя  → отвергнут, exit=1          ← на этом стоит механизм
#   E2  push ТОГО ЖЕ SHA в занятое имя  → «Everything up-to-date», exit=0  ← ЛОЖНЫЙ УСПЕХ
#   E3  то же с `--force-with-lease`    → exit=0: no-op обрезается КЛИЕНТОМ до проверки lease
#   P3  тот же результат на живом GitHub — дыра не свойство песочницы
# Типовой случай двух параллельных ролей — обе бутстрапятся от ОДНОЙ вершины `origin/main`,
# то есть E2 не экзотика, а норма. Поэтому резервирующий строит СВОЙ, никем не повторимый
# коммит: `git commit-tree <дерево с origin> -m "reserve <ID> <роль> <UTC> <хост> <pid>
# <nonce>"`. Случай «тот же SHA» становится недостижим по построению, и работает E1.
# Payload — один объект-коммит (~200 байт): дерево уже лежит на сервере.
#
# ── ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО ─────────────────────────────────────────────────────────
# 1. НЕТ предварительного `ls-remote` «а не занято ли имя» на пути ВЗЯТИЯ резерва. Он (а) не
#    атомарен — два процесса пройдут проверку одновременно; (б) МАСКИРУЕТ дыру E2: наивная
#    реализация с предпроверкой разошлась бы по номерам в последовательном прогоне, и проба
#    против неё стала бы ЗЕЛЁНОЙ — механизм лишился бы собственного оракула. Единственный
#    арбитр взятия — отклонение push'а сервером. (На пути УДАЛЕНИЯ предпроверка, наоборот,
#    обязательна — там нет CAS-семантики, которую она могла бы подменить; см. `--release`.)
# 2. НЕТ пост-проверки «ref на origin указывает на мой SHA». Она не ловит E2 (там ref и
#    правда указывает на наш SHA — он общий), а другого слома, который её ронял бы, нет:
#    `--force` ловится сценарием REISSUE (кража чужого ref'а). Код, который нечем уронить, —
#    украшение, и в этом файле его нет: у КАЖДОЙ проверки есть сценарий пробы, который
#    краснеет при её снятии (таблица «шов → мутант → сценарий» ниже).
#
# ── ПРЕДЕЛ, названный явно (`C-084` N-1) ─────────────────────────────────────────────
# **Резерв НЕОБЯЗАТЕЛЕН, и потому гонка НЕ закрыта как класс.** Механизм снимает её только
# для того, кто вызвал обёртку; две роли, взявшие номер напрямую у `next_artifact_id.sh`,
# столкнутся ровно как раньше, и поймает их постфактум-барьер `check_artifact_ids.sh`.
# Это ЭШЕЛОНИРОВАНИЕ (дешёвый резерв впереди, барьер сзади), а не устранение класса, и
# выдавать одно за другое запрещено. Сделать резерв обязательным нечем: аллокатор
# герметичен по построению (сеть в нём превратила бы гейт `verify_M-61.sh` в измеритель
# доступности origin — класс `TD-135`), а барьер судит СОСТАВ КОММИТА, а не то, каким
# способом автор узнал номер.
#
# ── NONCE: источник задан, вырожденность ОБНАРУЖИВАЕТСЯ (`C-084` N-2) ────────────────
# Источник — `${RESERVE_NONCE_SOURCE}`, по умолчанию `/proc/sys/kernel/random/uuid`, затем
# `/dev/urandom` (16 байт → hex). Источника нет → exit 2 FAIL-CLOSED: тихого отката на
# `$RANDOM` (15 бит, сеется из pid+времени — у двух одновременных ролей совпадает
# регулярно) НЕТ. Перед работой берутся ДВА независимых чтения: равны или короче 16
# значимых символов ⇒ источник ВЫРОЖДЕН ⇒ exit 2. Это обнаружение вырожденного ИСТОЧНИКА,
# а НЕ доказательство недостижимости коллизии; недостижимость одинакового СООБЩЕНИЯ у двух
# параллельных запусков держится на композиции `<UTC> <хост> <pid>` — она различает
# процессы даже при мёртвом источнике энтропии, и это её роль, а не украшение.
# ГРАНИЦА ЧИСЛА ПОПЫТОК — `${RESERVE_MAX_ATTEMPTS}`, по умолчанию 8, обязана быть целым
# ≥1 (мусор → exit 1). Исчерпание — exit 3 с явным сообщением; молчаливого зацикливания
# нет. Восемь достаточно с запасом: одна отвергнутая попытка перепрыгивает ВЕСЬ занятый
# блок (см. ниже), поэтому >2 попыток означает живую конкуренцию, а не длинный хвост.
#
# ── ОПЕРАЦИОННЫЙ ХВОСТ `refs/reserved/*` (`C-084` N-3) ───────────────────────────────
# Цена протухшего резерва названа и ограничена:
#   * номер ПРОПУСКАЕТСЯ навсегда — `gates.md` §12 «разрывы не занимаются», это не дефект;
#   * стоимость для следующего резервирующего НЕ растёт с длиной хвоста: после отклонения
#     кандидат сдвигается на `max(занятые номера класса) + 1` — один прыжок через весь блок,
#     а не шаг +1. Сценарий `TAIL` пробы меряет это ЧИСЛОМ ПОПЫТОК на хвосте в 200 резервов
#     (не временем: время мерило бы окружение, `testing.md` «целостность гейта», свойство 2);
#   * хвост НАБЛЮДАЕМ (`--list`) и подготовлен к разбору (`--sweep <дней>` печатает
#     кандидатов и команды, но НИЧЕГО не удаляет: удаление возвращает номер в оборот, а
#     «брошенность» доказывается молчанием во времени — `branch-hygiene.md` §8, — не
#     снимком. Решение об удалении — founder'а/диспетчера, руками `--release`).
# `refs/reserved/*` не приезжают дефолтным fetch'ем (`+refs/heads/*:refs/remotes/origin/*`)
# и в `refs_all()` аллокатора и барьера не попадают — оба остаются герметичны и не тронуты
# этим механизмом НИ ОДНОЙ строкой.
#
# ── ШВЫ ДЛЯ МУТАЦИИ (почему часть функций — однострочные) ────────────────────────────
# `build_sha`, `draw_nonce`, `remote_has_ref` и помеченные ниже строки написаны В ОДНУ
# СТРОКУ намеренно: проба `scripts/tests/red_reserve_id.sh --battery` подменяет ровно одну
# строку на мутанта и требует, чтобы каждый мутант уронил ЗАЯВЛЕННОЕ множество сценариев —
# ни больше, ни меньше. Шов → мутант → сценарий, который краснеет:
#   build_sha (уникальный SHA)      → sametip      → PARALLEL TWICE STALE LIST SWEEP
#   git push (без --force)          → forcepush    → те же + REISSUE BLOCK TAIL EXHAUST
#   прыжок через занятый блок       → nojump       → BLOCK TAIL
#   граница попыток                 → nolimit      → EXHAUST
#   draw_nonce (источник энтропии)  → weaknonce    → NONCESRC NONCEDEG
#   сверка двух чтений              → nodegen      → NONCEDEG
#   сверка формата с аллокатором    → nofmtcheck   → FMTDRIFT
#   код возврата аллокатора         → allocblind   → ALLOCFAIL
#   предпроверка в --release        → blindrelease → RELEASE
# Множества ИЗМЕРЕНЫ прогоном батареи, а не предположены; расхождение — красный вердикт.
#
# ── ИНТЕРФЕЙС ────────────────────────────────────────────────────────────────────────
#   reserve_artifact_id.sh <TD|R|C|A|M>   — взять номер; stdout = РОВНО идентификатор
#                                            (drop-in замена `next_artifact_id.sh`)
#   reserve_artifact_id.sh --release <ID> — снять резерв (делает приземливший НОСИТЕЛЯ)
#   reserve_artifact_id.sh --list [класс] — что зарезервировано: кем, когда, сколько дней
#   reserve_artifact_id.sh --sweep <дней> [класс] — кандидаты на ручной разбор (не удаляет)
# Диагностика — в stderr; stdout несёт ТОЛЬКО результат.
# Коды возврата: 0 — взято · 1 — употребление/окружение · 2 — источник nonce ·
#                3 — попытки исчерпаны (fail-closed).
# Переменные: RESERVE_REMOTE (origin) · RESERVE_MAX_ATTEMPTS (8) · RESERVE_ROLE ($USER) ·
#             RESERVE_NONCE_SOURCE (авто) · ALLOC (путь к next_artifact_id.sh).
#
# Проба: `scripts/tests/red_reserve_id.sh` (герметична, локальный bare-origin, без сети),
# джоб CI `reserve-ids` — в `needs` у `status-check`, иначе проба была бы декорацией.

set -uo pipefail

SELF_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ALLOC="${ALLOC:-${SELF_DIR}/next_artifact_id.sh}"
REMOTE="${RESERVE_REMOTE:-origin}"
MAXA="${RESERVE_MAX_ATTEMPTS:-8}"                                          # шов: nolimit
ROLE="${RESERVE_ROLE:-${USER:-unknown}}"

die()  { echo "FAIL  $*" >&2; exit 1; }
die2() { echo "FAIL  $*" >&2; exit 2; }
die3() { echo "FAIL  $*" >&2; exit 3; }
note() { echo "reserve: $*" >&2; }

usage() {
  cat >&2 <<'EOF'
usage: reserve_artifact_id.sh <TD|R|C|A|M>
       reserve_artifact_id.sh --release <ID>
       reserve_artifact_id.sh --list  [класс]
       reserve_artifact_id.sh --sweep <дней> [класс]
EOF
}

# Класс — ТОТ ЖЕ перечень, что у аллокатора (`next_artifact_id.sh`). Расхождение перечней
# ловится не здесь, а сценарием ALLOCFAIL: класс, по которому аллокатор отказал, обязан
# утащить за собой резерв.
valid_class() { case "$1" in TD|R|C|A|M) return 0 ;; *) return 1 ;; esac; }
valid_id()    { printf '%s' "$1" | grep -qE '^(TD|R|C|A|M)-[0-9]{1,6}[a-z]?$'; }

# ФОРМАТ ПЕЧАТИ — вынужденный дубль правила аллокатора (M — двузначный, прочие —
# трёхзначные). Дубль назван, а не спрятан, и СВЕРЯЕТСЯ в рантайме (ниже): `fmt_id`,
# применённый к собственной выдаче аллокатора, обязан воспроизвести её побайтово. Иначе
# расхождение форматов вылезло бы месяцами позже — именем файла, разъехавшимся с резервом.
fmt_id() { case "$1" in M) printf 'M-%02d' "$2" ;; *) printf '%s-%03d' "$1" "$2" ;; esac; }

# ─── nonce ──────────────────────────────────────────────────────────────────────────
nonce_source() {
  if [ -n "${RESERVE_NONCE_SOURCE:-}" ]; then printf '%s\n' "${RESERVE_NONCE_SOURCE}"; return 0; fi
  local s
  for s in /proc/sys/kernel/random/uuid /dev/urandom; do
    [ -r "$s" ] && { printf '%s\n' "$s"; return 0; }
  done
  return 1
}
# Однострочно — шов weaknonce. Пустая выдача (источника нет) роняет проверки длины ниже.
draw_nonce() { case "$1" in */urandom) od -An -tx1 -N16 "$1" 2>/dev/null | tr -cd '0-9a-f' ;; *) head -c 256 "$1" 2>/dev/null | tr -cd '0-9a-zA-Z-' ;; esac; }

# Однострочно — шов sametip: мутант возвращает вершину ветки вместо СВОЕГО коммита, то есть
# ровно наивную реализацию из §Р-1, на которой воспроизводится дыра E2.
build_sha() { GIT_AUTHOR_NAME=reserve GIT_AUTHOR_EMAIL=reserve@hft.local GIT_COMMITTER_NAME=reserve GIT_COMMITTER_EMAIL=reserve@hft.local git commit-tree "${TREE}" -m "$1" 2>/dev/null; }

# Однострочно — шов blindrelease.
remote_has_ref() { [ -n "$(git ls-remote "${REMOTE}" "refs/reserved/$1" 2>/dev/null)" ]; }

# ─── дерево для бесхозного коммита ───────────────────────────────────────────────────
# Берём дерево, УЖЕ существующее на remote: тогда push несёт один объект-коммит. Порядок —
# от самого вероятного к безусловному; пустое дерево (последний рубеж) тоже годится, оно
# лишь чуть увеличивает payload, если сервер его не знает.
resolve_tree() {
  local r t
  for r in "refs/remotes/${REMOTE}/HEAD" "refs/remotes/${REMOTE}/main" \
           "refs/remotes/${REMOTE}/master" HEAD; do
    t="$(git rev-parse --verify --quiet "${r}^{tree}" 2>/dev/null)"
    [ -n "${t}" ] && { printf '%s\n' "${t}"; return 0; }
  done
  git hash-object -w -t tree /dev/null 2>/dev/null
}

# Максимум занятых резервов класса. Буква (`C-058b`) аллокатором не выдаётся, но если резерв
# под ней возьмут руками — числовая часть обязана считаться занятой (та же асимметрия
# «широкая занятость / узкое введение», что в аллокаторе).
reserved_max() {
  git ls-remote "${REMOTE}" "refs/reserved/$1-*" 2>/dev/null \
    | sed -nE "s#^[0-9a-f]+[[:space:]]+refs/reserved/$1-0*([0-9]+)[a-z]?\$#\1#p" \
    | sort -n | tail -1
}

# ══ РЕЖИМЫ ══════════════════════════════════════════════════════════════════════════
MODE=reserve; ARG="${1:-}"; ARG2="${2:-}"
case "${ARG}" in
  "" | -h | --help) usage; exit 1 ;;
  --release) MODE=release; ARG="${2:-}" ;;
  --list)    MODE=list;    ARG="${2:-}" ;;
  --sweep)   MODE=sweep;   ARG="${2:-}"; ARG2="${3:-}" ;;
  -*)        die "неизвестный режим '${ARG}'" ;;
esac

git rev-parse --git-dir >/dev/null 2>&1 || die "не git-репозиторий"
git remote get-url "${REMOTE}" >/dev/null 2>&1 || die "remote '${REMOTE}' не сконфигурирован"

# ─── --release ──────────────────────────────────────────────────────────────────────
if [ "${MODE}" = release ]; then
  valid_id "${ARG}" || die "'${ARG}' — не идентификатор вида КЛАСС-НОМЕР[буква]"
  # ЗАМЕР 2026-08-15 (второй случай того же класса, что E2, найден этой же работой):
  #   $ git push origin :refs/reserved/C-085     # ref'а на origin НЕТ
  #   remote: warning: deleting a non-existent ref
  #    - [deleted]  refs/reserved/C-085          exit=0
  # Удаление НЕСУЩЕСТВУЮЩЕГО ref'а — «успех». Без предпроверки опечатка в ID даёт оператору
  # «резерв снят», пока настоящий резерв продолжает висеть. Здесь предпроверка законна и
  # ничего не маскирует: у удаления нет CAS-семантики (в отличие от пути взятия резерва).
  remote_has_ref "${ARG}" || die "резерва ${ARG} на '${REMOTE}' нет — ничего не снято"
  out="$(git push "${REMOTE}" ":refs/reserved/${ARG}" 2>&1)"; rc=$?
  [ "${rc}" -eq 0 ] || { printf '%s\n' "${out}" >&2; die "резерв ${ARG} не снят (push exit=${rc})"; }
  git update-ref -d "refs/reserved-cache/${ARG}" 2>/dev/null
  note "резерв ${ARG} снят"
  exit 0
fi

# ─── --list / --sweep ───────────────────────────────────────────────────────────────
# Обе команды читают ТЕЛА резервных коммитов (роль/дата/nonce живут в сообщении), поэтому
# сперва тянут их в локальное пространство `refs/reserved-cache/*`. `--prune` обязателен:
# без него снятые соседом резервы жили бы в кэше вечно и хвост показывался бы длиннее, чем
# он есть — то есть инструмент наблюдения врал бы ровно в ту сторону, ради которой заведён.
if [ "${MODE}" = list ] || [ "${MODE}" = sweep ]; then
  if [ "${MODE}" = sweep ]; then
    printf '%s' "${ARG}" | grep -qE '^[0-9]+$' || die "--sweep требует возраст в днях (целое)"
    DAYS="${ARG}"; CLS_F="${ARG2}"
  else
    DAYS=0; CLS_F="${ARG}"
  fi
  [ -n "${CLS_F}" ] && { valid_class "${CLS_F}" || die "неизвестный класс '${CLS_F}'"; }
  git fetch --prune "${REMOTE}" "+refs/reserved/*:refs/reserved-cache/*" >/dev/null 2>&1 \
    || die "не удалось прочитать refs/reserved/* с '${REMOTE}'"
  now="$(date -u +%s)"; n=0
  while read -r id ts subj; do
    [ -z "${id}" ] && continue
    [ -n "${CLS_F}" ] && { printf '%s' "${id}" | grep -qE "^${CLS_F}-" || continue; }
    age=$(( (now - ts) / 86400 ))
    [ "${age}" -ge "${DAYS}" ] || continue
    n=$((n + 1))
    printf '%-8s %3d дн  %s\n' "${id}" "${age}" "${subj}"
    [ "${MODE}" = sweep ] && printf '         снять: bash scripts/reserve_artifact_id.sh --release %s\n' "${id}"
  done < <(git for-each-ref --sort=refname \
             --format='%(refname:lstrip=2) %(committerdate:unix) %(subject)' refs/reserved-cache)
  if [ "${MODE}" = sweep ]; then
    note "кандидатов старше ${DAYS} дн: ${n}. НИЧЕГО не удалено — удаление возвращает номер"
    note "в оборот, а брошенность доказывается молчанием во времени, не снимком (branch-hygiene §8)"
  else
    note "резервов: ${n}"
  fi
  exit 0
fi

# ─── резерв ─────────────────────────────────────────────────────────────────────────
CLS="${ARG}"
valid_class "${CLS}" || { usage; die "неизвестный класс '${CLS}' — допустимы: TD R C A M"; }
printf '%s' "${MAXA}" | grep -qE '^[0-9]+$' && [ "${MAXA}" -ge 1 ] \
  || die "RESERVE_MAX_ATTEMPTS='${MAXA}' — требуется целое ≥1"
[ -r "${ALLOC}" ] || die "аллокатор '${ALLOC}' не найден"

SRC="$(nonce_source)" || die2 "источника nonce нет (ни RESERVE_NONCE_SOURCE, ни /proc/sys/kernel/random/uuid, ни /dev/urandom); отката на \$RANDOM нет намеренно"
n1="$(draw_nonce "${SRC}")"; n2="$(draw_nonce "${SRC}")"
[ "${#n1}" -ge 16 ] || die2 "источник nonce '${SRC}' дал ${#n1} значимых символов (<16) — читается ли он?"
[ "${n1}" != "${n2}" ] || die2 "источник nonce '${SRC}' ВЫРОЖДЕН: два независимых чтения дали одно значение"

TREE="$(resolve_tree)"
[ -n "${TREE}" ] || die "не удалось получить дерево для бесхозного коммита"

base="$(bash "${ALLOC}" "${CLS}")" || die "аллокатор отказал по классу ${CLS} — резерв не берётся (номер от сломанного аллокатора хуже отсутствия номера)"
num="$(printf '%s' "${base}" | sed -nE "s/^${CLS}-0*([0-9]+)$/\1/p")"
[ -n "${num}" ] || die "аллокатор вернул '${base}' — это не форма ${CLS}-NNN"
[ "$(fmt_id "${CLS}" "${num}")" = "${base}" ] || die "формат обёртки разошёлся с аллокатором: '$(fmt_id "${CLS}" "${num}")' против '${base}'"

attempt=0
while [ "${attempt}" -lt "${MAXA}" ]; do
  attempt=$((attempt + 1))
  ID="$(fmt_id "${CLS}" "${num}")"
  nonce="$(draw_nonce "${SRC}")"
  [ "${#nonce}" -ge 16 ] || die2 "источник nonce '${SRC}' иссяк на попытке ${attempt}"
  msg="reserve ${ID} ${ROLE} $(date -u +%Y-%m-%dT%H:%M:%SZ) $(uname -n) $$ ${nonce}"
  sha="$(build_sha "${msg}")"
  [ -n "${sha}" ] || die "коммит резерва не построен (дерево ${TREE})"
  note "попытка ${attempt}/${MAXA} — ${ID} ← ${sha}"
  if git push "${REMOTE}" "${sha}:refs/reserved/${ID}" >/dev/null 2>&1; then
    printf '%s\n' "${ID}"
    note "резерв ${ID} взят; снять после приземления носителя:"
    note "  bash scripts/reserve_artifact_id.sh --release ${ID}"
    exit 0
  fi
  # Отклонение = имя занято (E1). Прыгаем через ВЕСЬ занятый блок сразу: стоимость
  # протухшего хвоста не должна расти с его длиной (`C-084` N-3).
  rmax="$(reserved_max "${CLS}")"; next=$(( num + 1 ))
  [ -n "${rmax}" ] && [ "${rmax}" -ge "${num}" ] && next=$(( rmax + 1 ))
  note "  ${ID} занят; следующий кандидат — $(fmt_id "${CLS}" "${next}")"
  num="${next}"
done

die3 "попытки исчерпаны (${MAXA}): номера класса ${CLS} разбираются быстрее, чем берётся резерв. Номер НЕ выдан — fail-closed. Подними RESERVE_MAX_ATTEMPTS или посмотри 'reserve --list'"
