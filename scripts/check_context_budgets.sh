#!/usr/bin/env bash
# Барьер бюджета обязательного чтения — M-60b G1.
# Спецификация: scripts/tests/red_context_budgets.sh (CB-1..CB-10b) + milestones/M-60b-gate-mechanisms.md §3.
#
# ЗАЧЕМ. Впрыскиваемое ядро (`CLAUDE.md` + `.claude/rules/*.md`) читает КАЖДАЯ роль при
# КАЖДОМ старте и после каждого сжатия контекста. Оно растёт молча: замер аудита — сжатие
# `9a9f533` (−433 строки) откачено на 28 % за десять дней, +120 строк за восемь дней после
# 06.08. Единственный механизм, работающий БЕЗ участия агента, — размерный кап в CI. Байты
# ловят РОСТ, не качество (предел назван в спеке §10).
#
# ── РЕЖИМЫ ────────────────────────────────────────────────────────────────────────────
#   default (прод-форма, как зовёт CI и verify):  bash scripts/check_context_budgets.sh
#       ROOT          = корень репозитория (вычисляется от пути скрипта, не от cwd);
#       таблица       = ВСТРОЕННАЯ ниже (`builtin_table`) — ноль строк прозы в правилах.
#   проба/эксперимент:  ROOT=<дерево> BUDGET_TABLE=<файл> bash scripts/check_context_budgets.sh
#       BUDGET_TABLE  — TSV `<путь-от-ROOT><TAB><лимит-в-байтах>`; `#`-строки — комментарии.
#   Переменные ROOT/BUDGET_TABLE существуют ДЛЯ ПРОБЫ. Прод-барьер обязан работать без них,
#   иначе встроенная таблица остаётся непроверенной (`C-064` F-064-4) — поэтому шаг D
#   `verify_M-60b.sh` гоняет ИМЕННО default-режим и требует, чтобы исчезновение КАЖДОГО
#   файла ядра ловилось поимённо.
#
# ── КОДЫ ВОЗВРАТА ─────────────────────────────────────────────────────────────────────
#   0 — все файлы таблицы существуют, читаемы и укладываются в лимит;
#   1 — есть нарушение бюджета/предмета (перечисляются ВСЕ, а не первое);
#   2 — предмет проверки не установлен достоверно (нет/пуста/нечитаема таблица, ROOT не
#       каталог, конфликтующие дубли строк). Fail-closed: «проверять нечего» ≠ «всё хорошо».
# Отсутствие файла — FAIL, а не пропуск: «файла нет» даёт нулевой размер, то есть
# бесконечный запас бюджета. Гейт, зеленеющий от исчезновения предмета, — не гейт (CB-5).

set -uo pipefail

SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SELF_DIR}/.." && pwd)"
ROOT="${ROOT:-${REPO_ROOT}}"
TABLE="${BUDGET_TABLE:-}"

FAILED=0
bad() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
die() {
  echo "FAIL  $*"
  echo
  echo "Барьер fail-closed: предмет проверки не установлен достоверно."
  exit 2
}

# ── ВСТРОЕННАЯ ТАБЛИЦА ────────────────────────────────────────────────────────────────
# Накрывает РОВНО впрыскиваемое ядро: `CLAUDE.md` + все `.claude/rules/*.md` ПОИМЁННО
# (не маской: маска не ловит ИСЧЕЗНОВЕНИЕ файла, а именно исчезновение зеленит бюджет).
#
# ЗАМЕР 2026-08-15 на ДЕРЕВЕ СЛИЯНИЯ (`origin/main` = d29b9ee; ветка M-60b ядро не трогает,
# проверено `git diff --name-only $(git merge-base origin/main HEAD) HEAD -- .claude/rules CLAUDE.md`
# — пусто, поэтому лимиты берутся от main, а не от отставшей на 85 коммитов ветки; норма
# «документ проверяется на дереве слияния» — `gates.md` §8):
#     branch-hygiene.md 12171 · commit-discipline.md 8579 · gates.md 45641 ·
#     handoff-block.md 6610 · scope-guard.md 7268 · testing.md 20589 · CLAUDE.md 8716
#     ИТОГО 109 574 B ≈ 107 KB × ≈6.3 впрыска/сутки × 9 ролей (сумма предъявлена прогоном
#     барьера на дереве main, а не сложена в уме).
#
# ЗАПАС — 5 % на файл, и это НАЗВАННОЕ число, а не «на глаз». Обоснование замером: корпус
# рос на +120 строк за 8 дней ≈ +8 KB ≈ +8 % ⇒ 5 % запаса краснеют примерно через 4–5 дней
# роста ТЕКУЩИМ темпом. Меньше — красное на правке опечатки; больше — храповик не держит.
# Запас предназначен для правок в пределах существующей формы, а не для новых разделов:
# новый раздел обязан войти ВЫЧИСТКОЙ старого (спека §8: «поднимать бюджет вместо дренажа»
# запрещено — урок einhard R13, где красное 80 KB против 20 KB просто терпится).
#
# ЗАВИСИМОСТЬ, НАЗВАННАЯ ЯВНО: спека §3 требует лимиты «от факта ПОСЛЕ M-60c′» (чистка
# корпуса). M-60c′ НЕ смержен на дату замера — значит эти числа ПРОВИЗОРНЫ СВЕРХУ и
# подлежат пересчёту (только ВНИЗ) первым коммитом после merge M-60c′.
builtin_table() {
  printf '%s\t%s\n' \
    '.claude/rules/branch-hygiene.md'    12800 \
    '.claude/rules/commit-discipline.md'  9000 \
    '.claude/rules/gates.md'             47900 \
    '.claude/rules/handoff-block.md'      6900 \
    '.claude/rules/scope-guard.md'        7600 \
    '.claude/rules/testing.md'           21600 \
    'CLAUDE.md'                           9100
}

[ -d "${ROOT}" ] || die "ROOT не каталог: «${ROOT}»"

if [ -n "${TABLE}" ]; then
  SOURCE="таблица ${TABLE}"
  [ -e "${TABLE}" ] || die "таблица бюджетов не существует: ${TABLE}"
  [ -f "${TABLE}" ] || die "таблица бюджетов — не обычный файл: ${TABLE}"
  [ -r "${TABLE}" ] || die "таблица бюджетов нечитаема: ${TABLE}"
  [ -s "${TABLE}" ] || die "таблица бюджетов пуста: ${TABLE}"
  table_stream() { cat -- "${TABLE}"; }
else
  SOURCE="встроенная таблица (default-режим)"
  [ -n "$(builtin_table)" ] || die "встроенная таблица пуста — гейт проверял бы ничто"
  table_stream() { builtin_table; }
fi

echo "── бюджет обязательного чтения: ${SOURCE}; ROOT=${ROOT}"

rows=0
seen=""
total=0
limit_total=0
while IFS=$'\t' read -r p lim rest; do
  p="${p%$'\r'}"
  case "${p:-}" in '' | '#'*) continue ;; esac
  rows=$((rows + 1))

  # Лишние колонки — не «мусор в хвосте», а несогласованный формат: молча их проглотив,
  # барьер начнёт судить не ту величину.
  [ -z "${rest:-}" ] || {
    bad "строка таблицы имеет лишние колонки: «${p}» + «${rest}»"
    continue
  }

  # Дубль пути — fail-closed В ОБЕ СТОРОНЫ (CB-9a/CB-9b): first-wins и last-wins парсеры
  # молча выбирают «одну жизнь» строки, и какая именно жизнь судится — ненаблюдаемо.
  case " ${seen} " in
    *" ${p} "*)
      bad "дубль строки таблицы: ${p} (какая из жизней пути судится — не определено)"
      continue
      ;;
  esac
  seen="${seen} ${p}"

  case "${lim:-}" in
    '' | *[!0-9]*)
      bad "негодный лимит для ${p}: «${lim:-}»"
      continue
      ;;
  esac
  [ "${#lim}" -le 18 ] || {
    bad "лимит для ${p} за пределами int64: «${lim}»"
    continue
  }

  f="${ROOT}/${p}"
  if [ ! -e "${f}" ]; then
    bad "файл из таблицы ОТСУТСТВУЕТ: ${p} (нет файла ⇒ нулевой размер ⇒ бесконечный запас)"
    continue
  fi
  if [ ! -f "${f}" ]; then
    bad "путь из таблицы — не обычный файл: ${p}"
    continue
  fi
  if [ ! -r "${f}" ]; then
    bad "файл из таблицы НЕЧИТАЕМ: ${p} (отказ носителя нельзя считать нулевым размером)"
    continue
  fi
  sz="$(wc -c <"${f}" 2>/dev/null | tr -d '[:space:]')"
  case "${sz:-}" in
    '' | *[!0-9]*)
      bad "размер ${p} не измеряется: «${sz:-}»"
      continue
      ;;
  esac

  total=$((total + sz))
  limit_total=$((limit_total + lim))
  if [ "${sz}" -le "${lim}" ]; then
    printf 'OK    %-40s %7s B / %7s B (запас %s B)\n' "${p}" "${sz}" "${lim}" "$((lim - sz))"
  else
    bad "$(printf '%-40s %7s B > лимита %7s B (перерасход %s B)' "${p}" "${sz}" "${lim}" "$((sz - lim))")"
  fi
done < <(table_stream)

[ "${rows}" -gt 0 ] || die "таблица не содержит ни одной строки бюджета"

echo
if [ "${FAILED}" -gt 0 ]; then
  echo "VERDICT: FAIL (${FAILED}) — обязательное чтение вышло за бюджет либо предмет исчез."
  echo "Лечится ВЫЧИСТКОЙ, а не поднятием лимита (спека M-60b §8; урок einhard R13:"
  echo "красное 80 KB против бюджета 20 KB терпится годами и перестаёт что-либо значить)."
  exit 1
fi
echo "VERDICT: PASS — ${rows} файлов, ${total} B из ${limit_total} B бюджета (запас $((limit_total - total)) B)"
