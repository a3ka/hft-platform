#!/usr/bin/env bash
# Барьер: ресурсный оракул мерит СВОЙ инвариант, а не окружение.
# Спецификация и проба: scripts/tests/red_resource_oracles.sh
#
# ЗАЧЕМ. `testing.md` («Целостность гейта», свойство 2) требует: ресурсный оракул на
# глобальном счётчике обязан быть single-threaded-по-замеру, конфаундинг-величину держать
# КОНСТАНТНОЙ. Правило написано, механической проверки не было — и класс сработал ДВАЖДЫ:
#
#   TD-098 / TD-129 — `red_snapshot_noclone.rs` вёл CUR/PEAK в `AtomicUsize` на весь
#   процесс, а `cargo test` гоняет тесты файла ПАРАЛЛЕЛЬНЫМИ потоками. `PEAK.fetch_max`
#   брал максимум по всему процессу ⇒ замер включал аллокации соседей. Наблюдалось на ОДНОМ
#   И ТОМ ЖЕ дереве: прогон на PR зелёный, прогон на `main` красный. Обязательный чек,
#   охраняющий `main`, был лотереей — а социальный ответ на такое («перезапусти до
#   зелёного») обнуляет смысл защиты ветки.
#
# ПОЧЕМУ БАРЬЕР СТРУКТУРНЫЙ, А НЕ ПРОГОННЫЙ. Соблазн — гонять оракул N раз и требовать
# одинакового исхода. Отвергнуто: флак с частотой 1 к 5 не ловится тремя прогонами, а
# ловится двадцатью — это минуты CI на каждый push. Структурная проверка ловит МЕХАНИЗМ,
# который даёт флак, ещё до того как флак проявится, стоит миллисекунды и детерминирована.
# Цена — покрывается класс аллокаций, а не все ресурсы (предел назван в §ПРЕДЕЛЫ).
#
# КОДЫ ВОЗВРАТА
#   0 — все найденные ресурсные оракулы ведут учёт потоково;
#   1 — есть оракул с процессным счётчиком (перечисляются ВСЕ, а не первый);
#   2 — предмет не установлен достоверно (ROOT не каталог; НИ ОДНОГО оракула не найдено).
# Ноль найденных — FAIL, а не пропуск: в репозитории такой оракул ЕСТЬ, и его исчезновение
# из поля зрения барьера означает поломку детектора, а не отсутствие предмета (урок CB-5:
# гейт, зеленеющий от исчезновения предмета, — не гейт).

set -uo pipefail

SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SELF_DIR}/.." && pwd)"
ROOT="${ROOT:-${REPO_ROOT}}"

FAILED=0
FOUND=0
bad() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }

[ -d "${ROOT}" ] || { echo "FAIL  ROOT не каталог: «${ROOT}»"; echo; echo "Барьер fail-closed: предмет не установлен."; exit 2; }

echo "── ресурсные оракулы: учёт обязан быть потоковым; ROOT=${ROOT}"

# ── ДЕТЕКТОР ─────────────────────────────────────────────────────────────────────────────
# Признак ресурсного оракула — объявление СВОЕГО аллокатора. Ищется по всему дереву, а не в
# одном каталоге: оракул может жить в любом крейте (`crates/*/tests`, `crates/*/src`,
# `scripts/tests` с inline-Rust). Форма атрибута допускает пробелы и перенос, поэтому
# сопоставление идёт по `global_allocator` без привязки к `#[`.
mapfile -t ORACLES < <(
  grep -rl --include='*.rs' 'global_allocator' "${ROOT}" 2>/dev/null \
    | grep -v '/target/' | sort -u
)

for f in "${ORACLES[@]:-}"; do
  [ -n "${f}" ] || continue
  FOUND=$((FOUND + 1))
  rel="${f#"${ROOT}"/}"

  # ── ПРОВЕРКА: процессный изменяемый счётчик рядом с аллокатором ────────────────────────
  # `static ИМЯ: AtomicXxx` — счётчик, общий на процесс. Именно он делает замер зависимым
  # от соседних тестов. Константы (`static FOO: usize = 5;`) не ловятся: тип обязан быть
  # атомарным, то есть предназначенным для межпоточного изменения.
  procwide="$(grep -nE '^[[:space:]]*static[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]*:[[:space:]]*Atomic[A-Za-z0-9]+' "${f}" 2>/dev/null || true)"

  # Потоковый учёт — оправдание: если он есть, процессные атомики допустимы для СЛУЖЕБНЫХ
  # нужд (флаг «замер идёт»), потому что сам замер ведётся в thread_local.
  # `grep -c` ПЕЧАТАЕТ 0 и ВОЗВРАЩАЕТ 1 при отсутствии совпадений. Прежняя редакция
  # дописывала `|| echo 0`, получая двухстрочное «0\n0», и сравнение `-eq 0` падало —
  # барьер молча уходил в ветку «учёт потоковый». Страж, который не срабатывает, есть
  # ровно тот дефект, против которого он написан; поймано пробой RO-2/RO-4/RO-5/RO-8.
  threadlocal="$(grep -cE 'thread_local!' "${f}" 2>/dev/null)"
  threadlocal="${threadlocal:-0}"

  # ── ЧИСЛО СОСЕДЕЙ — И ЕСТЬ ИНВАРИАНТ ──────────────────────────────────────────────────
  # Процессный счётчик портит замер ТОЛЬКО когда в том же бинаре есть кому аллоцировать
  # параллельно: `cargo test` гоняет `#[test]` одного файла разными потоками. При ОДНОМ
  # тесте соседей нет, и процессный счётчик ведёт себя ровно как потоковый — файл исправен,
  # трогать его незачем (работающее не чинят).
  #
  # Первая редакция барьера ловила САМ ФАКТ процессного счётчика — то есть ПРОКСИ, а не
  # инвариант. На реальном дереве это дало 11 красных из 13, из которых семь не сломаны.
  # Барьер, охраняющий правило «мерь свой инвариант, а не прокси», сам его нарушал.
  #
  # Латентность при этом не игнорируется, а ОБЕЗВРЕЖИВАЕТСЯ: как только в «безопасный» файл
  # допишут второй тест, барьер покраснеет в ТОМ ЖЕ PR — мина ловится в момент постановки,
  # а не постфактум на красном `main`.
  tests="$(grep -cE '^[[:space:]]*#\[test\]' "${f}" 2>/dev/null)"
  tests="${tests:-0}"

  if [ -n "${procwide}" ] && [ "${threadlocal}" -eq 0 ] && [ "${tests}" -ge 2 ]; then
    bad "${rel}: процессный счётчик при ${tests} тестах в бинаре — замер портится соседями"
    echo "${procwide}" | sed 's/^/        /'
    echo "        ↳ cargo test гоняет тесты одного бинаря ПАРАЛЛЕЛЬНЫМИ потоками: замер"
    echo "          включит аллокации соседей, и исход станет зависеть от планировщика."
    echo "          Лечение: thread_local! с const-инициализатором + try_with (образец —"
    echo "          crates/gateway/tests/red_snapshot_noclone.rs, коммит 955f409)."
  else
    if [ -n "${procwide}" ] && [ "${threadlocal}" -eq 0 ]; then
      echo "OK    ${rel}: процессный счётчик, но тестов в бинаре ${tests} — соседей нет, замер чист"
    else
      echo "OK    ${rel}: учёт потоковый"
    fi
  fi
done

if [ "${FOUND}" -eq 0 ]; then
  echo "FAIL  не найдено НИ ОДНОГО ресурсного оракула — детектор сломан либо предмет исчез"
  echo
  echo "Барьер fail-closed: в репозитории такой оракул есть (crates/gateway/tests/"
  echo "red_snapshot_noclone.rs). Ноль найденных означает поломку поиска, а не чистоту."
  exit 2
fi

echo
if [ "${FAILED}" -eq 0 ]; then
  echo "VERDICT: PASS — оракулов проверено: ${FOUND}, процессных счётчиков не найдено"
  exit 0
fi
echo "VERDICT: FAIL (${FAILED} из ${FOUND}) — ресурсный оракул мерит окружение, а не свой инвариант"
exit 1

# ── ПРЕДЕЛЫ, НАЗВАННЫЕ ЧЕСТНО ────────────────────────────────────────────────────────────
# 1. Покрыт класс АЛЛОКАЦИЙ. Оракулы, мерящие ВРЕМЯ (`Instant::now` против константы) и
#    СВОБОДНОЕ МЕСТО (`free_bytes` против порога хоста — класс TD-151), этим барьером НЕ
#    ловятся. Они того же рода «мерю окружение», и это кандидат на расширение, а не
#    сделанное: барьер, объявленный шире своего охвата, хуже отсутствующего.
# 2. Барьер СТРУКТУРНЫЙ: он ловит известный механизм, а не флак как явление. Оракул,
#    зависящий от окружения иначе (общий каталог, сетевой порт, порядок файлов), пройдёт.
# 3. Барьер судит по ЧИСЛУ `#[test]` в файле. Тест, порождающий потоки САМ, конфаундит свой
#    же замер при единственном `#[test]` — этого барьер не видит. Класс назван, не закрыт.
# 4. `thread_local!` засчитывается по НАЛИЧИЮ, не по применению: файл, объявивший его и
#    продолжающий считать в атомике, барьер пропустит. Проверка «замер идёт именно в
#    thread_local» требует разбора потока данных и здесь не делается — названо как предел.
