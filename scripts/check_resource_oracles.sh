#!/usr/bin/env bash
# Барьер: ресурсный оракул мерит СВОЙ инвариант, а не окружение.
# Спецификация и проба: scripts/tests/red_resource_oracles.sh
#
# ЗАЧЕМ. `testing.md` («Целостность гейта», свойство 2) требует: ресурсный оракул на
# глобальном счётчике обязан быть single-threaded-по-замеру, конфаундинг-величину держать
# КОНСТАНТНОЙ. Правило написано, механической проверки не было — и класс сработал ДВАЖДЫ:
#
#   TD-098 / TD-129 — `red_snapshot_noclone.rs` вёл CUR/PEAK в `AtomicUsize` на весь
#   процесс, а `cargo test` гоняет тесты файла ПАРАЛЛЕЛЬНЫМИ потоками. `PEAK.fetch_max`
#   брал максимум по всему процессу ⇒ замер включал аллокации соседей. Наблюдалось на ОДНОМ
#   И ТОМ ЖЕ дереве: прогон на PR зелёный, прогон на `main` красный. Обязательный чек,
#   охраняющий `main`, был лотереей — а социальный ответ на такое («перезапусти до
#   зелёного») обнуляет смысл защиты ветки.
#
# ПОЧЕМУ БАРЬЕР СТРУКТУРНЫЙ, А НЕ ПРОГОННЫЙ. Соблазн — гонять оракул N раз и требовать
# одинакового исхода. Отвергнуто: флак с частотой 1 к 5 не ловится тремя прогонами, а
# ловится двадцатью — это минуты CI на каждый push. Структурная проверка ловит МЕХАНИЗМ,
# который даёт флак, ещё до того как флак проявится, стоит миллисекунды и детерминирована.
# Цена — покрывается класс аллокаций, а не все ресурсы (предел назван в §ПРЕДЕЛЫ).
#
# КОДЫ ВОЗВРАТА
#   0 — все найденные ресурсные оракулы ведут учёт потоково;
#   1 — есть оракул с процессным счётчиком (перечисляются ВСЕ, а не первый);
#   2 — предмет не установлен достоверно (ROOT не каталог; НИ ОДНОГО оракула не найдено).
# Ноль найденных — FAIL, а не пропуск: в репозитории такой оракул ЕСТЬ, и его исчезновение
# из поля зрения барьера означает поломку детектора, а не отсутствие предмета (урок CB-5:
# гейт, зеленеющий от исчезновения предмета, — не гейт).

set -uo pipefail

SELF_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "${SELF_DIR}/.." && pwd)"
ROOT="${ROOT:-${REPO_ROOT}}"

FAILED=0
FOUND=0
bad() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }

[ -d "${ROOT}" ] || { echo "FAIL  ROOT не каталог: «${ROOT}»"; echo; echo "Барьер fail-closed: предмет не установлен."; exit 2; }

echo "── ресурсные оракулы: учёт обязан быть потоковым; ROOT=${ROOT}"


# ═══════════════════════════════════════════════════════════════════════════════════════════
# ПРЕДЕЛЫ, НАЗВАННЫЕ ЧЕСТНО (решение founder'а 2026-08-17, вариант «признать предел»)
# ═══════════════════════════════════════════════════════════════════════════════════════════
#
# ЛОВИТ: неосторожность — процессный счётчик, объявленный обычной формой рядом с аллокатором.
# ЧЕГО БАРЬЕР НЕ ЛОВИТ — перечень ОДИН, и он в блоке `§ПРЕДЕЛЫ` в конце файла.
#
# Здесь перечня БОЛЬШЕ НЕТ намеренно. Прежняя редакция дублировала его в двух местах, и
# они разошлись: шапка написана коммитом `a071496` ДО фикса `7d154ff`, который закрыл
# `C-097` R2/R3/R8/R10, но шапку не синхронизировал. Итог — `C-121` B-1: **из шести форм,
# объявленных «не ловит», ПЯТЬ ловятся** (проверено исполнением, замер ниже). Направление
# безопасное — покрытие занижено, не завышено, — но этим текстом обосновывался
# founder-override, а override «пределы названы честно» не может опираться на перечень, где
# пять пунктов из шести не пределы.
#
# Замер 2026-08-22 (каждая форма — синтетическая фикстура + прогон этого барьера):
#   ЛОВЯТСЯ: `OnceLock<AtomicUsize>` · `lazy_static!` · `#[tokio::test]` · `#[rstest]` ·
#            `thread_local!` в строчном комментарии · `#[global_allocator]` в блочном
#            комментарии `/* */` (последнее — ложное ПОЛОЖИТЕЛЬНОЕ, см. `§ПРЕДЕЛЫ` п.6)
#   НЕ ЛОВЯТСЯ: `#[test_case]` (`§ПРЕДЕЛЫ` п.5) · макрос-аллокатор из другого файла и
#            счётчик в соседнем модуле (оба — `TD-157`, принятый предел однофайловости) ·
#            `thread_local!` по НАЛИЧИЮ (`§ПРЕДЕЛЫ` п.4)
#
# Правило, из которого это следует: перечень пределов живёт в ОДНОМ месте. Второй носитель
# не «дублирует для удобства» — он расходится при первой же правке первого.
#
# ЧТО ЭТО ЗНАЧИТ ПРАКТИЧЕСКИ: зелёное этого барьера не означает «ресурсные оракулы честны».
# Оно означает «типовых форм процессного учёта не найдено». Красное — надёжно: ложных
# срабатываний в круге 3 не найдено ни одного.
#
# ПОЧЕМУ НЕ ДОВЕДЕНО: решение владельца после трёх кругов (пропущено 4 из 8 стабов → 6 из 10).
# Вердикт `C-097` остаётся REJECT и снятым НЕ объявляется; влитие — founder-override
# (`gates.md` §5) с этим текстом как названным обоснованием.
# ═══════════════════════════════════════════════════════════════════════════════════════════

# ── ДЕТЕКТОР ─────────────────────────────────────────────────────────────────────────────
# Признак ресурсного оракула — объявление СВОЕГО аллокатора. Ищется по всему дереву, а не в
# одном каталоге: оракул может жить в любом крейте (`crates/*/tests`, `crates/*/src`,
# `scripts/tests` с inline-Rust). Форма атрибута допускает пробелы и перенос, поэтому
# сопоставление идёт по `global_allocator` без привязки к `#[` — НО строка обязана быть
# ОБЪЯВЛЕНИЕМ, а не упоминанием (`C-095` F-2): прежняя редакция ловила слово в КОММЕНТАРИИ и
# заводила на учёт файл, который аллокатора не объявляет вовсе. Отсюда две правки:
#   · строки, начинающиеся с `//` или `*` (тело блочного комментария), отбрасываются;
#   · требуется атрибутная форма — `#[` в той же или предыдущей непустой строке.
# Предел назван: `#[` и имя, разнесённые ЧЕРЕЗ комментарий между ними, не разбираются.
mapfile -t ORACLES < <(
  grep -rl --include='*.rs' 'global_allocator' "${ROOT}" 2>/dev/null \
    | grep -v '/target/' | sort -u \
    | while read -r cand; do
        awk '
          { line=$0
            sub(/^[[:space:]]+/, "", line)
            if (line ~ /^\/\// || line ~ /^\*/) { prev=""; next }
            if (index(line, "global_allocator") > 0) {
              if (index(line, "#[") > 0 || index(prev, "#[") > 0) { found=1; exit }
            }
            if (line != "") prev=line
          }
          END { exit(found ? 0 : 1) }
        ' "${cand}" && printf '%s\n' "${cand}"
      done
)

for f in "${ORACLES[@]:-}"; do
  [ -n "${f}" ] || continue
  FOUND=$((FOUND + 1))
  rel="${f#"${ROOT}"/}"

  # ── ПРОВЕРКА: процессный изменяемый счётчик рядом с аллокатором ────────────────────────
  # `static ИМЯ: AtomicXxx` — счётчик, общий на процесс. Именно он делает замер зависимым
  # от соседних тестов. Константы (`static FOO: usize = 5;`) не ловятся: тип обязан быть
  # атомарным, то есть предназначенным для межпоточного изменения.
  # Формы, которые прежняя регулярка ПРОПУСКАЛА (`C-095` F-3): `pub static`, `static mut`,
  # и полностью квалифицированный путь типа (`std::sync::atomic::AtomicUsize`). Каждая —
  # обычный, не экзотический Rust, и каждая давала процессный счётчик мимо барьера.
  # `C-097` R2/R3: атомик, ОБЁРНУТЫЙ в `OnceLock`/`Mutex`/`RwLock`/`Lazy` или объявленный
  # через `lazy_static!`/`static ref`, — тот же процессный счётчик, только записанный иначе.
  # Прежняя регулярка требовала, чтобы `Atomic…` шёл сразу после двоеточия, и обе формы
  # проходили мимо. Теперь `Atomic…` ищется в ЛЮБОМ месте объявления статика, а `static ref`
  # (форма `lazy_static!`) распознаётся наравне со `static`.
  # Комментарии срезаны по той же причине, что и у `thread_local!` (R10): объявление в
  # комментарии — не объявление.
  # Якорь начала строки СНЯТ (`C-097` R3): `lazy_static! { static ref CUR: AtomicUsize … }`
  # держит объявление ПОСЛЕ открывающей скобки макроса, то есть не в начале строки. Вместо
  # `^` допускается начало строки, пробел или `{` — этого хватает на обе формы и не ловит
  # `Atomic` внутри имени идентификатора (перед `static` обязан стоять разделитель).
  procwide="$(sed 's|//.*$||' "${f}" 2>/dev/null | grep -nE '(^|[[:space:]]|\{)[[:space:]]*(pub[[:space:]]+(\([^)]*\)[[:space:]]*)?)?static([[:space:]]+(mut|ref))?[[:space:]]+[A-Za-z_][A-Za-z0-9_]*[[:space:]]*:[^=;]*Atomic[A-Za-z0-9]+' || true)"

  # Потоковый учёт — оправдание: если он есть, процессные атомики допустимы для СЛУЖЕБНЫХ
  # нужд (флаг «замер идёт»), потому что сам замер ведётся в thread_local.
  # `grep -c` ПЕЧАТАЕТ 0 и ВОЗВРАЩАЕТ 1 при отсутствии совпадений. Прежняя редакция
  # дописывала `|| echo 0`, получая двухстрочное «0\n0», и сравнение `-eq 0` падало —
  # барьер молча уходил в ветку «учёт потоковый». Страж, который не срабатывает, есть
  # ровно тот дефект, против которого он написан; поймано пробой RO-2/RO-4/RO-5/RO-8.
  # `C-097` R10 (ЛОЖНОЕ ЗЕЛЁНОЕ, ранг REJECT): слово `thread_local!` в КОММЕНТАРИИ
  # засчитывалось как потоковый учёт — дефектный оракул проходил барьер, потому что кто-то
  # упомянул лечение в комментарии. Это тот же класс, что «упоминание против утверждения»,
  # который сегодня трижды красил вердикты в `verify_design_claims.sh`: текст о механизме
  # принимался за механизм. Строчные комментарии срезаются ДО подсчёта.
  # Предел назван честно: блочные комментарии `/* … */` не срезаются — для этого нужен
  # разбор вложенности, а не построчный фильтр. Направление остатка БЕЗОПАСНОЕ ровно в
  # одну сторону: `thread_local!` внутри `/* */` даст ложное зелёное, как и прежде. Ловится
  # сценарием RO-R10b, который его ПРЕДЪЯВЛЯЕТ как известный предел, а не прячет.
  threadlocal="$(sed 's|//.*$||' "${f}" 2>/dev/null | grep -cE 'thread_local!')"
  threadlocal="${threadlocal:-0}"

  # ── ЧИСЛО СОСЕДЕЙ — И ЕСТЬ ИНВАРИАНТ ──────────────────────────────────────────────────
  # Процессный счётчик портит замер ТОЛЬКО когда в том же бинаре есть кому аллоцировать
  # параллельно: `cargo test` гоняет `#[test]` одного файла разными потоками. При ОДНОМ
  # тесте соседей нет, и процессный счётчик ведёт себя ровно как потоковый — файл исправен,
  # трогать его незачем (работающее не чинят).
  #
  # Первая редакция барьера ловила САМ ФАКТ процессного счётчика — то есть ПРОКСИ, а не
  # инвариант. На реальном дереве это дало 11 красных из 13, из которых семь не сломаны.
  # Барьер, охраняющий правило «мерь свой инвариант, а не прокси», сам его нарушал.
  #
  # Латентность при этом не игнорируется, а ОБЕЗВРЕЖИВАЕТСЯ: как только в «безопасный» файл
  # допишут второй тест, барьер покраснеет в ТОМ ЖЕ PR — мина ловится в момент постановки,
  # а не постфактум на красном `main`.
  # `C-097` R8: считались ТОЛЬКО `#[test]`. Асинхронные оракулы объявляются
  # `#[tokio::test]` (в этом корпусе — большинство оракулов gateway-serve), и файл с двумя
  # такими тестами барьер объявлял «соседей нет, замер чист» — ложное зелёное ровно в том
  # классе, ради которого барьер написан. Считаются любые атрибуты, ОКАНЧИВАЮЩИЕСЯ на
  # `test]`: `#[test]`, `#[tokio::test]`, `#[tokio::test(flavor = "multi_thread")]`,
  # `#[async_std::test]`. Комментарии срезаны по той же причине.
  tests="$(sed 's|//.*$||' "${f}" 2>/dev/null | grep -cE '^[[:space:]]*#\[[A-Za-z_:]*test(\([^)]*\))?\]')"
  tests="${tests:-0}"

  if [ -n "${procwide}" ] && [ "${threadlocal}" -eq 0 ] && [ "${tests}" -ge 2 ]; then
    bad "${rel}: процессный счётчик при ${tests} тестах в бинаре — замер портится соседями"
    echo "${procwide}" | sed 's/^/        /'
    echo "        ↳ cargo test гоняет тесты одного бинаря ПАРАЛЛЕЛЬНЫМИ потоками: замер"
    echo "          включит аллокации соседей, и исход станет зависеть от планировщика."
    echo "          Лечение: thread_local! с const-инициализатором + try_with (образец —"
    echo "          crates/gateway/tests/red_snapshot_noclone.rs, коммит 955f409)."
  else
    if [ -n "${procwide}" ] && [ "${threadlocal}" -eq 0 ]; then
      echo "OK    ${rel}: процессный счётчик, но тестов в бинаре ${tests} — соседей нет, замер чист"
    else
      echo "OK    ${rel}: учёт потоковый"
    fi
  fi
done

if [ "${FOUND}" -eq 0 ]; then
  echo "FAIL  не найдено НИ ОДНОГО ресурсного оракула — детектор сломан либо предмет исчез"
  echo
  echo "Барьер fail-closed: в репозитории такой оракул есть (crates/gateway/tests/"
  echo "red_snapshot_noclone.rs). Ноль найденных означает поломку поиска, а не чистоту."
  exit 2
fi

echo
if [ "${FAILED}" -eq 0 ]; then
  echo "VERDICT: PASS — оракулов проверено: ${FOUND}, процессных счётчиков не найдено"
  exit 0
fi
echo "VERDICT: FAIL (${FAILED} из ${FOUND}) — ресурсный оракул мерит окружение, а не свой инвариант"
exit 1

# ── ПРЕДЕЛЫ, НАЗВАННЫЕ ЧЕСТНО ────────────────────────────────────────────────────────────
# 1. Покрыт класс АЛЛОКАЦИЙ. Оракулы, мерящие ВРЕМЯ (`Instant::now` против константы) и
#    СВОБОДНОЕ МЕСТО (`free_bytes` против порога хоста — класс TD-151), этим барьером НЕ
#    ловятся. Они того же рода «мерю окружение», и это кандидат на расширение, а не
#    сделанное: барьер, объявленный шире своего охвата, хуже отсутствующего.
# 2. Барьер СТРУКТУРНЫЙ: он ловит известный механизм, а не флак как явление. Оракул,
#    зависящий от окружения иначе (общий каталог, сетевой порт, порядок файлов), пройдёт.
# 3. Барьер судит по ЧИСЛУ `#[test]` в файле. Тест, порождающий потоки САМ, конфаундит свой
#    же замер при единственном `#[test]` — этого барьер не видит. Класс назван, не закрыт.
# 4. `thread_local!` засчитывается по НАЛИЧИЮ, не по применению: файл, объявивший его и
#    продолжающий считать в атомике, барьер пропустит. Проверка «замер идёт именно в
#    thread_local» требует разбора потока данных и здесь не делается — названо как предел.
# 5. `#[test_case]` в счёт соседей НЕ входит: регулярка считает атрибуты, ОКАНЧИВАЮЩИЕСЯ на
#    `test]`, а `#[test_case]` оканчивается на `case]`. Файл с двумя такими тестами и
#    процессным счётчиком барьер объявит одиночным — ложное ЗЕЛЁНОЕ. Замер 2026-08-22:
#    exit=0 на синтетической фикстуре. В репозитории `#[test_case]` сегодня НЕТ
#    (`grep -rn '#\[test_case' crates/` — пусто), класс латентный. Не чинится здесь
#    сознательно: правка регулярки под форму, которой в корпусе нет, — барьер под «класс,
#    который может быть» (ограничитель §3bis(2) требует УЖЕ СЛУЧИВШЕГОСЯ инцидента).
#    Появится первый `#[test_case]` — чинить одной регуляркой.
# 6. Ложное ПОЛОЖИТЕЛЬНОЕ, названное отдельно от ложных отрицательных: `#[global_allocator]`
#    внутри БЛОЧНОГО комментария `/* */` засчитывается как объявленный аллокатор (фильтр
#    срезает только строчные `//`). Направление безопасное — лишнее красное, не пропуск, —
#    но красное на закомментированном коде есть трение, из-за которого барьеры отключают.
#    Замер 2026-08-22: exit=1 на фикстуре с `/* #[global_allocator] */`.
