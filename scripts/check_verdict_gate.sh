#!/usr/bin/env bash
# Барьер непогашенного отказа: ветка не вливается, пока вердикт гейта на ней держит merge.
# Спецификация — `scripts/tests/red_verdict_gate.sh` (VG-*).
#
# ── ЧТО ЭТО МЕХАНИЗИРУЕТ ───────────────────────────────────────────────────────────────
# `gates.md` §5: «KILL/CONCERNS блокирует merge до устранения находок»; §4: вердикт reviewer'а
# — артефакт, а не сообщение; §0: решение арбитра обязательно к исполнению. Все три нормы
# говорили, что отказной вердикт держит приземление, и ни одна не имела носителя: `gh pr
# checks` наблюдает ЧЕКИ, а не вердикты, и зелёный агрегат ничего о вердиктах не знает.
# `docs/workflow/binding-requires-mechanism.md` даёт на такое ровно две ветки — механизм либо
# `COGNITIVE-ONLY` с признанием остаточного риска. Это первая ветка.
#
# ── ЗАМЕР, А НЕ ИСТОРИЯ ПРО ОДИН СЛУЧАЙ (2026-08-20, `origin/main`) ────────────────────
# По 34 merge-коммитам вида «Merge pull request» из последних 400 коммитов `main`: в диапазоне
# СОБСТВЕННОЙ ветки на момент слияния лежал непогашенный отказной вердикт — СЕМЬ раз, на шести
# разных PR:
#   PR  #7 `feat/M-60b-barriers`      ключ `M-60b` = REJECT   (`C-090`)
#   PR  #7 то же слияние               ключ `M-60`  = ESCALATE (`C-088`)
#   PR #13 `docs/reading-map`          ключ `C-092` = REJECT   (`C-092`)
#   PR #19 `docs/founder-decisions`    ключ `R-090` = REJECT   (`R-090`)
#   PR #27 `feat/deploy-catchup`       ключ `R-4`   = REJECT   (`C-097`)
#   PR #31 `docs/session-handoff`      ключ `PR-31` = REJECT   (`R-094`)
#   PR #34 `feat/harness-branch-build` ключ `A-010` = REJECT   (`C-105`)
# Класс воспроизводится, и воспроизводится в том числе на харнесс-работе.
#
# ── ЧЕГО ЭТОТ БАРЬЕР НЕ ЛОВИТ — НАЗВАНО, А НЕ ПОДРАЗУМЕВАЕТСЯ ─────────────────────────
# Инцидент 19.08 (PR #41 слит через 49 мин после публикации `C-107`, прямо запрещавшего merge)
# этим барьером НЕ ловится, и выдавать обратное нельзя. Замер: диапазон PR #41
# (`af1fd06..52d88c7`) не содержит НИ ОДНОГО файла вердикта — `C-107` жил на ДРУГОЙ ветке
# (`docs/process-package-2026-08-19`) и нёс в шапке ключ `PR-42`, а запрет на merge PR #41
# был ПРОЗОЙ внутри тела. Машиночитаемой связи между `C-107` и PR #41 не существует;
# вычислить её — это класс «барьер ВЫЧИСЛЯЕТ предмет артефакта», упразднённый решением
# founder'а 12.08 по M-61 (см. шапку `check_gate_meta.sh`). Барьер закрывает СВОЙ класс —
# «ветка несёт непогашенный отказ о СВОЁМ предмете» — и ровно его.
#
# ── ПРЕДМЕТ СУЖДЕНИЯ: ДИАПАЗОН, А НЕ ДЕРЕВО ───────────────────────────────────────────
# Судятся вердикты, ДОБАВЛЕННЫЕ ИЛИ ИЗМЕНЁННЫЕ диапазоном события, — та же граница, что у
# `check_gate_meta.sh` (GM-8). Правило «взять всё, что лежит в дереве» проверено замером и
# отвергнуто: в `origin/main` на 2026-08-20 последним по ключу отказным вердиктом стоят
# `M-60`=ESCALATE, `M-60b`=REJECT, `C-092`=REJECT, `R-4`=REJECT, `R-090`=REJECT, `PR-31`=REJECT
# — то есть барьер по дереву был бы КРАСЕН НА `main` с первого дня и в тот же день был бы
# объявлен шумом и выключен (`harness-track.md` §3, позитивный контроль).
# Следствие-предел: вердикт, уже лежавший в базе, барьер не видит. Это осознанно.
#
# ── ПРАВИЛО ───────────────────────────────────────────────────────────────────────────
# По каждому ключу `milestone:` берётся ПОСЛЕДНИЙ вердикт диапазона; отказной и не перекрытый
# более поздним проходным по тому же ключу ⇒ FAIL.
#   • порядок — позиция коммита в `git rev-list --reverse --topo-order`, а не время: даты
#     коммитов переписываются rebase'ом, топология — нет (`DET-I-1` по духу: решение обязано
#     быть воспроизводимым);
#   • ОДИН коммит, два вердикта на один ключ — «позже» не определено, и барьер НЕ УГАДЫВАЕТ:
#     отказ в такой паре побеждает (fail-closed). Штатный путь погашения — отдельный коммит;
#   • порядок недоказуем (файл рождён merge'ем и не виден обходом) ⇒ отказ такого файла
#     БЛОКИРУЕТ, а проходной такого файла НЕ ГАСИТ. Неизвестность не работает в пользу merge'а;
#   • отказные исходы = перечень МИНУС проходные (`scripts/lib/gate_meta.sh`): `REJECT`,
#     `CONCERNS`, `KILL`, `ESCALATE`. Отдельного литерала нет намеренно — два независимых
#     списка разошлись бы, и новый исход оказался бы ни проходным, ни отказным;
#   • значение вне перечня или пустое поле ⇒ НЕИЗВЕСТНО ⇒ FAIL. «Похоже на проходное» —
#     не состояние. В `main` такие шапки реально есть (`BLOCKED-ARBITER` у `R-042`).
#
# ── ВЫХОД ИЗ БАРЬЕРА ──────────────────────────────────────────────────────────────────
# Строка `VERDICT-CLEARED: <ключ> — <причина>` в теле ЛЮБОГО коммита диапазона.
#   • ПОКЛЮЧЕВОЙ: токен обязан НАЗЫВАТЬ ключ. Бланкетного «здесь всё погашено» нет — иначе
#     первый токен закрывал бы собой остальные ключи (класс GM-20 у соседнего барьера);
#   • причина ≥12 символов помимо ключа — тот же порог, что у `FOUNDER-APPROVED`
#     (`check_docs_freeze.sh`) и `ARCHIVED-VERDICT`: токен-ритуал неотличим от его отсутствия;
#   • срабатывание ГРОМКОЕ: печатается `NOTE` с ключом и коммитом-носителем.
# Предел назван честно: токен ПОДДЕЛЫВАЕМ — это аудит-след, а не доказательство того, что
# находки устранены. Та же оговорка, что у `ALLOW-SUBJECT-CHANGE` и `FOUNDER-APPROVED`
# (`gates.md` §11).
#
# ── КОМПОЗИЦИЯ С `check_gate_meta.sh` (без неё у барьера дыра) ─────────────────────────
# Вердикт БЕЗ шапки ключа не имеет и здесь не судится — печатается `NOTE` и считается, но не
# роняет прогон. Дыру «сними шапку — обойди барьер» закрывает не этот скрипт, а соседний:
# `check_gate_meta.sh` роняет прогон на вердикте без шапки, и его джоб `gate-meta` стоит в том
# же агрегате `All checks passed`. Композиция названа явно, потому что по отдельности каждый
# из двух барьеров обходится, а вместе — нет. Остаточный путь: `ARCHIVED-VERDICT` освобождает
# файл от шапки у соседа и тем прячет его от нас; цена обхода — поддельный токен с причиной,
# и это принятое ограничение, а не недосмотр.
#
# ── ПРОД-ФОРМА ВЫЗОВА ─────────────────────────────────────────────────────────────────
#   EVENT_NAME=push         PUSH_BEFORE=<github.event.before>         bash scripts/check_verdict_gate.sh
#   EVENT_NAME=pull_request PR_BASE_SHA=<event.pull_request.base.sha> bash scripts/check_verdict_gate.sh
#   (первый позиционный аргумент — ручной прогон: база сравнения явно)
# База берётся ИЗ СОБЫТИЯ, а не из `origin/main`: на push-событии `actions/checkout` ставит
# `origin/main` на ТОЛЬКО ЧТО ЗАПУШЕННЫЙ коммит, диапазон пуст и барьер зеленел бы ВСЕГДА
# (блокер B1 `C-006`). Требуется `fetch-depth: 0`.
# ДОЛГ, НАЗВАННЫЙ ЯВНО: разрешение базы — пятая копия одного и того же блока (`check_docs_freeze`,
# `check_protected_artifacts`, `check_artifact_ids`, `check_gate_meta`). В библиотеку он в этом
# круге НЕ вынесен: проба соседа пиннит лишь две из шести его осей (GM-9 zero-SHA, GM-27
# pull_request), то есть извлечение осталось бы НЕДОКАЗАННЫМ на барьере, стоящем в агрегате.
# Это отдельный предмет со своим кругом, а не попутная правка.
#
# ── КОДЫ ВОЗВРАТА ─────────────────────────────────────────────────────────────────────
#   0 — ни один ключ диапазона не оставлен в отказном состоянии;
#   1 — есть непогашенные отказы либо непригодные шапки (печатаются ВСЕ: ни первый ключ, ни
#       первый файл не закрывают собой остальные);
#   2 — база события не установлена достоверно / библиотека разбора недоступна (fail-closed).

set -uo pipefail

__LIB="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)/lib/gate_meta.sh"
# shellcheck source=lib/gate_meta.sh
. "${__LIB}" 2>/dev/null || {
  echo "FAIL  библиотека разбора шапки «${__LIB}» недоступна — читать GATE-META нечем"
  echo "Барьер fail-closed: без разбора шапки «вердиктов нет» неотличимо от «прочитать нечем»."
  exit 2
}

VERDICT_DIRS="research/critiques research/reviews research/arbitration"

FAILED=0
NOTES=0
bad()  { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
note() { echo "NOTE  $*"; NOTES=$((NOTES + 1)); }
die()  {
  echo "FAIL  $*"
  echo
  echo "Барьер fail-closed: диапазон события не установлен достоверно."
  exit 2
}

# ── 1. База диапазона (форма — как у соседних барьеров; см. «ДОЛГ» в шапке) ────────────
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)
      raw="${PUSH_BEFORE:-}"
      [ -n "${raw}" ] || raw="${PR_BASE_SHA:-}"
      ;;
    pull_request)
      raw="${PR_BASE_SHA:-}"
      [ -n "${raw}" ] || raw="${PUSH_BEFORE:-}"
      ;;
    "") die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *) die "неизвестное событие «${EVENT_NAME}» — база сравнения не определена" ;;
  esac
fi
[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?}) — что вошло в push, недоказуемо"
case "${raw}" in
  *[!0]*) : ;;
  *) die "база = zero-SHA (создание ветки или force-push) — диапазон недоказуем" ;;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || die "база «${raw}» отсутствует в истории (force-push / поверхностный клон — нужен fetch-depth: 0)"
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || die "база «${raw}» НЕ предок HEAD — история переписана; что вошло в диапазон, недоказуемо"
BASE="$(git rev-parse "${raw}^{commit}")"

echo "── VERDICT-GATE: диапазон ${BASE:0:8}..HEAD"

# ── 2. Порядок коммитов диапазона ─────────────────────────────────────────────────────
# Топологический, а не по дате: даты переписываются rebase'ом, топология — нет.
declare -A COMMIT_ORD=()
idx=0
while IFS= read -r c; do
  [ -n "${c}" ] || continue
  idx=$((idx + 1))
  COMMIT_ORD["${c}"]="${idx}"
done < <(git rev-list --reverse --topo-order "${BASE}..HEAD" 2>/dev/null || true)

# Позиция ПОСЛЕДНЕГО коммита диапазона, тронувшего файл. `-m` разворачивает merge'и по
# родителям — иначе файл, рождённый merge'ем, остался бы вовсе без позиции.
declare -A FILE_ORD=()
cur=""
while IFS= read -r line; do
  case "${line}" in
    "commit "*)
      cur="${line#commit }"
      ;;
    "")
      ;;
    *)
      f="${line#*$'\t'}"
      [ -n "${f}" ] || continue
      o="${COMMIT_ORD[${cur}]:-}"
      [ -n "${o}" ] || continue
      prev="${FILE_ORD[${f}]:-0}"
      [ "${o}" -gt "${prev}" ] && FILE_ORD["${f}"]="${o}"
      ;;
  esac
done < <(git log --reverse --topo-order -m --format='commit %H' --name-status --diff-filter=AM \
           "${BASE}..HEAD" -- ${VERDICT_DIRS} 2>/dev/null || true)

# ── 3. Токены погашения ───────────────────────────────────────────────────────────────
# Тело читается `git log --format='%B'`, а не `git show`: последний отдал бы и текст ДИФФА, и
# файл, ЦИТИРУЮЩИЙ токен, открывал бы барьер сам себе (класс, названный в check_docs_freeze).
cleared_token_for() { # $1=ключ → SHA коммита-носителя; 1, если токена нет
  local c line rest tokkey reason __r
  while IFS= read -r c; do
    [ -n "${c}" ] || continue
    while IFS= read -r line; do
      case "${line}" in "VERDICT-CLEARED: "*) : ;; *) continue ;; esac
      rest="${line#VERDICT-CLEARED: }"
      # Ключ читается ПОЗИЦИОННО — первым словом после токена — и сверяется на РАВЕНСТВО.
      # Поиск ключа «где-нибудь в строке» отвергнут пробой (VG-20): причина, лишь УПОМЯНУВШАЯ
      # соседний ключ («…к M-60b отношения не имеет»), гасила его. Токен обязан НАЗЫВАТЬ свой
      # предмет, а не содержать его имя.
      tokkey="${rest%%[[:space:]]*}"
      [ "${tokkey}" = "$1" ] || continue
      reason="${rest#"${tokkey}"}"
      __r="${reason//[[:space:]]/}"
      [ "${#__r}" -ge 12 ] || continue
      printf '%s' "${c}"
      return 0
    done < <(git log -1 --format='%B' "${c}" 2>/dev/null || true)
  done < <(git rev-list "${BASE}..HEAD" 2>/dev/null || true)
  return 1
}

# ── 4. Разбор вердиктов диапазона ─────────────────────────────────────────────────────
changes="$(git diff --name-status --diff-filter=AM "${BASE}" HEAD -- ${VERDICT_DIRS} 2>/dev/null || true)"

declare -A KEY_ORD=()      # позиция последнего вердикта ключа
declare -A KEY_VERD=()     # его исход
declare -A KEY_FILE=()     # его файл
declare -A KEY_REFUSED=()  # 1, если на позиции KEY_ORD есть отказ

judged=0
headless=0
while IFS="$(printf '\t')" read -r st f; do
  [ -n "${f}" ] || continue
  case "${f}" in *.md) ;; *) continue ;; esac

  body="$(git show "HEAD:${f}" 2>/dev/null || true)"
  meta="$(gate_meta_block "${body}")"
  if [ -z "${meta}" ]; then
    # Ключа нет ⇒ судить нечего. Дыру закрывает джоб `gate-meta` в том же агрегате (см. шапку).
    headless=$((headless + 1))
    note "${f}: шапки GATE-META нет — ключ не определён, ключевое правило не применяется (роняет джоб gate-meta)"
    continue
  fi

  key="$(gate_meta_field milestone "${meta}")"
  vd="$(gate_meta_field verdict "${meta}")"

  if [ -z "${key}" ]; then
    bad "${f}: поле milestone пусто — предмет вердикта НЕИЗВЕСТЕН, погашение проверить не по чему"
    continue
  fi
  if [ -z "${vd}" ]; then
    bad "${f}: поле verdict пусто — исход НЕИЗВЕСТЕН, «непусто» не значит «проходной»"
    continue
  fi
  if ! gate_meta_in_list "${vd}" "${GATE_META_VERDICT_ENUM}"; then
    bad "${f}: verdict «${vd}» вне перечня (${GATE_META_VERDICT_ENUM}) — НЕИЗВЕСТНО, а не «похоже на проходной»"
    continue
  fi

  judged=$((judged + 1))
  ord="${FILE_ORD[${f}]:-0}"
  refused=0
  gate_meta_is_passing "${vd}" || refused=1

  if [ "${ord}" -eq 0 ]; then
    # Порядок недоказуем: отказ БЛОКИРУЕТ, проходной НЕ ГАСИТ.
    if [ "${refused}" -eq 1 ]; then
      note "${f}: позиция в диапазоне не определена (рождён merge'ем?) — отказ засчитан fail-closed"
      KEY_ORD["${key}"]="${KEY_ORD[${key}]:-0}"
      KEY_REFUSED["${key}"]=1
      KEY_VERD["${key}"]="${vd}"
      KEY_FILE["${key}"]="${f}"
    else
      note "${f}: позиция в диапазоне не определена — проходной исход НЕ засчитан как погашение"
    fi
    continue
  fi

  prev="${KEY_ORD[${key}]:--1}"
  if [ "${ord}" -gt "${prev}" ]; then
    KEY_ORD["${key}"]="${ord}"
    KEY_VERD["${key}"]="${vd}"
    KEY_FILE["${key}"]="${f}"
    KEY_REFUSED["${key}"]="${refused}"
  elif [ "${ord}" -eq "${prev}" ] && [ "${refused}" -eq 1 ]; then
    # Один коммит, два вердикта на ключ: «позже» не определено ⇒ отказ побеждает.
    KEY_VERD["${key}"]="${vd}"
    KEY_FILE["${key}"]="${f}"
    KEY_REFUSED["${key}"]=1
  fi
done <<EOF
${changes}
EOF

# ── 5. Решение по ключам ──────────────────────────────────────────────────────────────
# Порядок обхода ключей ОТСОРТИРОВАН: итерация по ассоциативному массиву в bash не упорядочена,
# и вывод барьера обязан быть воспроизводимым от прогона к прогону.
blocked=0
cleared=0
while IFS= read -r key; do
  [ -n "${key}" ] || continue
  [ "${KEY_REFUSED[${key}]:-0}" -eq 1 ] || continue
  if tok="$(cleared_token_for "${key}")"; then
    note "ключ ${key}: отказ (${KEY_VERD[${key}]}, ${KEY_FILE[${key}]}) погашен явным VERDICT-CLEARED в ${tok:0:8} (аудит-след, НЕ доказательство устранения находок)"
    cleared=$((cleared + 1))
    continue
  fi
  blocked=$((blocked + 1))
  bad "ключ ${key}: последний вердикт диапазона — ${KEY_VERD[${key}]} (${KEY_FILE[${key}]}); проходного по тому же ключу позже НЕТ"
  echo "      погашение — вердикт с проходным исходом по ключу ${key} ОТДЕЛЬНЫМ коммитом позже,"
  echo "      либо строка «VERDICT-CLEARED: ${key} — <причина ≥12 символов>» в теле коммита диапазона"
done < <(printf '%s\n' ${KEY_ORD[@]+"${!KEY_ORD[@]}"} | sort)

# ── 6. Итог ───────────────────────────────────────────────────────────────────────────
# Наблюдение ОТСУТСТВИЯ: «в диапазоне вердиктов не было» — законное состояние, и оно ПЕЧАТАЕТСЯ
# явно, чтобы «пусто» не читалось как «не запускалось» (`testing.md`, целостность гейта, св-во 4).
echo
echo "вердиктов в диапазоне: судимых ${judged}, без шапки ${headless}; ключей ${#KEY_ORD[@]}; погашено токеном ${cleared}"
if [ "${FAILED}" -gt 0 ]; then
  echo "VERDICT: FAIL (${FAILED}) — ветка несёт непогашенный отказ либо непригодную шапку; merge держится"
  exit 1
fi
echo "VERDICT: PASS — ни один ключ диапазона не оставлен в отказном состоянии"
