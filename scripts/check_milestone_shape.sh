#!/usr/bin/env bash
# check_milestone_shape.sh — барьер формы milestone-спеки.
#
# ЗАЧЕМ (замер, а не принцип). `docs/04-workflow.md` §6 задаёт форму milestone-контракта, но
# механизма у неё не было. 2026-08-18 architect подал набор M-69 без раздела `Allowed paths`;
# критик отклонил его (`C-099` B-1) — то есть класс поймал ЧЕЛОВЕКО-круг гейта, стоивший
# полного цикла: правка на десять строк против вердикта, номера артефакта и диспетчеризации.
# `docs/workflow/binding-requires-mechanism.md`: проза не принуждает, принуждают скрипты.
#
# ЧТО ПРОВЕРЯЕТ. Только milestone-файлы, ВВЕДЁННЫЕ В ЗОНУ в проверяемом диапазоне —
# `--diff-filter=AR`, а не `A`. Четыре несущих раздела: Objective · Allowed paths · §Tasks ·
# Acceptance.
#
# ПОЧЕМУ `AR`, А НЕ `A` (`C-101` B-3, воспроизведено). Git числит `milestones/M-98-old.md` →
# `milestones/M-99-renamed.md` статусом `R100`, а не `A`. При фильтре `A` барьер печатал
# «новых milestone-спек нет» и возвращал 0: НОВОЕ имя получало форму, которую никто не
# проверял. `--name-only` при `R` печатает ИМЕННО НОВЫЙ путь (проверено), поэтому смена
# фильтра — весь фикс. `C` в фильтр не добавлен намеренно: обнаружение копий требует `-C`,
# который здесь не передаётся, и статус `C` возникнуть не может — добавлять его значило бы
# изображать покрытие сценария, недостижимого этой проводкой.
#
# ПОЧЕМУ ТОЛЬКО ВВЕДЁННЫЕ — замер 2026-08-18 по `milestones/M-*.md` (53 файла):
#     без `Allowed paths` — 36 · без `§Tasks` — 31 · без `Acceptance` — 30 · без `Objective` — 20
# Барьер, проверяющий ВСЕ спеки, был бы красным с рождения, а такой барьер «объявляют шумом и
# выключают» (`docs/workflow/harness-track.md` §3). Проверка ИЗМЕНЁННЫХ файлов тоже отвергнута:
# правка одной строки в старой спеке заставляла бы дописывать четыре раздела и блокировала бы
# работу, не связанную с формой.
#
# ═══ ГРАММАТИКА, КОТОРУЮ БАРЬЕР ОБЕЩАЕТ (названа по требованию `C-176`) ═══
# Барьер НЕ реализует CommonMark и больше не заявляет, что оставляет «видимое CommonMark-тело».
# Четвёртый круг адверсария показал, почему: каждая починка закрывала ОДНО правило спецификации,
# а следующий круг находил соседнее (символ забора → длина и хвост → сырой HTML → граница титула).
# Догонять спецификацию правилом за правилом в awk — проигранная гонка; вместо этого объявлена
# УЗКАЯ грамматика, и всё, что вне неё, РАЗДЕЛОМ НЕ СЧИТАЕТСЯ (fail-closed, не fail-open):
#
#   РАЗДЕЛ = строка, начинающаяся С КОЛОНКИ 0 (ни одного ведущего пробела или табуляции),
#            вида `##`/`###`, затем ОДИН ИЛИ БОЛЕЕ пробелов, затем ТОЧНОЕ имя раздела,
#            затем допускается только необязательная закрывающая ATX-последовательность `#`
#            и пробелы до конца строки.
#   НЕ РАЗДЕЛ (скрыто): fenced-code (``` и ~~~), HTML-комментарий, сырой HTML-блок
#            (`pre`, `script`, `style`, `textarea`) до своего закрывающего тега.
#   НЕ РАЗДЕЛ (не совпадёт): любой отступ; `##Allowed paths` без пробела; `#### X`;
#            `## Allowed pathsXXX` — иной заголовок, разделяющий префикс.
#
# СУЖЕНИЕ ОБЪЯВЛЕНО, А НЕ УМОЛЧАНО (`C-176` B-11): CommonMark допускает у ATX-заголовка до трёх
# ведущих пробелов; мы их НЕ допускаем. Направление безопасное — легитимно отступленный
# заголовок будет ОТВЕРГНУТ, и автор перепишет его с колонки 0. Шаблон `04-workflow` §6 пишет
# заголовки с колонки 0, так что цена сужения — ноль, а выигрыш в том, что граница
# «заголовок против indented-code» перестаёт зависеть от подсчёта пробелов.
#
# ЗАКРЫТИЕ ЗАБОРА — ТРИ УСЛОВИЯ, А НЕ ОДНО (`C-175` B-8, воспроизведено). Тот же символ,
# длина НЕ МЕНЬШЕ открывающей, и после маркера только пробелы. Круг 3 хранил лишь символ:
# ```` закрывался ```, а ``` с текстом после него считался закрытием — оба входа оставляли
# раздел ВНУТРИ фенса при зелёном барьере.
#
# ЗАГОЛОВОК — ATX-ФОРМА, А НЕ ПРЕФИКС (`C-173` B-6, воспроизведено). Регексп требует
# `#{2,3} +имя`: между решётками и именем ОБЯЗАН быть пробел. Прежняя редакция писала ` *`
# (ноль и более), и `##Allowed paths` печаталось `OK` при exit=0 — а это не заголовок ATX и
# не раздел по `docs/04-workflow.md` §6. Глубина `#{2,3}` при этом ЗНАЧИМА: `#### Allowed
# paths` отвергается, потому что после первых двух-трёх решёток обязан идти пробел, а идёт
# решётка.
#
# ЗАГОЛОВОК СЧИТАЕТСЯ ТОЛЬКО В ВИДИМОМ ТЕЛЕ (`C-101` B-1, воспроизведено). Строка
# `## Allowed paths` внутри ```-фенса или внутри `<!-- -->` — ПРИМЕР или закомментированный
# черновик, а не раздел этого документа. Прежняя редакция подавала весь Markdown в `grep` и
# печатала `OK` для спеки, у которой настоящего раздела нет, а есть образец в фенсе: ложное
# зелёное ровно на обещанном инварианте. Фенс распознаётся по ``` и ~~~ с отступом до трёх
# пробелов (правило CommonMark), комментарий — по паре `<!--`/`-->`, в том числе однострочной.
#
# ПРЕДЕЛ, НАЗВАННЫЙ ЧЕСТНО. Барьер НЕ заставляет 36 старых спек дорасти до формы — миграция
# остаётся открытой и не блокирует. Барьер проверяет НАЛИЧИЕ раздела, а не его осмысленность:
# `## Allowed paths` с пустым телом пройдёт. Это тот же класс предела, что у `FOUNDER-APPROVED`
# (`gates.md` §11) — токен ловит отсутствие строки, а не ложность причины. Отдельно: заголовок
# в НЕЗАКРЫТОМ фенсе до конца файла считается скрытым — это осознанный fail-closed выбор
# (незакрытый фенс делает документ нечитаемым и без нас).
set -uo pipefail

die() { echo "FAIL  $*" >&2; echo "      ↳ Барьер fail-closed: база не установлена достоверно." >&2; exit 1; }

# ── база из СОБЫТИЯ (та же проводка, что check_artifact_ids.sh / check_protected_artifacts.sh) ──
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}" ;;
    pull_request) raw="${PR_BASE_SHA:-}" ;;
    "")           die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *)            die "неизвестное событие '${EVENT_NAME}' — база не определена" ;;
  esac
fi
[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?})"
case "${raw}" in
  *[!0]*) : ;;
  *)      die "база = zero-SHA (создание ветки / force-push) — что введено, недоказуемо" ;;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || die "база '${raw}' отсутствует в истории (force-push / поверхностный клон)"
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || die "база '${raw}' НЕ предок HEAD — история переписана; что введено, недоказуемо"

BASE="${raw}"

# ── введённые milestone-спеки в диапазоне ────────────────────────────────────────────
# `-z`: git КВОТИРУЕТ не-ASCII имена в текстовом режиме, и файл под русским именем выпал бы
# из проверки молча (тот же класс, что `R-046` Б-3 в check_artifact_ids.sh).
mapfile -d '' -t added < <(
  git diff --diff-filter=AR --name-only -z "${BASE}" HEAD -- 'milestones/M-*.md' 2>/dev/null
)

if [ "${#added[@]}" -eq 0 ]; then
  echo "OK: в диапазоне ${BASE:0:7}..HEAD новых milestone-спек нет — проверять нечего"
  exit 0
fi

# ── обязательные разделы: имя → regex заголовка ──────────────────────────────────────
# Форма допускает `## X` и `### X`; `§` перед Tasks необязателен. Регистр игнорируется:
# спеки пишут и «Objective», и «objective».
FAIL=0

# Тело БЕЗ fenced-code и БЕЗ HTML-комментариев: заголовок засчитывается только здесь.
visible_body() {
  git show "HEAD:$1" 2>/dev/null | awk '
    # ГРАММАТИКА НАЗВАНА ЯВНО (C-176). Барьер НЕ реализует CommonMark и не притворяется:
    # он СКРЫВАЕТ три формы, внутри которых заголовок заголовком не является, — fenced-code,
    # HTML-комментарий и СЫРОЙ HTML-БЛОК (pre/script/style/textarea). Всё остальное считается
    # видимым телом. Сужения перечислены в шапке файла, а не подразумеваются.
    #
    # C-175 B-8: забор закрывается ТРЕМЯ условиями — тот же символ, длина не меньше
    # открывающей, после маркера только пробелы.
    # C-176 B-9: `<script>## Allowed paths</script>` печатался как видимое тело, и барьер
    # возвращал 0 при отсутствии настоящего раздела. По CommonMark pre/script/style/textarea
    # открывают сырой HTML-блок до СВОЕГО закрывающего тега; разметка внутри разметкой не является.
    BEGIN { fence = 0; fchar = ""; flen = 0; comment = 0; html = 0; htag = "" }
    {
      line = $0
      lower = tolower(line)
      body = line
      indent = 0
      while (substr(body, 1, 1) == " ") { indent++; body = substr(body, 2) }
      c = substr(body, 1, 1)
      run = 0
      if (c == "`" || c == "~") { while (substr(body, run + 1, 1) == c) run++ }
      rest = substr(body, run + 1)
      # Отступ >3 пробелов — это indented code, а не забор (CommonMark).
      is_marker = (run >= 3 && indent <= 3)
      tail_blank = (rest ~ /^[ \t]*$/)

      if (fence == 1) {
        if (is_marker && c == fchar && run >= flen && tail_blank) { fence = 0 }
        next
      }
      if (html == 1) {
        if (index(lower, "</" htag ">") > 0) { html = 0; htag = "" }
        next
      }
      if (comment == 1) { if (line ~ /-->/) comment = 0; next }
      if (is_marker) { fchar = c; flen = run; fence = 1; next }
      if (line ~ /<!--/) { if (line !~ /-->/) comment = 1; next }
      # Сырой HTML-блок: открывающий тег одной из четырёх форм, закрытие — свой тег.
      # Однострочная форма `<script>…</script>` схлопывается тут же и телом не считается.
      if (match(lower, /<(pre|script|style|textarea)[ \t>]/) || match(lower, /<(pre|script|style|textarea)$/)) {
        t = substr(lower, RSTART + 1, RLENGTH - 1)
        gsub(/[ \t>]$/, "", t)
        htag = t
        if (index(lower, "</" htag ">") == 0) { html = 1 }
        next
      }
      print line
    }'
}

check_section() {
  local file="$1" human="$2" re="$3"
  if visible_body "${file}" | grep -qiE "${re}"; then
    return 0
  fi
  echo "FAIL  ${file}: отсутствует обязательный раздел «${human}»" >&2
  FAIL=$((FAIL + 1))
}

for f in "${added[@]}"; do
  [ -n "$f" ] || continue
  echo "=== проверяю форму: $f ==="
  check_section "$f" "Objective"     '^#{2,3} +Objective[ \t]*#*[ \t]*$'
  check_section "$f" "Allowed paths" '^#{2,3} +Allowed paths[ \t]*#*[ \t]*$'
  check_section "$f" "§Tasks"        '^#{2,3} +§?Tasks[ \t]*#*[ \t]*$'
  check_section "$f" "Acceptance"    '^#{2,3} +Acceptance[ \t]*#*[ \t]*$'
done

if [ "$FAIL" -ne 0 ]; then
  cat >&2 <<'MSG'

Форма milestone-контракта задана `docs/04-workflow.md` §6. Без `Allowed paths` critic не может
выполнить scope-блок (`gates.md` §4), а dev не знает границы своей зоны — и заполняет пробел
по-своему, имея на это право (`testing.md` §«Спека правки существующего кода»).
Основание барьера: `C-099` B-1 — набор M-69 подан без этого раздела и стоил круга гейта.
MSG
  exit 1
fi

echo "OK: все введённые milestone-спеки несут обязательные разделы формы (§6)"
exit 0
