#!/usr/bin/env bash
# Механический барьер: ЗАКРЫТИЕ ПРЕДМЕТА НЕ ПРОХОДИТ МОЛЧА МИМО РОАДМАПА.
#
# Требование founder'а 2026-09-07: роадмап, который architect читает на старте и с которого
# продолжает. У нас его не было, и это не оплошность сессии, а дефект процесса: на вопрос
# «что дальше» отвечали ШЕСТЬ документов, ни один не главный, а преемственность фактически
# жила в 23 записках сессий — каждая пересказ памяти предыдущей. Цена замерена: план из 11
# пунктов от 2026-09-05 содержал ПЯТЬ ошибок, вскрытых аудитом 2026-09-07.
#
# ── ПОЧЕМУ БЕЗ БАРЬЕРА НЕЛЬЗЯ ────────────────────────────────────────────────────────
# У нас действует обязывающее правило: новое требование живёт вместе со СВОИМ механизмом
# либо объявляет себя когнитивным (`gates.md` §11, `docs/workflow/binding-requires-mechanism.md`).
# Шесть документов выше протухли ровно потому, что их обновление держалось на намерении.
# Седьмой такой же не нужен: у `SESSION-HANDOFF.md` в заголовке написано «живой индекс», и
# он протух на девять дней.
#
# ── ЧТО ИМЕННО ПРОВЕРЯЕТСЯ ───────────────────────────────────────────────────────────
# Триггер — CLOSE-OUT: коммит(ы) диапазона уносят спеку милестоуна в `docs/archive/M-*.md`.
# Это наблюдаемый и однозначный признак закрытия предмета (норма переезда — `04-workflow.md`
# §Close-out). При сработавшем триггере `docs/ROADMAP.md` обязан быть тронут В ТОМ ЖЕ
# ДИАПАЗОНЕ.
#
# Почему триггер именно переезд, а не «милестоун закрыт»: закрытость машинно НЕ ВЫВОДИТСЯ —
# `R-098` §3.1 предъявил три ревизии машинного критерия по прозе `PROJECT-STATE.md`, давшие
# ТРИ РАЗНЫХ ответа. Барьер, притворяющийся, что умеет вычислить суждение, хуже
# отсутствующего. Переезд же — факт дерева: файл был в `milestones/`, стал в `docs/archive/`.
#
# ── ПРЕДЕЛ НАЗВАН, А НЕ ИЗОБРАЖЁН ────────────────────────────────────────────────────
# Барьер ловит ОТСУТСТВИЕ правки роадмапа, а не её ОСМЫСЛЕННОСТЬ: строка, обновлённая
# неверно, пройдёт. Это тот же класс предела, что у `FOUNDER-APPROVED` (`gates.md` §11) —
# контур видит наличие, не истинность. Против неверной строки работает круг гейта.
# Второй предел: барьер молчит, когда предмет ЗАБРОШЕН без переезда — заброшенность
# наблюдаемого признака не имеет вовсе.
#
# Проба: `scripts/tests/red_roadmap_sync.sh` — анти-плацебо в обе стороны.
set -uo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")/.." || { echo "FAIL  не удалось встать в корень репозитория"; exit 1; }

ROADMAP="docs/ROADMAP.md"

die() { echo "FAIL  $*"; echo; echo "Барьер fail-closed: база сравнения не установлена достоверно."; exit 1; }

# ── БАЗА СРАВНЕНИЯ = СОСТОЯНИЕ ДО СОБЫТИЯ ───────────────────────────────────────────
# Та же дисциплина и по той же причине, что у `check_protected_artifacts.sh`: на push-событии
# `actions/checkout` ставит `origin/main` на ТОЛЬКО ЧТО запушенный коммит, поэтому диапазон
# от `origin/main` пуст и барьер был бы зелёным ВСЕГДА.
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}" ;;
    pull_request) raw="${PR_BASE_SHA:-}" ;;
    "")           die "событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" ;;
    *)            die "неизвестное событие '${EVENT_NAME}' — база сравнения не определена" ;;
  esac
fi
[ -n "${raw}" ] || die "база события пуста (EVENT_NAME=${EVENT_NAME:-?})"
case "${raw}" in
  *[!0]*) : ;;
  *)      die "база = zero-SHA (создание ветки или force-push) — диапазон не определим" ;;
esac
git rev-parse --verify --quiet "${raw}^{commit}" >/dev/null || die "база ${raw} отсутствует в истории"
BASE="$(git rev-parse "${raw}^{commit}")"

# ── 0. РОАДМАП ОБЯЗАН СУЩЕСТВОВАТЬ И НЕ БЫТЬ ЗАГЛУШКОЙ ──────────────────────────────
# Пустой файл удовлетворил бы проверку «тронут» и обнулил бы весь смысл барьера.
if [ ! -f "$ROADMAP" ]; then
  echo "FAIL  $ROADMAP отсутствует — единственный источник порядка работ снесён"
  echo "VERDICT: FAIL"
  exit 1
fi
ITEMS="$(grep -cE '^\| *[0-9]+ *\|' "$ROADMAP" || true)"
if [ "${ITEMS:-0}" -lt 3 ]; then
  echo "FAIL  $ROADMAP несёт $ITEMS пунктов плана (нужно ≥3) — файл выхолощен до заглушки"
  echo "VERDICT: FAIL"
  exit 1
fi

# ── 1. ТРИГГЕР: переезд спеки милестоуна в архив ────────────────────────────────────
# `--diff-filter=A` по `docs/archive/M-*.md`: переезд `git mv` виден как добавление в
# целевом пути независимо от того, распознал git переименование или нет.
mapfile -t ARCHIVED < <(git diff --name-only --diff-filter=A "${BASE}..HEAD" -- 'docs/archive/M-*.md' 2>/dev/null || true)

if [ "${#ARCHIVED[@]}" -eq 0 ] || [ -z "${ARCHIVED[0]:-}" ]; then
  echo "OK: close-out в диапазоне ${BASE:0:8}..HEAD не обнаружен — роадмап не обязан меняться"
  echo "    (в плане пунктов: $ITEMS)"
  echo "VERDICT: PASS"
  exit 0
fi

# ── 2. ПРИ СРАБОТАВШЕМ ТРИГГЕРЕ РОАДМАП ОБЯЗАН БЫТЬ ТРОНУТ ──────────────────────────
TOUCHED="$(git diff --name-only "${BASE}..HEAD" -- "$ROADMAP" 2>/dev/null || true)"
if [ -n "$TOUCHED" ]; then
  echo "OK: close-out (${#ARCHIVED[@]}) сопровождён правкой $ROADMAP"
  for a in "${ARCHIVED[@]}"; do echo "    закрыт: $a"; done
  echo "VERDICT: PASS"
  exit 0
fi

echo "FAIL  предмет закрыт, а порядок работ не обновлён:"
for a in "${ARCHIVED[@]}"; do echo "        $a уехал в архив"; done
echo "      $ROADMAP в диапазоне ${BASE:0:8}..HEAD НЕ ТРОНУТ"
echo
echo "Закрытие предмета — это и есть момент, когда роадмап меняется: пункт получает"
echo "состояние, а следующий становится первым. Пропуск этого шага и есть механизм, которым"
echo "протухли ШЕСТЬ предыдущих документов о планах (замер — шапка docs/ROADMAP.md)."
echo
echo "Колонка «Состояние» — зона reviewer'а; перечень и порядок — зона architect'а."
echo "VERDICT: FAIL"
exit 1
