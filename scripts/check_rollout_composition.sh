#!/usr/bin/env bash
# Барьер состава записи — TD-196 (закрывает TD-194 и R-168 Н-2).
# Проба: scripts/tests/red_rollout_composition.sh
#
# ЗАЧЕМ. Состав записываемых данных — граница C (`gates.md` §0.1): его меняет подпись
# владельца, не инженер. Пока M-45 шёл через гейты, литерал сторожили шаги T10/T10c
# в `scripts/verify_M-45.sh`. Замер при close-out (`TD-194`): `grep -c 'verify_M-45'
# .github/workflows/ci.yml` → 0. То есть защита ИСТЕКЛА В МОМЕНТ MERGE'А — следующий
# коммит, дописавший символ в `docker-compose.yml`, не встретил бы ни одного красного
# джоба. Класс «built-not-wired» наоборот: механизм построен и отключён приёмкой.
#
# ЧТО ИМЕННО ПРОВЕРЯЕТСЯ — не «символы равны BTCUSDT,ETHUSDT», а СОГЛАСОВАННОСТЬ трёх мест:
#   1. `docker-compose.yml` — что получит recorder;
#   2. блок `ACTIVE-COMPOSITION` в `docs/data-epochs.md` — что объявлено действующим;
#   3. `docs/PENDING-SIGNATURE.md` — что подпись, названная декларацией, существует.
# Зашитых символов в барьере НЕТ намеренно: состав меняется с каждой новой подписью, и
# барьер с константой пришлось бы править кодом при каждом решении границы C — то есть
# совершать решение владельца правкой кода (`M-45` §1 против этого и написан).
#
# ── КОДЫ ВОЗВРАТА ─────────────────────────────────────────────────────────────────────
#   0 — три места согласованы; состав записан ЛИТЕРАЛОМ; подпись существует.
#   1 — расхождение (перечисляются ВСЕ, а не первое).
#   2 — предмет не установлен достоверно: нет файла, нет/дублируется блок декларации,
#       не найден сервис recorder, недоступен python/pyyaml. Fail-closed: «проверять
#       нечего» никогда не равно «всё хорошо» (`testing.md` §«Целостность гейта» св. 3).
#
# ПЕРЕМЕННЫЕ ROOT/COMPOSE/EPOCHS/SIGNATURES существуют ДЛЯ ПРОБЫ. Прод-форма — без них.

set -uo pipefail

ROOT="${ROOT:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
COMPOSE="${COMPOSE:-$ROOT/docker-compose.yml}"
EPOCHS="${EPOCHS:-$ROOT/docs/data-epochs.md}"
SIGNATURES="${SIGNATURES:-$ROOT/docs/PENDING-SIGNATURE.md}"
CLI="${CLI:-$ROOT/scripts/lib/rollout_symbols_check.py}"

setup_fail() { echo "FAIL  SETUP НЕ СОСТОЯЛСЯ — $*"; echo; echo "VERDICT: FAIL (setup)"; exit 2; }

for f in "$COMPOSE" "$EPOCHS" "$SIGNATURES" "$CLI"; do
  [ -r "$f" ] || setup_fail "нечитаем или отсутствует: $f"
done
command -v python3 >/dev/null 2>&1 || setup_fail "python3 недоступен"

# ── Декларация: блок обязан быть РОВНО ОДИН ───────────────────────────────────────────
# Ноль блоков = состав никем не объявлен; два = неизвестно, какой действует. Оба случая —
# отказ, а не выбор первого попавшегося.
# Открывающих блоков ровно один. Ноль = состав никем не объявлен; два = неизвестно, какой
# действует. Оба — отказ, а не выбор первого попавшегося.
# ЛОЖНОЕ КРАСНОЕ НАЗВАНО (`C-206` Н-4): будущий fenced-ПРИМЕР блока в документе даст
# OPEN_N=2 и exit 2. Это красное громкое и ложное, но fail-closed, и цена принята: пример
# оформляется отступом, а не второй копией маркера.
OPEN_N=$(grep -c '^<!-- ACTIVE-COMPOSITION[[:space:]]*$' "$EPOCHS" || true)
[ "$OPEN_N" -eq 1 ] || setup_fail "блоков ACTIVE-COMPOSITION в $EPOCHS: $OPEN_N (нужен ровно 1)"

# Блок обязан быть ЗАКРЫТ (`C-206` Б-3 S1). Без этого стража `awk` молча берёт всё до EOF:
# незакрытый блок прячет весь документ внутрь HTML-комментария, поля при этом находятся, и
# барьер зеленел на файле, который в рендере исчез.
CLOSE_N=$(awk '/^<!-- ACTIVE-COMPOSITION[[:space:]]*$/{f=1;next} f&&/^-->[[:space:]]*$/{print;exit}' "$EPOCHS" | wc -l)
[ "$CLOSE_N" -eq 1 ] || setup_fail "блок ACTIVE-COMPOSITION не закрыт '-->' в $EPOCHS"

# `tr -d '\r'` — против CRLF (`C-206` Н-1): невидимый хвостовой возврат каретки давал
# ложное красное с ВРУЩЕЙ диагностикой («X не равен X» при визуально одинаковых значениях).
DECL="$(awk '/^<!-- ACTIVE-COMPOSITION[[:space:]]*$/{f=1;next} f&&/^-->[[:space:]]*$/{exit} f' "$EPOCHS" | tr -d '\r')"

# Единственность КАЖДОГО ПОЛЯ, а не только блока (`C-206` Б-3 S2). Прежняя редакция брала
# `head -1`: собственная философия барьера («два = неизвестно, какой действует») была
# применена к блокам и не применена к полям, и низ блока, видимый человеку, судьёй не был.
# ВАЖНО: проверка единственности вынесена ИЗ подстановки. `setup_fail` внутри `$( )`
# завершал бы ПОДОБОЛОЧКУ, а не барьер — поле молча становилось пустым, и вместо кода 2
# («предмет не установлен») получался код 1 («нарушение»). Поймано собственной пробой.
for fld in epoch_id l2delta_symbols signature; do
  n=$(printf '%s\n' "$DECL" | grep -cE "^$fld:" || true)
  [ "$n" -eq 1 ] || setup_fail "поле '$fld' в декларации встречается $n раз (нужно ровно 1)"
done
decl_field() { printf '%s\n' "$DECL" | sed -n "s/^$1:[[:space:]]*//p"; }

D_EPOCH="$(decl_field epoch_id)"
D_SYMS="$(decl_field l2delta_symbols)"
D_SIGN="$(decl_field signature)"
for pair in "epoch_id:$D_EPOCH" "l2delta_symbols:$D_SYMS" "signature:$D_SIGN"; do
  [ -n "${pair#*:}" ] || setup_fail "в декларации пусто поле ${pair%%:*}"
done

# ── Что получит recorder: снимается ТЕМ ЖЕ CLI, что судит форму значения ──────────────
# `Р-1`: мера на границе потребителя. Второй разбор YAML здесь был бы редекларацией —
# ошибка, уже стоившая круга гейта на M-45 (`C-202` B-2).
EX_OUT="$(python3 "$CLI" --extract "$COMPOSE" 2>&1)"; EX_ST=$?
[ "$EX_ST" -eq 0 ] || setup_fail "извлечение конфигурации вернуло $EX_ST: $EX_OUT"
C_SYMS="$(printf '%s\n' "$EX_OUT" | sed -n 's/^L2DELTA_CAPTURE_SYMBOLS=//p')"
C_EPOCH="$(printf '%s\n' "$EX_OUT" | sed -n 's/^EPOCH_ID=//p')"
[ -n "$C_SYMS" ] && [ -n "$C_EPOCH" ] || setup_fail "в выводе --extract нет ожидаемых строк: $EX_OUT"

BAD=0
bad() { echo "FAIL  $*"; BAD=$((BAD + 1)); }
ok()  { echo "PASS  $*"; }

# ── 1. Состав: ЛИТЕРАЛ и равен объявленному ──────────────────────────────────────────
# Подстановка `${VAR:-...}` выглядит подписанной и переопределяется одной переменной
# окружения хоста — эффективный обход подписи (`M-45` §3quinquies, находка `C-202` B-1).
if printf '%s' "$C_SYMS" | grep -qE '\$\{[^}]*\}|\$[A-Za-z_][A-Za-z0-9_]*'; then
  bad "состав записан ПОДСТАНОВКОЙ ($C_SYMS) — переопределяется окружением, подпись не удержана"
# Ветка ИЗБЫТОЧНА по исходу и оставлена ради ДИАГНОСТИКИ (`C-206` Н-2): её случай ловит и
# сверка равенства ниже с тем же кодом, поэтому мутация ветки пробу не роняет. Названо здесь,
# а не оставлено миной следующему редактору: убрать можно, но сообщение станет хуже.
elif [ "$C_SYMS" = "<ОТСУТСТВУЕТ>" ]; then
  bad "L2DELTA_CAPTURE_SYMBOLS отсутствует на сервисе recorder, а декларация объявляет '$D_SYMS'"
elif [ "$C_SYMS" != "$D_SYMS" ]; then
  bad "состав в compose ('$C_SYMS') НЕ РАВЕН объявленному в ACTIVE-COMPOSITION ('$D_SYMS') — \
изменение состава записи есть решение границы C и требует подписи владельца, а не правки конфига"
else
  ok "состав литералом и равен объявленному ($C_SYMS)"
fi

# ── 2. Эпоха: равна объявленной ──────────────────────────────────────────────────────
# Состав, сменившийся без смены эпохи, делает события двух составов машинно неразличимыми:
# класс E-001, стоивший разбора 123 млн событий постфактум.
if [ "$C_EPOCH" = "<ОТСУТСТВУЕТ>" ]; then
  bad "EPOCH_ID отсутствует на сервисе recorder, а декларация объявляет '$D_EPOCH'"
elif [ "$C_EPOCH" != "$D_EPOCH" ]; then
  bad "эпоха в compose ('$C_EPOCH') НЕ РАВНА объявленной ('$D_EPOCH') — граница эпохи разъедется с составом (E-001)"
else
  ok "эпоха равна объявленной ($C_EPOCH)"
fi

# ── 3. Подпись, названная декларацией, СУЩЕСТВУЕТ ────────────────────────────────────
# Барьер не судит содержание подписи — только что ссылка не висячая. Декларация, ссылающаяся
# в пустоту, есть та же ложь, что документ, обосновывающий инвариант несуществующим
# механизмом (класс `TD-138`).
# ФОРМА ссылки пиннится ДО подстановки в регексп (`C-206` Б-3 S3). Прежняя редакция
# интерполировала значение в ERE неэкранированным: декларация с `signature: .*` проходила на
# ЛЮБОМ файле подписей с любым `## `-заголовком, то есть не называя НИ ОДНОЙ подписи.
if ! printf '%s' "$D_SIGN" | grep -qE '^П-[0-9]+$'; then
  bad "поле signature ('$D_SIGN') не имеет формы П-<число> — ссылка на подпись обязана быть \
идентификатором, а не образцом: подстановка образца в поиск принимает любой заголовок"
elif grep -qE "^## ${D_SIGN}([^0-9]|$)" "$SIGNATURES"; then
  ok "подпись $D_SIGN существует в $(basename "$SIGNATURES")"
else
  bad "декларация ссылается на подпись '$D_SIGN', которой НЕТ в $(basename "$SIGNATURES") — висячая ссылка"
fi

# ── 4. СВЯЗКА ВО ВРЕМЕНИ: состав изменился ⇒ эпоха И подпись обязаны измениться ────────
# `C-206` Б-2. Проверки 1-3 сверяют ТРИ МЕСТА МЕЖДУ СОБОЙ в одном срезе — и потому пропускали
# мир, где состав расширен СИНХРОННО в compose и декларации, а эпоха и подпись прежние: три
# места согласованы, подпись существует, всё зелено. Между тем декларация обещает ровно
# обратное («тронув её, обязан назвать новую эпоху и подпись, которая состав разрешила»), а
# комментарий проверки 2 ссылается на E-001 — случай «состав сменился без смены эпохи»,
# который и был зелёным. Обещание без механизма есть та же ложь, что документ, обосновывающий
# инвариант несуществующим механизмом (класс `TD-138`).
#
# ЧТО ЭТО ДЕРЖИТ И ЧЕГО НЕ ДЕРЖИТ. Держит: расширить состав, не назвав НОВУЮ подпись,
# невозможно — то есть аудит-след существует всегда. НЕ держит: что названная подпись
# действительно разрешает именно этот состав. Семантику текста подписи механизм судить не
# может, и это предел, а не недоделка (`C-206` Б-2 п.3 признаёт разделение).
#
# БАЗА берётся из окружения; её ОТСУТСТВИЕ объявляется ГРОМКО, а не проглатывается: шаг,
# молча пропускающий проверку, неотличим от пройденной (`testing.md` св. 4).
BASE_SHA="${PR_BASE_SHA:-${BASE_REF:-}}"
if [ -z "$BASE_SHA" ]; then
  echo "SKIP  связка «состав↔эпоха↔подпись во времени» НЕ ПРОВЕРЕНА — база диапазона не задана \
(PR_BASE_SHA/BASE_REF пусты). В CI база передаётся джобом; локально это ожидаемо."
elif ! git -C "$ROOT" rev-parse --verify --quiet "$BASE_SHA^{commit}" >/dev/null 2>&1; then
  setup_fail "база '$BASE_SHA' не существует в истории — диапазон недостоверен"
else
  base_field() {
    git -C "$ROOT" show "$BASE_SHA:${EPOCHS#$ROOT/}" 2>/dev/null \
      | awk '/^<!-- ACTIVE-COMPOSITION[[:space:]]*$/{f=1;next} f&&/^-->[[:space:]]*$/{exit} f' \
      | tr -d '\r' | sed -n "s/^$1:[[:space:]]*//p" | head -1
  }
  B_SYMS="$(base_field l2delta_symbols)"; B_EPOCH="$(base_field epoch_id)"; B_SIGN="$(base_field signature)"
  if [ -z "$B_SYMS" ]; then
    echo "PASS  связка: на базе декларации ещё не было — сверять во времени нечего"
  elif [ "$B_SYMS" = "$D_SYMS" ]; then
    echo "PASS  связка: состав не менялся против базы ($D_SYMS)"
  else
    LINK=0
    [ "$B_EPOCH" != "$D_EPOCH" ] || { bad "состав изменён ('$B_SYMS' → '$D_SYMS'), а эпоха ОСТАЛАСЬ \
прежней ('$D_EPOCH') — события двух составов станут машинно неразличимы (класс E-001)"; LINK=1; }
    [ "$B_SIGN" != "$D_SIGN" ] || { bad "состав изменён ('$B_SYMS' → '$D_SYMS'), а подпись ОСТАЛАСЬ \
прежней ('$D_SIGN') — изменение состава записи есть решение границы C и требует НОВОГО решения \
владельца, а не переиспользования старого"; LINK=1; }
    [ "$LINK" -eq 1 ] || echo "PASS  связка: состав изменён вместе с новой эпохой и новой подписью"
  fi
fi

echo
if [ "$BAD" -gt 0 ]; then
  echo "VERDICT: FAIL ($BAD нарушений)"
  exit 1
fi
echo "VERDICT: PASS — состав, эпоха и подпись согласованы"
exit 0
