#!/usr/bin/env bash
# gc_holder.sh — решение «держит ли кто-то это дерево», ВЫНЕСЕННОЕ В ОТДЕЛЬНЫЙ ПРОЦЕСС.
#
# Предписание арбитра `A-020` (research/arbitration/A-020-three-guards-canary-vs-isolation.md),
# пункт 1. Созыв арбитража — `gates.md` §0: семь кругов гейта по одному предмету
# (`C-140` `C-141` `C-145` `C-146` `C-147` `C-150` `C-151`).
#
# ── ЗАЧЕМ ОТДЕЛЬНЫЙ ПРОЦЕСС, А НЕ ФУНКЦИЯ ─────────────────────────────────────────────
# Инвариант: решение о держателе — функция ДЕРЕВА и состояния `/proc`, и ничего больше. Ни
# один параметр вызова `gc_worktrees.sh` (`MODE`, `DRY`, `IDLE_H`) не имеет права на него
# влиять. Пять кругов подряд критик находил условность по очередной переменной, шестой и
# седьмой — дефекты САМОГО инструмента, которым эту условность ловили (текстовая канарейка
# над телом функции: ложное красное на `honest=0` и `declare`, ложное зелёное на вложенной
# функции и на `local IDLE_H="$IDLE_H"`).
#
# Арбитр установил, почему это не чинится латанием: требование «различать значения по
# ИСТОЧНИКУ, а не по написанию имени» — свойство ПОТОКА ДАННЫХ, а канарейка есть регулярное
# выражение. В bash множество легальных каналов переноса значения ОТКРЫТО, и арбитр
# предъявил три следующих исполнением: `local IDLE_H="$IDLE_H"` (правая часть вычисляется
# ДО связывания), `local -n ref=IDLE_H` (nameref), `${!x}` (косвенное раскрытие); дальше
# `eval`, `printf -v`, `declare -p`. Инструмент воспроизводил ту самую болезнь, которую
# лечил: покрывал то, о чём вспомнил автор.
#
# Граница процесса эту болезнь снимает КОНСТРУКЦИЕЙ. Неэкспортированные переменные родителя
# ребёнку не видны; синтаксического обхода «изнутри тела» не существует, потому что тела в
# том же процессе больше нет.
#
# ── ПОЧЕМУ `env -i`, А НЕ ПРОСТО ДОЧЕРНИЙ ВЫЗОВ ───────────────────────────────────────
# Замер арбитра, case 2: атрибут `export` ПЕРЕЖИВАЕТ переприсваивание. Если вызывающая
# среда где-то сделала `export DRY`, то родительское `DRY=1` уедет ребёнку, и гарантия
# тихо исчезнет — она стала бы свойством чужого профиля. Поэтому вызов идёт через `env -i`
# с ЗАКРЫТЫМ позитивным белым списком: что не названо в строке вызова, того для этого
# процесса не существует. Запрет превращается из свойства, которое надо доказывать
# лексером, в свойство, читаемое в диффе ОДНОЙ строки.
#
# ── ИНТЕРФЕЙС (контракт с `gc_worktrees.sh`) ──────────────────────────────────────────
#   argv:   $1 — путь дерева; $2 — файл-счётчик неопрошенных чужих процессов
#   stdout: PID'ы держателей, по одному в строке, с прежними маркерами:
#             <pid>   — cwd внутри дерева (точное совпадение или префикс)
#             <pid>?  — cwd НЕЧИТАЕМ у процесса НАШЕГО uid (аномалия ⇒ fail-closed)
#             <pid>~  — cwd — АЛИАС того же каталога (совпал `dev:inode`)
#             ?       — `/proc` пуст/нечитаем целиком: «не знаю» ⇒ «держит»
#   exit:   0 — держит ЛИБО не знаю (fail-closed);  1 — точно никто не держит
#
# ── ЧТО ГАРАНТИЯ НЕ ПОКРЫВАЕТ (названо, а не подразумевается) ─────────────────────────
#   1. Открытые файлы: смотрим `cwd`, не `/proc/*/fd`. Процесс, работающий в дереве по
#      абсолютным путям из другого `cwd`, не ловится.
#   2. Чужие процессы с нечитаемым `cwd`: считаются и печатаются вызывающим, но не
#      блокируют — иначе инструмент мёртв (замер 24.08: 590 из 817 нечитаемых, 483 root).
#   3. Подкаталог ПОД алиасом дерева: у него свой инод, префикс не совпадёт.
#   4. `GC_PROC_ROOT` проходит через белый список — это ШОВ ПРОБЫ; прод его не задаёт.
#      Мутант, условный по самому шву, — известное ограничение любого шва.
set -uo pipefail

wt="${1:?путь дерева не задан}"
uninspect="${2:?файл-счётчик не задан}"

PROC_ROOT="${GC_PROC_ROOT:-/proc}"
MY_UID="$(id -u)"

found=0
readable=0
wtid="$(stat -c '%d:%i' "${wt}" 2>/dev/null || true)"

for p in "${PROC_ROOT}"/[0-9]*; do
  [ -e "${p}" ] || continue
  readable=1
  pid="${p##*/}"
  if ! t="$(readlink "${p}/cwd" 2>/dev/null)"; then
    # Сначала — умер ли процесс. В живом `/proc` доминирующая причина отказа `readlink` не
    # права, а исчезнувший PID; мёртвый держателем не является ни в каком смысле.
    [ -d "${p}" ] || continue
    if [ "$(stat -c '%u' "${p}" 2>/dev/null || echo -1)" = "${MY_UID}" ]; then
      echo "${pid}?"; found=1
    else
      printf 'x' >> "${uninspect}"
    fi
    continue
  fi
  t="${t% (deleted)}"
  case "${t}" in "${wt}" | "${wt}"/*) echo "${pid}"; found=1; continue ;; esac
  # Идентичность каталога решается парой устройство:инод, а не строкой: алиас (bind-mount,
  # путь через симлинк) ведёт в тот же инод по другому пути.
  if [ -n "${wtid}" ]; then
    cwdid="$(stat -Lc '%d:%i' "${p}/cwd" 2>/dev/null || true)"
    [ -n "${cwdid}" ] && [ "${cwdid}" = "${wtid}" ] && { echo "${pid}~"; found=1; }
  fi
done

[ "${readable}" = "1" ] || { echo "?"; exit 0; }
[ "${found}" = "1" ]
