#!/usr/bin/env bash
# scripts/check_docs_freeze.sh — замок процессного слоя M-60a.
#
# Инвариант (милестоун §3bis.1, формулировка от РЕЗУЛЬТАТА):
#   ни одно изменение зоны замка не попадает в проверяемый диапазон без токена
#   FOUNDER-APPROVED в СВОЁМ коммите — независимо от способа изменения, типа события и
#   формы истории.
#
# Зона замка (пять членов, не один префикс):
#   .claude/rules/** · .claude/agents/** · .claude/wrappers/** · CLAUDE.md · docs/04-workflow.md
#
# БАЗА СРАВНЕНИЯ — ИЗ СОБЫТИЯ (блокер B1, C-006). Прежняя проводка по `origin/main` давала
# ЛОЖНЫЙ гейт: на push-событии `actions/checkout` ставит origin/main на ТОЛЬКО ЧТО
# ЗАПУШЕННЫЙ коммит ⇒ `merge-base(origin/main, HEAD) == HEAD` ⇒ диапазон пуст ⇒ PASS ВСЕГДА.
# Правильная база:
#   push         → PUSH_BEFORE   (состояние ветки ДО пуша)
#   pull_request → PR_BASE_SHA   (база PR)
#   иначе        → EXIT 1 (неизвестное событие)
# Все формы «не могу установить базу достоверно» (пусто, zero-SHA при создании ветки или
# force-push, база отсутствует в истории, база НЕ предок HEAD ⇒ история переписана) →
# FAIL, а не пропуск: «базы нет» не значит «проверять нечего».
#
# ПРОВЕРКА per-commit: для КАЖДОГО коммита диапазона, чей дифф (с merge-cc содержимым)
# трогает зону, токен ОБЯЗАН быть в ТЕЛЕ этого коммита. Тема (subject) не считается
# (ось 5/subject); содержимое файла не считается — самоавторизация запрещена
# (ось 5/содержимое файла); путь файла не считается (ось 5/путь файла); причина короче
# 12 символов не авторизует (ось 5/негодная причина). Семантика per-commit нормативна
# (§3bis.5): реверт-пара блокируется, даже если net-diff чист — коммит без токена БЫЛ.
#
# Этот скрипт зовётся CI ровно так: `EVENT_NAME/.../.../bash scripts/check_docs_freeze.sh`
# из `.github/workflows/ci.yml` (job `docs-freeze`). Гейт, проверенный не тем вызовом,
# каким его зовёт прод, — не проверен.

set -uo pipefail
ZERO=0000000000000000000000000000000000000000

# ─── БАЗА СРАВНЕНИЯ — fail-closed при ЛЮБОЙ ошибке установки ─────────────────────────
raw="${1:-}"
if [ -z "${raw}" ]; then
  case "${EVENT_NAME:-}" in
    push)         raw="${PUSH_BEFORE:-}" ;;
    pull_request) raw="${PR_BASE_SHA:-}" ;;
    "")           echo "FAIL  событие не задано (EVENT_NAME пуст) — барьер зовут не так, как его зовёт CI" >&2; exit 1 ;;
    *)            echo "FAIL  неизвестное событие '${EVENT_NAME}' — база сравнения не определена" >&2; exit 1 ;;
  esac
fi

[ -n "${raw}" ] || { echo "FAIL  база события пуста (EVENT_NAME=${EVENT_NAME:-?}) — fail-closed" >&2; exit 1; }
case "${raw}" in
  *[!0]*) : ;;  # есть хоть один ненулевой символ — не zero-SHA
  *)      echo "FAIL  база = zero-SHA (создание ветки или force-push) — целостность процессного слоя не доказуема" >&2; exit 1 ;;
esac
git rev-parse -q --verify "${raw}^{commit}" >/dev/null 2>&1 \
  || { echo "FAIL  база '${raw}' отсутствует в истории (переписана force-push'ем / поверхностный клон)" >&2; exit 1; }
git merge-base --is-ancestor "${raw}" HEAD 2>/dev/null \
  || { echo "FAIL  база '${raw}' НЕ предок HEAD — история переписана (force-push); что в зоне менялось, недоказуемо" >&2; exit 1; }

BASE=$(git rev-parse "${raw}^{commit}")

# ─── ЗОНА ────────────────────────────────────────────────────────────────────────────
in_zone() {
  case "$1" in
    .claude/rules/*|.claude/agents/*|.claude/wrappers/*|CLAUDE.md|docs/04-workflow.md) return 0 ;;
    *) return 1 ;;
  esac
}

# ─── ТОКЕН: ТОЛЬКО в ТЕЛЕ коммита, причина ≥12 символов ────────────────────────────────
# subject / содержимое файла / путь файла — НЕ разрешение (ось 5 милестоуна).
# grep по `git show "$c"` ловил бы текст ДИФФА (строку `FOUNDER-APPROVED: …` ВНУТРИ
# изменённого файла): это самоавторизация, токен авторизует саму себя (A-005 §4 #1).
# `git log -1 --format='%b'` возвращает ТОЛЬКО тело коммита — ровно то, что в нём написано.
tok() {
  local body
  body=$(git log -1 --format='%b' "$1" 2>/dev/null) || return 1
  printf '%s\n' "$body" | grep -qE '^FOUNDER-APPROVED: .{12,}'
}

# ─── ТРОГАЕТ ЛИ КОММИТ ЗОНУ ──────────────────────────────────────────────────────────
# `git show --cc` показывает COMBINED diff: для merge-коммита это diff между merge-результатом
# и обеими родителями одновременно (по merge-cc). Плоский `diff-tree` (A-005 §4 #5) на merge
# МОЛЧИТ — сценарий «правка зоны только в дереве merge» проходит. `--cc` ловит оба класса:
# merge, внёсший правку в дерево результата через разрешение конфликта ИЛИ прямой правкой в
# merge-state; и merge, привнесший правку из второй ветки (хотя бы в одной из merge-cc-частей).
#
# `--no-renames` расщепляет rename на D+A, поэтому переименование из зоны наружу (A1R, ось 1/R)
# видно по СТАРОМУ пути — старый путь ещё в зоне; переименование В зону видно по новому пути.
# Оба направления ловятся единственной проверкой `in_zone` на каждой строке --name-only.
touches() {
  local f
  while IFS= read -r f; do
    [ -n "$f" ] && in_zone "$f" && return 0
  done < <(git show --cc --name-only --no-renames --format= "$1")
  return 1
}

# ─── ГЛАВНЫЙ ЦИКЛ ────────────────────────────────────────────────────────────────────
# Per-commit семантика (милестоун §3bis.5): коммит без токена в СВОЁМ теле, чей дифф трогает
# зону, ВАЛИТ барьер. Это значит: токен «позже» не покрывает правку «раньше» (ось 3/токен
# позже, A-005 §8.6); токен «раньше» не покрывает правку «позже» (ось 3/токен раньше);
# токен в теле MERGE не покрывает SIDE-коммит (ось 3/тело merge); реверт-пара блокируется,
# даже если net-diff чист (ось 3/реверт-пара). Все четыре значения выведены из ГРАММАТИКИ
# инварианта «для каждого коммита диапазона», а не подобраны перебором.
for c in $(git rev-list "${BASE}..HEAD"); do
  if touches "$c"; then tok "$c" || exit 1; fi
done
exit 0
