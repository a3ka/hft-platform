#!/usr/bin/env bash
# Барьер: ПОТРЕБИТЕЛЬ артефакта покрытия обязан ДОСТАВАТЬ его, а не просто называть тот же путь.
#
# ── ЗАМЕР, ИЗ-ЗА КОТОРОГО БАРЬЕР ЗАВЕДЁН (2026-09-08) ────────────────────────────────
# Ретеншен на проде не удалял НИЧЕГО с момента постройки: каждый кандидат отклонялся с
# «checkpoint coverage artifact absent (fail-closed)», отчёт — `freed_bytes: 0`. Причина
# найдена исполнением, а не чтением:
#
#   $ docker run --rm -v hft-platform_gateway-ckpt:/ckpt:ro alpine cat /ckpt/covered_through_seq
#   509966298                                     ← артефакт ЕСТЬ и свежий
#   $ docker compose run --rm --entrypoint sh journal-retention -c 'ls -la /ckpt'
#   ls: cannot access '/ckpt': No such file or directory   ← ПОТРЕБИТЕЛЬ его не видит
#
# Том с чекпоинтами в сервис `journal-retention` не смонтирован. Обе стороны при этом
# НАЗЫВАЮТ один и тот же путь `/ckpt/covered_through_seq` — и существующая канарейка
# композиции (`verify_M-48.sh`) сравнивает ровно эти две СТРОКИ, поэтому она ЗЕЛЕНА, пока
# механизм мёртв. Это ровно класс, который `testing.md` называет прямо: «проверка должна
# быть по ВЫЗОВУ (исполнением/поведением), а не по тексту».
#
# ── ЧТО ПРОВЕРЯЕТСЯ ЗДЕСЬ, ЧЕГО НЕ ПРОВЕРЯЛА КАНАРЕЙКА ───────────────────────────────
# Не совпадение строк, а ДОСТИЖИМОСТЬ: сервис-потребитель обязан монтировать ТОТ ЖЕ
# ИМЕНОВАННЫЙ ТОМ, в который пишет сервис-производитель, и монтировать его в каталог,
# накрывающий объявленный путь. Рассогласование «оба говорят /ckpt, но том один» ловится,
# а «оба говорят /ckpt, а тома у потребителя нет» — тем более.
#
# ── ПРЕДЕЛ НАЗВАН, А НЕ ИЗОБРАЖЁН ───────────────────────────────────────────────────
# Барьер СТАТИЧЕСКИЙ: он читает `docker-compose.yml` и обёртки, а не запускает контейнеры.
# Он поймал бы сегодняшнюю дыру (у потребителя нет монтирования) и поймает рассогласование
# томов. Он НЕ поймает: том смонтирован, но пуст; артефакт протух; права не дают читать.
# Это остаётся за прод-гейтом `gates.md` §8 (eyes-on) и за самим fail-closed отказом
# ретеншена — который, в отличие от барьера, виден только в логе и только постфактум.
set -uo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Швы для пробы: прод-путь — дефолт, проба подставляет синтетические файлы. Без швов барьер
# нельзя проверить иначе как правкой прод-конфига, то есть нельзя проверить.
COMPOSE="${RETENTION_COMPOSE:-${ROOT}/docker-compose.yml}"
FAILED=0
pass() { echo "PASS  $*"; }
fail() { echo "FAIL  $*"; FAILED=$((FAILED + 1)); }
die()  { echo "SETUP НЕ СОСТОЯЛСЯ: $*" >&2; exit 2; }

[ -f "${COMPOSE}" ] || die "нет ${COMPOSE}"

# Блок сервиса из compose: от «^  <имя>:» до следующего сервиса того же уровня.
svc_block() { awk -v s="  $1:" '$0==s{f=1;next} f&&/^  [^ ]/{exit} f' "${COMPOSE}"; }

PROD_BLOCK="$(svc_block gateway-checkpoint)"
CONS_BLOCK="$(svc_block journal-retention)"
[ -n "${PROD_BLOCK}" ] || die "в compose нет сервиса gateway-checkpoint"
[ -n "${CONS_BLOCK}" ] || die "в compose нет сервиса journal-retention"

# ── 1. Производитель объявляет путь артефакта покрытия ──────────────────────────────
OUT_PATH="$(printf '%s\n' "${PROD_BLOCK}" | sed -n 's/.*--coverage-out=\([^ "]*\).*/\1/p' | head -1)"
if [ -n "${OUT_PATH}" ]; then
  pass "производитель объявляет артефакт покрытия: ${OUT_PATH}"
else
  fail "gateway-checkpoint НЕ объявляет --coverage-out — производителя артефакта нет"
fi

# ── 2. Обёртка-потребитель просит ТОТ ЖЕ путь ──────────────────────────────────────
# Путь берётся ИСПОЛНЕНИЕМ обёртки (её штатный режим печати argv), а НЕ текстом скрипта:
# в argv стоит `${RETENTION_CHECKPOINT_COVERAGE}`, и текстовый разбор увидел бы имя
# переменной вместо значения. Первая редакция этого шага так и сделала и выдала ЛОЖНУЮ
# находку «потребитель пути не просит» — при том, что он его просит. Барьер, врущий в
# сторону тревоги, обесценивает себя так же верно, как врущий в сторону тишины.
CRON="${RETENTION_CRON:-${ROOT}/deploy/bin/journal-retention-cron.sh}"
IN_PATH=""
[ -f "${CRON}" ] && IN_PATH="$(HFT_CRON_PRINT_ARGV=1 bash "${CRON}" 2>/dev/null \
  | tr ' ' '\n' | sed -n 's/^--checkpoint-coverage=//p' | head -1)"
if [ -n "${IN_PATH}" ] && [ "${IN_PATH}" = "${OUT_PATH}" ]; then
  pass "потребитель просит ТОТ ЖЕ путь: ${IN_PATH}"
else
  fail "путь потребителя «${IN_PATH:-∅}» ≠ пути производителя «${OUT_PATH:-∅}»"
fi

# ── 3. ГЛАВНОЕ: потребитель МОНТИРУЕТ том производителя ────────────────────────────
# Именно этого не проверял никто, и именно это было мертво на проде.
MOUNT_DIR="$(dirname "${OUT_PATH:-/}")"
prod_vol() { printf '%s\n' "$1" | sed -n "s#^ *- *\([A-Za-z0-9_-]*\):${MOUNT_DIR}\(:[a-z,]*\)\?\$#\1#p" | head -1; }
PROD_VOL="$(prod_vol "${PROD_BLOCK}")"
CONS_VOL="$(prod_vol "${CONS_BLOCK}")"
if [ -z "${PROD_VOL}" ]; then
  fail "производитель пишет в ${OUT_PATH}, но НЕ монтирует том в ${MOUNT_DIR} — артефакт не переживёт контейнер"
elif [ -z "${CONS_VOL}" ]; then
  fail "ПОТРЕБИТЕЛЬ НЕ МОНТИРУЕТ ${MOUNT_DIR}: journal-retention объявляет путь ${OUT_PATH}, но тома у него нет.
      Внутри контейнера это «No such file or directory» ⇒ fail-closed ⇒ НЕ УДАЛЯЕТСЯ НИЧЕГО.
      Ровно это и происходило на проде: freed_bytes: 0 при живом и свежем артефакте.
      Лечится строкой в volumes сервиса journal-retention: - ${PROD_VOL}:${MOUNT_DIR}:ro"
elif [ "${PROD_VOL}" != "${CONS_VOL}" ]; then
  fail "тома РАЗНЫЕ: производитель пишет в «${PROD_VOL}», потребитель читает «${CONS_VOL}» — оба видят ${MOUNT_DIR}, но это РАЗНЫЕ данные"
else
  pass "потребитель монтирует ТОТ ЖЕ том «${CONS_VOL}» в ${MOUNT_DIR} — артефакт достижим"
fi

echo
if [ "${FAILED}" -eq 0 ]; then
  echo "VERDICT: PASS — путь артефакта покрытия достижим потребителем, а не только назван"
  exit 0
fi
echo "VERDICT: FAIL (${FAILED})"
exit 1
